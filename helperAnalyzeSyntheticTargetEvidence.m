function value = localStringField(inputStruct, fieldName, defaultValue)

value = defaultValue;

if isfield(inputStruct, fieldName)
    value = string(inputStruct.(fieldName));
end

end

function value = localDoubleField(inputStruct, fieldName, defaultValue)

value = defaultValue;

if isfield(inputStruct, fieldName)
    value = double(inputStruct.(fieldName));
end

end

function value = localTrackString(track, fieldName, defaultValue)

value = defaultValue;

if isfield(track, fieldName)
    value = string(track.(fieldName));
end

end

function value = localTrackDouble(track, fieldName, defaultValue)

value = double(defaultValue);

if isfield(track, fieldName) && ~isempty(track.(fieldName))
    value = double(track.(fieldName));
end

