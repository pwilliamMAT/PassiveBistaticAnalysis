function localWriteTextFile(filePath, lines)

if isstring(lines)
    lineArray = lines(:);
elseif ischar(lines)
    lineArray = string(lines);
else
    lineArray = string(lines);
end

lineArray = lineArray(:);
textBody = strjoin(lineArray, newline);

try
    fileId = fopen(filePath, "w");
catch fopenException
    error("runG1G2SessionComparison:OpenFileFailed", ...
        "Failed to open %s for writing: %s", filePath, ...
        fopenException.message);
end

if fileId == -1
    error("runG1G2SessionComparison:OpenFileFailed", ...
        "Failed to open %s for writing.", filePath);
end

cleanupObject = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s\n", textBody);

end

