function results = runG1G2SessionComparison(baselineDatasetId, ...
    candidateDatasetId, repoRoot, options)
%RUNG1G2SESSIONCOMPARISON Compare saved G1 and G2 artifacts across sessions.
%
%   RESULTS = RUNG1G2SESSIONCOMPARISON(BASELINE, CANDIDATE) loads the
%   latest comparison_snapshot.mat artifacts for G1, G2 Stage 1, and G2
%   Stage 2 from the baseline and candidate sessions, then writes a
%   hardware-iteration comparison bundle under:
%   artifacts/comparisons/<baseline>_vs_<candidate>/<runTimestampZ>/
%
%   This runner is artifact-only. It never re-runs single-session analysis.

arguments
    baselineDatasetId (1,1) string = "20260622T102123"
    candidateDatasetId (1,1) string = ""
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

repoRoot = helperResolveRepoRoot(repoRoot);
baselineDatasetId = string(baselineDatasetId);
candidateDatasetId = string(candidateDatasetId);

if strlength(strtrim(candidateDatasetId)) == 0
    error("runG1G2SessionComparison:MissingCandidateDatasetId", ...
        "Candidate dataset ID is required. Call " + ...
        "runG1G2SessionComparison(""20260622T102123"", " + ...
        """<candidateDatasetId>"", ...).");
end

runnerOptions = localResolveRunnerOptions(options);
runTimestampZ = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss'Z'"));
comparisonId = baselineDatasetId + "_vs_" + candidateDatasetId;
bundleRoot = fullfile(repoRoot, "artifacts", "comparisons", ...
    comparisonId, runTimestampZ);
figureRoot = fullfile(bundleRoot, "figures");

fprintf("Running G1/G2 artifact-only session comparison\n");
fprintf("Baseline dataset:\t%s\n", baselineDatasetId);
fprintf("Candidate dataset:\t%s\n", candidateDatasetId);
fprintf("Repository root:\t%s\n", repoRoot);

try
    localEnsureFolder(bundleRoot);
    localEnsureFolder(figureRoot);

    baselineSnapshots = localLoadSnapshotSet(baselineDatasetId, repoRoot);
    candidateSnapshots = localLoadSnapshotSet(candidateDatasetId, repoRoot);

    overallSummaryTable = localBuildOverallSummaryTable( ...
        baselineSnapshots, candidateSnapshots, bundleRoot);
    g1ComparisonTable = localBuildStageComparisonTable( ...
        baselineSnapshots.G1, candidateSnapshots.G1);
    g2Stage1ComparisonTable = localBuildStageComparisonTable( ...
        baselineSnapshots.G2Stage1, candidateSnapshots.G2Stage1);
    g2Stage2ComparisonTable = localBuildStageComparisonTable( ...
        baselineSnapshots.G2Stage2, candidateSnapshots.G2Stage2);

    summaryLines = localBuildSummaryLines(baselineSnapshots, ...
        candidateSnapshots, bundleRoot, runTimestampZ);
    interpretationNoteLines = localBuildInterpretationNoteLines( ...
        baselineSnapshots, candidateSnapshots);

    sessionSummaryPath = fullfile(bundleRoot, ...
        "session_comparison_summary.csv");
    g1ComparisonPath = fullfile(bundleRoot, "g1_comparison_table.csv");
    g2Stage1ComparisonPath = fullfile(bundleRoot, ...
        "g2_stage1_comparison_table.csv");
    g2Stage2ComparisonPath = fullfile(bundleRoot, ...
        "g2_stage2_comparison_table.csv");
    summaryPath = fullfile(bundleRoot, "summary.md");
    interpretationPath = fullfile(bundleRoot, "interpretation_note.md");
    resultsMatPath = fullfile(bundleRoot, "comparison_results.mat");
    rolePowerFigurePath = fullfile(figureRoot, ...
        "figure_01_stage2_role_power_ordering.png");
    worstMetricsFigurePath = fullfile(figureRoot, ...
        "figure_02_stage2_worst_metrics.png");

    try
        writetable(overallSummaryTable, sessionSummaryPath);
        writetable(g1ComparisonTable, g1ComparisonPath);
        writetable(g2Stage1ComparisonTable, g2Stage1ComparisonPath);
        writetable(g2Stage2ComparisonTable, g2Stage2ComparisonPath);
    catch writeTableException
        error("runG1G2SessionComparison:WriteTableFailed", ...
            "Failed to write a comparison table artifact: %s", ...
            writeTableException.message);
    end

    localWriteTextFile(summaryPath, summaryLines);
    localWriteTextFile(interpretationPath, interpretationNoteLines);

    localRenderStage2RolePowerFigure(baselineSnapshots.G2Stage2, ...
        candidateSnapshots.G2Stage2, rolePowerFigurePath, ...
        runnerOptions.ShowFigures);
    localRenderStage2WorstMetricsFigure(baselineSnapshots.G2Stage2, ...
        candidateSnapshots.G2Stage2, worstMetricsFigurePath, ...
        runnerOptions.ShowFigures);

    results = struct();
    results.BaselineDatasetId = baselineDatasetId;
    results.CandidateDatasetId = candidateDatasetId;
    results.RunTimestampZ = runTimestampZ;
    results.BundleRoot = string(bundleRoot);
    results.BaselineSnapshots = baselineSnapshots;
    results.CandidateSnapshots = candidateSnapshots;
    results.OverallSummaryTable = overallSummaryTable;
    results.G1ComparisonTable = g1ComparisonTable;
    results.G2Stage1ComparisonTable = g2Stage1ComparisonTable;
    results.G2Stage2ComparisonTable = g2Stage2ComparisonTable;
    results.InterpretationNoteLines = interpretationNoteLines;
    results.FigurePaths = [string(rolePowerFigurePath); ...
        string(worstMetricsFigurePath)];

    try
        save(resultsMatPath, "results");
    catch saveException
        error("runG1G2SessionComparison:SaveResultsFailed", ...
            "Failed to write comparison_results.mat: %s", ...
            saveException.message);
    end

    fprintf("Comparison bundle:\t%s\n", bundleRoot);
    fprintf("Stage 2 median reference-minus-surveillance delta:\t%.3f dB\n", ...
        candidateSnapshots.G2Stage2.ReferenceMinusSurveillancePowerMedian_dB - ...
        baselineSnapshots.G2Stage2.ReferenceMinusSurveillancePowerMedian_dB);
catch mainException
    localWriteFailureBundle(bundleRoot, mainException);
    rethrow(mainException);
end

end

