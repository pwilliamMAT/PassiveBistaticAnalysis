if strlength(string(bundleRoot)) == 0
    return
end

try
    if ~isfolder(bundleRoot)
        mkdir(bundleRoot);
    end

    localWriteTextFile(fullfile(bundleRoot, "summary.md"), [ ...
        "# G1/G2 Session Comparison Failure"; ...
        ""; ...
        sprintf("- Error identifier: `%s`", mainException.identifier); ...
        sprintf("- Message: %s", string(mainException.message)) ...
        ]);
catch
    % Ignore secondary failure-bundle errors.
end

