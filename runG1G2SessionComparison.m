function takeawayText = localBuildHardwareTakeaway(baselineStage2, ...
    candidateStage2)

powerMedianDelta = ...
    candidateStage2.ReferenceMinusSurveillancePowerMedian_dB - ...
    baselineStage2.ReferenceMinusSurveillancePowerMedian_dB;

if powerMedianDelta > 0.5
    powerText = sprintf("The candidate improves Stage 2 reference-power ordering by %.3f dB.", ...
        powerMedianDelta);
elseif powerMedianDelta < -0.5
    powerText = sprintf("The candidate weakens Stage 2 reference-power ordering by %.3f dB.", ...
        abs(powerMedianDelta));
else
    powerText = "The candidate leaves Stage 2 reference-power ordering essentially unchanged.";
end

if candidateStage2.ReferenceMinusSurveillancePowerMedian_dB >= 0.0
    thresholdText = "The candidate reaches a non-negative median reference-minus-surveillance power difference.";
else
    thresholdText = "The candidate still has a negative median reference-minus-surveillance power difference, so the accepted reference remains weaker than surveillance on a session-wide basis.";
end

takeawayText = powerText + " " + thresholdText;

end

function localRenderStage2RolePowerFigure(baselineSnapshot, ...
    candidateSnapshot, figurePath, showFigures)

figureHandle = figure("Visible", localFigureVisibility(showFigures));
tiledlayout(1, 1, "TileSpacing", "compact", "Padding", "compact");
nexttile;

categoryNames = categorical(["Minimum", "Median", "Maximum"]);
categoryNames = reordercats(categoryNames, ["Minimum", "Median", "Maximum"]);
powerMatrix = [ ...
    baselineSnapshot.ReferenceMinusSurveillancePowerMin_dB, ...
    baselineSnapshot.ReferenceMinusSurveillancePowerMedian_dB, ...
    baselineSnapshot.ReferenceMinusSurveillancePowerMax_dB; ...
    candidateSnapshot.ReferenceMinusSurveillancePowerMin_dB, ...
    candidateSnapshot.ReferenceMinusSurveillancePowerMedian_dB, ...
    candidateSnapshot.ReferenceMinusSurveillancePowerMax_dB ...
    ];

bar(categoryNames, powerMatrix.');
yline(0.0, "--k", "0 dB threshold");
grid on;
xlabel("Statistic");
ylabel("Reference Minus Surveillance Power [dB]");
title("Stage 2 Role Power Ordering");
legend([string(baselineSnapshot.DatasetId), ...
    string(candidateSnapshot.DatasetId)], "Location", "best");

try
    exportgraphics(figureHandle, figurePath);
catch figureException
    close(figureHandle);
    error("runG1G2SessionComparison:SaveFigureFailed", ...
        "Failed to write figure %s: %s", figurePath, ...
        figureException.message);
end

if ~showFigures
    close(figureHandle);
end

end

