function comparisonTable = localBuildStageComparisonTable(baselineSnapshot, ...
    candidateSnapshot)

baselineTable = localPrepareSummaryTable(baselineSnapshot.SummaryTable);
candidateTable = localPrepareSummaryTable(candidateSnapshot.SummaryTable);

baselineTable = renamevars(baselineTable, ...
    ["MetricLabel", "ValueType", "NumericValue", "TextValue", ...
    "Units", "Notes", "DisplayOrder"], ...
    ["BaselineMetricLabel", "BaselineValueType", ...
    "BaselineNumericValue", "BaselineTextValue", "BaselineUnits", ...
    "BaselineNotes", "BaselineDisplayOrder"]);
candidateTable = renamevars(candidateTable, ...
    ["MetricLabel", "ValueType", "NumericValue", "TextValue", ...
    "Units", "Notes", "DisplayOrder"], ...
    ["CandidateMetricLabel", "CandidateValueType", ...
    "CandidateNumericValue", "CandidateTextValue", "CandidateUnits", ...
    "CandidateNotes", "CandidateDisplayOrder"]);

joinedTable = outerjoin(baselineTable, candidateTable, ...
    "Keys", "MetricId", "MergeKeys", true, "Type", "full");

displayOrder = joinedTable.BaselineDisplayOrder;
missingBaselineOrderMask = isnan(displayOrder);
displayOrder(missingBaselineOrderMask) = ...
    joinedTable.CandidateDisplayOrder(missingBaselineOrderMask);

comparisonTable = table();
comparisonTable.MetricId = string(joinedTable.MetricId);
comparisonTable.MetricLabel = localCoalesceString( ...
    joinedTable.BaselineMetricLabel, joinedTable.CandidateMetricLabel);
comparisonTable.ValueType = localCoalesceString( ...
    joinedTable.BaselineValueType, joinedTable.CandidateValueType);
comparisonTable.Units = localCoalesceString( ...
    joinedTable.BaselineUnits, joinedTable.CandidateUnits);
comparisonTable.BaselineValue = string(joinedTable.BaselineTextValue);
comparisonTable.CandidateValue = string(joinedTable.CandidateTextValue);
comparisonTable.BaselineNumericValue = ...
    double(joinedTable.BaselineNumericValue);
comparisonTable.CandidateNumericValue = ...
    double(joinedTable.CandidateNumericValue);
comparisonTable.NumericDelta = NaN(height(joinedTable), 1);
comparisonTable.ChangeAssessment = localBuildChangeAssessment( ...
    comparisonTable.ValueType, comparisonTable.BaselineValue, ...
    comparisonTable.CandidateValue, ...
    comparisonTable.BaselineNumericValue, ...
    comparisonTable.CandidateNumericValue);
comparisonTable.Notes = localCoalesceString( ...
    joinedTable.BaselineNotes, joinedTable.CandidateNotes);

numericMask = comparisonTable.ValueType == "numeric" | ...
    comparisonTable.ValueType == "logical";
availableDeltaMask = numericMask & ...
    ~isnan(comparisonTable.BaselineNumericValue) & ...
    ~isnan(comparisonTable.CandidateNumericValue);
comparisonTable.NumericDelta(availableDeltaMask) = ...
    comparisonTable.CandidateNumericValue(availableDeltaMask) - ...
    comparisonTable.BaselineNumericValue(availableDeltaMask);

comparisonTable.DisplayOrder = displayOrder;
comparisonTable = sortrows(comparisonTable, "DisplayOrder");
comparisonTable.DisplayOrder = [];

end

function summaryTable = localPrepareSummaryTable(summaryTable)

if ~ismember("DisplayOrder", summaryTable.Properties.VariableNames)
    summaryTable.DisplayOrder = (1:height(summaryTable)).';
end

summaryTable.MetricId = string(summaryTable.MetricId);
summaryTable.MetricLabel = string(summaryTable.MetricLabel);
summaryTable.ValueType = string(summaryTable.ValueType);
summaryTable.NumericValue = double(summaryTable.NumericValue);
summaryTable.TextValue = string(summaryTable.TextValue);
summaryTable.Units = string(summaryTable.Units);
summaryTable.Notes = string(summaryTable.Notes);
summaryTable.DisplayOrder = double(summaryTable.DisplayOrder);

end

function outputValues = localCoalesceString(primaryValues, secondaryValues)

primaryValues = string(primaryValues);
secondaryValues = string(secondaryValues);
outputValues = primaryValues;
emptyMask = strlength(strtrim(outputValues)) == 0;
outputValues(emptyMask) = secondaryValues(emptyMask);

end

function changeAssessment = localBuildChangeAssessment(valueType, ...
    baselineValue, candidateValue, baselineNumericValue, ...
    candidateNumericValue)

rowCount = numel(valueType);
changeAssessment = strings(rowCount, 1);

for idx = 1:rowCount
    if valueType(idx) == "numeric" || valueType(idx) == "logical"
        if isnan(baselineNumericValue(idx)) || isnan(candidateNumericValue(idx))
            changeAssessment(idx) = "n/a";
            continue
        end

        deltaValue = candidateNumericValue(idx) - baselineNumericValue(idx);

        if abs(deltaValue) < 1.0e-12
            changeAssessment(idx) = "unchanged";
        elseif deltaValue > 0.0
            changeAssessment(idx) = "candidate higher";
        else
            changeAssessment(idx) = "candidate lower";
        end

        continue
    end

    if strtrim(baselineValue(idx)) == strtrim(candidateValue(idx))
        changeAssessment(idx) = "matched";
    else
        changeAssessment(idx) = "changed";
    end
end

end

