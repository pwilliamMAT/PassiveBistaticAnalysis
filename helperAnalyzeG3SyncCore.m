function analysis = helperAnalyzeG3SyncCore(sessionData, ...
    collectionMetadataInfo, options)
%HELPERANALYZEG3SYNCCORE Analyze Stage 3 sync questions for the baseline.
%
%   ANALYSIS = HELPERANALYZEG3SYNCCORE(SESSIONDATA, ...
%   COLLECTIONMETADATAINFO, OPTIONS) evaluates the Stage 3 lag, residual
%   frequency, CPI coherence, and correction-strategy questions for the
%   baseline dataset only. The helper is question-driven on purpose: each
%   returned table row carries the Stage 3 question it exists to answer.

arguments
    sessionData (1,1) struct
    collectionMetadataInfo (1,1) struct
    options (1,1) struct = struct()
end

syncPrep = helperPrepareG3SyncInputs(sessionData, ...
    collectionMetadataInfo, options);
resolvedOptions = syncPrep.ResolvedOptions;
roleInfo = syncPrep.RoleInfo;
windowObservations = syncPrep.WindowObservations;
lagTable = localBuildLagTable(sessionData, windowObservations, ...
    resolvedOptions);
residualFrequencyTable = localBuildResidualFrequencyTable(sessionData, ...
    windowObservations, resolvedOptions);
cpiCoherenceTable = localBuildCpiCoherenceTable(sessionData, ...
    windowObservations, resolvedOptions);
[strategyComparisonTable, recommendedStrategyCandidate] = ...
    localBuildStrategyComparisonTable(windowObservations, ...
    resolvedOptions);
[questionSummaries, blockingFindings] = localBuildQuestionSummaries( ...
    lagTable, residualFrequencyTable, cpiCoherenceTable, ...
    strategyComparisonTable, recommendedStrategyCandidate, roleInfo, ...
    resolvedOptions);
interpretation = localBuildInterpretation(questionSummaries, ...
    blockingFindings, recommendedStrategyCandidate, roleInfo, ...
    resolvedOptions);

analysis = struct();
analysis.DatasetId = string(sessionData.DatasetId);
analysis.StageId = "G3_Sync_Core";
analysis.Options = localBuildOptionsOutput(resolvedOptions);
analysis.QuestionSummaries = questionSummaries;
analysis.LagTable = lagTable;
analysis.ResidualFrequencyTable = residualFrequencyTable;
analysis.CpiCoherenceTable = cpiCoherenceTable;
analysis.StrategyComparisonTable = strategyComparisonTable;
analysis.Metrics = localBuildMetrics(roleInfo, lagTable, ...
    residualFrequencyTable, cpiCoherenceTable, ...
    strategyComparisonTable, questionSummaries, interpretation, ...
    blockingFindings, recommendedStrategyCandidate, resolvedOptions);
analysis.Interpretation = interpretation;
analysis.RecommendedStrategyCandidate = recommendedStrategyCandidate;
analysis.BlockingFindings = blockingFindings;

end

