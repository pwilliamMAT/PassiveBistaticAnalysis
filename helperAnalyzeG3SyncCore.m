rowIndex = 0;

for repetitionIndex = 1:height(sessionData.RadarTable)
    for cpiIndex = 1:numel(resolvedOptions.CpiDefinitions)
        cpiLabel = resolvedOptions.CpiDefinitions(cpiIndex).Label;
        subset = windowObservations( ...
            windowObservations.Repetition == ...
            sessionData.RadarTable.Repetition(repetitionIndex) & ...
            windowObservations.CpiLabel == cpiLabel, :);
        [interpretationLabel, rationale] = ...
            localClassifyResidualFrequencySubset(subset, resolvedOptions);
        rowIndex = rowIndex + 1;
        residualRows(rowIndex) = struct( ...
            "QuestionId", "Q2", ...
            "QuestionText", ...
            "Is residual frequency or phase drift small enough to support a consistent correction model?", ...
            "Repetition", double(sessionData.RadarTable.Repetition(repetitionIndex)), ...
