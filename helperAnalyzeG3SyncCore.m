function [interpretationLabel, rationale] = localClassifyCoherenceSubset( ...
    subset, resolvedOptions)

coherenceMedian = median(subset.CoherenceMean);
coherencePassFraction = mean(subset.CoherenceMean >= ...
    resolvedOptions.CoherencePassThreshold);

if ~localTableHasFiniteNumericValues(subset)
    interpretationLabel = "blocked";
    rationale = "Coherence metrics were not finite across all windows.";
    return
end

if coherenceMedian >= resolvedOptions.CoherencePassThreshold && ...
        coherencePassFraction >= ...
        resolvedOptions.CoherenceReadyPassFractionThreshold
    interpretationLabel = "ready";
elseif coherenceMedian >= resolvedOptions.CoherenceCaveatedThreshold && ...
        coherencePassFraction >= ...
        resolvedOptions.CoherenceBlockedPassFractionThreshold
    interpretationLabel = "caveated";
else
    interpretationLabel = "blocked";
end

rationale = sprintf("Median band coherence was %.3f with %.1f%% of " + ...
    "windows above the %.2f pass threshold.", coherenceMedian, ...
    100.0 * coherencePassFraction, ...
    resolvedOptions.CoherencePassThreshold);

end

function [strategyComparisonTable, recommendedStrategyCandidate] = ...
    localBuildStrategyComparisonTable(windowObservations, resolvedOptions)

baseObservations = windowObservations( ...
    windowObservations.CpiLabel == ...
    resolvedOptions.StrategyComparisonCpiLabel, :);
strategyNames = [ ...
    "global_session_correction"; ...
    "per_capture_correction"; ...
    "subwindow_correction" ...
    ];
strategyScopes = ["session"; "per_repetition"; "per_window"];
complexityRank = [1; 2; 3];
strategyRows = repmat(localBuildStrategyRowTemplate(), ...
    numel(strategyNames), 1);

globalLag = round(median(baseObservations.CanonicalLagSamples));
globalFrequencyHz = median(baseObservations.ResidualFrequencyHz);
repetitionVector = unique(baseObservations.Repetition);
perCaptureLag = containers.Map("KeyType", "double", "ValueType", "double");
perCaptureFrequencyHz = containers.Map("KeyType", "double", ...
    "ValueType", "double");

for repetitionIndex = 1:numel(repetitionVector)
    repetitionValue = repetitionVector(repetitionIndex);
    repetitionMask = baseObservations.Repetition == repetitionValue;
    perCaptureLag(repetitionValue) = round(median( ...
        baseObservations.CanonicalLagSamples(repetitionMask)));
    perCaptureFrequencyHz(repetitionValue) = median( ...
        baseObservations.ResidualFrequencyHz(repetitionMask));
end

for strategyIndex = 1:numel(strategyNames)
    lagResidual = zeros(height(baseObservations), 1);
    phaseResidual = zeros(height(baseObservations), 1);

    for observationIndex = 1:height(baseObservations)
        repetitionValue = baseObservations.Repetition(observationIndex);

        switch strategyNames(strategyIndex)
            case "global_session_correction"
                candidateLag = globalLag;
                candidateFrequencyHz = globalFrequencyHz;
            case "per_capture_correction"
                candidateLag = perCaptureLag(repetitionValue);
                candidateFrequencyHz = perCaptureFrequencyHz( ...
                    repetitionValue);
            case "subwindow_correction"
                candidateLag = ...
                    baseObservations.CanonicalLagSamples(observationIndex);
                candidateFrequencyHz = ...
                    baseObservations.ResidualFrequencyHz(observationIndex);
        end

        lagResidual(observationIndex) = abs( ...
            baseObservations.CanonicalLagSamples(observationIndex) - ...
            candidateLag);
        phaseResidual(observationIndex) = abs( ...
            baseObservations.ResidualFrequencyHz(observationIndex) - ...
            candidateFrequencyHz) * ...
            baseObservations.CpiDuration_s(observationIndex) * 360.0;
    end

    passMask = lagResidual <= resolvedOptions.StrategyLagPassThresholdSamples & ...
        phaseResidual <= resolvedOptions.StrategyPhasePassThreshold_deg & ...
        baseObservations.CoherenceMean >= ...
        resolvedOptions.CoherencePassThreshold;
    passFraction = mean(passMask);
    interpretationLabel = localClassifyStrategyRow(passFraction);
    rationale = sprintf("%s explains %.1f%% of short-CPI windows " + ...
        "within %.1f sample and %.1f deg residual limits.", ...
        strrep(strategyNames(strategyIndex), "_", " "), ...
        100.0 * passFraction, ...
        resolvedOptions.StrategyLagPassThresholdSamples, ...
        resolvedOptions.StrategyPhasePassThreshold_deg);

    strategyRows(strategyIndex) = struct( ...
        "QuestionId", "Q4", ...
        "QuestionText", ...
        "Which correction strategy is most defensible for downstream use?", ...
        "StrategyCandidate", strategyNames(strategyIndex), ...
        "StrategyScope", strategyScopes(strategyIndex), ...
        "EvaluationCpiLabel", ...
        resolvedOptions.StrategyComparisonCpiLabel, ...
        "EvaluationWindowCount", double(height(baseObservations)), ...
        "LagResidualMedian_samples", median(lagResidual), ...
        "LagResidualMax_samples", max(lagResidual), ...
        "PhaseResidualMedian_deg", median(phaseResidual), ...
        "PhaseResidualMax_deg", max(phaseResidual), ...
        "ObservablePassFraction", passFraction, ...
        "ComplexityRank", complexityRank(strategyIndex), ...
        "WithinBestMargin", false, ...
        "Recommended", false, ...
        "InterpretationLabel", interpretationLabel, ...
        "Rationale", rationale ...
        );
end

strategyComparisonTable = struct2table(strategyRows);
bestStrategyIndex = localSelectBestStrategy(strategyComparisonTable);
bestPassFraction = strategyComparisonTable.ObservablePassFraction( ...
    bestStrategyIndex);
bestLagResidual = strategyComparisonTable.LagResidualMedian_samples( ...
    bestStrategyIndex);
bestPhaseResidual = strategyComparisonTable.PhaseResidualMedian_deg( ...
    bestStrategyIndex);
withinBestMargin = ...
    strategyComparisonTable.ObservablePassFraction >= ...
    bestPassFraction - resolvedOptions.StrategyPassFractionMargin & ...
    strategyComparisonTable.LagResidualMedian_samples <= ...
    bestLagResidual + ...
    resolvedOptions.StrategyLagEquivalenceMarginSamples & ...
    strategyComparisonTable.PhaseResidualMedian_deg <= ...
    bestPhaseResidual + ...
    resolvedOptions.StrategyPhaseEquivalenceMargin_deg;
strategyComparisonTable.WithinBestMargin = withinBestMargin;
recommendedIndex = find(strategyComparisonTable.WithinBestMargin, ...
    1, "first");

if isempty(recommendedIndex)
    recommendedIndex = bestStrategyIndex;
end

strategyComparisonTable.Recommended(recommendedIndex) = true;
recommendedStrategyCandidate = ...
    strategyComparisonTable.StrategyCandidate(recommendedIndex);

end

