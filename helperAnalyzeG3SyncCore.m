function [interpretationLabel, rationale] = localClassifyLagSubset( ...
    subset, resolvedOptions)

lagSpread = max(subset.CanonicalLagSamples) - min(subset.CanonicalLagSamples);
sharpnessMedian = median(subset.PeakToSidelobe_dB);
agreementFraction = mean(subset.DelayEstimateAgreement);
canonicalLag = median(subset.CanonicalLagSamples);

if ~localTableHasFiniteNumericValues(subset)
    interpretationLabel = "blocked";
    rationale = "Lag metrics were not finite across all windows.";
    return
end

if lagSpread <= resolvedOptions.LagReadySpreadThresholdSamples && ...
        sharpnessMedian >= resolvedOptions.LagReadySharpnessThreshold_dB && ...
        agreementFraction >= resolvedOptions.DelayAgreementReadyThreshold
    interpretationLabel = "ready";
elseif lagSpread <= resolvedOptions.LagBlockedSpreadThresholdSamples && ...
        sharpnessMedian >= resolvedOptions.LagBlockedSharpnessThreshold_dB && ...
        agreementFraction >= resolvedOptions.DelayAgreementBlockedThreshold
    interpretationLabel = "caveated";
else
    interpretationLabel = "blocked";
end

rationale = sprintf("Lag stayed near %.1f sample with %.1f-sample " + ...
    "spread across %d windows and median peak-to-sidelobe %.2f dB.", ...
    canonicalLag, lagSpread, height(subset), sharpnessMedian);

end

