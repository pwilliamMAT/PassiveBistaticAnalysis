function interpretationLabel = localClassifyStrategyRow(passFraction)

if passFraction >= 0.90
    interpretationLabel = "ready";
elseif passFraction >= 0.50
    interpretationLabel = "caveated";
else
    interpretationLabel = "blocked";
end

end

function bestStrategyIndex = localSelectBestStrategy(strategyComparisonTable)

bestStrategyIndex = 1;

for idx = 2:height(strategyComparisonTable)
    currentRow = strategyComparisonTable(idx, :);
    bestRow = strategyComparisonTable(bestStrategyIndex, :);

    if currentRow.ObservablePassFraction > bestRow.ObservablePassFraction
        bestStrategyIndex = idx;
        continue
    end

    if currentRow.ObservablePassFraction == bestRow.ObservablePassFraction && ...
            currentRow.PhaseResidualMedian_deg < ...
            bestRow.PhaseResidualMedian_deg
        bestStrategyIndex = idx;
        continue
    end

    if currentRow.ObservablePassFraction == bestRow.ObservablePassFraction && ...
            currentRow.PhaseResidualMedian_deg == ...
            bestRow.PhaseResidualMedian_deg && ...
            currentRow.LagResidualMedian_samples < ...
            bestRow.LagResidualMedian_samples
        bestStrategyIndex = idx;
    end
end

end

