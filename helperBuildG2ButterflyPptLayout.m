function lines = localBuildSlide2Lines(boxes, colors)

lineCount = max(0, numel(boxes) - 1);
lines = repmat(localLineTemplate(), 1, lineCount);

for lineIndex = 1:lineCount
    sourceBox = boxes(lineIndex);
    targetBox = boxes(lineIndex + 1);
    lines(lineIndex) = localMakeLine( ...
        sourceBox.X + sourceBox.Width, ...
        sourceBox.Y + sourceBox.Height / 2, ...
        targetBox.X, ...
        targetBox.Y + targetBox.Height / 2, ...
        colors.SecondaryLine, ...
        1.75, ...
        true, ...
        "" ...
    );
end
end

function formatted = localFormatWingBoxes(rawValues)

formatted = strings(size(rawValues));

for valueIndex = 1:numel(rawValues)
    formatted(valueIndex) = localBreakAtFirstColon(rawValues(valueIndex));
end
end

function formatted = localFormatCenterItems(rawValues)

formatted = strings(size(rawValues));

for valueIndex = 1:numel(rawValues)
    formatted(valueIndex) = "- " + rawValues(valueIndex);
end
end

function formatted = localFormatFlowSteps(rawValues)

formatted = strings(size(rawValues));

for valueIndex = 1:numel(rawValues)
    currentValue = rawValues(valueIndex);
    currentValue = regexprep(currentValue, "^\s*(\d+)\.\s*", ...
        "$1" + string(newline));
    formatted(valueIndex) = localBreakAtFirstColon(currentValue);
end
end

function formatted = localFormatFlowFooter(rawValues)

formatted = strings(size(rawValues));

for valueIndex = 1:numel(rawValues)
    currentValue = regexprep(rawValues(valueIndex), "^\s*\d+\.\s*", "");
    currentValue = strrep(currentValue, ": ", " - ");
    formatted(valueIndex) = currentValue;
end
end

function value = localBreakAtFirstColon(value)

colonIndex = strfind(value, ": ");

if isempty(colonIndex)
    return;
end

firstIndex = colonIndex(1);
value = extractBefore(value, firstIndex) + newline + ...
    extractAfter(value, firstIndex + 1);
end

