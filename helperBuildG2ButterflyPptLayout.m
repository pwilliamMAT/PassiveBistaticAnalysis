function boxes = localBuildSlide1Boxes(spec, colors)

leftTexts = localFormatWingBoxes(spec.LeftWing);
doubleNewline = string(newline) + string(newline);
centerText = strjoin(localFormatCenterItems(spec.Center), doubleNewline);
rightTexts = localFormatWingBoxes(spec.RightWing);

leftX = 34;
rightX = 706;
boxWidth = 220;
boxHeight = 64;
boxGap = 14;
startY = 156;

leftBoxes = repmat(localBoxTemplate(), 1, numel(leftTexts));
rightBoxes = repmat(localBoxTemplate(), 1, numel(rightTexts));

for boxIndex = 1:numel(leftTexts)
    currentY = startY + (boxIndex - 1) * (boxHeight + boxGap);
    leftBoxes(boxIndex) = localMakeBox( ...
        "LEFT_" + string(boxIndex), leftTexts(boxIndex), leftX, currentY, ...
        boxWidth, boxHeight, colors.LeftFill, colors.LeftLine, 11, true, ...
        colors.Text, 1, "center");
end

for boxIndex = 1:numel(rightTexts)
    currentY = startY + (boxIndex - 1) * (boxHeight + boxGap);
    rightBoxes(boxIndex) = localMakeBox( ...
        "RIGHT_" + string(boxIndex), rightTexts(boxIndex), rightX, currentY, ...
        boxWidth, boxHeight, colors.RightFill, colors.RightLine, 11, true, ...
        colors.Text, 1, "center");
end

centerBox = localMakeBox( ...
    "CENTER_GATE", centerText, 328, 184, 304, 168, colors.CenterFill, ...
    colors.CenterLine, 13, true, colors.Text, 1, "center");

boxes = [leftBoxes centerBox rightBoxes];
end

function lines = localBuildSlide1Lines(boxes, colors)

leftBoxes = boxes(contains(string({boxes.Id}), "LEFT_"));
centerBox = boxes(strcmp(string({boxes.Id}), "CENTER_GATE"));
rightBoxes = boxes(contains(string({boxes.Id}), "RIGHT_"));

lineCount = numel(leftBoxes) + numel(rightBoxes);
lines = repmat(localLineTemplate(), 1, lineCount);
lineIndex = 0;

for boxIndex = 1:numel(leftBoxes)
    currentBox = leftBoxes(boxIndex);
    lineIndex = lineIndex + 1;
    lines(lineIndex) = localMakeLine( ...
        currentBox.X + currentBox.Width, ...
        currentBox.Y + currentBox.Height / 2, ...
        centerBox.X, ...
        centerBox.Y + centerBox.Height / 2, ...
        colors.PrimaryLine, ...
        1.75, ...
        true, ...
        "" ...
    );
end

for boxIndex = 1:numel(rightBoxes)
    currentBox = rightBoxes(boxIndex);
    lineIndex = lineIndex + 1;
    lines(lineIndex) = localMakeLine( ...
        centerBox.X + centerBox.Width, ...
        centerBox.Y + centerBox.Height / 2, ...
        currentBox.X, ...
        currentBox.Y + currentBox.Height / 2, ...
        colors.PrimaryLine, ...
        1.75, ...
        true, ...
        "" ...
    );
end
end

