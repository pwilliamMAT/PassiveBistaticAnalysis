function [maps, geometry] = localBuildMapTriplet( ...
    mode, backgroundId, caseId)

if nargin < 3
    caseId = "injected_case";
end

[delayAxis_s, dopplerAxis_Hz, geometry] = localBuildAxes();
baseMap = ones(numel(dopplerAxis_Hz), ...
    numel(delayAxis_s), "single");
targetLocations = localTargetLocations();
candidateNames = [ ...
    "none"; "conservative_lms"; "aggressive_lms"];
maps = repmat(struct( ...
    "CampaignId", "fixture", ...
    "BackgroundId", string(backgroundId), ...
    "CaseId", string(caseId), ...
    "CandidateName", "", ...
    "WindowLabel", "center", ...
    "AxisOrientation", "rows_doppler_columns_delay", ...
    "MapLinear", baseMap, ...
    "DelayAxis_s", delayAxis_s, ...
    "DopplerAxis_Hz", dopplerAxis_Hz), 3, 1);

for candidateIndex = 1:numel(candidateNames)
    maps(candidateIndex).CandidateName = ...
        candidateNames(candidateIndex);
    includeFirstTarget = localCandidateHasTarget( ...
        mode, candidateNames(candidateIndex));

    if includeFirstTarget
        candidateMap = maps(candidateIndex).MapLinear;
        candidateMap(targetLocations(1, 1), ...
            targetLocations(1, 2)) = 100.0;
        maps(candidateIndex).MapLinear = candidateMap;
    end

    if mode == "two_targets"
        candidateMap = maps(candidateIndex).MapLinear;
        candidateMap(targetLocations(2, 1), ...
            targetLocations(2, 2)) = 90.0;
        maps(candidateIndex).MapLinear = candidateMap;
    end
end

geometry.TargetLocations = targetLocations;

end

function hasTarget = localCandidateHasTarget(mode, candidateName)

hasTarget = mode == "common" || mode == "two_targets";

if mode == "conservative"
    hasTarget = candidateName == "conservative_lms";
elseif mode == "aggressive"
    hasTarget = candidateName == "aggressive_lms";
elseif mode == "none"
    hasTarget = candidateName == "none";
end

end

function maps = localBuildMonotonicMapTriplet()

[maps, geometry] = localBuildMapTriplet("none", "bg_a");
peakPowers = [5.0; 7.0; 10.0; 20.0];
cutLocations = [40, 8; 110, 12; 180, 18; 250, 24];

for candidateIndex = 1:numel(maps)
    candidateMap = ones(size(maps(candidateIndex).MapLinear), ...
        "single");

    for peakIndex = 1:numel(peakPowers)
        rowIndex = geometry.CutRows(cutLocations(peakIndex, 1));
        columnIndex = geometry.CutColumns( ...
            cutLocations(peakIndex, 2));
        candidateMap(rowIndex, columnIndex) = ...
            peakPowers(peakIndex);
    end

    maps(candidateIndex).MapLinear = candidateMap;
end

end

