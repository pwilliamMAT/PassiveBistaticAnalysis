classdef helperAnalyzeG6ProductDiscriminationTest < ...
        matlab.unittest.TestCase
    %HELPERANALYZEG6PRODUCTDISCRIMINATIONTEST Focused G6-D tests.

    properties (SetAccess = private)
        RepoRoot
    end

    methods (TestClassSetup)
        function addRepositoryToPath(testCase)
            testFile = string(mfilename("fullpath"));
            testCase.RepoRoot = fileparts(fileparts(testFile));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture( ...
                testCase.RepoRoot));
        end
    end

    methods (Test)
        function testCutBoundariesAndCount(testCase)
            [maps, geometry] = localBuildMapTriplet("common", "bg_a");

            result = helperAnalyzeG6ProductDiscrimination( ...
                maps, table(), struct(CampaignId="fixture"));

            testCase.verifyEqual(result.MapTable.CutCount, ...
                12832 .* ones(3, 1), AbsTol=0.0);
            testCase.verifyEqual(result.MapTable.CutDelayMinimum_s, ...
                repmat(geometry.DelayCut(1), 3, 1), ...
                AbsTol=1.0e-15);
            testCase.verifyEqual(result.MapTable.CutDelayMaximum_s, ...
                repmat(geometry.DelayCut(end), 3, 1), ...
                AbsTol=1.0e-15);
            testCase.verifyEqual(result.MapTable.CutDopplerMinimum_Hz, ...
                -750.0 .* ones(3, 1), AbsTol=0.0);
            testCase.verifyEqual(result.MapTable.CutDopplerMaximum_Hz, ...
                750.0 .* ones(3, 1), AbsTol=0.0);
            testCase.verifyTrue(result.Integrity.AxisValid);
        end

        function testThresholdAndDetectionCountMonotonicity(testCase)
            maps = localBuildMonotonicMapTriplet();

            result = helperAnalyzeG6ProductDiscrimination( ...
                maps, table(), struct(CampaignId="fixture"));
            rows = result.OperatingPointTable( ...
                result.OperatingPointTable.CandidateName == "none", :);

            testCase.verifyGreaterThanOrEqual( ...
                diff(rows.ThresholdMedian), zeros(8, 1));
            testCase.verifyLessThanOrEqual( ...
                diff(rows.DetectionCount), zeros(8, 1));
            testCase.verifyTrue(any(diff(rows.DetectionCount) < 0.0));
            testCase.verifyTrue(all( ...
                result.MapTable.ThresholdMonotonic));
            testCase.verifyTrue(all( ...
                result.MapTable.DetectionCountMonotonic));
        end

        function testNmsSuppressionAndPlateauTie(testCase)
            maps = localBuildNmsMapTriplet();

            result = helperAnalyzeG6ProductDiscrimination( ...
                maps, table(), struct(CampaignId="fixture"));
            detections = result.DetectionTable( ...
                result.DetectionTable.CandidateName == "none" & ...
                result.DetectionTable.PfaIndex == 1, ...
                {'RowIndex', 'ColumnIndex'});
            detections = sortrows(detections, ...
                {'RowIndex', 'ColumnIndex'});
            expected = table([65.0; 115.0], [15.0; 20.0], ...
                VariableNames={'RowIndex', 'ColumnIndex'});

            testCase.verifyEqual(detections, expected);
        end

        function testOneToOneMultiTargetAssociation(testCase)
            [maps, geometry] = localBuildMapTriplet( ...
                "two_targets", "bg_a");
            truth = localBuildTruthTable( ...
                maps, geometry, "injected", 2);

            result = helperAnalyzeG6ProductDiscrimination( ...
                maps, truth, struct(CampaignId="fixture"));
            opportunities = result.TruthOpportunityTable( ...
                result.TruthOpportunityTable.CandidateName == "none" & ...
                result.TruthOpportunityTable.PfaIndex == 1, :);

            testCase.verifyEqual(height(opportunities), 2);
            testCase.verifyTrue(all(opportunities.Matched));
            testCase.verifyEqual(numel(unique( ...
                opportunities.DetectionId)), 2);
            testCase.verifyLessThanOrEqual( ...
                opportunities.NormalizedDelayError, ones(2, 1));
            testCase.verifyLessThanOrEqual( ...
                opportunities.NormalizedDopplerError, ones(2, 1));
        end

        function testMatchedControlsAreNuisanceAlarms(testCase)
            [maps, geometry] = localBuildMapTriplet( ...
                "common", "bg_a", "control");
            truth = localBuildTruthTable( ...
                maps, geometry, "matched_control", 1);

            result = helperAnalyzeG6ProductDiscrimination( ...
                maps, truth, struct(CampaignId="fixture"));
            detections = result.DetectionTable( ...
                result.DetectionTable.PfaIndex == 1, :);
            operatingRows = result.OperatingPointTable( ...
                result.OperatingPointTable.PfaIndex == 1, :);

            testCase.verifyEmpty(result.TruthOpportunityTable);
            testCase.verifyEqual(unique( ...
                detections.AssociationRole), ...
                "nuisance_control_alarm");
            testCase.verifyFalse(any( ...
                detections.FalseAlarmClaimed));
            testCase.verifyEqual( ...
                operatingRows.ControlAlarmCount, ones(3, 1));
            testCase.verifyEqual( ...
                operatingRows.TargetHitCount, zeros(3, 1));
        end

