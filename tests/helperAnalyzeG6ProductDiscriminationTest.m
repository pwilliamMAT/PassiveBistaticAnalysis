function maps = localBuildMalformedMapTriplet(mode)

maps = localBuildMapTriplet("common", "bg_a");

if mode == "negative"
    maps(1).MapLinear(1, 1) = -1.0;
else
    maps(1).DelayAxis_s = maps(1).DelayAxis_s(1:end - 1);
end

end

function truth = localBuildTruthTable( ...
    maps, geometry, evidenceRole, targetCount)

rowCount = numel(maps) .* targetCount;
backgroundId = strings(rowCount, 1);
caseId = strings(rowCount, 1);
candidateName = strings(rowCount, 1);
windowLabel = repmat("center", rowCount, 1);
role = repmat(string(evidenceRole), rowCount, 1);
targetId = strings(rowCount, 1);
expectedDelay_s = zeros(rowCount, 1);
expectedDoppler_Hz = zeros(rowCount, 1);
searchDelayHalfExtent_s = repmat( ...
    1.1 .* geometry.DelaySpacing_s, rowCount, 1);
searchDopplerHalfExtent_Hz = repmat( ...
    1.1 .* geometry.DopplerSpacing_Hz, rowCount, 1);
sourceCaseId = strings(rowCount, 1);
callsign = strings(rowCount, 1);
geometryClass = repmat("fixture", rowCount, 1);
rowIndex = 0;

for mapIndex = 1:numel(maps)
    for targetIndex = 1:targetCount
        rowIndex = rowIndex + 1;
        location = geometry.TargetLocations(targetIndex, :);
        backgroundId(rowIndex) = maps(mapIndex).BackgroundId;
        caseId(rowIndex) = maps(mapIndex).CaseId;
        candidateName(rowIndex) = maps(mapIndex).CandidateName;
        targetId(rowIndex) = "target_" + targetIndex;
        expectedDelay_s(rowIndex) = ...
            maps(mapIndex).DelayAxis_s(location(2));
        expectedDoppler_Hz(rowIndex) = ...
            maps(mapIndex).DopplerAxis_Hz(location(1));
        sourceCaseId(rowIndex) = "source_" + targetIndex;
        callsign(rowIndex) = "CALL" + targetIndex;
    end
end

truth = table(backgroundId, caseId, candidateName, ...
    windowLabel, role, targetId, expectedDelay_s, ...
    expectedDoppler_Hz, searchDelayHalfExtent_s, ...
    searchDopplerHalfExtent_Hz, sourceCaseId, callsign, ...
    geometryClass, VariableNames={ ...
    'BackgroundId', 'CaseId', 'CandidateName', 'WindowLabel', ...
    'EvidenceRole', 'TargetId', 'ExpectedDelay_s', ...
    'ExpectedDoppler_Hz', 'SearchDelayHalfExtent_s', ...
    'SearchDopplerHalfExtent_Hz', 'SourceCaseId', 'Callsign', ...
    'GeometryClass'});

end

function [delayAxis_s, dopplerAxis_Hz, geometry] = localBuildAxes()

delayCut = linspace(-1.20e-3, -0.15e-3, 32);
delaySpacing_s = delayCut(2) - delayCut(1);
delayAxis_s = [ ...
    delayCut(1) + (-5:-1) .* delaySpacing_s, ...
    delayCut, ...
    delayCut(end) + (1:5) .* delaySpacing_s];
dopplerCut = linspace(-750.0, 750.0, 401).';
dopplerSpacing_Hz = dopplerCut(2) - dopplerCut(1);
dopplerAxis_Hz = [ ...
    dopplerCut(1) + (-15:-1).' .* dopplerSpacing_Hz; ...
    dopplerCut; ...
    dopplerCut(end) + (1:15).' .* dopplerSpacing_Hz];
geometry = struct();
geometry.DelayCut = delayCut;
geometry.DopplerCut = dopplerCut;
geometry.DelaySpacing_s = delaySpacing_s;
geometry.DopplerSpacing_Hz = dopplerSpacing_Hz;
geometry.CutRows = (16:416).';
geometry.CutColumns = 6:37;
geometry.TargetLocations = localTargetLocations();

end

