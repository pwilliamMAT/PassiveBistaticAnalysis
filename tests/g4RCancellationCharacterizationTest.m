function shard = localCoordinatorShardFixture( ...
        backgroundId, benchmarkPath, manifest)

controlRows = manifest.ControlTable( ...
    manifest.ControlTable.BackgroundId == backgroundId, :);
methods = ["none"; "current_reset_nlms"; "frozen_native_nlms"];
rowCount = height(controlRows) .* numel(methods);
mapBackgroundId = strings(rowCount, 1);
mapTimePairId = strings(rowCount, 1);
mapMethod = strings(rowCount, 1);
mapCriteriaPass = true(rowCount, 1);
mapDirectPathRatio = zeros(rowCount, 1);
rowIndex = 0;

for controlIndex = 1:height(controlRows)
    for methodIndex = 1:numel(methods)
        rowIndex = rowIndex + 1;
        mapBackgroundId(rowIndex) = backgroundId;
        mapTimePairId(rowIndex) = controlRows.TimePairId(controlIndex);
        mapMethod(rowIndex) = methods(methodIndex);

        switch methods(methodIndex)
            case "none"
                mapDirectPathRatio(rowIndex) = 10.0;
            case "current_reset_nlms"
                mapDirectPathRatio(rowIndex) = 8.0;
            otherwise
                mapDirectPathRatio(rowIndex) = 6.0;
        end
    end
end

mapRateMetricTable = table( ...
    mapBackgroundId, mapTimePairId, mapMethod, mapCriteriaPass, ...
    mapDirectPathRatio, ...
    VariableNames=["BackgroundId", "TimePairId", "Method", ...
    "AllPairCriteriaPass", "ReducedDirectPathToOffRidge_dB"]);
heldOutMetricTable = localCoordinatorHeldOutFixture(mapRateMetricTable);

if backgroundId == manifest.TargetGuardBackgroundId
    targetGuardTable = table( ...
        methods, true(numel(methods), 1), [10.0; 9.0; 9.5], ...
        VariableNames=["Method", "TruthPeakWithinOneCell", ...
        "InjectedVsControlTruthContrast_dB"]);
else
    targetGuardTable = table( ...
        strings(0, 1), false(0, 1), zeros(0, 1), ...
        VariableNames=["Method", "TruthPeakWithinOneCell", ...
        "InjectedVsControlTruthContrast_dB"]);
end

shard = struct();
shard.SchemaVersion = "g4r_cancellation_characterization_v1";
shard.ExecutionMode = "background_shard";
shard.ResultPath = "";
shard.Configuration = struct("BenchmarkResultPath", string(benchmarkPath));
shard.WienerSelection = struct( ...
    "Nominated", false, "SelectedTapCount", NaN);
shard.MapRateMetricTable = mapRateMetricTable;
shard.HeldOutMetricTable = heldOutMetricTable;
shard.TargetGuardTable = targetGuardTable;
shard.WienerCoefficientRecords = struct([]);
shard.HardwareEvidenceTable = table( ...
    backgroundId, "antenna", "name", "recorded", "recorded", ...
    VariableNames=["BackgroundId", "EvidenceCategory", "MetadataField", ...
    "RecordedValue", "EvidenceStatus"]);
