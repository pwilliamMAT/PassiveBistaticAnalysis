classdef g4RCancellationCharacterizationTest < matlab.unittest.TestCase
    %G4RCANCELLATIONCHARACTERIZATIONTEST Focused G4-R cancellation tests.

    properties (SetAccess = private)
        RepoRoot
    end

    methods (TestClassSetup)
        function addRepositoryToPath(testCase)
            testFile = string(mfilename("fullpath"));
            testCase.RepoRoot = fileparts(fileparts(testFile));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(testCase.RepoRoot));
        end
    end

    methods (TestMethodSetup)
        function preserveRandomState(testCase)
            originalRandomState = rng;
            testCase.addTeardown(@() rng(originalRandomState));
        end
    end

    methods (Test)
        function testRegularizedWienerRecoversKnownFir(testCase)
            rng(501, "twister");
            reference = complex(randn(8192, 1), randn(8192, 1));
            knownCoefficients = [0.8 + 0.1j; -0.25 + 0.15j; 0.1 - 0.05j];
            desired = filter(knownCoefficients, 1, reference);

            estimate = helperEstimateG4RWienerFir( ...
                reference, desired, numel(knownCoefficients), ...
                struct("RegularizationFraction", 1.0e-6));

            recoveryError = norm(estimate.Coefficients - knownCoefficients) ./ ...
                norm(knownCoefficients);
            testCase.verifyLessThan(recoveryError, 0.02);
            testCase.verifyEqual(estimate.CorrelationEstimator, ...
                "xcorr_biased");
        end

        function testFrozenNativeNlmsExplicitlyDisablesScoreAdaptation(testCase)
            rng(502, "twister");
            calibrationReference = complex(randn(4096, 1), randn(4096, 1));
            scoreReference = complex(randn(4096, 1), randn(4096, 1));
            calibrationSurveillance = filter([0.7; -0.2], 1, ...
                calibrationReference);
            scoreSurveillance = filter([0.7; -0.2], 1, scoreReference);

            result = helperApplyG4RNativeFirstCancellation( ...
                calibrationReference, calibrationSurveillance, ...
                scoreReference, scoreSurveillance, "frozen_nlms");

            testCase.verifyFalse(result.ScoreAdaptationEnabled);
            testCase.verifyTrue(all(isfinite(result.ResidualSignal)));
            testCase.verifyGreaterThan(result.MaxStepSize, 0.0);
        end

        function testNativeFirstResidualUsesProductionResamplePath(testCase)
            rng(503, "twister");
            reference = complex(randn(8001, 1), randn(8001, 1));
            surveillance = filter([0.6; -0.15], 1, reference);
            estimate = helperEstimateG4RWienerFir( ...
                reference(1:4096), surveillance(1:4096), 2.0);

            cancellation = helperApplyG4RNativeFirstCancellation( ...
                reference(1:4096), surveillance(1:4096), ...
                reference, surveillance, "wiener_fir", ...
                struct("WienerCoefficients", estimate.Coefficients));
            [reducedResidual, coefficients] = helperResampleG4FullRepetition( ...
                cancellation.ResidualSignal, 4.0);
            reconstruction = helperReconstructG4Resample( ...
                cancellation.ResidualSignal, 4.0, coefficients);

            testCase.verifyEqual(numel(reducedResidual), ...
                reconstruction.ActualOutputSampleCount, AbsTol=0.0);
            testCase.verifyTrue(all(isfinite( ...
                reconstruction.FilteredNativeOutput)));
        end

        function testDryRunPreservesFixedTargetFreeManifest(testCase)
            result = runG4RCancellationCharacterization( ...
                testCase.RepoRoot, struct( ...
                "ExecutionMode", "dry_run", "SaveResult", false));

            manifest = result.Manifest.ControlTable;
            testCase.verifyEqual(height(manifest), 9.0, AbsTol=0.0);
            testCase.verifyTrue(all( ...
                manifest.CalibrationRepetition ~= manifest.ScoreRepetition));
            testCase.verifyTrue(all(manifest.CalibrationTargetFree));
            testCase.verifyEqual(result.Configuration.MapContract, ...
                "r4_factor200_production_full_map_common_physical_grid");
            testCase.verifyFalse(result.FormalG5Enabled);
            testCase.verifyFalse(result.FormalG6Enabled);
            testCase.verifyFalse(result.FormalG8Enabled);
        end

        function testSelectedScoreManifestRetainsPartAndEpoch(testCase)
            outputRoot = string(tempname);
            mkdir(outputRoot);
            testCase.addTeardown(@() rmdir(outputRoot, "s"));
            [baseManifestPath, scoreScan] = localSelectedScoreManifestFixture( ...
                outputRoot);
            selectedManifestRoot = fullfile(outputRoot, "selected_score");

            selection = helperBuildG4RSelectedScoreManifest( ...
                baseManifestPath, scoreScan, selectedManifestRoot);
            selectedManifest = jsondecode(fileread(selection.ManifestPath));

            testCase.verifyTrue(selection.SinglePartContract);
            testCase.verifyEqual( ...
                string(fileparts(selection.ManifestPath)), ...
                string(selectedManifestRoot));
            [~, manifestName, manifestExtension] = fileparts( ...
                selection.ManifestPath);
            testCase.verifyEqual(string(manifestName) + ...
                string(manifestExtension), "session_manifest.json");
            testCase.verifyEqual(numel(selectedManifest.radar_files), 1.0, ...
                AbsTol=0.0);
            testCase.verifyEqual(string(selectedManifest.radar_files{1}), ...
                string(scoreScan.FilePath));
            testCase.verifyEqual(selectedManifest.radar_epoch_utc, ...
                scoreScan.RecordingUTC, AbsTol=1.0e-12);
            testCase.verifyEqual(selectedManifest.capture_duration_s, ...
                scoreScan.Duration_s, AbsTol=1.0e-12);
            testCase.verifyEqual( ...
                selectedManifest.g4r_selected_score_capture.source_score_repetition, ...
                scoreScan.Repetition, AbsTol=0.0);

            producerRoot = fullfile(fileparts(testCase.RepoRoot), ...
                "flightTest_SynthDataBranch", "SyntheticHDTVSimulation");
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(producerRoot));
            context = helperSyntheticResolveSessionContext( ...
                selection.ManifestPath, RepoRoot=fileparts(testCase.RepoRoot));
            testCase.verifyEqual(string(context.radar_files{1}), ...
                string(scoreScan.FilePath));
            testCase.verifyEqual(context.radar_epoch_utc, ...
                scoreScan.RecordingUTC, AbsTol=1.0e-12);
        end

        function testDecisionRulesRequireMapSuppressionAndTargetGuard(testCase)
            [mapRateTable, targetGuardTable] = localDecisionFixture();
            selection = struct("Nominated", false);
            decision = helperEvaluateG4RCancellationDecision( ...
                mapRateTable, targetGuardTable, selection);

            frozenRow = decision.MethodDecisionTable( ...
                decision.MethodDecisionTable.Method == "frozen_native_nlms", :);
            resetRow = decision.MethodDecisionTable( ...
                decision.MethodDecisionTable.Method == "current_reset_nlms", :);
            testCase.verifyTrue( ...
                frozenRow.RecommendReviewedUpstreamCorrection);
            testCase.verifyFalse( ...
                resetRow.RecommendReviewedUpstreamCorrection);
            testCase.verifyEqual(decision.Outcome, ...
                "candidate_requires_reviewed_upstream_correction");

            mapRateTable.ReducedDirectPathToOffRidge_dB( ...
                mapRateTable.Method == "frozen_native_nlms") = 8.0;
            decision = helperEvaluateG4RCancellationDecision( ...
                mapRateTable, targetGuardTable, selection);
            testCase.verifyEqual(decision.Outcome, ...
                "rate_order_semantics_supported_no_promoted_candidate");
        end

        function testCoordinatorRequiresExactIsolatedShardManifest(testCase)
            outputRoot = string(tempname);
            mkdir(outputRoot);
            testCase.addTeardown(@() rmdir(outputRoot, "s"));
            benchmarkPath = fullfile(outputRoot, "benchmark.mat");
            benchmark = localCoordinatorBenchmarkFixture(benchmarkPath);
            result = benchmark;
            save(benchmarkPath, "result");

            backgroundIds = unique( ...
                string(benchmark.Manifest.ControlTable.BackgroundId), ...
                "stable");
            shardPaths = strings(numel(backgroundIds), 1);

            for backgroundIndex = 1:numel(backgroundIds)
                shardPaths(backgroundIndex) = fullfile(outputRoot, ...
                    "shard_" + backgroundIds(backgroundIndex) + ".mat");
                shard = localCoordinatorShardFixture( ...
                    backgroundIds(backgroundIndex), benchmarkPath, ...
                    benchmark.Manifest);
                result = shard;
                save(shardPaths(backgroundIndex), "result");
            end

            combined = runG4RCancellationCharacterizationCoordinator( ...
                testCase.RepoRoot, struct( ...
                "BenchmarkResultPath", benchmarkPath, ...
                "ShardResultPaths", shardPaths, ...
                "OutputRoot", outputRoot, "SaveResult", true));

            testCase.verifyEqual(height(combined.ShardAuditTable), 3.0, ...
                AbsTol=0.0);
            testCase.verifyEqual(height(combined.MapRateMetricTable), 27.0, ...
                AbsTol=0.0);
            testCase.verifyTrue(isfile(fullfile( ...
                combined.BundleRoot, "report_manifest.json")));
            testCase.verifyTrue(combined.HtmlReport.ExternalDependencyFree);
        end

        function testHtmlReportUsesLocalAssetsOnly(testCase)
            outputRoot = string(tempname);
            mkdir(outputRoot);
            testCase.addTeardown(@() rmdir(outputRoot, "s"));
            reportInput = localBuildReportFixture();

            report = helperBuildG4RCancellationHtmlReport( ...
                reportInput, outputRoot);

            testCase.verifyTrue(isfile(report.HtmlPath));
            testCase.verifyTrue(isfolder(report.AssetRoot));
            testCase.verifyEqual(height(report.FigureTable), 3.0, ...
                AbsTol=0.0);
            testCase.verifyTrue(all(isfile(fullfile( ...
                outputRoot, report.FigureTable.RelativePath))));
            testCase.verifyTrue(report.ExternalDependencyFree);
            testCase.verifyTrue(contains( ...
                string(fileread(report.HtmlPath)), "report_assets/"));
            testCase.verifyTrue(contains( ...
                string(fileread(report.HtmlPath)), "href=""summary.html"""));
        end
    end
end

