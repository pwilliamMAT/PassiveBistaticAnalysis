function selectedRows = localSelectG4Rows(mapSummaryTable, resolvedOptions)

rowMask = ismember(string(mapSummaryTable.CpiLabel), ...
    resolvedOptions.ReviewCpiLabels) & ...
    ismember(string(mapSummaryTable.WindowLabel), ...
    resolvedOptions.ReviewWindowLabels) & ...
    ismember(double(mapSummaryTable.Repetition), ...
    resolvedOptions.ReviewRepetitions);
selectedRows = sortrows(mapSummaryTable(rowMask, :), ...
    ["Repetition", "CpiLabel", "WindowStartSample"]);

if isempty(selectedRows)
    error("helperAnalyzeG5Mitigation:NoSelectedG4Rows", ...
        "No G4 rows matched the requested G5 review slice.");
end

if isfinite(resolvedOptions.MaxReviewRows)
    keepCount = min(height(selectedRows), ...
        round(resolvedOptions.MaxReviewRows));
    selectedRows = selectedRows(1:keepCount, :);
end

end

function preprocessedSignals = localBuildPreprocessedSignals(sessionData, ...
    selectedRows, roleInfo, appliedCorrection, resolvedOptions)

neededRepetitions = unique(double(selectedRows.Repetition));
preprocessedSignals = repmat(struct( ...
    "Repetition", NaN, ...
    "RelativePath", "", ...
    "ReferenceMapSamples", single([]), ...
    "SurveillanceMapSamples", single([]) ...
    ), max(neededRepetitions), 1);

for idx = 1:numel(neededRepetitions)
    repetitionValue = neededRepetitions(idx);
    scan = localResolveScanWithSamples(sessionData, repetitionValue);
    referenceSamples = double(scan.Samples(:, ...
        roleInfo.ReferenceColumnIndex));
    surveillanceSamples = double(scan.Samples(:, ...
        roleInfo.SurveillanceColumnIndex));
    correctedSurveillance = localApplyIntegerDelay(surveillanceSamples, ...
        appliedCorrection.AppliedLag_samples);
    correctedSurveillance = localApplyResidualFrequencyCorrection( ...
        correctedSurveillance, ...
        appliedCorrection.AppliedResidualFrequency_Hz, ...
        resolvedOptions.SampleRateHz);
    preprocessedSignals(repetitionValue).Repetition = repetitionValue;
    preprocessedSignals(repetitionValue).RelativePath = ...
        string(scan.RelativePath);
    preprocessedSignals(repetitionValue).ReferenceMapSamples = ...
        single(resample(referenceSamples, 1, ...
        resolvedOptions.MapDecimationFactor));
    preprocessedSignals(repetitionValue).SurveillanceMapSamples = ...
        single(resample(correctedSurveillance, 1, ...
        resolvedOptions.MapDecimationFactor));
end

end

function [metricTable, protectedDetailTable, residualErrorPowerTable, ...
    representativeMaps] = localEvaluateCandidates(selectedRows, ...
    preprocessedSignals, candidateProfiles, appliedCorrection, ...
    productDefinition, resolvedOptions)

rowCount = height(selectedRows);
candidateCount = numel(candidateProfiles);
metricRows = repmat(localMetricRowTemplate(), rowCount * candidateCount, 1);
protectedRows = repmat(localProtectedRowTemplate(), ...
    rowCount * candidateCount, 1);
residualRows = repmat(localResidualRowTemplate(), ...
    rowCount * candidateCount, 1);
representativeMaps = repmat(localRepresentativeMapTemplate(), ...
    candidateCount, 1);
metricIndex = 0;
protectedIndex = 0;
residualIndex = 0;

for rowIndex = 1:rowCount
    selectedRow = selectedRows(rowIndex, :);
    repetitionValue = double(selectedRow.Repetition(1));
    signal = preprocessedSignals(repetitionValue);
    mapWindowStart = localConvertStartSampleToMapDomain( ...
        selectedRow.WindowStartSample(1), ...
        resolvedOptions.MapDecimationFactor);
    mapWindowStop = mapWindowStart + double(selectedRow.CpiSamples(1)) - 1;

    if mapWindowStop > numel(signal.ReferenceMapSamples)
        error("helperAnalyzeG5Mitigation:InvalidMapWindow", ...
            "Map-domain window [%d %d] does not fit repetition %d.", ...
            mapWindowStart, mapWindowStop, repetitionValue);
    end

    referenceWindow = signal.ReferenceMapSamples(mapWindowStart: ...
        mapWindowStop);
    surveillanceWindow = signal.SurveillanceMapSamples(mapWindowStart: ...
        mapWindowStop);
    cpiDefinition = localBuildCpiDefinition(selectedRow);
    candidateProducts = cell(candidateCount, 1);

    for candidateIndex = 1:candidateCount
        profile = candidateProfiles(candidateIndex);
        [candidateSurveillance, residualInfo] = localApplyCandidate( ...
            referenceWindow, surveillanceWindow, profile);
        mapProduct = localBuildMapProduct(referenceWindow, ...
            candidateSurveillance, cpiDefinition, productDefinition, ...
            resolvedOptions);
        [interpretationLabel, rationale] = localClassifyMapProduct( ...
            mapProduct, resolvedOptions);
        candidateProducts{candidateIndex} = mapProduct;
        metricIndex = metricIndex + 1;
        metricRows(metricIndex) = localBuildMetricRow(rowIndex, ...
            selectedRow, profile, mapProduct, appliedCorrection, ...
            interpretationLabel, rationale);
        residualIndex = residualIndex + 1;
        residualRows(residualIndex) = localBuildResidualRow(rowIndex, ...
            selectedRow, profile, residualInfo);

        if rowIndex == 1
            representativeMaps(candidateIndex) = ...
                localBuildRepresentativeMap(profile, selectedRow, ...
                mapProduct);
        end
    end

    protectedRegion = localBuildProtectedRegion(candidateProducts{1}, ...
        productDefinition, resolvedOptions);

    for candidateIndex = 1:candidateCount
        protectedIndex = protectedIndex + 1;
        protectedRows(protectedIndex) = localBuildProtectedRow( ...
            rowIndex, selectedRow, candidateProfiles(candidateIndex), ...
            protectedRegion, candidateProducts{candidateIndex}, ...
            resolvedOptions);
    end
end

metricTable = struct2table(metricRows(1:metricIndex));
protectedDetailTable = struct2table(protectedRows(1:protectedIndex));
residualErrorPowerTable = struct2table(residualRows(1:residualIndex));

end

