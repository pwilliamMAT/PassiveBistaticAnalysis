function [candidateSurveillance, residualInfo] = localApplyCandidate( ...
    referenceWindow, surveillanceWindow, profile)

referenceWindow = referenceWindow(:);
surveillanceWindow = surveillanceWindow(:);
residualInfo = struct();
residualInfo.InputReferencePower = mean(abs(referenceWindow) .^ 2, ...
    "omitnan");
residualInfo.InputSurveillancePower = mean(abs(surveillanceWindow) .^ 2, ...
    "omitnan");

if string(profile.CandidateName) == "none"
    modeledLeakage = zeros(size(surveillanceWindow), "like", ...
        surveillanceWindow);
    residualError = surveillanceWindow;
    weights = zeros(0, 1);
else
    lmsFilter = dsp.LMSFilter( ...
        "Method", char(profile.LmsMethod), ...
        "Length", round(double(profile.FilterLength)), ...
        "StepSize", double(profile.StepSize), ...
        "LeakageFactor", double(profile.LeakageFactor));
    [modeledLeakage, residualError, weights] = lmsFilter( ...
        referenceWindow, surveillanceWindow);
end

candidateSurveillance = single(residualError(:));
residualInfo.ModeledLeakagePower = mean(abs(modeledLeakage) .^ 2, ...
    "omitnan");
residualInfo.ResidualErrorPower = mean(abs(residualError) .^ 2, ...
    "omitnan");
residualInfo.FinalWeightsNorm = norm(double(weights(:)));
residualInfo.LmsConvergedFinite = all(isfinite(residualError), "all") && ...
    all(isfinite(weights), "all");

end

