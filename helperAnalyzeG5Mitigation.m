function analysis = helperAnalyzeG5Mitigation(sessionData, ...
    collectionMetadataInfo, g3SyncResults, g4Analysis, options)
%HELPERANALYZEG5MITIGATION Analyze the first G5 mitigation slice.
%
%   ANALYSIS = HELPERANALYZEG5MITIGATION(SESSIONDATA, ...
%   COLLECTIONMETADATAINFO, G3SYNCRESULTS, G4ANALYSIS, OPTIONS) compares
%   none, conservative_lms, and aggressive_lms mitigation candidates on a
%   bounded set of G4 map rows. LMS candidates use dsp.LMSFilter, and all
%   candidate maps are recomputed with ambgfun.

arguments
    sessionData (1,1) struct
    collectionMetadataInfo (1,1) struct
    g3SyncResults (1,1) struct
    g4Analysis (1,1) struct
    options (1,1) struct = struct()
end

localValidateNativeFunctions();
localValidateG4Analysis(g4Analysis);

resolvedOptions = localResolveOptions(sessionData, g4Analysis, options);
candidateProfiles = localBuildCandidateProfiles(resolvedOptions);
candidateTable = localBuildCandidateTable(candidateProfiles, ...
    resolvedOptions);
roleInfo = localResolveRoleInfo(sessionData, collectionMetadataInfo, ...
    g4Analysis);
appliedCorrection = localResolveAppliedCorrection(g4Analysis);
productDefinition = localResolveProductDefinition(g4Analysis, ...
    resolvedOptions);
selectedRows = localSelectG4Rows(g4Analysis.MapSummaryTable, ...
    resolvedOptions);
preprocessedSignals = localBuildPreprocessedSignals(sessionData, ...
    selectedRows, roleInfo, appliedCorrection, resolvedOptions);

[metricTable, protectedDetailTable, residualErrorPowerTable, ...
    representativeMaps] = localEvaluateCandidates(selectedRows, ...
    preprocessedSignals, candidateProfiles, appliedCorrection, ...
    productDefinition, resolvedOptions);
suppressionSummaryTable = localBuildSuppressionSummary(metricTable, ...
    candidateProfiles);
protectedRetentionTable = localBuildProtectedRetentionSummary( ...
    protectedDetailTable, candidateProfiles, resolvedOptions);
detectabilityProxyTable = localBuildDetectabilityProxyTable( ...
    metricTable, protectedRetentionTable, candidateProfiles, ...
    resolvedOptions);
upstreamCaveatTable = localBuildUpstreamCaveatTable(g3SyncResults, ...
    g4Analysis);
causalAssessmentTable = localBuildCausalAssessmentTable( ...
    suppressionSummaryTable, protectedRetentionTable, ...
    detectabilityProxyTable, upstreamCaveatTable, candidateProfiles, ...
    resolvedOptions);
acquisitionImplicationTable = localBuildAcquisitionImplicationTable( ...
    causalAssessmentTable, g4Analysis);
decisionComparisonTable = localBuildDecisionComparisonTable( ...
    suppressionSummaryTable, protectedRetentionTable, ...
    detectabilityProxyTable, causalAssessmentTable, candidateProfiles, ...
    g4Analysis);
decision = localBuildDecision(decisionComparisonTable, ...
    causalAssessmentTable, g4Analysis, resolvedOptions);
requirementsCoverageTable = localBuildRequirementsCoverageTable( ...
    decision, selectedRows);

analysis = struct();
analysis.DatasetId = string(sessionData.DatasetId);
analysis.StageId = "G5_Mitigation";
analysis.AnalysisStageId = "G5_Mitigation_First_Slice";
analysis.AnalysisScope = string(resolvedOptions.AnalysisScope);
analysis.Options = resolvedOptions;
analysis.RoleInfo = roleInfo;
analysis.AppliedCorrection = appliedCorrection;
analysis.BaselineProductDefinition = productDefinition;
analysis.SelectedG4MapRows = selectedRows;
analysis.G4OverallLabel = localResolveG4Label(g4Analysis, "OverallLabel");
analysis.G4SceneObservabilityLabel = localResolveG4Label(g4Analysis, ...
    "SceneObservabilityLabel");
analysis.G4FullRateAuditAgreementLabel = localResolveG4Label(g4Analysis, ...
    "FullRateAuditAgreementLabel");
analysis.GateDecision = decision.GateDecision;
analysis.ReviewStatus = decision.ReviewStatus;
analysis.DecisionLabel = decision.DecisionLabel;
analysis.DecisionRationale = decision.Rationale;
analysis.NextBranch = decision.NextBranch;
analysis.FormalGateDecisionEmitted = decision.FormalGateDecisionEmitted;
analysis.MitigationCandidateTable = candidateTable;
analysis.MitigationMetricTable = metricTable;
analysis.SuppressionSummaryTable = suppressionSummaryTable;
analysis.ProtectedRegionRetentionTable = protectedRetentionTable;
analysis.ProtectedRegionRetentionDetailTable = protectedDetailTable;
analysis.ResidualErrorPowerTable = residualErrorPowerTable;
analysis.DetectabilityProxyTable = detectabilityProxyTable;
analysis.MitigationCausalAssessmentTable = causalAssessmentTable;
analysis.AcquisitionImplicationTable = acquisitionImplicationTable;
analysis.DecisionComparisonTable = decisionComparisonTable;
analysis.UpstreamCaveatsCarriedForward = upstreamCaveatTable;
analysis.RequirementsCoverageTable = requirementsCoverageTable;
analysis.RepresentativeMaps = representativeMaps;

end

function localValidateNativeFunctions()

if exist("ambgfun", "file") ~= 2
    error("helperAnalyzeG5Mitigation:MissingAmbgfun", ...
        "G5 map recomputation requires ambgfun.");
end

if exist("dsp.LMSFilter", "class") ~= 8
    error("helperAnalyzeG5Mitigation:MissingLMSFilter", ...
        "G5 LMS candidates require dsp.LMSFilter.");
end

end

function localValidateG4Analysis(g4Analysis)

requiredFields = ["Interpretation"; "MapSummaryTable"; ...
    "BaselineProductDefinition"];

for idx = 1:numel(requiredFields)
    if ~isfield(g4Analysis, requiredFields(idx))
        error("helperAnalyzeG5Mitigation:MissingG4Field", ...
            "G5 requires g4Analysis.%s.", requiredFields(idx));
    end
end

if ~istable(g4Analysis.MapSummaryTable) || isempty(g4Analysis.MapSummaryTable)
    error("helperAnalyzeG5Mitigation:InvalidG4MapSummary", ...
        "G5 requires a nonempty G4 MapSummaryTable.");
end

requiredVariables = ["Repetition"; "RelativePath"; "CpiLabel"; ...
    "WindowLabel"; "WindowStartSample"; "WindowIndex"; ...
    "CpiDuration_s"; "CpiSamples"];
variableNames = string(g4Analysis.MapSummaryTable.Properties.VariableNames);

for idx = 1:numel(requiredVariables)
    if ~any(variableNames == requiredVariables(idx))
        error("helperAnalyzeG5Mitigation:MissingG4MapVariable", ...
            "G4 MapSummaryTable is missing %s.", requiredVariables(idx));
    end
end

end

