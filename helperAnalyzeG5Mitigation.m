function defaultRepetitions = localDefaultReviewRepetitions(mapSummaryTable, ...
    g4Options)

if isfield(g4Options, "FullRateAuditRepetitions")
    defaultRepetitions = double(g4Options.FullRateAuditRepetitions(:));
    return
end

availableRepetitions = unique(double(mapSummaryTable.Repetition));

if numel(availableRepetitions) <= 3
    defaultRepetitions = availableRepetitions(:);
    return
end

middleIndex = ceil(numel(availableRepetitions) ./ 2.0);
defaultRepetitions = [availableRepetitions(1); ...
    availableRepetitions(middleIndex); availableRepetitions(end)];

end

function localValidateCandidateNames(candidateNames)

requiredNames = ["none"; "conservative_lms"; "aggressive_lms"];

if ~isequal(sort(candidateNames), sort(requiredNames))
    error("helperAnalyzeG5Mitigation:InvalidCandidateSet", ...
        "G5 requires exactly none, conservative_lms, and aggressive_lms.");
end

end

function candidateProfiles = localBuildCandidateProfiles(resolvedOptions)

candidateNames = resolvedOptions.CandidateNames;
candidateProfiles = repmat(localBuildCandidateProfileTemplate(), ...
    numel(candidateNames), 1);

for idx = 1:numel(candidateNames)
    candidateName = candidateNames(idx);
    profile = localBuildCandidateProfileTemplate();
    profile.CandidateName = candidateName;
    profile.ReferenceInput = "corrected_reference_map_window";
    profile.DesiredInput = "corrected_surveillance_map_window";
    profile.AdaptationSpan = "current_cpi_window_only";
    profile.LeakageFactor = 1.0;

    if candidateName == "none"
        profile.Intent = "baseline_no_mitigation";
        profile.MitigationMethod = "none";
        profile.ToolboxFunction = "none";
        profile.UsesDspLMSFilter = false;
        profile.ReferenceInput = "not_used";
        profile.AdaptationSpan = "none";
        profile.EligibilityLabel = "baseline_required";
        profile.Rationale = "Required no-mitigation baseline.";
    elseif candidateName == "conservative_lms"
        profile.Intent = "lower_risk_adaptive_leakage_cancellation";
        profile.MitigationMethod = "lms_residual_error";
        profile.ToolboxFunction = "dsp.LMSFilter";
        profile.UsesDspLMSFilter = true;
        profile.LmsMethod = string(resolvedOptions.LmsMethod);
        profile.FilterLength = double(resolvedOptions.ConservativeLmsLength);
        profile.StepSize = double(resolvedOptions.ConservativeLmsStepSize);
        profile.LeakageFactor = ...
            double(resolvedOptions.ConservativeLmsLeakageFactor);
        profile.EligibilityLabel = "candidate_required";
        profile.Rationale = "Lower step size and shorter filter length.";
    else
        profile.Intent = "higher_suppression_adaptive_cancellation";
        profile.MitigationMethod = "lms_residual_error";
        profile.ToolboxFunction = "dsp.LMSFilter";
        profile.UsesDspLMSFilter = true;
        profile.LmsMethod = string(resolvedOptions.LmsMethod);
        profile.FilterLength = double(resolvedOptions.AggressiveLmsLength);
        profile.StepSize = double(resolvedOptions.AggressiveLmsStepSize);
        profile.LeakageFactor = ...
            double(resolvedOptions.AggressiveLmsLeakageFactor);
        profile.EligibilityLabel = "candidate_required";
        profile.Rationale = "Higher step size and longer filter length.";
    end

    candidateProfiles(idx) = profile;
end

end

