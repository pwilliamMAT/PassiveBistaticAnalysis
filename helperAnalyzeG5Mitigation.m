function summaryTable = localBuildProtectedRetentionSummary( ...
    protectedDetailTable, candidateProfiles, resolvedOptions)

rows = repmat(localProtectedSummaryRowTemplate(), ...
    numel(candidateProfiles), 1);

for idx = 1:numel(candidateProfiles)
    candidateName = string(candidateProfiles(idx).CandidateName);
    candidateRows = protectedDetailTable( ...
        protectedDetailTable.CandidateName == candidateName, :);
    retentionRatio = candidateRows.ProtectedRetentionRatio;
    belowBudgetCount = sum(retentionRatio < ...
        resolvedOptions.ProtectedRegionMinRetentionRatio);

    if candidateName == "none"
        retentionLabel = "baseline_reference";
    elseif belowBudgetCount == 0
