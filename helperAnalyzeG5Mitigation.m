function delayedSignal = localApplyIntegerDelay(inputSignal, sampleDelay)

sampleDelay = double(sampleDelay);
signalLength = numel(inputSignal);

if sampleDelay == 0 || signalLength == 0
    delayedSignal = inputSignal;
    return
end

if sampleDelay > 0
    if sampleDelay >= signalLength
        delayedSignal = zeros(size(inputSignal), "like", inputSignal);
        return
    end

    delayedSignal = [zeros(sampleDelay, 1, "like", inputSignal); ...
        inputSignal(1:end - sampleDelay)];
    return
end

advanceCount = abs(sampleDelay);

if advanceCount >= signalLength
    delayedSignal = zeros(size(inputSignal), "like", inputSignal);
    return
end

delayedSignal = [inputSignal(advanceCount + 1:end); ...
    zeros(advanceCount, 1, "like", inputSignal)];

end

function correctedSignal = localApplyResidualFrequencyCorrection( ...
    inputSignal, residualFrequencyHz, sampleRateHz)

sampleCount = numel(inputSignal);
sampleIndex = (0:sampleCount - 1).';
correctionPhase = exp(-1j * 2.0 * pi * residualFrequencyHz .* ...
    sampleIndex ./ sampleRateHz);
correctedSignal = inputSignal(:) .* correctionPhase;

end

