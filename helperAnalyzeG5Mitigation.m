function mapProduct = localBuildMapProduct(referenceWindow, ...
    surveillanceWindow, cpiDefinition, productDefinition, resolvedOptions)

[mapMagnitude, delayAxis_s, dopplerAxis_Hz] = ambgfun( ...
    referenceWindow, surveillanceWindow, resolvedOptions.MapSampleRateHz, ...
    cpiDefinition.PRFVector_Hz);
mapLinear = max(single(mapMagnitude) .^ 2, eps("single"));
delayAxis_s = double(delayAxis_s(:).');
dopplerAxis_Hz = double(dopplerAxis_Hz(:));
delayAxis_samples = delayAxis_s .* resolvedOptions.MapSampleRateHz;
[globalPeakPower, globalPeakIndex] = max(mapLinear, [], "all");
[globalPeakRow, globalPeakCol] = ind2sub(size(mapLinear), ...
    globalPeakIndex);
globalPeakDelay_samples = delayAxis_samples(globalPeakCol);
globalPeakDoppler_Hz = dopplerAxis_Hz(globalPeakRow);
originMask = localBuildOriginMask(delayAxis_samples, dopplerAxis_Hz, ...
    productDefinition);
originCandidateIndices = find(originMask);

if isempty(originCandidateIndices)
    error("helperAnalyzeG5Mitigation:EmptyOriginSearchMask", ...
        "The G5 origin-search mask is empty for CPI %s.", ...
        cpiDefinition.Label);
end

[directPathPower, originPeakIndex] = max(mapLinear(originMask));
directPathIndex = originCandidateIndices(originPeakIndex);
[directPathRow, directPathCol] = ind2sub(size(mapLinear), ...
    directPathIndex);
directPathDelay_samples = delayAxis_samples(directPathCol);
directPathDoppler_Hz = dopplerAxis_Hz(directPathRow);
localAnnulusValues = localBuildLocalAnnulus(mapLinear, directPathRow, ...
    directPathCol, resolvedOptions.LocalProminenceOuterRadius_bins);
clutterValues = localBuildClutterValues(mapLinear, delayAxis_samples, ...
    dopplerAxis_Hz, directPathDelay_samples, ...
    productDefinition.ExclusionDelayRadius_samples);
backgroundValues = localBuildBackgroundValues(mapLinear, ...
    delayAxis_samples, dopplerAxis_Hz, productDefinition);
directPathExclusionMask = localBuildDirectPathExclusionMask( ...
    delayAxis_samples, dopplerAxis_Hz, directPathDelay_samples, ...
    directPathDoppler_Hz, productDefinition);
offOriginMask = ~directPathExclusionMask;
zeroDopplerRidgeMask = repmat(abs(dopplerAxis_Hz) <= ...
    productDefinition.ZeroDopplerRidgeExclusion_Hz, ...
    1, numel(delayAxis_samples));
offOriginNonzeroDopplerMask = offOriginMask & ~zeroDopplerRidgeMask;
totalMapPower = max(sum(mapLinear, "all"), eps("single"));
offOriginValues = double(mapLinear(offOriginNonzeroDopplerMask));
offOriginEnergyFraction = double(sum(mapLinear( ...
    offOriginNonzeroDopplerMask), "all") ./ totalMapPower);
zeroDopplerEnergyFraction = double(sum(mapLinear( ...
    zeroDopplerRidgeMask), "all") ./ totalMapPower);
occupiedThreshold = max(single(directPathPower) .* single(10.0 .^ ...
    (resolvedOptions.ProtectedRegionThresholdRelativeToDirectPath_dB ./ ...
    10.0)), eps("single"));

if nnz(offOriginNonzeroDopplerMask) == 0
    occupiedFraction = 0.0;
else
    occupiedFraction = double(nnz(mapLinear( ...
        offOriginNonzeroDopplerMask) >= occupiedThreshold) ./ ...
        nnz(offOriginNonzeroDopplerMask));
end

if isempty(offOriginValues)
    offOriginValues = eps;
end

directPathToOffRidge_dB = pow2db(double(directPathPower) ./ ...
    max(median(offOriginValues, "omitnan"), eps));
offOriginPeakToBackground_dB = pow2db(max(max(offOriginValues), eps) ./ ...
    max(median(backgroundValues, "omitnan"), eps));
sceneScore = localComputeSceneScore(offOriginEnergyFraction, ...
    occupiedFraction, zeroDopplerEnergyFraction, ...
    directPathToOffRidge_dB, resolvedOptions);
reviewLinearMap = single(imresize(mapLinear, ...
    [resolvedOptions.ReviewMapRows, resolvedOptions.ReviewMapCols], ...
    "bilinear"));
reviewDelayAxis_samples = linspace(delayAxis_samples(1), ...
    delayAxis_samples(end), resolvedOptions.ReviewMapCols);
reviewDopplerAxis_Hz = linspace(dopplerAxis_Hz(1), ...
    dopplerAxis_Hz(end), resolvedOptions.ReviewMapRows).';

mapProduct = struct();
mapProduct.MapRateMode = string(resolvedOptions.MapRateMode);
mapProduct.MapDecimationFactor = ...
    double(resolvedOptions.MapDecimationFactor);
mapProduct.MapSampleRateHz = double(resolvedOptions.MapSampleRateHz);
mapProduct.MapLinear = mapLinear;
mapProduct.RawDelayAxis_samples = delayAxis_samples;
mapProduct.RawDopplerAxis_Hz = dopplerAxis_Hz;
mapProduct.GlobalPeakDelay_samples = double(globalPeakDelay_samples);
mapProduct.GlobalPeakDoppler_Hz = double(globalPeakDoppler_Hz);
mapProduct.GlobalPeak_dB = pow2db(double(globalPeakPower));
mapProduct.OriginNeighborhoodContainsGlobalPeak = ...
    logical(originMask(globalPeakIndex));
mapProduct.DirectPathDelay_samples = double(directPathDelay_samples);
mapProduct.DirectPathDoppler_Hz = double(directPathDoppler_Hz);
mapProduct.DirectPathPower = single(directPathPower);
mapProduct.DirectPathPeak_dB = pow2db(double(directPathPower));
mapProduct.DirectPathLocalProminence_dB = pow2db( ...
    double(directPathPower) ./ max(double(max(localAnnulusValues)), eps));
mapProduct.DirectPathToClutter_dB = pow2db(double(directPathPower) ./ ...
    max(double(median(clutterValues, "omitnan")), eps));
mapProduct.DirectPathToFloor_dB = pow2db(double(directPathPower) ./ ...
    max(double(median(backgroundValues, "omitnan")), eps));
mapProduct.OffOriginEnergyFraction = double(sum(mapLinear( ...
    offOriginMask), "all") ./ totalMapPower);
mapProduct.OffOriginNonzeroDopplerEnergyFraction = ...
    offOriginEnergyFraction;
mapProduct.ZeroDopplerRidgeEnergyFraction = zeroDopplerEnergyFraction;
mapProduct.OffOriginOccupiedFraction_abovePeakMinus20dB = ...
    occupiedFraction;
mapProduct.DirectPathToOffRidgeEnergy_dB = ...
    double(directPathToOffRidge_dB);
mapProduct.OffOriginPeakToBackground_dB = ...
    double(offOriginPeakToBackground_dB);
mapProduct.SceneObservabilityScore = double(sceneScore);
mapProduct.OffOriginNonzeroDopplerMask = offOriginNonzeroDopplerMask;
mapProduct.ZeroDopplerRidgeMask = zeroDopplerRidgeMask;
reviewMagnitude = sqrt(max(reviewLinearMap, eps("single")));
mapProduct.ReviewMap_dB = max(mag2db(reviewMagnitude), ...
    resolvedOptions.FigureFloor_dB);
mapProduct.ReviewDelayAxis_samples = reviewDelayAxis_samples;
mapProduct.ReviewDopplerAxis_Hz = reviewDopplerAxis_Hz;

end

function originMask = localBuildOriginMask(delayAxis_samples, ...
    dopplerAxis_Hz, productDefinition)

delayMask = abs(delayAxis_samples) <= ...
    productDefinition.OriginSearchDelayRadius_samples;
dopplerMask = abs(dopplerAxis_Hz) <= ...
    productDefinition.OriginSearchDopplerRadius_Hz;
originMask = logical(dopplerMask & delayMask);

end

function exclusionMask = localBuildDirectPathExclusionMask( ...
    delayAxis_samples, dopplerAxis_Hz, directPathDelay_samples, ...
    directPathDoppler_Hz, productDefinition)

delayMask = abs(delayAxis_samples - directPathDelay_samples) <= ...
    productDefinition.ExclusionDelayRadius_samples;
dopplerMask = abs(dopplerAxis_Hz - directPathDoppler_Hz) <= ...
    productDefinition.ExclusionDopplerRadius_Hz;
exclusionMask = logical(dopplerMask & delayMask);

end

function exclusionMask = localBuildOriginExclusionMask(delayAxis_samples, ...
    dopplerAxis_Hz, productDefinition)

delayMask = abs(delayAxis_samples) <= ...
    productDefinition.ExclusionDelayRadius_samples;
dopplerMask = abs(dopplerAxis_Hz) <= ...
    productDefinition.ExclusionDopplerRadius_Hz;
exclusionMask = logical(dopplerMask & delayMask);

end

function annulusValues = localBuildLocalAnnulus(mapLinear, ...
    directPathRow, directPathCol, radiusBins)

radiusBins = round(double(radiusBins));
rowIndices = max(1, directPathRow - radiusBins): ...
    min(size(mapLinear, 1), directPathRow + radiusBins);
colIndices = max(1, directPathCol - radiusBins): ...
    min(size(mapLinear, 2), directPathCol + radiusBins);
[columnGrid, rowGrid] = meshgrid(colIndices, rowIndices);
distanceGrid = max(abs(rowGrid - directPathRow), ...
    abs(columnGrid - directPathCol));
annulusMask = distanceGrid >= 2 & distanceGrid <= radiusBins;
localPatch = mapLinear(rowIndices, colIndices);
annulusValues = double(localPatch(annulusMask));

if isempty(annulusValues)
    annulusValues = double(mapLinear(:));
end

end

function clutterValues = localBuildClutterValues(mapLinear, ...
    delayAxis_samples, dopplerAxis_Hz, directPathDelay_samples, ...
    exclusionDelayRadius_samples)

delayMask = abs(delayAxis_samples - directPathDelay_samples) <= ...
    exclusionDelayRadius_samples;
dopplerMask = abs(dopplerAxis_Hz) <= 25.0;
clutterMask = dopplerMask & ~delayMask;
clutterValues = double(mapLinear(clutterMask));

if isempty(clutterValues)
    clutterValues = double(mapLinear(:));
end

end

function backgroundValues = localBuildBackgroundValues(mapLinear, ...
    delayAxis_samples, dopplerAxis_Hz, productDefinition)

backgroundMask = ~localBuildOriginExclusionMask(delayAxis_samples, ...
    dopplerAxis_Hz, productDefinition) & ...
    abs(dopplerAxis_Hz) > productDefinition.ZeroDopplerRidgeExclusion_Hz;
backgroundValues = double(mapLinear(backgroundMask));

if isempty(backgroundValues)
    backgroundValues = double(mapLinear(:));
end

end

function score = localComputeSceneScore(offOriginEnergyFraction, ...
    occupiedFraction, zeroDopplerEnergyFraction, directPathToOffRidge_dB, ...
    resolvedOptions)

score = ...
    resolvedOptions.SceneScoreOffOriginEnergyWeight .* ...
    double(offOriginEnergyFraction) + ...
    resolvedOptions.SceneScoreOccupiedFractionWeight .* ...
    double(occupiedFraction) - ...
    resolvedOptions.SceneScoreZeroDopplerPenaltyWeight .* ...
    double(zeroDopplerEnergyFraction) - ...
    resolvedOptions.SceneScoreDirectPathDominancePenaltyWeight .* ...
    max(double(directPathToOffRidge_dB) - ...
    resolvedOptions.SceneScoreDirectPathDominanceReference_dB, 0.0);

end

function [label, rationale] = localClassifyMapProduct(mapProduct, ...
    resolvedOptions)

if ~mapProduct.OriginNeighborhoodContainsGlobalPeak
    label = "implementation_suspect";
    rationale = "Global peak did not stay inside the origin neighborhood.";
    return
end

sceneReviewable = mapProduct.OffOriginNonzeroDopplerEnergyFraction >= ...
    resolvedOptions.SceneCaveatedOffOriginNonzeroDopplerEnergyFraction && ...
    mapProduct.OffOriginOccupiedFraction_abovePeakMinus20dB >= ...
    resolvedOptions.SceneCaveatedOffOriginOccupiedFraction && ...
    mapProduct.ZeroDopplerRidgeEnergyFraction <= ...
    resolvedOptions.SceneCaveatedMaxZeroDopplerRidgeEnergyFraction && ...
    mapProduct.DirectPathToOffRidgeEnergy_dB <= ...
    resolvedOptions.SceneCaveatedMaxDirectPathToOffRidgeEnergy_dB;

if sceneReviewable
    label = "reviewable_scene_present";
else
    label = "scene_limited_direct_path_dominated";
end

rationale = sprintf("off_origin=%.3f | occupied_minus20dB=%.4f | " + ...
    "zero_doppler=%.3f | direct_path_to_off_ridge=%.2f dB", ...
    mapProduct.OffOriginNonzeroDopplerEnergyFraction, ...
    mapProduct.OffOriginOccupiedFraction_abovePeakMinus20dB, ...
    mapProduct.ZeroDopplerRidgeEnergyFraction, ...
    mapProduct.DirectPathToOffRidgeEnergy_dB);

end

function protectedRegion = localBuildProtectedRegion(baselineProduct, ...
    productDefinition, resolvedOptions)

candidateMask = baselineProduct.OffOriginNonzeroDopplerMask & ...
    ~baselineProduct.ZeroDopplerRidgeMask;
threshold = max(baselineProduct.DirectPathPower .* single(10.0 .^ ...
    (resolvedOptions.ProtectedRegionThresholdRelativeToDirectPath_dB ./ ...
    10.0)), eps("single"));
protectedMask = candidateMask & baselineProduct.MapLinear >= threshold;
definition = ...
    "baseline_off_origin_nonzero_doppler_above_peak_minus_20db";

if nnz(protectedMask) == 0
    protectedMask = candidateMask;
    definition = ...
        "baseline_off_origin_nonzero_doppler_floor_region_no_occupied_cells";
end

if nnz(protectedMask) == 0
    protectedMask = ~localBuildOriginExclusionMask( ...
        baselineProduct.RawDelayAxis_samples, ...
        baselineProduct.RawDopplerAxis_Hz, productDefinition);
    definition = "fallback_non_direct_path_region";
end

protectedRegion = struct();
protectedRegion.Mask = protectedMask;
protectedRegion.Definition = definition;
protectedRegion.CellCount = nnz(protectedMask);
protectedRegion.BaselineProtectedPower = max(sum( ...
    baselineProduct.MapLinear(protectedMask), "all"), eps("single"));

end

