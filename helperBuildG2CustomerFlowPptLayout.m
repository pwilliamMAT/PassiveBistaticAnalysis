function layout = helperBuildG2CustomerFlowPptLayout(spec, projectRoot, pptPath)
%HELPERBUILDG2CUSTOMERFLOWPPTLAYOUT Build the customer-facing G2 slide layout.

arguments
    spec (1, 1) struct
    projectRoot (1, :) char
    pptPath (1, :) char
end

relativeMarkdownPath = strrep(char(spec.MarkdownPath), ...
    [projectRoot filesep], "");
relativeArtifactDir = strrep(fileparts(pptPath), [projectRoot filesep], "");

colors = localBuildColorPalette();
slideWidth = 960;
slideHeight = 540;

slide1Texts = localBuildSlide1Texts(spec, colors, relativeMarkdownPath, ...
    relativeArtifactDir);
[slide1Boxes, slide1Headers] = localBuildSlide1Boxes(spec, colors);
slide1Lines = localBuildSlide1Lines(slide1Boxes, colors);

slide2Texts = localBuildSlide2Texts(spec, colors, relativeMarkdownPath, ...
    relativeArtifactDir);
slide2Boxes = localBuildSlide2Boxes(spec, colors);
slide2Lines = localBuildSlide2Lines(slide2Boxes, colors);

layout = struct();
layout.SlideWidth = slideWidth;
layout.SlideHeight = slideHeight;
layout.ExportSlideIndex = 1;
layout.Slides = [ ...
    struct( ...
        "Title", "G2 Customer Flow", ...
        "Boxes", [slide1Headers slide1Boxes], ...
        "Texts", slide1Texts, ...
        "Lines", slide1Lines ...
    ) ...
    struct( ...
        "Title", "G2 Requirement Coverage", ...
        "Boxes", slide2Boxes, ...
        "Texts", slide2Texts, ...
        "Lines", slide2Lines ...
    ) ...
    ];
end

