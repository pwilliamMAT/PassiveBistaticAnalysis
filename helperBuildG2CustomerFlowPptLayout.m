function lines = localSegmentLines(value, maxSegments)

if nargin < 2
    maxSegments = inf;
end

segments = split(string(value), ";");
segments = strtrim(segments);
segments = segments(strlength(segments) > 0);

if isfinite(maxSegments)
    segments = segments(1:min(numel(segments), maxSegments));
end

lines = "- " + segments;
end

