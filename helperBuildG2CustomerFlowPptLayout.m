function [boxes, headers] = localBuildSlide1Boxes(spec, colors)

stageCount = 5;
cardWidth = 176;
cardHeight = 246;
headerHeight = 24;
startX = 20;
startY = 130;
gap = 10;

boxes = repmat(localBoxTemplate(), 1, stageCount);
headers = repmat(localBoxTemplate(), 1, stageCount);

for stageIndex = 1:stageCount
    currentStage = spec.Stages(stageIndex);
    currentX = startX + (stageIndex - 1) * (cardWidth + gap);
    isDecisionStage = stageIndex == stageCount;

    if isDecisionStage
        bodyFill = colors.DecisionFill;
        bodyLine = colors.DecisionLine;
        bodyFont = colors.DecisionText;
    else
        bodyFill = colors.StageFill(stageIndex);
        bodyLine = colors.StageLine(stageIndex);
        bodyFont = colors.Text;
    end

    headers(stageIndex) = localMakeBox( ...
        "HEADER_" + string(stageIndex), currentStage.Title, currentX, 104, ...
        cardWidth, headerHeight, colors.StageHeader(stageIndex), ...
        colors.StageLine(stageIndex), 11, true, colors.HeaderText, 1, ...
        "center", 3);
    boxes(stageIndex) = localMakeBox( ...
        "BODY_" + string(stageIndex), localFormatStageBody(currentStage), ...
        currentX, startY, cardWidth, cardHeight, bodyFill, bodyLine, 8.5, ...
        false, bodyFont, 1, "left", 1);
end
end

function lines = localBuildSlide1Lines(boxes, colors)

lineCount = numel(boxes) - 1;
lines = repmat(localLineTemplate(), 1, lineCount);

for lineIndex = 1:lineCount
    sourceBox = boxes(lineIndex);
    targetBox = boxes(lineIndex + 1);

    lines(lineIndex) = localMakeLine( ...
        sourceBox.X + sourceBox.Width, ...
        sourceBox.Y + sourceBox.Height / 2, ...
        targetBox.X, ...
        targetBox.Y + targetBox.Height / 2, ...
        colors.Line, ...
        1.75, ...
        true, ...
        "", ...
        0, ...
        0, ...
        0, ...
        0, ...
        0, ...
        "center" ...
    );
end
end

