function metadataInfo = helperReadCollectionMetadata(metadataPath, datasetId)
%HELPERREADCOLLECTIONMETADATA Read dataset-local manual collection metadata.

arguments
    metadataPath (1,1) string
    datasetId (1,1) string
end

metadataInfo = localBuildEmptyMetadataInfo(metadataPath, datasetId);

if ~isfile(metadataPath)
    return
end

try
    rawMetadata = jsondecode(fileread(metadataPath));
catch readException
    error("helperReadCollectionMetadata:ReadFailed", ...
        "Failed to read collection metadata %s: %s", metadataPath, ...
        readException.message);
end

metadataInfo.MetadataPresent = true;
metadataInfo.SessionId = localGetFieldText(rawMetadata, "session_id");
metadataInfo.SessionIdMatches = strlength(metadataInfo.SessionId) > 0 && ...
    metadataInfo.SessionId == string(datasetId);
metadataInfo.MetadataSource = localGetFieldText(rawMetadata, ...
    "metadata_source");
metadataInfo.ReferenceChannel = localNormalizeChannelMetadata(rawMetadata, ...
    "reference_channel");
metadataInfo.SurveillanceChannel = localNormalizeChannelMetadata( ...
    rawMetadata, "surveillance_channel");
metadataInfo.SiteContext = localNormalizeSiteContext(rawMetadata);
metadataInfo.AcquisitionControls = localNormalizeAcquisitionControls( ...
    rawMetadata);

end

function metadataInfo = localBuildEmptyMetadataInfo(metadataPath, datasetId)

metadataInfo = struct();
metadataInfo.MetadataPath = string(metadataPath);
metadataInfo.MetadataPresent = false;
metadataInfo.DatasetId = string(datasetId);
metadataInfo.SessionId = "";
metadataInfo.SessionIdMatches = false;
metadataInfo.MetadataSource = "";
metadataInfo.ReferenceChannel = localBuildEmptyChannelMetadata();
metadataInfo.SurveillanceChannel = localBuildEmptyChannelMetadata();
metadataInfo.SiteContext = struct( ...
    "SiteRegion", "", ...
    "SurveillanceBoresightDescription", "", ...
    "ExpectedAirTrafficNote", "", ...
    "IlluminatorNote", "", ...
    "ReceiverLocationNote", "", ...
    "ObstructionsOrClutterNote", "");
metadataInfo.AcquisitionControls = struct( ...
    "GainMappingNote", "", ...
    "GainModeNote", "", ...
    "LockStatusNote", "", ...
    "OverrunNote", "", ...
    "ChannelMappingVerificationNote", "", ...
    "OperatorNotes", "");

end

