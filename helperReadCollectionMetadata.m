function fieldText = localGetFieldText(inputStruct, fieldName)

fieldText = "";

if ~isstruct(inputStruct)
    return
end

if ~isfield(inputStruct, fieldName)
    return
end

fieldValue = inputStruct.(fieldName);

if isnumeric(fieldValue) || islogical(fieldValue)
    fieldText = string(fieldValue);
elseif isstring(fieldValue) || ischar(fieldValue)
    fieldText = string(fieldValue);
else
    fieldText = "";
end

fieldText = strtrim(fieldText);

end

function outputStruct = localGetStructField(inputStruct, fieldName)

outputStruct = struct();

if ~isstruct(inputStruct)
    return
end

if ~isfield(inputStruct, fieldName)
    return
end

fieldValue = inputStruct.(fieldName);

if isstruct(fieldValue)
    outputStruct = fieldValue;
end

end
