function localValidateComparableAcquisition(baseline, candidate)

if baseline.SampleRate_Hz ~= candidate.SampleRate_Hz
    error("helperAnalyzeDirectPathQuickView:SampleRateMismatch", ...
        "Baseline and candidate manifest sample rates differ.");
end

if baseline.CenterFrequency_Hz ~= candidate.CenterFrequency_Hz
    error("helperAnalyzeDirectPathQuickView:CenterFrequencyMismatch", ...
        "Baseline and candidate manifest center frequencies differ.");
end

end

function comparisonTable = localBuildComparisonTable(baseline, candidate, ...
    definitions)

rowTemplate = struct( ...
    "MetricId", "", ...
    "DisplayName", "", ...
    "Unit", "", ...
    "FieldName", "", ...
    "DisplayFormat", "", ...
    "DifferenceApplicable", false, ...
    "DifferenceNote", "", ...
    "BaselineReference", NaN, ...
    "BaselineSurveillance", NaN, ...
    "BaselineReferenceMinusSurveillance", NaN, ...
    "CandidateReference", NaN, ...
    "CandidateSurveillance", NaN, ...
    "CandidateReferenceMinusSurveillance", NaN, ...
    "DeltaReference", NaN, ...
    "DeltaSurveillance", NaN, ...
    "DeltaReferenceMinusSurveillance", NaN);
rows = repmat(rowTemplate, numel(definitions), 1);

for metricIndex = 1:numel(definitions)
    definition = definitions(metricIndex);
    baselineRow = baseline.ChannelSummaryTable(metricIndex, :);
    candidateRow = candidate.ChannelSummaryTable(metricIndex, :);
    baselineDifference = NaN;
    candidateDifference = NaN;
    differenceOfDifferences = NaN;

    if definition.DifferenceApplicable
        baselineDifference = ...
            baselineRow.ReferenceMinusSurveillanceMedian;
        candidateDifference = ...
            candidateRow.ReferenceMinusSurveillanceMedian;
        differenceOfDifferences = candidateDifference - ...
            baselineDifference;
    end

    rows(metricIndex) = struct( ...
        "MetricId", definition.MetricId, ...
        "DisplayName", definition.DisplayName, ...
        "Unit", definition.Unit, ...
        "FieldName", definition.FieldName, ...
        "DisplayFormat", definition.DisplayFormat, ...
        "DifferenceApplicable", definition.DifferenceApplicable, ...
        "DifferenceNote", definition.DifferenceNote, ...
        "BaselineReference", baselineRow.ReferenceMedian, ...
        "BaselineSurveillance", baselineRow.SurveillanceMedian, ...
        "BaselineReferenceMinusSurveillance", baselineDifference, ...
        "CandidateReference", candidateRow.ReferenceMedian, ...
        "CandidateSurveillance", candidateRow.SurveillanceMedian, ...
        "CandidateReferenceMinusSurveillance", candidateDifference, ...
        "DeltaReference", candidateRow.ReferenceMedian - ...
        baselineRow.ReferenceMedian, ...
        "DeltaSurveillance", candidateRow.SurveillanceMedian - ...
        baselineRow.SurveillanceMedian, ...
        "DeltaReferenceMinusSurveillance", differenceOfDifferences);
end

comparisonTable = struct2table(rows);

end

