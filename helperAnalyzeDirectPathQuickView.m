        "SurveillanceIQR", surveillanceStats.IQR, ...
        "SurveillanceMin", surveillanceStats.Min, ...
        "SurveillanceMax", surveillanceStats.Max, ...
        "ReferenceMinusSurveillanceMedian", ...
        differenceStats.Median, ...
        "ReferenceMinusSurveillanceIQR", differenceStats.IQR, ...
        "ReferenceMinusSurveillanceMin", differenceStats.Min, ...
        "ReferenceMinusSurveillanceMax", differenceStats.Max);
