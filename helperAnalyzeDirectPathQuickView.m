function session = localAnalyzeSession(datasetId, repoRoot, options, ...
    metricDefinitions, pairwiseMetricDefinitions)

datasetRoot = fullfile(repoRoot, datasetId);
manifestPath = fullfile(datasetRoot, "session_manifest.json");
manifest = localReadManifest(manifestPath);
localValidateManifest(manifest, datasetId);

radarRelativePaths = string(manifest.radar_files(:));
repetitionIndices = localSelectRepetitions(numel(radarRelativePaths), ...
    options.Mode);
gainVector = localParseGainSpec(manifest.gain_spec);
channelRows = repmat(localEmptyChannelRow(), ...
    numel(repetitionIndices) * 2, 1);
pairwiseRows = repmat(localEmptyPairwiseRow(), ...
    numel(repetitionIndices), 1);
sampleRateHz = double(manifest.sdr_defaults.sample_rate_hz);
centerFrequencyHz = double(manifest.sdr_defaults.center_frequency_hz);

for selectionIndex = 1:numel(repetitionIndices)
    manifestIndex = repetitionIndices(selectionIndex);
    relativePath = radarRelativePaths(manifestIndex);
    capturePath = fullfile(datasetRoot, ...
        strrep(relativePath, "/", filesep));
    scan = helperScanBasebandCaptureFile(capturePath, true);
    [referenceIndex, surveillanceIndex] = localValidateCapture( ...
        scan, manifest, options, capturePath);
    windowIndices = localAnalysisWindowIndices(scan.NumSamples, ...
        sampleRateHz, options);
    referenceSamples = double(scan.Samples(windowIndices, referenceIndex));
    surveillanceSamples = double( ...
        scan.Samples(windowIndices, surveillanceIndex));
    referenceMetrics = localComputeChannelMetrics(referenceSamples, ...
        sampleRateHz, options);
    surveillanceMetrics = localComputeChannelMetrics( ...
        surveillanceSamples, sampleRateHz, options);
    pairwiseMetrics = localComputePairwiseMetrics(referenceSamples, ...
        surveillanceSamples, sampleRateHz, options);

    referenceRowIndex = (selectionIndex - 1) * 2 + 1;
    surveillanceRowIndex = referenceRowIndex + 1;
    channelRows(referenceRowIndex) = localBuildChannelRow(datasetId, ...
        scan.Repetition, manifestIndex, relativePath, "reference", ...
        options.ReferenceChannelLabel, windowIndices, referenceMetrics);
    channelRows(surveillanceRowIndex) = localBuildChannelRow(datasetId, ...
        scan.Repetition, manifestIndex, relativePath, "surveillance", ...
        options.SurveillanceChannelLabel, windowIndices, ...
        surveillanceMetrics);
    pairwiseRows(selectionIndex) = localBuildPairwiseRow(datasetId, ...
        scan.Repetition, manifestIndex, relativePath, windowIndices, ...
        pairwiseMetrics);
end

channelMetricTable = struct2table(channelRows);
pairwiseMetricTable = struct2table(pairwiseRows);
channelSummaryTable = localBuildChannelSummary(channelMetricTable, ...
    metricDefinitions);
pairwiseSummaryTable = localBuildPairwiseSummary(pairwiseMetricTable, ...
    pairwiseMetricDefinitions);

session = struct();
session.DatasetId = string(datasetId);
session.DatasetRoot = string(datasetRoot);
session.ManifestPath = string(manifestPath);
session.ManifestGainSpec = string(manifest.gain_spec);
session.SurveillanceGain_dB = gainVector(1);
session.ReferenceGain_dB = gainVector(2);
session.SampleRate_Hz = sampleRateHz;
session.CenterFrequency_Hz = centerFrequencyHz;
session.AnalysisWindowDuration_s = ...
    (channelMetricTable.WindowEndSample(1) - ...
    channelMetricTable.WindowStartSample(1) + 1) / sampleRateHz;
session.WindowDescription = localWindowDescription(options.Mode);
session.SelectedManifestIndices = repetitionIndices(:).';
session.SelectedRepetitions = unique(channelMetricTable.Repetition, ...
    "stable").';
session.ChannelMetricTable = channelMetricTable;
session.PairwiseMetricTable = pairwiseMetricTable;
session.ChannelSummaryTable = channelSummaryTable;
session.PairwiseSummaryTable = pairwiseSummaryTable;

end

function manifest = localReadManifest(manifestPath)

if ~isfile(manifestPath)
    error("helperAnalyzeDirectPathQuickView:MissingManifest", ...
        "Manifest not found: %s", manifestPath);
end

try
    manifest = jsondecode(fileread(manifestPath));
catch manifestException
    error("helperAnalyzeDirectPathQuickView:ReadManifestFailed", ...
        "Failed to read %s: %s", manifestPath, ...
        manifestException.message);
end

end

function localValidateManifest(manifest, datasetId)

requiredFields = ["session_id", "gain_spec", "radar_files", ...
    "sdr_defaults"];

for fieldIndex = 1:numel(requiredFields)
    fieldName = requiredFields(fieldIndex);

    if ~isfield(manifest, fieldName)
        error("helperAnalyzeDirectPathQuickView:IncompleteManifest", ...
            "Manifest for %s is missing %s.", datasetId, fieldName);
    end
end

if string(manifest.session_id) ~= datasetId
    error("helperAnalyzeDirectPathQuickView:SessionIdMismatch", ...
        "Manifest session_id %s does not match requested dataset %s.", ...
        string(manifest.session_id), datasetId);
end

if ~isfield(manifest.sdr_defaults, "sample_rate_hz") || ...
        ~isfield(manifest.sdr_defaults, "center_frequency_hz")
    error("helperAnalyzeDirectPathQuickView:IncompleteManifestSettings", ...
        "Manifest for %s lacks sample-rate or center-frequency settings.", ...
        datasetId);
end

if isempty(manifest.radar_files)
    error("helperAnalyzeDirectPathQuickView:NoRadarFiles", ...
        "Manifest for %s contains no radar files.", datasetId);
end

end

function indices = localSelectRepetitions(repetitionCount, mode)

if mode == "confirm"
    indices = 1:repetitionCount;
    return
end

middleIndex = round((repetitionCount + 1) / 2);
indices = unique([1, middleIndex, repetitionCount], "stable");

end

function gains = localParseGainSpec(gainSpec)

gainTokens = split(strtrim(string(gainSpec)), ",");
gains = str2double(strtrim(gainTokens));

if numel(gains) ~= 2 || any(~isfinite(gains))
    error("helperAnalyzeDirectPathQuickView:InvalidGainSpec", ...
        "Expected manifest gain_spec to contain two numeric values.");
end

gains = double(gains(:).');

end

function [referenceIndex, surveillanceIndex] = localValidateCapture( ...
    scan, manifest, options, capturePath)

channelLabels = [string(scan.Antenna1), string(scan.Antenna2)];
referenceIndex = find(channelLabels == ...
    options.ReferenceChannelLabel, 1, "first");
surveillanceIndex = find(channelLabels == ...
    options.SurveillanceChannelLabel, 1, "first");

if isempty(referenceIndex) || isempty(surveillanceIndex) || ...
        referenceIndex == surveillanceIndex
    error("helperAnalyzeDirectPathQuickView:ChannelMappingMismatch", ...
        "Capture %s must contain exactly the enforced mapping " + ...
        "SURV=%s and REF=%s.", capturePath, ...
        options.SurveillanceChannelLabel, options.ReferenceChannelLabel);
end

manifestSampleRateHz = double(manifest.sdr_defaults.sample_rate_hz);
manifestCenterFrequencyHz = ...
    double(manifest.sdr_defaults.center_frequency_hz);

if scan.SampleRate ~= manifestSampleRateHz || ...
        scan.CenterFrequency ~= manifestCenterFrequencyHz
    error("helperAnalyzeDirectPathQuickView:HeaderManifestMismatch", ...
        "Capture header settings disagree with the manifest for %s.", ...
        capturePath);
end

if scan.DataType ~= "int16"
    error("helperAnalyzeDirectPathQuickView:UnsupportedDataType", ...
        "Direct-path dBFS normalization currently requires int16 IQ.");
end

end

function indices = localAnalysisWindowIndices(numSamples, sampleRateHz, ...
    options)

if options.Mode == "confirm"
    indices = 1:numSamples;
    return
end

windowSampleCount = round(options.WindowDuration_s * sampleRateHz);

if windowSampleCount > numSamples
    error("helperAnalyzeDirectPathQuickView:WindowTooLong", ...
        "The requested analysis window exceeds the capture duration.");
end

startIndex = floor((numSamples - windowSampleCount) / 2) + 1;
indices = startIndex:(startIndex + windowSampleCount - 1);

end

function description = localWindowDescription(mode)

if mode == "confirm"
    description = "full capture";
else
    description = "centered window";
end

end

function metrics = localComputeChannelMetrics(samples, sampleRateHz, ...
    options)

fullScale = double(intmax("int16"));
samples = double(samples(:));
normalizedSamples = samples ./ fullScale;
welchWindow = hann(options.WelchLength, "periodic");
[psdValues, frequencyHz] = pwelch(normalizedSamples, welchWindow, ...
    options.WelchOverlap, options.WelchNfft, sampleRateHz, "centered");
psdValues = max(real(double(psdValues(:))), eps);
frequencyHz = double(frequencyHz(:));

pilotSearchMask = abs(frequencyHz - options.ExpectedPilotOffset_Hz) <= ...
    options.PilotSearchHalfWidth_Hz;

if ~any(pilotSearchMask)
    error("helperAnalyzeDirectPathQuickView:EmptyPilotSearchBand", ...
        "The expected ATSC pilot search band is outside the PSD support.");
end

pilotSearchMetrics = helperComputePilotAwarePsdMetrics( ...
    frequencyHz(pilotSearchMask), psdValues(pilotSearchMask), ...
    options.PilotExclusionHalfWidth_Hz);
pilotFrequencyHz = pilotSearchMetrics.PilotFrequency_Hz;
pilotPsd = db2pow(pilotSearchMetrics.PilotPsd_dB);
bandLowerHz = max(-options.AtscBandHalfWidth_Hz, min(frequencyHz));
bandUpperHz = min(options.AtscBandHalfWidth_Hz, max(frequencyHz));
dataBandMask = frequencyHz >= bandLowerHz;
dataBandMask = dataBandMask & frequencyHz <= bandUpperHz;
dataBandMask = dataBandMask & ...
    abs(frequencyHz - pilotFrequencyHz) > ...
    options.PilotExclusionHalfWidth_Hz;

if ~any(dataBandMask)
    error("helperAnalyzeDirectPathQuickView:EmptyDataBand", ...
        "Pilot exclusion removed the entire ATSC data band.");
end

dataBandPsd = psdValues(dataBandMask);
dataBandMedianPsd = median(dataBandPsd, "omitnan");
dataBandPeakPsd = max(dataBandPsd, [], "omitnan");
fullBandPower = bandpower(psdValues, frequencyHz, ...
    [bandLowerHz, bandUpperHz], "psd");
pilotBandLowerHz = max(bandLowerHz, ...
    pilotFrequencyHz - options.PilotExclusionHalfWidth_Hz);
pilotBandUpperHz = min(bandUpperHz, ...
    pilotFrequencyHz + options.PilotExclusionHalfWidth_Hz);
pilotBandPower = bandpower(psdValues, frequencyHz, ...
    [pilotBandLowerHz, pilotBandUpperHz], "psd");
pilotExcludedBandPower = max(fullBandPower - pilotBandPower, eps);

meanPower = mean(abs(normalizedSamples) .^ 2);
maxMagnitude = max(abs(normalizedSamples));
maxComponentAbs = max([ ...
    max(abs(real(samples))), ...
    max(abs(imag(samples))) ...
    ]);
nearRailMask = abs(real(samples)) >= ...
    options.NearRailThresholdFraction * fullScale;
nearRailMask = nearRailMask | abs(imag(samples)) >= ...
    options.NearRailThresholdFraction * fullScale;
exactRailMask = abs(real(samples)) >= fullScale;
exactRailMask = exactRailMask | abs(imag(samples)) >= fullScale;
realSamples = real(normalizedSamples);
imagSamples = imag(normalizedSamples);
realCentered = realSamples - mean(realSamples);
imagCentered = imagSamples - mean(imagSamples);
realScale = sqrt(mean(realCentered .^ 2));
imagScale = sqrt(mean(imagCentered .^ 2));
iqCorrelation = localNormalizedCorrelation(realCentered, imagCentered);
phaseProxyDegrees = asind(max(min(iqCorrelation, 1.0), -1.0));
iqAmplitudeImbalanceDb = 20.0 * log10( ...
    max(realScale, eps) / max(imagScale, eps));
iqImpropriety = abs(mean(normalizedSamples .^ 2)) / ...
    max(meanPower, eps);
dcSpikeDb = localComputeDcSpike(psdValues, frequencyHz, options);

try
    occupiedBandwidthHz = obw(normalizedSamples, sampleRateHz);
catch bandwidthException
    error("helperAnalyzeDirectPathQuickView:OccupiedBandwidthFailed", ...
        "Occupied-bandwidth calculation failed: %s", ...
        bandwidthException.message);
end

metrics = struct();
metrics.PilotExcludedAtscBandPower_dBFS = ...
    pow2db(pilotExcludedBandPower);
metrics.AtscPilotPsd_dBFSHz = pow2db(max(pilotPsd, eps));
metrics.MeanIqPower_dBFS = pow2db(max(meanPower, eps));
metrics.DataBandMedianPsd_dBFSHz = ...
    pow2db(max(dataBandMedianPsd, eps));
metrics.PilotProminence_dB = pow2db( ...
    max(pilotPsd, eps) / max(dataBandMedianPsd, eps));
metrics.PilotFrequencyError_kHz = ...
    (pilotFrequencyHz - options.ExpectedPilotOffset_Hz) / 1.0e3;
metrics.DataBandPeakProminence_dB = pow2db( ...
    max(dataBandPeakPsd, eps) / max(dataBandMedianPsd, eps));
metrics.OccupiedBandwidth_MHz = occupiedBandwidthHz / 1.0e6;
metrics.PeakToAverageRatio_dB = pow2db( ...
    (maxMagnitude ^ 2) / max(meanPower, eps));
metrics.PeakHeadroom_dB = 20.0 * log10( ...
    fullScale / max(maxComponentAbs, eps));
metrics.NearRailOccupancy_ppm = mean(nearRailMask) * 1.0e6;
metrics.ExactRailSampleCount = double(nnz(exactRailMask));
metrics.DcSpike_dB = dcSpikeDb;
metrics.IqAmplitudeImbalance_dB = iqAmplitudeImbalanceDb;
metrics.IqPhaseProxy_deg = phaseProxyDegrees;
metrics.IqImpropriety = iqImpropriety;

end

function value = localComputeDcSpike(psdValues, frequencyHz, options)

[~, dcIndex] = min(abs(frequencyHz));
localMask = abs(frequencyHz) <= ...
    options.DcSpikeLocalHalfWidth_Hz;
localMask = localMask & abs(frequencyHz) >= ...
    options.DcSpikeExclusionHalfWidth_Hz;

if ~any(localMask)
    value = NaN;
    return
end

localMedian = median(psdValues(localMask), "omitnan");
value = pow2db(psdValues(dcIndex) / max(localMedian, eps));

end

function value = localNormalizedCorrelation(firstValues, secondValues)

denominator = sqrt(sum(abs(firstValues) .^ 2) * ...
    sum(abs(secondValues) .^ 2));

if denominator <= eps
    value = 0.0;
    return
end

value = real(sum(firstValues .* conj(secondValues)) / denominator);

end

function metrics = localComputePairwiseMetrics(referenceSamples, ...
    surveillanceSamples, sampleRateHz, options)

fullScale = double(intmax("int16"));
referenceSamples = double(referenceSamples(:)) ./ fullScale;
surveillanceSamples = double(surveillanceSamples(:)) ./ fullScale;
welchWindow = hann(options.WelchLength, "periodic");
[coherenceValues, coherenceFrequencyHz] = mscohere(referenceSamples, ...
    surveillanceSamples, welchWindow, options.WelchOverlap, ...
    options.WelchNfft, sampleRateHz, "centered");
bandMask = abs(coherenceFrequencyHz) <= options.AtscBandHalfWidth_Hz;
meanBandCoherence = mean(coherenceValues(bandMask), "omitnan");

correlationSampleCount = min(numel(referenceSamples), ...
    options.CorrelationSampleCount);
correlationStart = floor((numel(referenceSamples) - ...
    correlationSampleCount) / 2) + 1;
correlationIndices = correlationStart:( ...
    correlationStart + correlationSampleCount - 1);
[correlationValues, correlationLags] = xcorr( ...
    referenceSamples(correlationIndices), ...
    surveillanceSamples(correlationIndices), ...
    options.CorrelationMaxLag_samples, "normalized");
[peakCorrelation, peakIndex] = max(abs(correlationValues));

metrics = struct();
metrics.MeanBandCoherence = double(meanBandCoherence);
metrics.PeakNormalizedCorrelation = double(peakCorrelation);
metrics.PeakCorrelationLag_samples = ...
    double(correlationLags(peakIndex));

end

