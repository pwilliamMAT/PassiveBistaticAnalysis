function analysis = helperAnalyzeDirectPathQuickView( ...
    baselineDatasetId, candidateDatasetId, repoRoot, options)
%HELPERANALYZEDIRECTPATHQUICKVIEW Compare direct-path capture evidence.
%
%   ANALYSIS = HELPERANALYZEDIRECTPATHQUICKVIEW(BASELINEID, CANDIDATEID,
%   REPOROOT, OPTIONS) reads manifest-listed baseband captures, enforces
%   RF0 as surveillance and RF1 as reference, and returns channel and
%   pairwise measurements. Quick mode uses centered 125 ms windows from
%   the first, middle, and last repetitions. Confirm mode uses the same
%   centered window from every repetition.

arguments
    baselineDatasetId (1,1) string
    candidateDatasetId (1,1) string
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

repoRoot = helperResolveRepoRoot(repoRoot);
resolvedOptions = localResolveOptions(options);
metricDefinitions = localBuildMetricDefinitions();
pairwiseMetricDefinitions = localBuildPairwiseMetricDefinitions();

baseline = localAnalyzeSession(baselineDatasetId, repoRoot, ...
    resolvedOptions, metricDefinitions, pairwiseMetricDefinitions);
candidate = localAnalyzeSession(candidateDatasetId, repoRoot, ...
    resolvedOptions, metricDefinitions, pairwiseMetricDefinitions);
localValidateComparableAcquisition(baseline, candidate);

comparisonTable = localBuildComparisonTable(baseline, candidate, ...
    metricDefinitions);
pairwiseComparisonTable = localBuildPairwiseComparisonTable( ...
    baseline, candidate, pairwiseMetricDefinitions);
evidenceTable = localBuildEvidenceTable(baseline, candidate, ...
    comparisonTable, resolvedOptions);

analysis = struct();
analysis.AnalysisId = "DirectPathQuickView";
analysis.BaselineDatasetId = baseline.DatasetId;
analysis.CandidateDatasetId = candidate.DatasetId;
analysis.Mode = resolvedOptions.Mode;
analysis.WindowDuration_s = baseline.AnalysisWindowDuration_s;
analysis.WindowDescription = baseline.WindowDescription;
analysis.Mapping = struct( ...
    "Reference", resolvedOptions.ReferenceRfChain, ...
    "Surveillance", resolvedOptions.SurveillanceRfChain, ...
    "Source", "fixed analysis contract");
analysis.Options = resolvedOptions;
analysis.MetricDefinitions = struct2table(metricDefinitions);
analysis.PairwiseMetricDefinitions = ...
    struct2table(pairwiseMetricDefinitions);
analysis.Baseline = baseline;
analysis.Candidate = candidate;
analysis.ComparisonTable = comparisonTable;
analysis.PairwiseComparisonTable = pairwiseComparisonTable;
analysis.EvidenceTable = evidenceTable;
analysis.Trend = localBuildTrend(evidenceTable);
analysis.LocalizationSuitability = localBuildLocalizationAssessment( ...
    evidenceTable);

end

function options = localResolveOptions(userOptions)

options = struct();
options.Mode = "quick";
options.WindowDuration_s = 0.125;
options.ReferenceRfChain = "RF1";
options.SurveillanceRfChain = "RF0";
options.ReferenceChannelLabel = "RF1:RX2";
options.SurveillanceChannelLabel = "RF0:RX2";
options.ExpectedPilotOffset_Hz = -2.690559441e6;
options.PilotSearchHalfWidth_Hz = 150.0e3;
options.PilotExclusionHalfWidth_Hz = 50.0e3;
options.AtscBandHalfWidth_Hz = 3.0e6;
options.WelchLength = 8192;
options.WelchOverlap = 4096;
options.WelchNfft = 8192;
options.NearRailThresholdFraction = 0.98;
options.DcSpikeLocalHalfWidth_Hz = 50.0e3;
options.DcSpikeExclusionHalfWidth_Hz = 5.0e3;
options.CorrelationSampleCount = 131072;
options.CorrelationMaxLag_samples = 4096;
options.ControlStabilityThreshold_dB = 2.0;
options.MaterialChangeThreshold_dB = 3.0;
options.PilotFrequencyTolerance_kHz = 20.0;
options.PilotProminenceThreshold_dB = 8.0;
options.NearRailLimit_ppm = 100.0;
options.HeadroomWarningThreshold_dB = 3.0;

optionNames = fieldnames(userOptions);

for optionIndex = 1:numel(optionNames)
    optionName = optionNames{optionIndex};
    options.(optionName) = userOptions.(optionName);
end

options.Mode = lower(string(options.Mode));

if ~ismember(options.Mode, ["quick", "confirm"])
    error("helperAnalyzeDirectPathQuickView:InvalidMode", ...
        "Mode must be either ""quick"" or ""confirm"".");
end

if options.WindowDuration_s <= 0
    error("helperAnalyzeDirectPathQuickView:InvalidWindowDuration", ...
        "WindowDuration_s must be positive.");
end

if options.WelchLength < 32 || ...
        options.WelchOverlap < 0 || ...
        options.WelchOverlap >= options.WelchLength
    error("helperAnalyzeDirectPathQuickView:InvalidWelchSettings", ...
        "WelchLength and WelchOverlap do not define a valid PSD setup.");
end

options.WelchNfft = max(options.WelchNfft, options.WelchLength);

end

