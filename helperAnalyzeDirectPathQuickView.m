function summaryTable = localBuildChannelSummary(channelMetricTable, ...
    metricDefinitions)

rowTemplate = struct( ...
    "MetricId", "", ...
    "DisplayName", "", ...
    "Unit", "", ...
    "FieldName", "", ...
    "DisplayFormat", "", ...
    "DifferenceApplicable", false, ...
    "DifferenceNote", "", ...
