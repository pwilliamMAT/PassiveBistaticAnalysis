end

function stats = localComputeStats(values)

values = double(values(:));
values = values(isfinite(values));

if isempty(values)
    stats = localEmptyStats();
    return
end

quartiles = prctile(values, [25, 75]);
stats = struct();
stats.Median = median(values);
stats.IQR = quartiles(2) - quartiles(1);
stats.Min = min(values);
stats.Max = max(values);

end

function stats = localEmptyStats()

stats = struct("Median", NaN, "IQR", NaN, "Min", NaN, "Max", NaN);

end

