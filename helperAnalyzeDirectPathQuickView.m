function tableOut = localBuildEvidenceTable(baseline, candidate, ...
    comparisonTable, options)

gainComparable = ...
    baseline.SurveillanceGain_dB == candidate.SurveillanceGain_dB;
gainComparable = gainComparable && ...
    baseline.ReferenceGain_dB == candidate.ReferenceGain_dB;
gainResult = localChoose(gainComparable, "Met", "Not met");
gainExplanation = localChoose(gainComparable, ...
    "Both manifest gain vectors match exactly.", ...
    "Manifest gain vectors differ; amplitude changes are not controlled.");

meanPowerRow = localFindMetric(comparisonTable, "mean_iq_power");
pilotPsdRow = localFindMetric(comparisonTable, "atsc_pilot_psd");
bandPowerRow = localFindMetric(comparisonTable, "atsc_band_power");
controlDeltas = [ ...
    meanPowerRow.DeltaSurveillance, ...
    pilotPsdRow.DeltaSurveillance ...
    ];
controlStable = all(abs(controlDeltas) <= ...
    options.ControlStabilityThreshold_dB);
controlResult = localChoose(controlStable, "Met", "Not met");
controlExplanation = localChoose(controlStable, ...
    "Both RF0 amplitude deltas remain within the control tolerance.", ...
    "At least one RF0 amplitude delta exceeds the control tolerance.");

referenceDeltas = [ ...
    meanPowerRow.DeltaReference, ...
    pilotPsdRow.DeltaReference, ...
    bandPowerRow.DeltaReference ...
    ];
referenceResult = localClassifyThreeMetricChange(referenceDeltas, ...
    options.MaterialChangeThreshold_dB);
referenceExplanation = localDescribeThreeMetricChange(referenceResult, ...
    "RF1");
relativeDeltas = [ ...
    meanPowerRow.DeltaReferenceMinusSurveillance, ...
    pilotPsdRow.DeltaReferenceMinusSurveillance, ...
    bandPowerRow.DeltaReferenceMinusSurveillance ...
    ];
relativeResult = localClassifyThreeMetricChange(relativeDeltas, ...
    options.MaterialChangeThreshold_dB);
relativeExplanation = localDescribeThreeMetricChange(relativeResult, ...
    "control-corrected REF-SURV");

pilotErrorRow = localFindMetric(comparisonTable, ...
    "pilot_frequency_error");
pilotIdentityMet = ...
    abs(pilotErrorRow.CandidateReference) <= ...
    options.PilotFrequencyTolerance_kHz;
pilotIdentityMet = pilotIdentityMet && ...
    abs(pilotErrorRow.CandidateSurveillance) <= ...
    options.PilotFrequencyTolerance_kHz;
pilotIdentityResult = localChoose(pilotIdentityMet, "Met", "Not met");
pilotIdentityExplanation = localChoose(pilotIdentityMet, ...
    "Both candidate channels place the pilot within tolerance.", ...
    "At least one candidate channel places the pilot outside tolerance.");

pilotProminenceRow = localFindMetric(comparisonTable, ...
    "pilot_prominence");
pilotProminenceMet = ...
    pilotProminenceRow.CandidateReference >= ...
    options.PilotProminenceThreshold_dB;
pilotProminenceMet = pilotProminenceMet && ...
    pilotProminenceRow.CandidateSurveillance >= ...
    options.PilotProminenceThreshold_dB;
pilotProminenceResult = localChoose(pilotProminenceMet, "Met", ...
    "Not met");
pilotProminenceExplanation = localChoose(pilotProminenceMet, ...
    "Both candidate channels exceed the pilot-prominence threshold.", ...
    "At least one candidate channel is below the pilot-prominence threshold.");

candidateRows = candidate.ChannelMetricTable;
candidateReferenceRows = candidateRows( ...
    candidateRows.Role == "reference", :);
candidateSurveillanceRows = candidateRows( ...
    candidateRows.Role == "surveillance", :);
worstExactRailCount = max(candidateRows.ExactRailSampleCount);
worstNearRailPpm = max(candidateRows.NearRailOccupancy_ppm);
clippingMet = worstExactRailCount == 0;
clippingMet = clippingMet && ...
    worstNearRailPpm < options.NearRailLimit_ppm;
clippingResult = localChoose(clippingMet, "Met", "Clipping detected");
clippingExplanation = localChoose(clippingMet, ...
    "No exact rails and near-rail occupancy stays below the limit.", ...
    "Exact rails or excessive near-rail occupancy occur in the candidate.");

referenceHeadroom = min(candidateReferenceRows.PeakHeadroom_dB);
surveillanceHeadroom = min(candidateSurveillanceRows.PeakHeadroom_dB);
headroomResult = localHeadroomResult(referenceHeadroom, ...
    surveillanceHeadroom, options.HeadroomWarningThreshold_dB);
headroomExplanation = localHeadroomExplanation(headroomResult);

trend = localClassifyTrend(gainComparable, ...
    bandPowerRow.DeltaReference, ...
    bandPowerRow.DeltaReferenceMinusSurveillance, ...
    options.MaterialChangeThreshold_dB);
trendExplanation = localTrendExplanation(trend, ...
    bandPowerRow.DeltaReference, bandPowerRow.DeltaSurveillance, ...
    bandPowerRow.DeltaReferenceMinusSurveillance);

rows = [ ...
    localEvidenceRow("Gain comparability", ...
    sprintf("BASE=%.15g,%.15g; CAND=%.15g,%.15g", ...
    baseline.SurveillanceGain_dB, baseline.ReferenceGain_dB, ...
    candidate.SurveillanceGain_dB, candidate.ReferenceGain_dB), ...
    "manifest dB gain settings", ...
    "candidate manifest versus baseline manifest", ...
    "Exact manifest match", "existing G2", gainResult, ...
    gainExplanation); ...
    localEvidenceRow("RF0 control stability", ...
    sprintf("Delta power=%+.2f; Delta pilot=%+.2f", controlDeltas), ...
    "dB", "candidate SURV minus baseline SURV", ...
    sprintf("|each| <= %.1f dB", ...
    options.ControlStabilityThreshold_dB), ...
    "field-screen heuristic", controlResult, controlExplanation); ...
    localEvidenceRow("RF1 amplitude change", ...
    sprintf("power=%+.2f; pilot=%+.2f; band=%+.2f", ...
    referenceDeltas), "dB", ...
    "candidate REF minus baseline REF", ...
    sprintf("Improvement >= +%.1f dB; degradation <= -%.1f dB", ...
    options.MaterialChangeThreshold_dB, ...
    options.MaterialChangeThreshold_dB), ...
    "field-screen heuristic", referenceResult, referenceExplanation); ...
    localEvidenceRow("Relative advantage", ...
    sprintf("Delta R-S=%+.2f,%+.2f,%+.2f", relativeDeltas), ...
    "dB", "candidate paired REF-SURV minus baseline paired REF-SURV", ...
    sprintf("Improvement >= +%.1f dB; degradation <= -%.1f dB", ...
    options.MaterialChangeThreshold_dB, ...
    options.MaterialChangeThreshold_dB), ...
    "field-screen heuristic", relativeResult, relativeExplanation); ...
    localEvidenceRow("Pilot identity", ...
    sprintf("error REF=%+.2f; SURV=%+.2f", ...
    pilotErrorRow.CandidateReference, ...
    pilotErrorRow.CandidateSurveillance), ...
    "kHz", "absolute candidate error from expected ATSC pilot", ...
    sprintf("Each <= %.1f kHz", ...
    options.PilotFrequencyTolerance_kHz), ...
    "existing G2", pilotIdentityResult, pilotIdentityExplanation); ...
    localEvidenceRow("Pilot prominence", ...
    sprintf("REF=%.2f; SURV=%.2f", ...
    pilotProminenceRow.CandidateReference, ...
    pilotProminenceRow.CandidateSurveillance), ...
    "dB", "candidate pilot PSD above pilot-excluded data median", ...
    sprintf("Each >= %.1f dB", ...
    options.PilotProminenceThreshold_dB), ...
    "existing G2", pilotProminenceResult, ...
    pilotProminenceExplanation); ...
    localEvidenceRow("Clipping", ...
    sprintf("worst exact rails=%.0f; worst near rails=%.1f", ...
    worstExactRailCount, worstNearRailPpm), ...
    "samples; ppm", "worst selected candidate repetition and channel", ...
    sprintf("0 samples and < %.1f ppm", options.NearRailLimit_ppm), ...
    "existing G2", clippingResult, clippingExplanation); ...
    localEvidenceRow("Headroom", ...
    sprintf("minimum REF=%.2f; SURV=%.2f", ...
    referenceHeadroom, surveillanceHeadroom), ...
    "dB", "minimum selected candidate repetition per channel", ...
    sprintf("Warning below %.1f dB", ...
    options.HeadroomWarningThreshold_dB), ...
    "field-screen heuristic", headroomResult, headroomExplanation); ...
    localEvidenceRow("Observed reference-path trend", ...
    sprintf("RF1 band Delta=%+.2f; RF0 band Delta=%+.2f; " + ...
    "Delta(R-S)=%+.2f", ...
    bandPowerRow.DeltaReference, bandPowerRow.DeltaSurveillance, ...
    bandPowerRow.DeltaReferenceMinusSurveillance), ...
    "dB", "candidate minus baseline; positive favors candidate REF", ...
    sprintf("Improved >= +%.1f dB; worse <= -%.1f dB for both RF1 " + ...
    "and control-corrected band changes", ...
    options.MaterialChangeThreshold_dB, ...
    options.MaterialChangeThreshold_dB), ...
    "field-screen heuristic", trend, trendExplanation); ...
    localEvidenceRow("Localization suitability", ...
    "No G3 synchronization or G4 localization evidence analyzed", ...
    "not applicable", "outside this direct-path measurement scope", ...
    "Requires G3/G4 evidence", "informational", "NOT ASSESSED", ...
    "Direct-path RF measurements cannot establish localization suitability") ...
    ];

tableOut = struct2table(rows);

end

function row = localFindMetric(comparisonTable, metricId)

row = comparisonTable(comparisonTable.MetricId == metricId, :);

if height(row) ~= 1
    error("helperAnalyzeDirectPathQuickView:MissingMetric", ...
        "Expected exactly one comparison row for %s.", metricId);
end

end

function value = localChoose(condition, trueValue, falseValue)

if condition
    value = string(trueValue);
else
    value = string(falseValue);
end

end

function result = localClassifyThreeMetricChange(values, threshold)

if all(values >= threshold)
    result = "Better";
elseif all(values <= -threshold)
    result = "Worse";
else
    result = "Mixed / below threshold";
end

end

function explanation = localDescribeThreeMetricChange(result, subject)

switch result
    case "Better"
        explanation = subject + ...
            " improved by at least the material-change threshold in all " + ...
            "three amplitude measurements.";
    case "Worse"
        explanation = subject + ...
            " degraded by at least the material-change threshold in all " + ...
            "three amplitude measurements.";
    otherwise
        explanation = subject + ...
            " changes are mixed or below the material-change threshold.";
end

end

function result = localHeadroomResult(referenceHeadroom, ...
    surveillanceHeadroom, threshold)

referenceWarning = referenceHeadroom < threshold;
surveillanceWarning = surveillanceHeadroom < threshold;

if referenceWarning && surveillanceWarning
    result = "REF and SURV warning";
elseif referenceWarning
    result = "REF warning";
elseif surveillanceWarning
    result = "SURV warning";
else
    result = "Met";
end

end

function explanation = localHeadroomExplanation(result)

if result == "Met"
    explanation = ...
        "Both candidate channels retain the requested peak headroom.";
else
    explanation = ...
        "The named candidate channel falls below the headroom warning level.";
end

end

function result = localClassifyTrend(gainComparable, ...
    referenceBandDelta, relativeBandDelta, threshold)

if ~gainComparable
    result = "NOT ASSESSED";
elseif referenceBandDelta >= threshold && ...
        relativeBandDelta >= threshold
    result = "IMPROVED";
elseif referenceBandDelta <= -threshold && ...
        relativeBandDelta <= -threshold
    result = "WORSE";
elseif abs(referenceBandDelta) < threshold && ...
        abs(relativeBandDelta) < threshold
    result = "NO MATERIAL CHANGE";
else
    result = "MIXED";
end

end

function explanation = localTrendExplanation(result, referenceBandDelta, ...
    surveillanceBandDelta, relativeBandDelta)

if result == "NOT ASSESSED"
    explanation = ...
        "Manifest gain comparability is not established.";
    return
end

explanation = sprintf( ...
    "RF1 ATSC-band power changed %+.2f dB while RF0 changed " + ...
    "%+.2f dB; the control-corrected REF-SURV advantage changed " + ...
    "%+.2f dB.", ...
    referenceBandDelta, surveillanceBandDelta, relativeBandDelta);

end

