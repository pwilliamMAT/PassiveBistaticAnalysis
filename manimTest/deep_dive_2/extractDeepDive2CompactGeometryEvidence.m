function evidence = extractDeepDive2CompactGeometryEvidence(projectRoot, options)
%EXTRACTDEEPDIVE2COMPACTGEOMETRYEVIDENCE Write compact sequel geometry evidence.
%
%   EVIDENCE = EXTRACTDEEPDIVE2COMPACTGEOMETRYEVIDENCE(PROJECTROOT) reads
%   only the Trajectory structures in the two hash-verified saved field-
%   background result bundles. It verifies their common Tx/Rx geometry,
%   converts Tx and the initial target waypoints to receiver-local ENU with
%   a WGS-84 ellipsoid, and writes scalar JSON for Deep Dive 2.
%
%   The extractor never loads IQ, retained maps, detector replays, or
%   processing helpers. It neither changes detector settings nor runs the
%   passive-bistatic pipeline.

arguments
    projectRoot (1, 1) string {mustBeNonzeroLengthText} = ...
        string(fileparts(fileparts(fileparts(mfilename("fullpath")))))
    options.OutputDirectory (1, 1) string = fullfile( ...
        fileparts(mfilename("fullpath")), "deep_dive_2_data_v1")
    options.WriteJson (1, 1) logical = true
end

if ~isfolder(projectRoot)
    error("extractDeepDive2CompactGeometryEvidence:ProjectRoot", ...
        "Project root does not exist: %s.", projectRoot);
end

sourceSpecs = localSourceSpecs(projectRoot);
trajectories = repmat(localEmptyTrajectory(), numel(sourceSpecs), 1);
sourceRecords = repmat(localEmptySourceRecord(), numel(sourceSpecs), 1);

for sourceIndex = 1:numel(sourceSpecs)
    spec = sourceSpecs(sourceIndex);
    if ~isfile(spec.AbsolutePath)
        error("extractDeepDive2CompactGeometryEvidence:MissingSource", ...
            "Required saved result is missing: %s.", spec.AbsolutePath);
    end

    actualHash = localSha256File(spec.AbsolutePath);
    if actualHash ~= spec.ExpectedSha256
        error("extractDeepDive2CompactGeometryEvidence:SourceHash", ...
            "SHA-256 mismatch for %s.", spec.RelativePath);
    end

    loaded = load(spec.AbsolutePath, "results");
    if ~isfield(loaded, "results") || ...
            ~isfield(loaded.results, "Trajectory")
        error("extractDeepDive2CompactGeometryEvidence:Trajectory", ...
            "Saved result %s does not contain results.Trajectory.", ...
            spec.RelativePath);
    end

    trajectories(sourceIndex) = localValidateTrajectory( ...
        loaded.results.Trajectory, spec.RelativePath);
    sourceRecords(sourceIndex) = struct( ...
        Id=spec.Id, ...
        RelativePath=spec.RelativePath, ...
        Sha256=actualHash, ...
        Role=spec.Role);
end

if ~localEqualLla(trajectories(1).TxLla_deg_m, ...
        trajectories(2).TxLla_deg_m) || ...
        ~localEqualLla(trajectories(1).RxLla_deg_m, ...
        trajectories(2).RxLla_deg_m)
    error("extractDeepDive2CompactGeometryEvidence:SharedGeometry", ...
        "The 45 km and 15 km sources do not share their Tx/Rx geometry.");
end

receiverLla = trajectories(1).RxLla_deg_m;
transmitterEnu = localReceiverLocalEnu( ...
    trajectories(1).TxLla_deg_m, receiverLla);
scenarios = repmat(localEmptyScenarioRecord(), numel(trajectories), 1);
for scenarioIndex = 1:numel(trajectories)
    scenarios(scenarioIndex) = localScenarioRecord( ...
        sourceSpecs(scenarioIndex), trajectories(scenarioIndex), receiverLla);
end

detectorSupport = struct( ...
    Delay_us=[-1200.0, -150.0], ...
    Doppler_Hz=[-750.0, 750.0], ...
    Description="Frozen diagnostic detector support; unchanged by this extractor.");

evidence = struct( ...
    SchemaVersion="deep_dive_2_compact_geometry_v1", ...
    Purpose="Compact scalar geometry evidence for a code-drawn instructional sequel.", ...
    ExtractionBoundary= ...
    "Read only results.Trajectory; no IQ, maps, replay, pipeline run, or detector modification.", ...
    Sources=sourceRecords, ...
    SharedTxRxGeometry=true, ...
    PlanView=struct( ...
    CoordinateFrame="receiver_local_ENU", ...
    Receiver=struct("East_km", 0.0, "North_km", 0.0), ...
    AltitudeOmitted=true, ...
    Limitation="Horizontal receiver-local East/North plan view; altitude is omitted."), ...
    Transmitter=localKilometerRecord(transmitterEnu), ...
    DetectorSupport=detectorSupport, ...
    DisplayConvention=struct( ...
    Delay="tau_display = -tau_excess", ...
    Doppler="f_display = -f_bistatic", ...
    Limitation= ...
    "This project's display convention, not a universal passive-bistatic or CAF sign rule."), ...
    Scenarios=scenarios, ...
    ClaimBoundary=struct( ...
    PipelineRecomputation=false, ...
    DetectorRetuning=false, ...
    DetectorSupportWidening=false, ...
    FieldAircraftDetectionClaim=false, ...
    ObjectDetectionEmitted=false, ...
    TrackingClaim=false));

if options.WriteJson
    if ~isfolder(options.OutputDirectory)
        mkdir(options.OutputDirectory);
    end
    outputPath = fullfile(options.OutputDirectory, "compact_geometry.json");
    fileIdentifier = fopen(outputPath, "w", "n", "UTF-8");
    if fileIdentifier < 0
        error("extractDeepDive2CompactGeometryEvidence:Output", ...
            "Cannot write %s.", outputPath);
    end
    cleanup = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, "%s\n", jsonencode(evidence, PrettyPrint=true));
    clear cleanup
end
end

