prohibitedNames = [ ...
    "rawiq"; "samples"; "maplinear"; "fullmapcollection"; ...
    "objectdetection"; "objectdetections"];
paths = localFindProhibitedFields(result, "", prohibitedNames);
audit = struct();
audit.Compact = isempty(paths);
audit.RawIqPresent = any(contains(paths, ...
    "rawiq", IgnoreCase=true)) || ...
    any(contains(paths, ".samples", IgnoreCase=true));
audit.FullMapCollectionPresent = any(contains(paths, ...
    "maplinear", IgnoreCase=true)) || ...
    any(contains(paths, "fullmapcollection", IgnoreCase=true));
audit.ObjectDetectionPresent = any(contains(paths, ...
    "objectdetection", IgnoreCase=true));
audit.ProhibitedFieldPaths = paths;

end

function paths = localFindProhibitedFields( ...
    value, currentPath, prohibitedNames)

paths = strings(0, 1);

if isstruct(value)
    fieldNames = string(fieldnames(value));

    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(fieldNames)
            fieldName = fieldNames(fieldIndex);
            fieldPath = currentPath + "." + fieldName;

            if any(lower(fieldName) == prohibitedNames)
                paths(end + 1, 1) = fieldPath; %#ok<AGROW>
            end

            nestedPaths = localFindProhibitedFields( ...
                value(elementIndex).(fieldName), ...
                fieldPath, prohibitedNames);
            paths = [paths; nestedPaths]; %#ok<AGROW>
        end
    end
elseif istable(value)
    variableNames = string(value.Properties.VariableNames);

    for variableIndex = 1:numel(variableNames)
        if any(lower(variableNames(variableIndex)) == prohibitedNames)
            paths(end + 1, 1) = currentPath + "." + ...
                variableNames(variableIndex); %#ok<AGROW>
        end
    end
elseif iscell(value)
    for elementIndex = 1:numel(value)
        nestedPaths = localFindProhibitedFields( ...
            value{elementIndex}, currentPath + "{" + ...
            elementIndex + "}", prohibitedNames);
        paths = [paths; nestedPaths]; %#ok<AGROW>
    end
end

end

function tableOut = localStructRowsToTable(rows, emptyTableFunction)

if isempty(rows)
    tableOut = emptyTableFunction();
else
    tableOut = struct2table(rows);
end

end

