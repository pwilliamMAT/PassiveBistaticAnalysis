function [operatingRows, detectionRows, truthOpportunityRows, ...
    associationValid] = localAssociatePostHoc( ...
    operatingRows, detectionRows, mapTruth, metadata, configuration)

truthOpportunityRows = repmat( ...
    localTruthOpportunityRowTemplate(), 0, 1);
associationValid = true;

for pfaIndex = 1:numel(configuration.Pfa)
    detectionIndices = find( ...
        [detectionRows.PfaIndex].' == pfaIndex);
    [pairs, normalizedDelayError, normalizedDopplerError] = ...
        localMatchTruthToDetections( ...
        mapTruth, detectionRows, detectionIndices);

    for pairIndex = 1:size(pairs, 1)
        truthIndex = pairs(pairIndex, 1);
        localDetectionIndex = pairs(pairIndex, 2);
        detectionIndex = detectionIndices(localDetectionIndex);
        evidenceRole = mapTruth.EvidenceRole(truthIndex);

        if evidenceRole == "injected"
            associationRole = "target_hit";
        else
            associationRole = "nuisance_control_alarm";
        end

        detectionRows(detectionIndex).AssociationRole = ...
            associationRole;
        detectionRows(detectionIndex).TargetId = ...
            mapTruth.TargetId(truthIndex);
        detectionRows(detectionIndex).SourceCaseId = ...
            mapTruth.SourceCaseId(truthIndex);
        detectionRows(detectionIndex).NormalizedDelayError = ...
            normalizedDelayError(truthIndex, localDetectionIndex);
        detectionRows(detectionIndex).NormalizedDopplerError = ...
            normalizedDopplerError(truthIndex, localDetectionIndex);
        detectionRows(detectionIndex).AssociationCost = hypot( ...
            normalizedDelayError(truthIndex, localDetectionIndex), ...
            normalizedDopplerError(truthIndex, localDetectionIndex));
        detectionRows(detectionIndex).TruthUsedPostHoc = true;
    end

    injectedTruthIndices = find( ...
        mapTruth.EvidenceRole == "injected");

    for injectedIndex = 1:numel(injectedTruthIndices)
        truthIndex = injectedTruthIndices(injectedIndex);
        pairRow = find(pairs(:, 1) == truthIndex, 1, "first");
        opportunity = localTruthOpportunityRowTemplate();
        opportunity.MapId = metadata.MapId;
        opportunity.CampaignId = metadata.CampaignId;
        opportunity.BackgroundId = metadata.BackgroundId;
        opportunity.CaseId = metadata.CaseId;
        opportunity.SourceCaseId = ...
            mapTruth.SourceCaseId(truthIndex);
        opportunity.CandidateName = metadata.CandidateName;
        opportunity.WindowLabel = metadata.WindowLabel;
        opportunity.PfaIndex = double(pfaIndex);
        opportunity.Pfa = configuration.Pfa(pfaIndex);
        opportunity.TargetId = mapTruth.TargetId(truthIndex);
        opportunity.Callsign = mapTruth.Callsign(truthIndex);
        opportunity.GeometryClass = ...
            mapTruth.GeometryClass(truthIndex);
        opportunity.ExpectedDelay_s = double( ...
            mapTruth.ExpectedDelay_s(truthIndex));
        opportunity.ExpectedDoppler_Hz = double( ...
            mapTruth.ExpectedDoppler_Hz(truthIndex));
        opportunity.SearchDelayHalfExtent_s = double( ...
            mapTruth.SearchDelayHalfExtent_s(truthIndex));
        opportunity.SearchDopplerHalfExtent_Hz = double( ...
            mapTruth.SearchDopplerHalfExtent_Hz(truthIndex));
        opportunity.TruthUsedPostHoc = true;

        if ~isempty(pairRow)
            localDetectionIndex = pairs(pairRow, 2);
            detectionIndex = detectionIndices(localDetectionIndex);
            opportunity.Matched = true;
            opportunity.DetectionId = ...
                detectionRows(detectionIndex).DetectionId;
            opportunity.NormalizedDelayError = ...
                normalizedDelayError(truthIndex, localDetectionIndex);
            opportunity.NormalizedDopplerError = ...
                normalizedDopplerError( ...
                truthIndex, localDetectionIndex);
            opportunity.AssociationCost = hypot( ...
                opportunity.NormalizedDelayError, ...
                opportunity.NormalizedDopplerError);
        end

        truthOpportunityRows(end + 1, 1) = ...
            opportunity; %#ok<AGROW>
    end

    associationRoles = string( ...
        {detectionRows(detectionIndices).AssociationRole}).';
    operatingRows(pfaIndex).TargetOpportunityCount = ...
        double(numel(injectedTruthIndices));
    operatingRows(pfaIndex).TargetHitCount = ...
        double(nnz(associationRoles == "target_hit"));
    operatingRows(pfaIndex).ControlAlarmCount = ...
        double(nnz(associationRoles == ...
        "nuisance_control_alarm"));
    operatingRows(pfaIndex).UnmatchedDetectionCount = ...
        double(nnz(associationRoles == "unmatched"));
    operatingRows(pfaIndex).AssociationValid = true;

    if ~isempty(pairs)
        associationValid = associationValid && ...
            numel(unique(pairs(:, 1))) == size(pairs, 1) && ...
            numel(unique(pairs(:, 2))) == size(pairs, 1);
    end
end

end

function [pairs, normalizedDelayError, normalizedDopplerError] = ...
    localMatchTruthToDetections( ...
    mapTruth, detectionRows, detectionIndices)

truthCount = height(mapTruth);
detectionCount = numel(detectionIndices);
normalizedDelayError = inf(truthCount, detectionCount);
normalizedDopplerError = inf(truthCount, detectionCount);
pairs = zeros(0, 2);

if truthCount == 0 || detectionCount == 0
    return
end

detectionDelay_s = double( ...
    [detectionRows(detectionIndices).Delay_s]);
detectionDoppler_Hz = double( ...
    [detectionRows(detectionIndices).Doppler_Hz]);
normalizedDelayError = abs( ...
    double(mapTruth.ExpectedDelay_s) - detectionDelay_s) ./ ...
    double(mapTruth.SearchDelayHalfExtent_s);
normalizedDopplerError = abs( ...
    double(mapTruth.ExpectedDoppler_Hz) - detectionDoppler_Hz) ./ ...
    double(mapTruth.SearchDopplerHalfExtent_Hz);
valid = normalizedDelayError <= 1.0 & ...
    normalizedDopplerError <= 1.0;
cost = hypot(normalizedDelayError, normalizedDopplerError);
cost(~valid) = Inf;
pairs = matchpairs(cost, 2.0, "min");

if ~isempty(pairs)
    pairLinearIndices = sub2ind(size(cost), ...
        pairs(:, 1), pairs(:, 2));
    pairs = pairs(isfinite(cost(pairLinearIndices)), :);
end

end

function diagnosticRows = localBuildTruthCutDiagnostics( ...
    mapTruth, metadata, cutRows, cutColumns, cutPower, ...
    noiseEstimate, thresholdMatrix, peakCutIndices, delayAxis_s, ...
    dopplerAxis_Hz, configuration)

diagnosticRows = repmat(localTruthCutDiagnosticRowTemplate(), 0, 1);

for truthIndex = 1:height(mapTruth)
    [selectedRow, selectedColumn] = ...
        localSelectRepresentativeTruthCut( ...
        double(mapTruth.ExpectedDelay_s(truthIndex)), ...
        double(mapTruth.ExpectedDoppler_Hz(truthIndex)), ...
        double(mapTruth.SearchDelayHalfExtent_s(truthIndex)), ...
        double(mapTruth.SearchDopplerHalfExtent_Hz(truthIndex)), ...
        delayAxis_s, dopplerAxis_Hz);
    rowPosition = find(cutRows == selectedRow, 1);
    columnPosition = find(cutColumns == selectedColumn, 1);
    cutWithinDetectorSupport = ~isempty(rowPosition) && ...
        ~isempty(columnPosition);

    if cutWithinDetectorSupport
        cutIndex = sub2ind( ...
            [numel(cutRows), numel(cutColumns)], ...
            rowPosition, columnPosition);
    else
        cutIndex = NaN;
    end

    for pfaIndex = 1:numel(configuration.Pfa)
        diagnostic = localTruthCutDiagnosticRowTemplate();
        diagnostic.MapId = metadata.MapId;
        diagnostic.CampaignId = metadata.CampaignId;
        diagnostic.BackgroundId = metadata.BackgroundId;
        diagnostic.CaseId = metadata.CaseId;
        diagnostic.CandidateName = metadata.CandidateName;
        diagnostic.WindowLabel = metadata.WindowLabel;
        diagnostic.EvidenceRole = mapTruth.EvidenceRole(truthIndex);
        diagnostic.TargetId = mapTruth.TargetId(truthIndex);
        diagnostic.PfaIndex = double(pfaIndex);
        diagnostic.Pfa = configuration.Pfa(pfaIndex);
        diagnostic.ExpectedDelay_s = ...
            double(mapTruth.ExpectedDelay_s(truthIndex));
        diagnostic.ExpectedDoppler_Hz = ...
            double(mapTruth.ExpectedDoppler_Hz(truthIndex));
        diagnostic.SelectedRowIndex = double(selectedRow);
        diagnostic.SelectedColumnIndex = double(selectedColumn);
        diagnostic.SelectedCutDelay_s = delayAxis_s(selectedColumn);
        diagnostic.SelectedCutDoppler_Hz = dopplerAxis_Hz(selectedRow);
        diagnostic.TruthCenterWithinDetectorSupport = ...
            diagnostic.ExpectedDelay_s >= ...
            configuration.CutDelayLimits_s(1) && ...
            diagnostic.ExpectedDelay_s <= ...
            configuration.CutDelayLimits_s(2) && ...
            diagnostic.ExpectedDoppler_Hz >= ...
            configuration.CutDopplerLimits_Hz(1) && ...
            diagnostic.ExpectedDoppler_Hz <= ...
            configuration.CutDopplerLimits_Hz(2);
        diagnostic.CutWithinDetectorSupport = ...
            cutWithinDetectorSupport;
        diagnostic.TruthUsedPostHoc = true;

        if cutWithinDetectorSupport
            diagnostic.CutPowerLinear = cutPower(cutIndex);
            diagnostic.LocalNoiseEstimate = noiseEstimate(cutIndex);
            diagnostic.CfarThreshold = ...
                thresholdMatrix(cutIndex, pfaIndex);
            diagnostic.NmsRetained = any( ...
                peakCutIndices == cutIndex);
            diagnostic.DetectionPassesThreshold = ...
                diagnostic.CutPowerLinear > diagnostic.CfarThreshold;
        end

        diagnosticRows(end + 1, 1) = diagnostic; %#ok<AGROW>
    end
end

end

function [rowIndex, columnIndex] = localSelectRepresentativeTruthCut( ...
    expectedDelay_s, expectedDoppler_Hz, delayHalfExtent_s, ...
    dopplerHalfExtent_Hz, delayAxis_s, dopplerAxis_Hz)

delayCandidates = find(abs(delayAxis_s - expectedDelay_s) <= ...
    delayHalfExtent_s);

if isempty(delayCandidates)
    [~, columnIndex] = min(abs(delayAxis_s - expectedDelay_s));
else
    columnIndex = delayCandidates(end);
end

dopplerCandidates = find(abs(dopplerAxis_Hz - expectedDoppler_Hz) <= ...
    dopplerHalfExtent_Hz);

if isempty(dopplerCandidates)
    [~, rowIndex] = min(abs(dopplerAxis_Hz - expectedDoppler_Hz));
else
    [~, localIndex] = min(abs( ...
        dopplerAxis_Hz(dopplerCandidates) - expectedDoppler_Hz));
    rowIndex = dopplerCandidates(localIndex);
end

end

