function result = helperAnalyzeG6ProductDiscrimination( ...
    mapProducts, truthTable, context, priorResult)
%HELPERANALYZEG6PRODUCTDISCRIMINATION Run the fixed G6-D detector study.
%
%   RESULT = HELPERANALYZEG6PRODUCTDISCRIMINATION(MAPPRODUCTS, TRUTHTABLE,
%   CONTEXT) applies the preregistered CA-CFAR and nonmaximum-suppression
%   configuration to full G5 map products. Detection generation is
%   completed before TRUTHTABLE is consulted for post-hoc association.
%
%   RESULT = HELPERANALYZEG6PRODUCTDISCRIMINATION(..., PRIORRESULT)
%   appends compact rows to a prior result. Set CONTEXT.Finalize to false
%   for case-by-case accumulation and make a final call with empty maps,
%   CONTEXT.Finalize=true, and the accumulated result to produce campaign
%   summaries, integrity status, and the diagnostic recommendation.

arguments
    mapProducts = struct([])
    truthTable table = table()
    context (1,1) struct = struct()
    priorResult (1,1) struct = struct()
end

resolvedContext = localResolveContext(context, priorResult);
configuration = localResolveDetectorConfiguration(resolvedContext);
result = localInitializeResult(priorResult, configuration, ...
    resolvedContext);

try
    if strlength(resolvedContext.StructuralIssue) > 0
        error( ...
            "helperAnalyzeG6ProductDiscrimination:StructuralIssue", ...
            "%s", resolvedContext.StructuralIssue);
    end

    if ~isempty(mapProducts)
        if ~isstruct(mapProducts)
            error( ...
                "helperAnalyzeG6ProductDiscrimination:InvalidMapProducts", ...
                "Map products must be a struct array.");
        end

        batch = localAnalyzeMapBatch(mapProducts(:), truthTable, ...
            resolvedContext, configuration);
        result = localAppendBatch(result, batch);
    end
catch analysisException
    result = localRecordIssue(result, analysisException);
end

result = localFinalizeResult(result, resolvedContext, configuration);

end

function configuration = localBuildConfiguration()

configuration = helperBuildG6DDetectorConfiguration();

end

function configuration = localResolveDetectorConfiguration(context)

configuration = localBuildConfiguration();

if isfield(context, "DetectorConfiguration") && ...
        ~isempty(context.DetectorConfiguration)
    configuration = context.DetectorConfiguration;
end

localValidateDetectorConfiguration(configuration);

end

function localValidateDetectorConfiguration(configuration)

baseline = localBuildConfiguration();
requiredFields = [ ...
    "SchemaVersion"; "CandidateNames"; "CutDelayLimits_s"; ...
    "CutDopplerLimits_Hz"; "ExpectedCutCount"; "GuardBandSize"; ...
    "TrainingBandSize"; "TrainingCellCount"; "Pfa"; "Alpha"; ...
    "NmsNeighborhood"; "AxisOrientation"; "CfarMethod"; ...
    "AssociationMethod"; "DetectionGenerationTruthBlind"; ...
    "TruthUse"; "ConfigurationMode"; "IsBaseline"; ...
    "SupportStatus"; "ActualCutCount"; "BaselineConfiguration"];

for fieldIndex = 1:numel(requiredFields)
    if ~isfield(configuration, requiredFields(fieldIndex))
        error( ...
            "helperAnalyzeG6ProductDiscrimination:DetectorConfiguration", ...
            "Detector configuration is missing %s.", ...
            requiredFields(fieldIndex));
    end
end

baselineFields = [ ...
    "SchemaVersion"; "CandidateNames"; "GuardBandSize"; ...
    "TrainingBandSize"; "TrainingCellCount"; "Pfa"; "Alpha"; ...
    "NmsNeighborhood"; "AxisOrientation"; "CfarMethod"; ...
    "AssociationMethod"; "DetectionGenerationTruthBlind"; "TruthUse"];

for fieldIndex = 1:numel(baselineFields)
    fieldName = baselineFields(fieldIndex);
    if ~isequal(configuration.(fieldName), baseline.(fieldName))
        error( ...
            "helperAnalyzeG6ProductDiscrimination:DetectorConfiguration", ...
            "Only detector support rectangles may differ from G6-D baseline.");
    end
end

if configuration.IsBaseline
    if configuration.ConfigurationMode ~= "baseline" || ...
            ~isequal(configuration.CutDelayLimits_s, ...
            baseline.CutDelayLimits_s) || ...
            ~isequal(configuration.CutDopplerLimits_Hz, ...
            baseline.CutDopplerLimits_Hz) || ...
            configuration.ExpectedCutCount ~= baseline.ExpectedCutCount
        error( ...
            "helperAnalyzeG6ProductDiscrimination:DetectorConfiguration", ...
            "Baseline detector configuration must exactly match G6-D.");
    end
else
    if configuration.ConfigurationMode ~= ...
            "exploratory_support_override" || ...
            ~isnan(configuration.ExpectedCutCount)
        error( ...
            "helperAnalyzeG6ProductDiscrimination:DetectorConfiguration", ...
            "Non-baseline support requires the explicit exploratory contract.");
    end
end

if numel(configuration.CutDelayLimits_s) ~= 2 || ...
        configuration.CutDelayLimits_s(1) >= ...
        configuration.CutDelayLimits_s(2) || ...
        numel(configuration.CutDopplerLimits_Hz) ~= 2 || ...
        configuration.CutDopplerLimits_Hz(1) >= ...
        configuration.CutDopplerLimits_Hz(2)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:DetectorConfiguration", ...
        "Detector support limits must be strictly increasing pairs.");
end

end

function context = localResolveContext(inputContext, priorResult)

context = struct();
context.CampaignId = "";
context.BackgroundId = "";
context.CaseId = "";
context.Finalize = true;
context.EnforceCampaignCounts = false;
context.ExpectedMapCount = NaN;
context.ExpectedOperatingPointCount = NaN;
context.ExpectedTruthOpportunityCount = NaN;
context.StructuralIssue = "";

if ~isempty(fieldnames(priorResult)) && ...
        isfield(priorResult, "CampaignId")
    context.CampaignId = string(priorResult.CampaignId);
end

fieldNames = fieldnames(inputContext);

for fieldIndex = 1:numel(fieldNames)
    fieldName = fieldNames{fieldIndex};
    context.(fieldName) = inputContext.(fieldName);
end

context.CampaignId = string(context.CampaignId);
context.BackgroundId = string(context.BackgroundId);
context.CaseId = string(context.CaseId);
context.Finalize = logical(context.Finalize);
context.EnforceCampaignCounts = logical( ...
    context.EnforceCampaignCounts);
context.ExpectedMapCount = double(context.ExpectedMapCount);
context.ExpectedOperatingPointCount = double( ...
    context.ExpectedOperatingPointCount);
context.ExpectedTruthOpportunityCount = double( ...
    context.ExpectedTruthOpportunityCount);
context.StructuralIssue = string(context.StructuralIssue);

end

function result = localInitializeResult( ...
    priorResult, configuration, context)

if isempty(fieldnames(priorResult))
    result = struct();
    result.SchemaVersion = ...
        "g6_product_discrimination_compact_v1";
    result.StageId = "G6_Product_Discrimination";
    result.CampaignId = context.CampaignId;
    result.Configuration = configuration;
    result.MapTable = localEmptyMapTable();
    result.OperatingPointTable = localEmptyOperatingPointTable();
    result.TruthOpportunityTable = localEmptyTruthOpportunityTable();
    result.TruthCutDiagnosticTable = ...
        localEmptyTruthCutDiagnosticTable();
    result.DetectionTable = localEmptyDetectionTable();
    result.ProductBackgroundSummaryTable = ...
        localEmptyProductBackgroundSummaryTable();
    result.PairedProductDeltaTable = ...
        localEmptyPairedProductDeltaTable();
    result.IntegrityIssues = strings(0, 1);
else
    result = priorResult;
    localValidatePriorResult(result, configuration);
end

if strlength(result.CampaignId) == 0
    result.CampaignId = context.CampaignId;
end

result.Finalized = false;
result.Recommendation = "pending";
result.RecommendationRationale = ...
    "Case-level compact rows are awaiting final aggregation.";
result.FormalG6FreezeEnabled = false;
result.FormalG8DetectionEnabled = false;
result.ObjectDetectionsEmitted = false;
result.TrackingStarted = false;

end

function localValidatePriorResult(result, configuration)

requiredFields = [ ...
    "Configuration"; "MapTable"; "OperatingPointTable"; ...
    "TruthOpportunityTable"; "TruthCutDiagnosticTable"; ...
    "DetectionTable"; ...
    "IntegrityIssues"];

for fieldIndex = 1:numel(requiredFields)
    if ~isfield(result, requiredFields(fieldIndex))
        error( ...
            "helperAnalyzeG6ProductDiscrimination:InvalidPriorResult", ...
            "Prior result is missing %s.", requiredFields(fieldIndex));
    end
end

semanticFields = [ ...
    "Pfa"; "GuardBandSize"; "TrainingBandSize"; ...
    "CutDelayLimits_s"; "CutDopplerLimits_Hz"; ...
    "NmsNeighborhood"; "ConfigurationMode"; "IsBaseline"];

for fieldIndex = 1:numel(semanticFields)
    fieldName = semanticFields(fieldIndex);
    if ~isequaln(result.Configuration.(fieldName), ...
            configuration.(fieldName))
        error( ...
            "helperAnalyzeG6ProductDiscrimination:ConfigurationMismatch", ...
            "Prior compact rows use a different detector configuration.");
    end
end

if ~isequal(result.Configuration.CandidateNames, ...
        configuration.CandidateNames) || ...
        ~isequal(result.Configuration.Alpha, configuration.Alpha)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:ConfigurationMismatch", ...
        "Prior compact rows use a different detector configuration.");
end

end

function truthTable = localNormalizeTruthTable(truthTable)

if isempty(truthTable)
    truthTable = localEmptyInputTruthTable();
    return
end

requiredVariables = [ ...
    "BackgroundId"; "CaseId"; "CandidateName"; "WindowLabel"; ...
    "EvidenceRole"; "TargetId"; "ExpectedDelay_s"; ...
    "ExpectedDoppler_Hz"; "SearchDelayHalfExtent_s"; ...
    "SearchDopplerHalfExtent_Hz"];
availableVariables = string(truthTable.Properties.VariableNames);
missingVariables = setdiff(requiredVariables, availableVariables);

if ~isempty(missingVariables)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:MissingTruthVariables", ...
        "Truth table is missing variables: %s.", ...
        strjoin(missingVariables, ", "));
end

stringVariables = [ ...
    "BackgroundId"; "CaseId"; "CandidateName"; "WindowLabel"; ...
    "EvidenceRole"; "TargetId"];

for variableIndex = 1:numel(stringVariables)
    variableName = stringVariables(variableIndex);
    truthTable.(variableName) = string(truthTable.(variableName));
end

truthTable = localAddOptionalStringVariable( ...
    truthTable, "SourceCaseId");
truthTable = localAddOptionalStringVariable(truthTable, "Callsign");
truthTable = localAddOptionalStringVariable( ...
    truthTable, "GeometryClass");
validRoles = ismember(truthTable.EvidenceRole, ...
    ["injected"; "matched_control"]);
numericValues = [ ...
    double(truthTable.ExpectedDelay_s), ...
    double(truthTable.ExpectedDoppler_Hz), ...
    double(truthTable.SearchDelayHalfExtent_s), ...
    double(truthTable.SearchDopplerHalfExtent_Hz)];

if any(~validRoles) || any(~isfinite(numericValues), "all") || ...
        any(truthTable.SearchDelayHalfExtent_s <= 0.0) || ...
        any(truthTable.SearchDopplerHalfExtent_Hz <= 0.0)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidTruthTable", ...
        "Truth rows require recognized roles, finite coordinates, and positive search half-extents.");
end

end

function truthTable = localEmptyInputTruthTable()

truthTable = table( ...
    strings(0, 1), strings(0, 1), strings(0, 1), ...
    strings(0, 1), strings(0, 1), strings(0, 1), ...
    zeros(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
    strings(0, 1), strings(0, 1), strings(0, 1), ...
    VariableNames={ ...
    'BackgroundId', 'CaseId', 'CandidateName', 'WindowLabel', ...
    'EvidenceRole', 'TargetId', 'ExpectedDelay_s', ...
    'ExpectedDoppler_Hz', 'SearchDelayHalfExtent_s', ...
    'SearchDopplerHalfExtent_Hz', 'SourceCaseId', 'Callsign', ...
    'GeometryClass'});

end

function tableOut = localAddOptionalStringVariable( ...
    tableIn, variableName)

tableOut = tableIn;

if ismember(variableName, string(tableOut.Properties.VariableNames))
    tableOut.(variableName) = string(tableOut.(variableName));
else
    tableOut = addvars(tableOut, strings(height(tableOut), 1), ...
        NewVariableNames=variableName);
end

end

function batch = localAnalyzeMapBatch( ...
    mapProducts, truthTable, context, configuration)

mapRows = repmat(localMapRowTemplate(), numel(mapProducts), 1);
operatingRows = repmat(localOperatingPointRowTemplate(), 0, 1);
detectionRows = repmat(localDetectionRowTemplate(), 0, 1);
truthOpportunityRows = repmat( ...
    localTruthOpportunityRowTemplate(), 0, 1);
truthCutDiagnosticRows = repmat( ...
    localTruthCutDiagnosticRowTemplate(), 0, 1);

for mapIndex = 1:numel(mapProducts)
    [mapRow, mapOperatingRows, mapDetectionRows, ...
        mapTruthOpportunityRows, mapTruthCutDiagnosticRows] = ...
        localAnalyzeOneMap( ...
        mapProducts(mapIndex), truthTable, context, configuration);
    mapRows(mapIndex) = mapRow;
    operatingRows = [operatingRows; ...
        mapOperatingRows(:)]; %#ok<AGROW>
    detectionRows = [detectionRows; ...
        mapDetectionRows(:)]; %#ok<AGROW>
    truthOpportunityRows = [truthOpportunityRows; ...
        mapTruthOpportunityRows(:)]; %#ok<AGROW>
    truthCutDiagnosticRows = [truthCutDiagnosticRows; ...
        mapTruthCutDiagnosticRows(:)]; %#ok<AGROW>
end

batch = struct();
batch.MapTable = struct2table(mapRows);
batch.OperatingPointTable = localStructRowsToTable( ...
    operatingRows, @localEmptyOperatingPointTable);
batch.DetectionTable = localStructRowsToTable( ...
    detectionRows, @localEmptyDetectionTable);
batch.TruthOpportunityTable = localStructRowsToTable( ...
    truthOpportunityRows, @localEmptyTruthOpportunityTable);
batch.TruthCutDiagnosticTable = localStructRowsToTable( ...
    truthCutDiagnosticRows, @localEmptyTruthCutDiagnosticTable);

end

function [mapRow, operatingRows, detectionRows, ...
    truthOpportunityRows, truthCutDiagnosticRows] = localAnalyzeOneMap( ...
    mapProduct, truthTable, context, configuration)

[mapLinear, delayAxis_s, dopplerAxis_Hz, mapMetadata] = ...
    localValidateAndNormalizeMap(mapProduct, context, configuration);
[cutRows, cutColumns, cutIndices] = localBuildCutIndices( ...
    delayAxis_s, dopplerAxis_Hz, configuration);
noiseEstimate = localEstimateCfarNoise( ...
    mapLinear, cutIndices, configuration);
cutPower = double(mapLinear(cutIndices(1, :) + ...
    (cutIndices(2, :) - 1) .* size(mapLinear, 1))).';
noiseEstimate = double(noiseEstimate(:));
thresholdMatrix = noiseEstimate .* configuration.Alpha.';
peakCutIndices = localFindNmsPeaks( ...
    mapLinear, cutRows, cutColumns, configuration);
[operatingRows, detectionRows] = ...
    localGenerateTruthBlindDetections( ...
    mapMetadata, cutIndices, cutPower, noiseEstimate, ...
    thresholdMatrix, peakCutIndices, delayAxis_s, dopplerAxis_Hz, ...
    configuration);
normalizedTruth = localNormalizeTruthTable(truthTable);
mapTruth = localSelectMapTruth(normalizedTruth, mapMetadata);
[operatingRows, detectionRows, truthOpportunityRows, ...
    associationValid] = localAssociatePostHoc( ...
    operatingRows, detectionRows, mapTruth, mapMetadata, ...
    configuration);
truthCutDiagnosticRows = localBuildTruthCutDiagnostics( ...
    mapTruth, mapMetadata, cutRows, cutColumns, ...
    cutPower, noiseEstimate, thresholdMatrix, peakCutIndices, ...
    delayAxis_s, dopplerAxis_Hz, configuration);
detectionCounts = double([operatingRows.DetectionCount]).';
thresholdMonotonic = all(diff(thresholdMatrix, 1, 2) >= 0.0, "all");
detectionCountMonotonic = all(diff(detectionCounts) <= 0.0);
mapRow = localMapRowTemplate();
mapRow.MapId = mapMetadata.MapId;
mapRow.CampaignId = mapMetadata.CampaignId;
mapRow.BackgroundId = mapMetadata.BackgroundId;
mapRow.CaseId = mapMetadata.CaseId;
mapRow.CandidateName = mapMetadata.CandidateName;
mapRow.WindowLabel = mapMetadata.WindowLabel;
mapRow.MapRows = double(size(mapLinear, 1));
mapRow.MapColumns = double(size(mapLinear, 2));
mapRow.CutRowCount = double(numel(cutRows));
mapRow.CutColumnCount = double(numel(cutColumns));
mapRow.CutCount = double(size(cutIndices, 2));
mapRow.CutDelayMinimum_s = delayAxis_s(cutColumns(1));
mapRow.CutDelayMaximum_s = delayAxis_s(cutColumns(end));
mapRow.CutDopplerMinimum_Hz = dopplerAxis_Hz(cutRows(1));
mapRow.CutDopplerMaximum_Hz = dopplerAxis_Hz(cutRows(end));
mapRow.DelayAxisStart_s = delayAxis_s(1);
mapRow.DelayAxisEnd_s = delayAxis_s(end);
mapRow.DelayAxisSpacing_s = median(diff(delayAxis_s));
mapRow.DopplerAxisStart_Hz = dopplerAxis_Hz(1);
mapRow.DopplerAxisEnd_Hz = dopplerAxis_Hz(end);
mapRow.DopplerAxisSpacing_Hz = median(diff(dopplerAxis_Hz));
mapRow.CfarCallCount = 1.0;
mapRow.NoiseEstimateFinite = all(isfinite(noiseEstimate));
mapRow.NoiseEstimateNonnegative = all(noiseEstimate >= 0.0);
mapRow.ThresholdMonotonic = thresholdMonotonic;
mapRow.DetectionCountMonotonic = detectionCountMonotonic;
mapRow.InjectedTruthCount = double(nnz( ...
    mapTruth.EvidenceRole == "injected"));
mapRow.ControlTruthCount = double(nnz( ...
    mapTruth.EvidenceRole == "matched_control"));
mapRow.AssociationValid = associationValid;
mapRow.MapFinite = true;
mapRow.MapNonnegative = true;
mapRow.AxesIncreasing = true;
mapRow.AxisOrientation = configuration.AxisOrientation;

end

function [mapLinear, delayAxis_s, dopplerAxis_Hz, metadata] = ...
    localValidateAndNormalizeMap(mapProduct, context, configuration)

requiredFields = [ ...
    "CandidateName"; "WindowLabel"; "MapLinear"; ...
    "DelayAxis_s"; "DopplerAxis_Hz"];

for fieldIndex = 1:numel(requiredFields)
    if ~isfield(mapProduct, requiredFields(fieldIndex))
        error( ...
            "helperAnalyzeG6ProductDiscrimination:MissingMapField", ...
            "Map product is missing %s.", requiredFields(fieldIndex));
    end
end

mapLinear = mapProduct.MapLinear;
delayAxis_s = double(mapProduct.DelayAxis_s(:).');
dopplerAxis_Hz = double(mapProduct.DopplerAxis_Hz(:));

if ~isnumeric(mapLinear) || ~isreal(mapLinear) || ...
        isempty(mapLinear) || ~ismatrix(mapLinear)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidMap", ...
        "MapLinear must be a nonempty real numeric matrix.");
end

if any(~isfinite(mapLinear), "all") || ...
        any(mapLinear < 0.0, "all")
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidMap", ...
        "MapLinear must contain finite nonnegative power.");
end

if numel(delayAxis_s) ~= size(mapLinear, 2) || ...
        numel(dopplerAxis_Hz) ~= size(mapLinear, 1)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:MapAxisMismatch", ...
        "Map rows must match Doppler and columns must match delay.");
end

if any(~isfinite(delayAxis_s)) || ...
        any(~isfinite(dopplerAxis_Hz)) || ...
        any(diff(delayAxis_s) <= 0.0) || ...
        any(diff(dopplerAxis_Hz) <= 0.0)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidAxes", ...
        "Map axes must be finite and strictly increasing.");
end

candidateName = string(mapProduct.CandidateName);

if ~isscalar(candidateName) || ...
        ~ismember(candidateName, configuration.CandidateNames)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidCandidate", ...
        "Map candidate must be one of the fixed G5 products.");
end

axisOrientation = localMapString(mapProduct, ...
    "AxisOrientation", configuration.AxisOrientation);

if axisOrientation ~= configuration.AxisOrientation
    error( ...
        "helperAnalyzeG6ProductDiscrimination:AxisOrientation", ...
        "Map orientation must be rows Doppler and columns delay.");
end

metadata = struct();
metadata.CampaignId = localMapString( ...
    mapProduct, "CampaignId", context.CampaignId);
metadata.BackgroundId = localMapString( ...
    mapProduct, "BackgroundId", context.BackgroundId);
metadata.CaseId = localMapString( ...
    mapProduct, "CaseId", context.CaseId);
metadata.CandidateName = candidateName;
metadata.WindowLabel = string(mapProduct.WindowLabel);

if strlength(metadata.BackgroundId) == 0 || ...
        strlength(metadata.CaseId) == 0 || ...
        strlength(metadata.WindowLabel) == 0
    error( ...
        "helperAnalyzeG6ProductDiscrimination:MissingMapIdentity", ...
        "Each map requires background, case, candidate, and window identity.");
end

metadata.MapId = metadata.BackgroundId + "|" + ...
    metadata.CaseId + "|" + metadata.CandidateName + "|" + ...
    metadata.WindowLabel;

end

function value = localMapString(inputStruct, fieldName, defaultValue)

value = string(defaultValue);

if isfield(inputStruct, fieldName)
    candidate = string(inputStruct.(fieldName));

    if isscalar(candidate)
        value = candidate;
    end
end

end

function [cutRows, cutColumns, cutIndices] = localBuildCutIndices( ...
    delayAxis_s, dopplerAxis_Hz, configuration)

cutRows = find(dopplerAxis_Hz >= ...
    configuration.CutDopplerLimits_Hz(1) & ...
    dopplerAxis_Hz <= configuration.CutDopplerLimits_Hz(2));
cutColumns = find(delayAxis_s >= ...
    configuration.CutDelayLimits_s(1) & ...
    delayAxis_s <= configuration.CutDelayLimits_s(2));
cutCount = numel(cutRows) .* numel(cutColumns);

if isempty(cutRows) || isempty(cutColumns)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:CutCount", ...
        "The detector support rectangle contains no CUTs.");
end

if configuration.IsBaseline && ...
        ~isequal(cutCount, double(configuration.ExpectedCutCount(1)))
    error( ...
        "helperAnalyzeG6ProductDiscrimination:CutCount", ...
        "The baseline CUT region must contain exactly %d cells; found %d.", ...
        configuration.ExpectedCutCount, cutCount);
end

rowMargin = sum(configuration.GuardBandSize(1) + ...
    configuration.TrainingBandSize(1));
columnMargin = sum(configuration.GuardBandSize(2) + ...
    configuration.TrainingBandSize(2));

if cutRows(1) <= rowMargin || ...
        cutRows(end) > numel(dopplerAxis_Hz) - rowMargin || ...
        cutColumns(1) <= columnMargin || ...
        cutColumns(end) > numel(delayAxis_s) - columnMargin
    error( ...
        "helperAnalyzeG6ProductDiscrimination:CfarGeometry", ...
        "The map does not provide the fixed CFAR training margin around every CUT.");
end

[cutRowGrid, cutColumnGrid] = ndgrid(cutRows, cutColumns);
cutIndices = double([cutRowGrid(:).'; cutColumnGrid(:).']);

end

function noiseEstimate = localEstimateCfarNoise( ...
    mapLinear, cutIndices, configuration)

if exist("phased.CFARDetector2D", "class") ~= 8
    error( ...
        "helperAnalyzeG6ProductDiscrimination:MissingCfarDetector", ...
        "G6-D requires phased.CFARDetector2D.");
end

cfarDetector = phased.CFARDetector2D( ...
    Method=configuration.CfarMethod, ...
    GuardBandSize=configuration.GuardBandSize, ...
    TrainingBandSize=configuration.TrainingBandSize, ...
    ThresholdFactor="Custom", ...
    CustomThresholdFactor=1.0, ...
    NoisePowerOutputPort=true);
[~, noiseEstimate] = cfarDetector(mapLinear, cutIndices);

if numel(noiseEstimate) ~= size(cutIndices, 2) || ...
        any(~isfinite(noiseEstimate)) || ...
        any(noiseEstimate < 0.0)
    error( ...
        "helperAnalyzeG6ProductDiscrimination:InvalidNoiseEstimate", ...
        "CA-CFAR returned an invalid noise estimate.");
end

end

function peakCutIndices = localFindNmsPeaks( ...
    mapLinear, cutRows, cutColumns, configuration)

if exist("imdilate", "file") ~= 2
    error( ...
        "helperAnalyzeG6ProductDiscrimination:MissingImdilate", ...
        "G6-D requires imdilate.");
end

rowRadius = floor(configuration.NmsNeighborhood(1) ./ 2.0);
columnRadius = floor(configuration.NmsNeighborhood(2) ./ 2.0);
cropRows = (cutRows(1) - rowRadius):(cutRows(end) + rowRadius);
cropColumns = (cutColumns(1) - columnRadius): ...
    (cutColumns(end) + columnRadius);
mapCrop = mapLinear(cropRows, cropColumns);
dilatedCrop = imdilate(mapCrop, true( ...
    configuration.NmsNeighborhood));
cutMap = mapLinear(cutRows, cutColumns);
dilatedCut = dilatedCrop( ...
    rowRadius + (1:numel(cutRows)), ...
    columnRadius + (1:numel(cutColumns)));
localMaximumMask = cutMap == dilatedCut;
components = bwconncomp(localMaximumMask, 8);
peakCutIndices = zeros(components.NumObjects, 1);

for componentIndex = 1:components.NumObjects
    [componentRows, componentColumns] = ind2sub( ...
        size(localMaximumMask), ...
        components.PixelIdxList{componentIndex});
    orderedCoordinates = sortrows( ...
        [componentRows(:), componentColumns(:)], [1, 2]);
    peakCutIndices(componentIndex) = sub2ind( ...
        size(localMaximumMask), ...
        orderedCoordinates(1, 1), orderedCoordinates(1, 2));
end

peakCutIndices = sort(peakCutIndices);

end

function [operatingRows, detectionRows] = ...
    localGenerateTruthBlindDetections( ...
    metadata, cutIndices, cutPower, noiseEstimate, thresholdMatrix, ...
    peakCutIndices, delayAxis_s, dopplerAxis_Hz, configuration)

pfaCount = numel(configuration.Pfa);
operatingRows = repmat(localOperatingPointRowTemplate(), ...
    pfaCount, 1);
detectionRows = repmat(localDetectionRowTemplate(), 0, 1);

for pfaIndex = 1:pfaCount
    threshold = thresholdMatrix(:, pfaIndex);
    selectedPeakIndices = peakCutIndices( ...
        cutPower(peakCutIndices) > threshold(peakCutIndices));
    operatingRow = localOperatingPointRowTemplate();
    operatingRow.MapId = metadata.MapId;
    operatingRow.CampaignId = metadata.CampaignId;
    operatingRow.BackgroundId = metadata.BackgroundId;
    operatingRow.CaseId = metadata.CaseId;
    operatingRow.CandidateName = metadata.CandidateName;
    operatingRow.WindowLabel = metadata.WindowLabel;
    operatingRow.PfaIndex = double(pfaIndex);
    operatingRow.Pfa = configuration.Pfa(pfaIndex);
    operatingRow.Alpha = configuration.Alpha(pfaIndex);
    operatingRow.CutCount = double(numel(cutPower));
    operatingRow.ThresholdMinimum = min(threshold);
    operatingRow.ThresholdMedian = median(threshold);
    operatingRow.ThresholdMaximum = max(threshold);
    operatingRow.DetectionCount = double(numel(selectedPeakIndices));
    operatingRow.DetectionGeneratedTruthBlind = true;
    operatingRows(pfaIndex) = operatingRow;

    for detectionOrdinal = 1:numel(selectedPeakIndices)
        cutIndex = selectedPeakIndices(detectionOrdinal);
        rowIndex = cutIndices(1, cutIndex);
        columnIndex = cutIndices(2, cutIndex);
        detectionRow = localDetectionRowTemplate();
        detectionRow.DetectionId = metadata.MapId + "|pfa_" + ...
            compose("%02d", pfaIndex) + "|detection_" + ...
            compose("%05d", detectionOrdinal);
