    "MapRows"; "MapColumns"; "DelayAxisStart_s"; ...
    "DelayAxisEnd_s"; "DelayAxisSpacing_s"; ...
    "DopplerAxisStart_Hz"; "DopplerAxisEnd_Hz"; ...
    "DopplerAxisSpacing_Hz"];

