    double(expectedOperatingPointCount);
integrity.ObservedOperatingPointCount = ...
    double(height(operatingTable));
integrity.ExpectedTruthOpportunityCount = ...
    double(expectedTruthOpportunityCount);
integrity.ObservedTruthOpportunityCount = ...
    double(height(truthTable));
integrity.TruthUsedOnlyPostHoc = true;
integrity.DetectionGenerationTruthBlind = true;
integrity.RawIqRetained = false;
integrity.FullMapCollectionRetained = false;
integrity.ObjectDetectionsEmitted = false;
