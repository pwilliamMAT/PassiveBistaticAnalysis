function deltaTable = localBuildPairedProductDeltas( ...
    summaryTable, configuration)

if isempty(summaryTable)
    deltaTable = localEmptyPairedProductDeltaTable();
    return
end

backgroundIds = unique(summaryTable.BackgroundId, "stable");
pairCountPerCell = numel(configuration.CandidateNames) .* ...
    (numel(configuration.CandidateNames) - 1);
rowCount = numel(backgroundIds) .* ...
    numel(configuration.Pfa) .* pairCountPerCell;
rows = repmat(localPairedProductDeltaRowTemplate(), rowCount, 1);
rowIndex = 0;

for backgroundIndex = 1:numel(backgroundIds)
    backgroundId = backgroundIds(backgroundIndex);

    for pfaIndex = 1:numel(configuration.Pfa)
        for candidateIndex = 1:numel(configuration.CandidateNames)
            candidateName = ...
                configuration.CandidateNames(candidateIndex);

            for comparatorIndex = 1:numel(configuration.CandidateNames)
                comparatorName = ...
                    configuration.CandidateNames(comparatorIndex);

                if candidateName == comparatorName
                    continue
                end

                candidate = summaryTable( ...
                    summaryTable.BackgroundId == backgroundId & ...
                    summaryTable.CandidateName == candidateName & ...
                    summaryTable.PfaIndex == pfaIndex, :);
                comparator = summaryTable( ...
                    summaryTable.BackgroundId == backgroundId & ...
                    summaryTable.CandidateName == comparatorName & ...
                    summaryTable.PfaIndex == pfaIndex, :);
                targetHitDelta = candidate.TargetHitCount - ...
                    comparator.TargetHitCount;
                controlAlarmDelta = candidate.ControlAlarmCount - ...
                    comparator.ControlAlarmCount;
                noWorse = targetHitDelta >= 0.0 && ...
                    controlAlarmDelta <= 0.0;
                strictlyBetter = targetHitDelta > 0.0 || ...
                    controlAlarmDelta < 0.0;
                rowIndex = rowIndex + 1;
                rows(rowIndex) = struct( ...
                    "BackgroundId", backgroundId, ...
                    "PfaIndex", double(pfaIndex), ...
                    "Pfa", configuration.Pfa(pfaIndex), ...
                    "CandidateName", candidateName, ...
                    "ComparatorName", comparatorName, ...
                    "TargetHitDelta", double(targetHitDelta), ...
                    "ControlAlarmDelta", ...
                    double(controlAlarmDelta), ...
                    "NoWorseAtCell", noWorse, ...
                    "StrictlyBetterAtCell", ...
                    noWorse && strictlyBetter);
            end
        end
    end
end

deltaTable = struct2table(rows);

end

function [recommendation, rationale] = localBuildRecommendation( ...
    summaryTable, deltaTable, integrity, configuration)

if ~integrity.AllPassed
    recommendation = "blocked";
    rationale = ...
        "At least one structural, count, map, axis, CFAR, or association integrity check failed.";
    return
end

if sum(summaryTable.TargetHitCount) == 0.0
    recommendation = "insufficient";
    rationale = ...
        "The complete valid sweep produced no matched truth detections.";
    return
end

robustDominance = false(numel(configuration.CandidateNames), 1);

for candidateIndex = 1:numel(configuration.CandidateNames)
    candidateName = configuration.CandidateNames(candidateIndex);
    candidateRows = deltaTable( ...
        deltaTable.CandidateName == candidateName, :);
    robustDominance(candidateIndex) = ...
        all(candidateRows.NoWorseAtCell) && ...
        any(candidateRows.StrictlyBetterAtCell);
end

exactTie = localAllProductsExactlyTied(summaryTable, configuration);
dominantProducts = configuration.CandidateNames(robustDominance);

if isscalar(dominantProducts) && ...
        dominantProducts == "conservative_lms"
    recommendation = "conservative";
    rationale = ...
        "Conservative LMS is no worse in target hits and control alarms in every background/Pfa cell and is strictly better in at least one cell.";
elseif isscalar(dominantProducts) && ...
        dominantProducts == "aggressive_lms"
    recommendation = "aggressive";
    rationale = ...
        "Aggressive LMS is no worse in target hits and control alarms in every background/Pfa cell and is strictly better in at least one cell.";
elseif isscalar(dominantProducts) && dominantProducts == "none"
    recommendation = "none";
    rationale = ...
        "No mitigation robustly dominates both LMS alternatives.";
elseif exactTie
    recommendation = "none";
    rationale = ...
        "All products are exactly tied and the sweep contains usable target detections.";
else
    recommendation = "retune";
    rationale = ...
        "Valid informative evidence contains product/background or operating-point crossovers without one robust winner.";
end

end

function tied = localAllProductsExactlyTied( ...
    summaryTable, configuration)

tied = true;
backgroundIds = unique(summaryTable.BackgroundId);

for backgroundIndex = 1:numel(backgroundIds)
    for pfaIndex = 1:numel(configuration.Pfa)
        rows = summaryTable( ...
            summaryTable.BackgroundId == ...
            backgroundIds(backgroundIndex) & ...
            summaryTable.PfaIndex == pfaIndex, :);
        tied = tied && isscalar(unique(rows.TargetHitCount)) && ...
            isscalar(unique(rows.ControlAlarmCount));
    end
end

end

function value = localSafeRatio(numerator, denominator)

if denominator == 0.0
    value = NaN;
else
    value = double(numerator) ./ double(denominator);
end

end

