    cutCountAccountingValid && ...
    axesCompatible;
cfarValid = all(mapTable.CfarCallCount == 1.0) && ...
    all(mapTable.NoiseEstimateFinite) && ...
    all(mapTable.NoiseEstimateNonnegative) && ...
    all(mapTable.ThresholdMonotonic) && ...
    all(mapTable.DetectionCountMonotonic);
matchedMask = logical(truthTable{:, "Matched"});
normalizedDelayErrors = ...
    double(truthTable{:, "NormalizedDelayError"});
normalizedDopplerErrors = ...
    double(truthTable{:, "NormalizedDopplerError"});
associationValid = all(mapTable.AssociationValid) && ...
    all(operatingTable.AssociationValid) && ...
    all(normalizedDelayErrors(matchedMask) <= 1.0) && ...
    all(normalizedDopplerErrors(matchedMask) <= 1.0);
integrity = struct();
integrity.StructuralValid = structuralValid;
integrity.CountValid = countValid;
integrity.MapValid = mapValid;
integrity.AxisValid = axisValid;
integrity.CfarValid = cfarValid;
