function roleSummaryTable = localBuildRoleSummaryTable(roleMetricTable, ...
    resolvedOptions)

roleNames = ["reference"; "surveillance"];
rowTemplate = struct( ...
    "Role", "", ...
    "ChannelLabel", "", ...
    "RepetitionCount", NaN, ...
    "MedianPilotFrequencyOffset_Hz", NaN, ...
    "MedianPilotFrequencyAbsolute_Hz", NaN, ...
    "PilotFrequencyStd_Hz", NaN, ...
    "MedianPilotOffsetError_Hz", NaN, ...
    "WorstPilotOffsetError_Hz", NaN, ...
    "MedianPilotPsd_dBHz", NaN, ...
    "MedianPilotProminence_dB", NaN, ...
    "WorstPilotProminence_dB", NaN, ...
    "MedianDataBandMedianPsd_dBHz", NaN, ...
    "MedianDataBandProminence_dB", NaN, ...
    "MedianPilotExcludedDataBandPower_dB", NaN, ...
    "MedianOccupiedBandwidth_Hz", NaN, ...
    "PilotConfidenceLabel", "", ...
    "PilotConfidenceRationale", "");
rows = repmat(rowTemplate, numel(roleNames), 1);

for roleIndex = 1:numel(roleNames)
    roleName = roleNames(roleIndex);
    roleRows = roleMetricTable(roleMetricTable.Role == roleName, :);
    medianPilotProminenceDb = median( ...
        roleRows.PilotProminence_dB, "omitnan");
    worstPilotProminenceDb = min( ...
        roleRows.PilotProminence_dB, [], "omitnan");
    pilotFrequencyStdHz = std( ...
        roleRows.PilotFrequencyOffset_Hz, 0, 1, "omitnan");
    medianPilotOffsetErrorHz = median( ...
        roleRows.PilotOffsetError_Hz, "omitnan");
    worstPilotOffsetErrorHz = max( ...
        abs(roleRows.PilotOffsetError_Hz), [], "omitnan");
    [confidenceLabel, confidenceRationale] = localClassifyRolePilot( ...
        medianPilotProminenceDb, pilotFrequencyStdHz, ...
        medianPilotOffsetErrorHz, resolvedOptions);

    rows(roleIndex) = struct( ...
        "Role", roleName, ...
        "ChannelLabel", string(roleRows.ChannelLabel(1)), ...
        "RepetitionCount", height(roleRows), ...
        "MedianPilotFrequencyOffset_Hz", median( ...
        roleRows.PilotFrequencyOffset_Hz, "omitnan"), ...
        "MedianPilotFrequencyAbsolute_Hz", median( ...
        roleRows.PilotFrequencyAbsolute_Hz, "omitnan"), ...
        "PilotFrequencyStd_Hz", pilotFrequencyStdHz, ...
        "MedianPilotOffsetError_Hz", medianPilotOffsetErrorHz, ...
        "WorstPilotOffsetError_Hz", worstPilotOffsetErrorHz, ...
        "MedianPilotPsd_dBHz", median( ...
        roleRows.PilotPsd_dBHz, "omitnan"), ...
        "MedianPilotProminence_dB", medianPilotProminenceDb, ...
        "WorstPilotProminence_dB", worstPilotProminenceDb, ...
        "MedianDataBandMedianPsd_dBHz", median( ...
        roleRows.DataBandMedianPsd_dBHz, "omitnan"), ...
        "MedianDataBandProminence_dB", median( ...
        roleRows.DataBandProminence_dB, "omitnan"), ...
        "MedianPilotExcludedDataBandPower_dB", median( ...
        roleRows.PilotExcludedDataBandPower_dB, "omitnan"), ...
        "MedianOccupiedBandwidth_Hz", median( ...
        roleRows.OccupiedBandwidth_Hz, "omitnan"), ...
        "PilotConfidenceLabel", confidenceLabel, ...
        "PilotConfidenceRationale", confidenceRationale);
end

roleSummaryTable = struct2table(rows);

end

function [confidenceLabel, confidenceRationale] = localClassifyRolePilot( ...
    medianPilotProminenceDb, pilotFrequencyStdHz, ...
    medianPilotOffsetErrorHz, resolvedOptions)

if ~isfinite(medianPilotProminenceDb)
    confidenceLabel = "no-confidence";
    confidenceRationale = "Pilot metrics are not finite.";
    return
end

stableReady = pilotFrequencyStdHz <= ...
    resolvedOptions.PilotFrequencyStableThreshold_Hz;
stableCaution = pilotFrequencyStdHz <= ...
    resolvedOptions.PilotFrequencyCautionStableThreshold_Hz;
offsetReady = abs(medianPilotOffsetErrorHz) <= ...
    resolvedOptions.PilotFrequencyReadyTolerance_Hz;
offsetCaution = abs(medianPilotOffsetErrorHz) <= ...
    resolvedOptions.PilotFrequencyCautionTolerance_Hz;

if medianPilotProminenceDb >= ...
        resolvedOptions.PilotProminenceReadyThreshold_dB && ...
        stableReady && offsetReady
    confidenceLabel = "ready";
    confidenceRationale = "Pilot line is prominent, stable, and near " + ...
        "the expected ATSC pilot offset.";
elseif medianPilotProminenceDb >= ...
        resolvedOptions.PilotProminenceCautionThreshold_dB && ...
        stableCaution && offsetCaution
    confidenceLabel = "caution";
    confidenceRationale = "Pilot-like evidence is present but does not " + ...
        "meet all ready thresholds.";
else
    confidenceLabel = "no-confidence";
    confidenceRationale = "Pilot-like evidence is weak, unstable, or far " + ...
        "from the expected ATSC pilot offset.";
end

end

function dashboardTable = localBuildDashboardTable(roleSummaryTable, ...
    comparisonMetricTable, resolvedOptions)

referenceSummary = roleSummaryTable(roleSummaryTable.Role == ...
    "reference", :);
surveillanceSummary = roleSummaryTable(roleSummaryTable.Role == ...
    "surveillance", :);
pilotDeltaMedianDb = median( ...
    comparisonMetricTable.ReferenceMinusSurveillancePilotPsd_dB, ...
    "omitnan");
dataBandMedianDeltaDb = median( ...
    comparisonMetricTable.ReferenceMinusSurveillanceDataBandMedianPsd_dB, ...
    "omitnan");
dataBandPowerDeltaDb = median( ...
    comparisonMetricTable.ReferenceMinusSurveillanceDataBandPower_dB, ...
    "omitnan");
rowTemplate = struct( ...
    "Question", "", ...
    "Metric", "", ...
    "Value", "", ...
    "ReviewLabel", "", ...
    "Rationale", "");
rows = repmat(rowTemplate, 5, 1);

[stabilityLabel, stabilityRationale] = localClassifyPilotStability( ...
    referenceSummary, surveillanceSummary, resolvedOptions);
rows(1) = struct( ...
    "Question", "Where is the dominant pilot-like line in each role?", ...
    "Metric", "Pilot frequency standard deviation", ...
    "Value", sprintf("reference %.3f kHz, surveillance %.3f kHz", ...
    referenceSummary.PilotFrequencyStd_Hz / 1.0e3, ...
    surveillanceSummary.PilotFrequencyStd_Hz / 1.0e3), ...
    "ReviewLabel", stabilityLabel, ...
    "Rationale", stabilityRationale);

[prominenceLabel, prominenceRationale] = localClassifyPilotProminence( ...
    referenceSummary, surveillanceSummary, resolvedOptions);
rows(2) = struct( ...
    "Question", "Does each channel see a strong transmitter pilot?", ...
    "Metric", "Median pilot prominence", ...
    "Value", sprintf("reference %.2f dB, surveillance %.2f dB", ...
    referenceSummary.MedianPilotProminence_dB, ...
    surveillanceSummary.MedianPilotProminence_dB), ...
    "ReviewLabel", prominenceLabel, ...
    "Rationale", prominenceRationale);

[dataBandLabel, dataBandRationale] = localClassifyDataBand( ...
    referenceSummary, surveillanceSummary, resolvedOptions);
rows(3) = struct( ...
    "Question", "Is the pilot-excluded data band smooth?", ...
    "Metric", "Median data-band peak prominence", ...
    "Value", sprintf("reference %.2f dB, surveillance %.2f dB", ...
    referenceSummary.MedianDataBandProminence_dB, ...
    surveillanceSummary.MedianDataBandProminence_dB), ...
    "ReviewLabel", dataBandLabel, ...
    "Rationale", dataBandRationale);

[pilotDeltaLabel, pilotDeltaRationale] = localClassifyPilotDelta( ...
    pilotDeltaMedianDb, resolvedOptions);
rows(4) = struct( ...
    "Question", "Is reference stronger for pilot energy?", ...
    "Metric", "Median reference-minus-surveillance pilot PSD", ...
    "Value", sprintf("%.2f dB", pilotDeltaMedianDb), ...
    "ReviewLabel", pilotDeltaLabel, ...
    "Rationale", pilotDeltaRationale);

[overallLabel, overallRationale] = localClassifyOverallDashboard( ...
    roleSummaryTable, stabilityLabel, prominenceLabel, dataBandLabel, ...
    pilotDeltaLabel);
rows(5) = struct( ...
    "Question", "What should we conclude before G2 Stage 3 work?", ...
    "Metric", "Overall pilot-aware manual review label", ...
    "Value", sprintf("data median delta %.2f dB, data power delta %.2f dB", ...
    dataBandMedianDeltaDb, dataBandPowerDeltaDb), ...
    "ReviewLabel", overallLabel, ...
    "Rationale", overallRationale);

dashboardTable = struct2table(rows);

end

function [label, rationale] = localClassifyPilotStability( ...
    referenceSummary, surveillanceSummary, resolvedOptions)

roleStdHz = [
    referenceSummary.PilotFrequencyStd_Hz
    surveillanceSummary.PilotFrequencyStd_Hz
    ];
roleOffsetErrorHz = abs([
    referenceSummary.MedianPilotOffsetError_Hz
    surveillanceSummary.MedianPilotOffsetError_Hz
    ]);

if all(roleStdHz <= resolvedOptions.PilotFrequencyStableThreshold_Hz) && ...
        all(roleOffsetErrorHz <= ...
        resolvedOptions.PilotFrequencyReadyTolerance_Hz)
    label = "ready";
    rationale = "Both roles show stable pilot-frequency estimates near " + ...
        "the expected ATSC offset.";
elseif all(roleStdHz <= ...
        resolvedOptions.PilotFrequencyCautionStableThreshold_Hz) && ...
        all(roleOffsetErrorHz <= ...
        resolvedOptions.PilotFrequencyCautionTolerance_Hz)
    label = "caution";
    rationale = "Pilot frequency estimates are usable but outside at " + ...
        "least one ready threshold.";
else
    label = "no-confidence";
    rationale = "Pilot frequency estimates are unstable or far from the " + ...
        "expected ATSC offset.";
end

end

function [label, rationale] = localClassifyPilotProminence( ...
    referenceSummary, surveillanceSummary, resolvedOptions)

roleProminenceDb = [
    referenceSummary.MedianPilotProminence_dB
    surveillanceSummary.MedianPilotProminence_dB
    ];

if all(roleProminenceDb >= ...
        resolvedOptions.PilotProminenceReadyThreshold_dB)
    label = "ready";
    rationale = "Both accepted roles show ready-level pilot prominence.";
elseif any(roleProminenceDb >= ...
        resolvedOptions.PilotProminenceCautionThreshold_dB)
    label = "caution";
    rationale = "At least one role shows pilot-like prominence, but the " + ...
        "two-role evidence is uneven.";
else
    label = "no-confidence";
    rationale = "Neither accepted role has enough pilot prominence.";
end

end

function [label, rationale] = localClassifyDataBand( ...
    referenceSummary, surveillanceSummary, resolvedOptions)

roleDataProminenceDb = [
    referenceSummary.MedianDataBandProminence_dB
    surveillanceSummary.MedianDataBandProminence_dB
    ];

if all(roleDataProminenceDb <= ...
        resolvedOptions.DataBandProminenceReadyThreshold_dB)
    label = "ready";
    rationale = "Pilot-excluded data-band peaks stay within the smooth " + ...
        "ready range.";
elseif all(roleDataProminenceDb <= ...
        resolvedOptions.DataBandProminenceCautionThreshold_dB)
    label = "caution";
    rationale = "The pilot-excluded data band has visible structure but " + ...
        "does not exceed the no-confidence threshold.";
else
    label = "no-confidence";
    rationale = "Pilot-excluded data-band structure is dominated by " + ...
        "large non-pilot peaks.";
end

end

function [label, rationale] = localClassifyPilotDelta( ...
    pilotDeltaMedianDb, resolvedOptions)

if pilotDeltaMedianDb >= ...
        resolvedOptions.ReferencePilotDeltaReadyThreshold_dB
    label = "ready";
    rationale = "Accepted reference has at least as much pilot PSD as " + ...
        "surveillance at the median repetition.";
elseif pilotDeltaMedianDb >= ...
        resolvedOptions.ReferencePilotDeltaCautionThreshold_dB
    label = "caution";
    rationale = "Reference pilot PSD is weaker than surveillance but " + ...
        "within the caution band.";
else
    label = "no-confidence";
    rationale = "Reference pilot PSD is materially weaker than the " + ...
        "accepted surveillance role.";
end

end

function [label, rationale] = localClassifyOverallDashboard( ...
    roleSummaryTable, stabilityLabel, prominenceLabel, dataBandLabel, ...
    pilotDeltaLabel)

referenceLabel = string(roleSummaryTable.PilotConfidenceLabel( ...
    roleSummaryTable.Role == "reference"));
surveillanceLabel = string(roleSummaryTable.PilotConfidenceLabel( ...
    roleSummaryTable.Role == "surveillance"));
roleLabels = [referenceLabel; surveillanceLabel];

if all(roleLabels == "ready") && stabilityLabel == "ready" && ...
        prominenceLabel == "ready" && dataBandLabel ~= "no-confidence" && ...
        pilotDeltaLabel ~= "no-confidence"
    label = "ready";
    rationale = "Pilot-aware evidence is strong enough for the next " + ...
        "development review question.";
elseif any(roleLabels ~= "no-confidence") && ...
        prominenceLabel ~= "no-confidence"
    label = "caution";
    rationale = "Pilot evidence exists, but at least one role, delta, or " + ...
        "data-band check remains caveated.";
else
    label = "no-confidence";
    rationale = "Pilot-aware evidence is too weak for a transmitter-" + ...
        "specific RF-health conclusion.";
end

end

