function [referenceSamples, surveillanceSamples] = localReadRoleSamples( ...
    sessionData, radarTable, roleInfo, repetitionIndex)

loadedSamples = complex(int16.empty(0, 0));

if isfield(sessionData, "RadarScans") && ...
        repetitionIndex <= numel(sessionData.RadarScans) && ...
        isfield(sessionData.RadarScans(repetitionIndex), "Samples")
    loadedSamples = sessionData.RadarScans(repetitionIndex).Samples;
end

if isempty(loadedSamples)
    if ~isfield(sessionData, "DatasetRoot")
        error("helperAnalyzeG2PilotAwareSignalQuality:MissingDatasetRoot", ...
            "DatasetRoot is required when samples are not preloaded.");
    end

    absoluteFilePath = fullfile(string(sessionData.DatasetRoot), ...
        strrep(radarTable.RelativePath(repetitionIndex), "/", filesep));

    try
        scan = helperScanBasebandCaptureFile(absoluteFilePath, true);
    catch scanException
        error("helperAnalyzeG2PilotAwareSignalQuality:ReadSamplesFailed", ...
            "Failed to read IQ samples from %s: %s", absoluteFilePath, ...
            scanException.message);
    end

    loadedSamples = scan.Samples;
end

if size(loadedSamples, 2) < 2
    error("helperAnalyzeG2PilotAwareSignalQuality:InsufficientChannels", ...
        "Pilot-aware G2 review requires at least two IQ channels.");
end

referenceSamples = double(loadedSamples(:, roleInfo.ReferenceColumnIndex));
surveillanceSamples = double(loadedSamples(:, ...
    roleInfo.SurveillanceColumnIndex));

end

function [channelMetrics, pxx, frequencyOffsetHz] = ...
    localComputeChannelPilotMetrics(samples, resolvedOptions)

samples = double(samples(:));

[pxx, frequencyOffsetHz] = pwelch(samples, ...
    resolvedOptions.WelchWindow, resolvedOptions.WelchOverlap, ...
    resolvedOptions.WelchNfft, resolvedOptions.SampleRateHz, ...
    "centered");
frequencyOffsetHz = double(frequencyOffsetHz(:));
pxx = max(real(double(pxx(:))), eps);
validMask = isfinite(frequencyOffsetHz) & isfinite(pxx);
pilotSearchMask = validMask & ...
    abs(frequencyOffsetHz - resolvedOptions.ExpectedPilotOffsetHz) <= ...
    resolvedOptions.PilotSearchHalfWidthHz;

if ~any(pilotSearchMask)
    pilotSearchMask = validMask;
end

pilotSearchMetrics = helperComputePilotAwarePsdMetrics( ...
    frequencyOffsetHz(pilotSearchMask), pxx(pilotSearchMask), ...
    resolvedOptions.PilotExclusionHalfWidthHz);
pilotFrequencyOffsetHz = pilotSearchMetrics.PilotFrequency_Hz;
pilotAbsoluteFrequencyHz = resolvedOptions.CenterFrequencyHz + ...
    pilotFrequencyOffsetHz;
pilotPsd = db2pow(pilotSearchMetrics.PilotPsd_dB);
[dataBandMetrics, dataBandMask] = localComputeDataBandMetrics( ...
    frequencyOffsetHz, pxx, pilotFrequencyOffsetHz, resolvedOptions);

try
    occupiedBandwidthHz = obw(samples, resolvedOptions.SampleRateHz);
catch obwException
    warning("helperAnalyzeG2PilotAwareSignalQuality:ObwFailed", ...
        "Occupied bandwidth calculation failed: %s", obwException.message);
    occupiedBandwidthHz = NaN;
end

fullScale = double(intmax("int16"));
meanPower = mean(abs(samples) .^ 2);

channelMetrics = struct();
channelMetrics.PilotFrequencyOffset_Hz = pilotFrequencyOffsetHz;
channelMetrics.PilotFrequencyAbsolute_Hz = pilotAbsoluteFrequencyHz;
channelMetrics.ExpectedPilotFrequencyOffset_Hz = ...
    resolvedOptions.ExpectedPilotOffsetHz;
channelMetrics.ExpectedPilotFrequencyAbsolute_Hz = ...
    resolvedOptions.ExpectedPilotFrequencyHz;
channelMetrics.PilotOffsetError_Hz = pilotFrequencyOffsetHz - ...
    resolvedOptions.ExpectedPilotOffsetHz;
channelMetrics.PilotPsd_dBHz = pilotSearchMetrics.PilotPsd_dB;
channelMetrics.PilotProminence_dB = pow2db( ...
    pilotPsd / max(dataBandMetrics.DataBandMedianPsd, eps));
channelMetrics.PilotSearchProminence_dB = ...
    pilotSearchMetrics.PilotProminence_dB;
channelMetrics.DataBandMedianPsd_dBHz = pow2db( ...
    dataBandMetrics.DataBandMedianPsd);
channelMetrics.DataBandPeakFrequencyOffset_Hz = ...
    dataBandMetrics.DataBandPeakFrequencyOffset_Hz;
channelMetrics.DataBandPeakFrequencyAbsolute_Hz = ...
    resolvedOptions.CenterFrequencyHz + ...
    dataBandMetrics.DataBandPeakFrequencyOffset_Hz;
channelMetrics.DataBandPeakPsd_dBHz = pow2db( ...
    dataBandMetrics.DataBandPeakPsd);
channelMetrics.DataBandProminence_dB = pow2db( ...
    dataBandMetrics.DataBandPeakPsd / ...
    max(dataBandMetrics.DataBandMedianPsd, eps));
channelMetrics.PilotExcludedDataBandPower_dB = pow2db( ...
    dataBandMetrics.PilotExcludedDataBandPower);
channelMetrics.OccupiedBandwidth_Hz = occupiedBandwidthHz;
channelMetrics.MeanPower_dBFS = pow2db( ...
    meanPower / (fullScale ^ 2) + eps);
channelMetrics.DataBandBinCount = sum(dataBandMask);

end

function [dataBandMetrics, dataBandMask] = localComputeDataBandMetrics( ...
    frequencyOffsetHz, pxx, pilotFrequencyOffsetHz, resolvedOptions)

dataBandRange = [-resolvedOptions.DataBandHalfWidthHz, ...
    resolvedOptions.DataBandHalfWidthHz];
dataBandLowerHz = max(dataBandRange(1), min(frequencyOffsetHz));
dataBandUpperHz = min(dataBandRange(2), max(frequencyOffsetHz));
dataBandMask = frequencyOffsetHz >= dataBandLowerHz & ...
    frequencyOffsetHz <= dataBandUpperHz & ...
    abs(frequencyOffsetHz - pilotFrequencyOffsetHz) > ...
    resolvedOptions.PilotExclusionHalfWidthHz & ...
    isfinite(pxx);

if ~any(dataBandMask)
    dataBandMask = isfinite(pxx);
end

dataBandFrequencyHz = frequencyOffsetHz(dataBandMask);
dataBandPsd = pxx(dataBandMask);
dataBandMedianPsd = max(median(dataBandPsd, "omitnan"), eps);
[dataBandPeakPsd, dataBandPeakIndex] = max(dataBandPsd, [], "omitnan");
pilotExcludedDataBandPower = localComputePilotExcludedBandPower( ...
    frequencyOffsetHz, pxx, dataBandLowerHz, dataBandUpperHz, ...
    pilotFrequencyOffsetHz, resolvedOptions);

dataBandMetrics = struct();
dataBandMetrics.DataBandMedianPsd = dataBandMedianPsd;
dataBandMetrics.DataBandPeakPsd = max(dataBandPeakPsd, eps);
dataBandMetrics.DataBandPeakFrequencyOffset_Hz = ...
    dataBandFrequencyHz(dataBandPeakIndex);
dataBandMetrics.PilotExcludedDataBandPower = ...
    pilotExcludedDataBandPower;

end

function pilotExcludedDataBandPower = localComputePilotExcludedBandPower( ...
    frequencyOffsetHz, pxx, dataBandLowerHz, dataBandUpperHz, ...
    pilotFrequencyOffsetHz, resolvedOptions)

if dataBandLowerHz >= dataBandUpperHz
    pilotExcludedDataBandPower = NaN;
    return
end

try
    fullDataBandPower = bandpower(pxx, frequencyOffsetHz, ...
        [dataBandLowerHz, dataBandUpperHz], "psd");
    pilotBandLowerHz = max(dataBandLowerHz, ...
        pilotFrequencyOffsetHz - ...
        resolvedOptions.PilotExclusionHalfWidthHz);
    pilotBandUpperHz = min(dataBandUpperHz, ...
        pilotFrequencyOffsetHz + ...
        resolvedOptions.PilotExclusionHalfWidthHz);

    if pilotBandLowerHz < pilotBandUpperHz
        pilotBandPower = bandpower(pxx, frequencyOffsetHz, ...
            [pilotBandLowerHz, pilotBandUpperHz], "psd");
    else
        pilotBandPower = 0.0;
    end
catch bandpowerException
    error("helperAnalyzeG2PilotAwareSignalQuality:BandpowerFailed", ...
        "Failed to compute pilot-excluded data-band power: %s", ...
        bandpowerException.message);
end

pilotExcludedDataBandPower = max(fullDataBandPower - pilotBandPower, eps);

end

