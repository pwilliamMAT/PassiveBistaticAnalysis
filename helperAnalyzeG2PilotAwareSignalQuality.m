function analysis = helperAnalyzeG2PilotAwareSignalQuality(sessionData, ...
    collectionMetadataInfo, options)
%HELPERANALYZEG2PILOTAWARESIGNALQUALITY Analyze ATSC pilot-aware RF health.
%
%   ANALYSIS = HELPERANALYZEG2PILOTAWARESIGNALQUALITY(SESSIONDATA,
%   COLLECTIONMETADATAINFO, OPTIONS) computes per-repetition pilot and
%   pilot-excluded spectral metrics for the accepted G2 reference and
%   surveillance roles. This helper does not demodulate ATSC and does not
%   compute MER or EVM.

arguments
    sessionData (1,1) struct
    collectionMetadataInfo (1,1) struct
    options (1,1) struct = struct()
end

resolvedOptions = localResolveOptions(sessionData, options);
roleInfo = localResolveRoleInfo(sessionData, collectionMetadataInfo);
[roleMetricTable, comparisonMetricTable, roleEvidence] = ...
    localBuildPilotAwareTables(sessionData, roleInfo, resolvedOptions);
roleSummaryTable = localBuildRoleSummaryTable(roleMetricTable, ...
    resolvedOptions);
dashboardTable = localBuildDashboardTable(roleSummaryTable, ...
    comparisonMetricTable, resolvedOptions);

analysis = struct();
analysis.StageId = "G2_PilotAwareSignalQuality_Development";
analysis.DatasetId = string(sessionData.DatasetId);
analysis.RoleInfo = roleInfo;
analysis.Options = localStripRuntimeOptions(resolvedOptions);
analysis.RoleMetricTable = roleMetricTable;
analysis.RoleSummaryTable = roleSummaryTable;
analysis.ComparisonMetricTable = comparisonMetricTable;
analysis.DashboardTable = dashboardTable;
analysis.RoleEvidence = roleEvidence;
analysis.CollectionMetadataInfo = collectionMetadataInfo;
analysis.Metrics = localBuildMetrics(analysis);

end

function resolvedOptions = localResolveOptions(sessionData, options)

sampleRateVector = unique(double(sessionData.RadarTable.SampleRate_Hz));
centerFrequencyVector = unique(double(sessionData.RadarTable.CenterFrequency_Hz));
sampleCountVector = double(sessionData.RadarTable.NumSamples);

resolvedOptions = struct();
resolvedOptions.SampleRateHz = sampleRateVector(1);
resolvedOptions.CenterFrequencyHz = centerFrequencyVector(1);
resolvedOptions.AtscChannelBandwidthHz = 6.0e6;
resolvedOptions.ExpectedPilotOffsetHz = -2.690559441e6;
resolvedOptions.ExpectedPilotFrequencyHz = ...
    resolvedOptions.CenterFrequencyHz + ...
    resolvedOptions.ExpectedPilotOffsetHz;
resolvedOptions.PilotSearchHalfWidthHz = 150.0e3;
resolvedOptions.PilotExclusionHalfWidthHz = 50.0e3;
resolvedOptions.DataBandHalfWidthHz = min( ...
    resolvedOptions.AtscChannelBandwidthHz / 2.0, ...
    resolvedOptions.SampleRateHz / 2.0);
resolvedOptions.WelchLength = 8192;
resolvedOptions.WelchOverlap = 4096;
resolvedOptions.WelchNfft = 8192;
resolvedOptions.MaxRepetitions = Inf;
resolvedOptions.PilotProminenceReadyThreshold_dB = 8.0;
resolvedOptions.PilotProminenceCautionThreshold_dB = 5.0;
resolvedOptions.PilotFrequencyReadyTolerance_Hz = 20.0e3;
resolvedOptions.PilotFrequencyCautionTolerance_Hz = 75.0e3;
resolvedOptions.PilotFrequencyStableThreshold_Hz = 5.0e3;
resolvedOptions.PilotFrequencyCautionStableThreshold_Hz = 25.0e3;
resolvedOptions.DataBandProminenceReadyThreshold_dB = 12.0;
resolvedOptions.DataBandProminenceCautionThreshold_dB = 20.0;
resolvedOptions.ReferencePilotDeltaReadyThreshold_dB = 0.0;
resolvedOptions.ReferencePilotDeltaCautionThreshold_dB = -6.0;

if isfield(options, "ExpectedPilotFrequencyOffsetHz") && ...
        ~isfield(options, "ExpectedPilotOffsetHz")
    options.ExpectedPilotOffsetHz = ...
        options.ExpectedPilotFrequencyOffsetHz;
    options = rmfield(options, "ExpectedPilotFrequencyOffsetHz");
end

optionFields = fieldnames(options);

for fieldIndex = 1:numel(optionFields)
    fieldName = optionFields{fieldIndex};
    resolvedOptions.(fieldName) = options.(fieldName);
end

if isfield(options, "ExpectedPilotFrequencyHz") && ...
        ~isfield(options, "ExpectedPilotOffsetHz")
    resolvedOptions.ExpectedPilotOffsetHz = ...
        resolvedOptions.ExpectedPilotFrequencyHz - ...
        resolvedOptions.CenterFrequencyHz;
end

resolvedOptions.ExpectedPilotFrequencyHz = ...
    resolvedOptions.CenterFrequencyHz + ...
    resolvedOptions.ExpectedPilotOffsetHz;
resolvedOptions.DataBandHalfWidthHz = min( ...
    resolvedOptions.DataBandHalfWidthHz, ...
    resolvedOptions.SampleRateHz / 2.0);
resolvedOptions.PilotSearchHalfWidthHz = max( ...
    resolvedOptions.PilotSearchHalfWidthHz, 0.0);
resolvedOptions.PilotExclusionHalfWidthHz = max( ...
    resolvedOptions.PilotExclusionHalfWidthHz, 0.0);
minimumSampleCount = max(32.0, min(sampleCountVector));
resolvedOptions.WelchLength = min(resolvedOptions.WelchLength, ...
    minimumSampleCount);
resolvedOptions.WelchLength = max(32.0, floor(resolvedOptions.WelchLength));
resolvedOptions.WelchOverlap = min(resolvedOptions.WelchOverlap, ...
    resolvedOptions.WelchLength - 1.0);
resolvedOptions.WelchOverlap = max(0.0, floor(resolvedOptions.WelchOverlap));
resolvedOptions.WelchNfft = max(resolvedOptions.WelchNfft, ...
    resolvedOptions.WelchLength);
resolvedOptions.WelchNfft = floor(resolvedOptions.WelchNfft);
resolvedOptions.WelchWindow = hann(resolvedOptions.WelchLength, ...
    "periodic");

end

function roleInfo = localResolveRoleInfo(sessionData, collectionMetadataInfo)

channel1Label = string(sessionData.RadarTable.Antenna1(1));
channel2Label = string(sessionData.RadarTable.Antenna2(1));
referenceLabel = strtrim( ...
    string(collectionMetadataInfo.ReferenceChannel.ChannelLabel));
surveillanceLabel = strtrim( ...
    string(collectionMetadataInfo.SurveillanceChannel.ChannelLabel));

roleInfo = struct();
roleInfo.Channel1Label = channel1Label;
roleInfo.Channel2Label = channel2Label;
roleInfo.ReferenceLabel = "";
roleInfo.SurveillanceLabel = "";
roleInfo.ReferenceColumnIndex = NaN;
roleInfo.SurveillanceColumnIndex = NaN;
roleInfo.RoleSource = "channel_order_fallback_unverified";
roleInfo.RoleNote = "Manual role mapping was unavailable or incomplete. " + ...
    "Pilot-aware review uses channel order fallback only.";

manualMappingValid = collectionMetadataInfo.MetadataPresent && ...
    collectionMetadataInfo.SessionIdMatches && ...
    strlength(referenceLabel) > 0 && ...
    strlength(surveillanceLabel) > 0 && ...
    any(referenceLabel == [channel1Label; channel2Label]) && ...
    any(surveillanceLabel == [channel1Label; channel2Label]) && ...
    referenceLabel ~= surveillanceLabel;

if manualMappingValid
    roleInfo.ReferenceLabel = referenceLabel;
    roleInfo.SurveillanceLabel = surveillanceLabel;
    roleInfo.RoleSource = "collection_metadata_manual_mapping";
    roleInfo.RoleNote = "Pilot-aware review uses the accepted G2 " + ...
        "collection_metadata.json channel-role mapping.";
else
    roleInfo.ReferenceLabel = channel1Label;
    roleInfo.SurveillanceLabel = channel2Label;
end

if roleInfo.ReferenceLabel == channel1Label
    roleInfo.ReferenceColumnIndex = 1;
else
    roleInfo.ReferenceColumnIndex = 2;
end

if roleInfo.SurveillanceLabel == channel1Label
    roleInfo.SurveillanceColumnIndex = 1;
else
    roleInfo.SurveillanceColumnIndex = 2;
end

end

function [roleMetricTable, comparisonMetricTable, roleEvidence] = ...
    localBuildPilotAwareTables(sessionData, roleInfo, resolvedOptions)

radarTable = sessionData.RadarTable;

if isfinite(resolvedOptions.MaxRepetitions)
    requestedRepetitionCount = min(height(radarTable), ...
        resolvedOptions.MaxRepetitions);
    requestedRepetitionCount = max(1.0, floor(requestedRepetitionCount));
    radarTable = radarTable(1:requestedRepetitionCount, :);
end

repetitionCount = height(radarTable);
roleRowTemplate = localBuildRoleRowTemplate();
comparisonRowTemplate = localBuildComparisonRowTemplate();
roleRows = repmat(roleRowTemplate, repetitionCount * 2, 1);
comparisonRows = repmat(comparisonRowTemplate, repetitionCount, 1);
referencePsdByRepetition = [];
surveillancePsdByRepetition = [];
psdFrequencyOffsetHz = [];

for repetitionIndex = 1:repetitionCount
    [referenceSamples, surveillanceSamples] = localReadRoleSamples( ...
        sessionData, radarTable, roleInfo, repetitionIndex);
    [referenceMetrics, referencePsd, psdFrequencyOffsetHz] = ...
        localComputeChannelPilotMetrics(referenceSamples, ...
        resolvedOptions);
    [surveillanceMetrics, surveillancePsd, ~] = ...
        localComputeChannelPilotMetrics(surveillanceSamples, ...
        resolvedOptions);

    if isempty(referencePsdByRepetition)
        referencePsdByRepetition = zeros(numel(referencePsd), ...
            repetitionCount);
        surveillancePsdByRepetition = zeros(numel(surveillancePsd), ...
            repetitionCount);
    end

    referencePsdByRepetition(:, repetitionIndex) = referencePsd;
    surveillancePsdByRepetition(:, repetitionIndex) = surveillancePsd;
    referenceRowIndex = (repetitionIndex - 1) * 2 + 1;
    surveillanceRowIndex = referenceRowIndex + 1;
    roleRows(referenceRowIndex) = localBuildRoleMetricRow(radarTable, ...
        repetitionIndex, "reference", roleInfo.ReferenceLabel, ...
        referenceMetrics);
    roleRows(surveillanceRowIndex) = localBuildRoleMetricRow(radarTable, ...
        repetitionIndex, "surveillance", roleInfo.SurveillanceLabel, ...
        surveillanceMetrics);
    comparisonRows(repetitionIndex) = localBuildComparisonMetricRow( ...
        radarTable, repetitionIndex, referenceMetrics, ...
        surveillanceMetrics);
end

roleMetricTable = struct2table(roleRows);
comparisonMetricTable = struct2table(comparisonRows);
roleEvidence = struct();
roleEvidence.PsdFrequencyOffset_Hz = psdFrequencyOffsetHz;
roleEvidence.PsdAbsoluteFrequency_Hz = ...
    resolvedOptions.CenterFrequencyHz + psdFrequencyOffsetHz;
roleEvidence.ReferencePsdByRepetition = referencePsdByRepetition;
roleEvidence.SurveillancePsdByRepetition = surveillancePsdByRepetition;
roleEvidence.ReferenceMeanPsd = mean(referencePsdByRepetition, 2);
roleEvidence.SurveillanceMeanPsd = mean(surveillancePsdByRepetition, 2);
roleEvidence.ReferenceMinusSurveillanceMeanPsd_dB = ...
    pow2db(roleEvidence.ReferenceMeanPsd + eps) - ...
    pow2db(roleEvidence.SurveillanceMeanPsd + eps);

end

