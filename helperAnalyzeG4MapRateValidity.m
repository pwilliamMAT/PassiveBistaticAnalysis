function analysis = helperAnalyzeG4MapRateValidity(pairInput, options)
%HELPERANALYZEG4MAPRATEVALIDITY Compare native- and reduced-rate maps.
%
%   ANALYSIS = HELPERANALYZEG4MAPRATEVALIDITY(PAIRINPUT, OPTIONS) forms a
%   bounded cross-ambiguity map from an aligned native-rate signal pair,
%   forms the corresponding reduced-rate map using RESAMPLE, and compares
%   both representations on identical physical delay/Doppler cells.
%
%   PAIRINPUT must contain ReferenceSignal, SurveillanceSignal, and
%   NativeSampleRateHz. Optional metadata fields are copied into the compact
%   result row. ReducedReferenceSignal and ReducedSurveillanceSignal may be
%   supplied when reduction was performed before extracting the CPI, as in
%   the established G4/G5 production path. Supplied reduced signals require
%   NativeWindowStartSample and ReducedWindowStartSample provenance.
%
%   Native ambiguity magnitude is evaluated with AMBGFUN Doppler cuts and
%   converted to linear power before native samples are averaged into the
%   reduced-rate physical cells. ReducedMapFormation controls whether the
%   reduced map uses streamed Doppler cuts or a transient production full map.
%   No complete map is retained in either mode.

arguments
    pairInput (1,1) struct
    options (1,1) struct = struct()
end

localValidateNativeFunctions();
resolvedOptions = localResolveOptions(options);
localValidatePairInput(pairInput, resolvedOptions);

factorCount = numel(resolvedOptions.DecimationFactors);
rows = repmat(localPairRowTemplate(), factorCount, 1);
mapProducts = cell(factorCount, 1);

for factorIndex = 1:factorCount
    decimationFactor = resolvedOptions.DecimationFactors(factorIndex);
    [rows(factorIndex), mapProducts{factorIndex}] = ...
        localEvaluateFactor(pairInput, decimationFactor, resolvedOptions);
end

pairTable = struct2table(rows);
factorSummaryTable = localBuildFactorSummaryTable(pairTable, ...
    resolvedOptions);

if any(factorSummaryTable.DecimationFactor == ...
        resolvedOptions.InitialDecimationFactor)
    selection = helperSelectG4RDecimationFactor(factorSummaryTable, ...
        resolvedOptions.InitialDecimationFactor, ...
        resolvedOptions.RetuneFactors);
else
    selection = struct( ...
        "Decision", "factor_evaluation_only", ...
        "Outcome", "retune", ...
        "SelectedDecimationFactor", NaN, ...
        "NextAction", ...
        "Combine these rows with the factor-200 pilot result.");
end

representativeComparisons = localSelectRepresentativeComparisons( ...
    mapProducts, pairTable, resolvedOptions);

analysis = struct();
analysis.SchemaVersion = "g4r_map_rate_validity_v1";
analysis.StageId = "G4_R_Map_Rate_Validity";
analysis.AnalysisTimestampZ = string(datetime("now", TimeZone="UTC", ...
    Format="yyyyMMdd'T'HHmmssSSS'Z'"));
analysis.Configuration = localBuildConfiguration(resolvedOptions);
analysis.PairTable = pairTable;
analysis.FactorSummaryTable = factorSummaryTable;
analysis.PilotDecision = selection.Decision;
analysis.Outcome = selection.Outcome;
analysis.SelectedDecimationFactor = selection.SelectedDecimationFactor;
analysis.NextAction = selection.NextAction;
analysis.RepresentativeComparisons = representativeComparisons;
analysis.FormalG5Enabled = false;
analysis.FormalG6Enabled = false;
analysis.FormalG8Enabled = false;
analysis.CompactResultAudit = localBuildCompactResultAudit(analysis);

end

function localValidateNativeFunctions()

if exist("ambgfun", "file") ~= 2
    error("helperAnalyzeG4MapRateValidity:MissingAmbgfun", ...
        "G4-R requires ambgfun from Phased Array System Toolbox.");
end

if exist("resample", "file") ~= 2
    error("helperAnalyzeG4MapRateValidity:MissingResample", ...
        "G4-R requires resample from Signal Processing Toolbox.");
end

end

