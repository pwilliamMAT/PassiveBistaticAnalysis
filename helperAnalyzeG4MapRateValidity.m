function summaryTable = localBuildFactorSummaryTable( ...
    pairTable, resolvedOptions)

factors = unique(pairTable.DecimationFactor, "stable");
rows = repmat(struct( ...
    "DecimationFactor", NaN, ...
    "PairCount", NaN, ...
    "MedianNormalizedMapCorrelation", NaN, ...
    "MinimumNormalizedMapCorrelation", NaN, ...
    "MaximumOffOriginEnergyFractionDifference", NaN, ...
    "MaximumZeroDopplerEnergyFractionDifference", NaN, ...
    "MaximumDirectPathToOffRidgeDifference_dB", NaN, ...
    "AllPeaksAgree", false, ...
    "AllDirectPathClassificationsUnchanged", false, ...
    "AllTargetClassificationsUnchanged", false, ...
    "AllCriteriaPass", false), numel(factors), 1);

for factorIndex = 1:numel(factors)
    factor = factors(factorIndex);
    subset = pairTable(pairTable.DecimationFactor == factor, :);
    rows(factorIndex).DecimationFactor = factor;
    rows(factorIndex).PairCount = double(height(subset));
    rows(factorIndex).MedianNormalizedMapCorrelation = ...
        median(subset.NormalizedMapCorrelation);
    rows(factorIndex).MinimumNormalizedMapCorrelation = ...
        min(subset.NormalizedMapCorrelation);
    rows(factorIndex).MaximumOffOriginEnergyFractionDifference = ...
        max(subset.OffOriginEnergyFractionDifference);
    rows(factorIndex).MaximumZeroDopplerEnergyFractionDifference = ...
        max(subset.ZeroDopplerEnergyFractionDifference);
    rows(factorIndex).MaximumDirectPathToOffRidgeDifference_dB = ...
        max(subset.DirectPathToOffRidgeDifference_dB);
    rows(factorIndex).AllPeaksAgree = all(subset.PeakAgreement);
    rows(factorIndex).AllDirectPathClassificationsUnchanged = ...
        all(subset.DirectPathClassificationUnchanged);
    rows(factorIndex).AllTargetClassificationsUnchanged = ...
        all(subset.TargetClassificationUnchanged);
    rows(factorIndex).AllCriteriaPass = ...
        rows(factorIndex).MedianNormalizedMapCorrelation >= ...
        resolvedOptions.MinimumMedianNormalizedMapCorrelation && ...
        rows(factorIndex).MinimumNormalizedMapCorrelation >= ...
        resolvedOptions.MinimumPairNormalizedMapCorrelation && ...
        rows(factorIndex).MaximumOffOriginEnergyFractionDifference <= ...
        resolvedOptions.MaximumOffOriginEnergyFractionDifference && ...
        rows(factorIndex).MaximumZeroDopplerEnergyFractionDifference <= ...
        resolvedOptions.MaximumZeroDopplerEnergyFractionDifference && ...
        rows(factorIndex).MaximumDirectPathToOffRidgeDifference_dB <= ...
        resolvedOptions.MaximumDirectPathToOffRidgeDifference_dB && ...
        rows(factorIndex).AllPeaksAgree && ...
        rows(factorIndex).AllDirectPathClassificationsUnchanged && ...
        rows(factorIndex).AllTargetClassificationsUnchanged;
end

summaryTable = struct2table(rows);

end

function comparisons = localSelectRepresentativeComparisons( ...
    mapProducts, pairTable, resolvedOptions)

comparisons = repmat(localMapProductTemplate(), 0, 1);

if ~resolvedOptions.RetainComparisonMaps || isempty(mapProducts) || ...
        resolvedOptions.MaximumRetainedComparisons == 0
    return
end

selectedIndices = 1;

if numel(mapProducts) > 1 && ...
        resolvedOptions.MaximumRetainedComparisons > 1
    [~, bestIndex] = max(pairTable.NormalizedMapCorrelation);

    if bestIndex ~= 1
        selectedIndices(end + 1) = bestIndex;
    end
end

selectedIndices = selectedIndices(1:min(numel(selectedIndices), ...
    resolvedOptions.MaximumRetainedComparisons));
comparisons = vertcat(mapProducts{selectedIndices});

end

