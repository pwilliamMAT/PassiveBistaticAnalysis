function mapLabelCounts = localBuildMapLabelCountTable(mapSummaryTable)

labelValues = unique(mapSummaryTable.InterpretationLabel);
labelValues = sort(labelValues);
labelCount = zeros(numel(labelValues), 1);

for idx = 1:numel(labelValues)
    labelCount(idx) = sum(mapSummaryTable.InterpretationLabel == ...
        labelValues(idx));
end

mapLabelCounts = table(labelValues, labelCount, VariableNames = ...
    {'InterpretationLabel', 'MapCount'});

end

function sceneMetricMedians = localBuildSceneMetricMedianTable(mapSummaryTable)

groupKeys = unique(mapSummaryTable(:, {'CpiLabel', 'WindowLabel'}), ...
    'rows');
rowCount = height(groupKeys);
cpiLabel = strings(rowCount, 1);
windowLabel = strings(rowCount, 1);
sceneObservabilityScore = zeros(rowCount, 1);
offOriginNonzeroDopplerEnergyFraction = zeros(rowCount, 1);
offOriginOccupiedFraction = zeros(rowCount, 1);
zeroDopplerRidgeEnergyFraction = zeros(rowCount, 1);
directPathToOffRidgeEnergy_dB = zeros(rowCount, 1);

for idx = 1:rowCount
    subset = mapSummaryTable(mapSummaryTable.CpiLabel == ...
        groupKeys.CpiLabel(idx) & mapSummaryTable.WindowLabel == ...
        groupKeys.WindowLabel(idx), :);
    cpiLabel(idx) = string(groupKeys.CpiLabel(idx));
    windowLabel(idx) = string(groupKeys.WindowLabel(idx));
    sceneObservabilityScore(idx) = median( ...
        subset.SceneObservabilityScore, "omitnan");
    offOriginNonzeroDopplerEnergyFraction(idx) = median( ...
        subset.OffOriginNonzeroDopplerEnergyFraction, "omitnan");
    offOriginOccupiedFraction(idx) = median( ...
        subset.OffOriginOccupiedFraction_abovePeakMinus20dB, "omitnan");
    zeroDopplerRidgeEnergyFraction(idx) = median( ...
        subset.ZeroDopplerRidgeEnergyFraction, "omitnan");
    directPathToOffRidgeEnergy_dB(idx) = median( ...
        subset.DirectPathToOffRidgeEnergy_dB, "omitnan");
end

sceneMetricMedians = table(cpiLabel, windowLabel, ...
    sceneObservabilityScore, offOriginNonzeroDopplerEnergyFraction, ...
    offOriginOccupiedFraction, zeroDopplerRidgeEnergyFraction, ...
    directPathToOffRidgeEnergy_dB, VariableNames = {'CpiLabel', ...
    'WindowLabel', 'SceneObservabilityScore', ...
    'OffOriginNonzeroDopplerEnergyFraction', ...
    'OffOriginOccupiedFraction_abovePeakMinus20dB', ...
    'ZeroDopplerRidgeEnergyFraction', ...
    'DirectPathToOffRidgeEnergy_dB'});
sceneMetricMedians = sortrows(sceneMetricMedians, ...
    {'CpiLabel', 'WindowLabel'});

end

function representativeMapIndex = localBuildRepresentativeMapIndexTable( ...
    representativeMaps)

