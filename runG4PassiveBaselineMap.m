directPathDelay_samples = zeros(mapCount, 1);
directPathDoppler_Hz = zeros(mapCount, 1);
mapRows = zeros(mapCount, 1);
mapColumns = zeros(mapCount, 1);

for idx = 1:mapCount
    representativeMap = representativeMaps(idx);
    cpiLabel(idx) = string(representativeMap.CpiLabel);
    windowLabel(idx) = string(representativeMap.WindowLabel);
    representativeRepetition(idx) = double( ...
        representativeMap.RepresentativeRepetition);
    directPathDelay_samples(idx) = double( ...
        representativeMap.DirectPathDelay_samples);
    directPathDoppler_Hz(idx) = double( ...
        representativeMap.DirectPathDoppler_Hz);
    mapRows(idx) = size(representativeMap.Map_dB, 1);
    mapColumns(idx) = size(representativeMap.Map_dB, 2);
end

representativeMapIndex = table(cpiLabel, windowLabel, ...
    representativeRepetition, directPathDelay_samples, ...
    directPathDoppler_Hz, mapRows, mapColumns, VariableNames = ...
    {'CpiLabel', 'WindowLabel', 'RepresentativeRepetition', ...
