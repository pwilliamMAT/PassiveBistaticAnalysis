function assessment = localResolveAnalysisExecutionAssessment(interpretation)

if string(interpretation.ImplementationConfidenceLabel) == "blocked"
    assessment = "analysis_path_blocked";
else
    assessment = "analysis_executed_no_helper_failure";
end

end

function label = localResolveLimitationSourceLabel(interpretation)

sceneLabel = string(interpretation.SceneObservabilityLabel);
rateAuditLabel = string(interpretation.FullRateAuditAgreementLabel);
implementationLabel = string(interpretation.ImplementationConfidenceLabel);

if implementationLabel == "blocked"
    label = "analysis_or_implementation_blocked";
elseif sceneLabel == "blocked" && rateAuditLabel == "disagreement"
    label = "dataset_scene_limited_with_raw_rate_audit_disagreement";
elseif sceneLabel == "blocked"
    label = "dataset_scene_limited";
elseif rateAuditLabel == "disagreement"
    label = "raw_rate_audit_disagreement";
elseif string(interpretation.OverallLabel) == "ready"
    label = "none_ready";
else
    label = "mixed_caveat";
end

end

function guidance = localResolveManualReviewGuidance(interpretation)

implementationLabel = string(interpretation.ImplementationConfidenceLabel);
sceneLabel = string(interpretation.SceneObservabilityLabel);
rateAuditLabel = string(interpretation.FullRateAuditAgreementLabel);

if implementationLabel == "blocked"
    guidance = "Inspect G4 implementation confidence and direct-path " + ...
        "localization before attributing this result to the dataset.";
elseif sceneLabel == "blocked" || rateAuditLabel == "disagreement"
    guidance = "G4 executed successfully. Treat the block as current " + ...
        "dataset scene limitation or rate-preservation caveat, not as a " + ...
        "helper execution failure.";
else
    guidance = "G4 executed successfully and did not identify a dataset " + ...
        "scene limitation in the current runner slice.";
end

end
