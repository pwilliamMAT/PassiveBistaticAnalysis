function localRenderRepresentativeMapFigure(representativeMaps, axisMode, ...
    figurePath, showFigures)

axisMode = string(axisMode);
figureHandle = figure("Visible", ...
    localResolveFigureVisibility(showFigures), ...
    "Name", "G4 Passive Baseline Representative Maps", ...
    "NumberTitle", "off");
cleanupObject = localCreateFigureCleanup(figureHandle, showFigures); %#ok<NASGU>
layoutHandle = tiledlayout(3, 5, "TileSpacing", "compact", ...
    "Padding", "compact");

for idx = 1:numel(representativeMaps)
    nexttile(layoutHandle);
    representativeMap = representativeMaps(idx);

    if axisMode == "display"
        delayAxis = representativeMap.DisplayDelayAxis_samples;
        dopplerAxis = representativeMap.DisplayDopplerAxis_Hz;
        axisLabel = "display";
    else
        delayAxis = representativeMap.DelayAxis_samples;
        dopplerAxis = representativeMap.DopplerAxis_Hz;
        axisLabel = "raw";
    end

    imagesc(delayAxis, dopplerAxis, representativeMap.Map_dB);
    axis xy
    xlabel("Delay [samples]");
    ylabel("Doppler [Hz]");
    title(sprintf("%s %s %s", string(representativeMap.CpiLabel), ...
        string(representativeMap.WindowLabel), axisLabel));
    colorbar;
end

drawnow
localExportGraphics(layoutHandle, figurePath);
clear cleanupObject

end

