function results = runG4PassiveBaselineMap(datasetId, repoRoot, options)
%RUNG4PASSIVEBASELINEMAP Execute the Stage 4 manual-review runner.
%
%   RESULTS = RUNG4PASSIVEBASELINEMAP() runs the current Stage 4 passive
%   baseline map review and writes an evidence bundle under:
%   artifacts/<datasetId>/G4_Passive_Baseline_Map/<runTimestampZ>/
%
%   This runner formalizes the implemented G4 helper slice. It does not
%   emit a formal pass / retune / reject gate decision.

arguments
    datasetId (1,1) string = "20260622T102123"
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

totalTimer = tic;
stepTimer = tic;
stageArtifactId = "G4_Passive_Baseline_Map";
repoRoot = helperResolveRepoRoot(repoRoot);
datasetId = string(datasetId);
[g4Options, runnerOptions] = localResolveRunnerOptions(options);
runTimestampZ = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss'Z'"));
bundleRoot = fullfile(repoRoot, "artifacts", datasetId, stageArtifactId, ...
    runTimestampZ);
figureRoot = fullfile(bundleRoot, "figures");
timingRows = helperMakeTimingSummaryRow(stageArtifactId, ...
    "resolve_inputs", 0.0, runnerOptions.ExecutionMode);
timingRows(1) = [];
timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
    "resolve_inputs", toc(stepTimer), runnerOptions.ExecutionMode, ...
    NaN, NaN, NaN, NaN, NaN, "");

fprintf("Running G4 Passive Baseline Map manual review for dataset %s\n", ...
    datasetId);
fprintf("Repository root:\t%s\n", repoRoot);
fprintf("Execution mode:\t%s\n", runnerOptions.ExecutionMode);

try
    localEnsureFolder(bundleRoot);
    localEnsureFolder(figureRoot);

    stepTimer = tic;
    loadOptions = struct();
    loadOptions.IncludeSamples = true;
    sessionData = loadIQData(datasetId, repoRoot, loadOptions);
    inputRepetitionCount = double(numel(sessionData.RadarScans));
    inputSampleCount = double(sum([sessionData.RadarScans.NumSamples]));
    collectionMetadataPath = fullfile(sessionData.DatasetRoot, ...
        "collection_metadata.json");
    collectionMetadataInfo = helperReadCollectionMetadata( ...
        collectionMetadataPath, datasetId);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "load_session_with_samples", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, ...
        "loadIQData IncludeSamples=true plus collection metadata parse.");

    stepTimer = tic;
    if isempty(fieldnames(runnerOptions.G3SyncResults))
        g3SyncResults = helperAnalyzeG3SyncCore(sessionData, ...
            collectionMetadataInfo, runnerOptions.G3Options);
        g3ResolutionNote = "Computed G3 sync results from current session.";
    else
        g3SyncResults = runnerOptions.G3SyncResults;
        g3ResolutionNote = "Used supplied G3 sync results.";
    end
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "resolve_g3_sync_results", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, g3ResolutionNote);

    stepTimer = tic;
    analysis = helperAnalyzeG4PassiveBaselineMap(sessionData, ...
        collectionMetadataInfo, g3SyncResults, g4Options);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "run_g4_passive_baseline_helper", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, ...
        "G4 passive-baseline map analysis helper.");

    stepTimer = tic;
    reviewSummaryTable = localBuildReviewSummaryTable(analysis);
    interpretationSummaryTable = localBuildInterpretationSummaryTable( ...
        analysis);
    cpiDefinitionsTable = localBuildCpiDefinitionTable(analysis);
    cpiComparisonTable = localBuildCpiComparisonTable(analysis);
    mapLabelCountsTable = localBuildMapLabelCountTable( ...
        analysis.MapSummaryTable);
    sceneMetricMediansTable = localBuildSceneMetricMedianTable( ...
        analysis.MapSummaryTable);
    representativeMapIndexTable = localBuildRepresentativeMapIndexTable( ...
        analysis.RepresentativeMaps);
    comparisonSummaryTable = localBuildComparisonSummaryTable(analysis);

    configSnapshot = localBuildConfigSnapshot(datasetId, repoRoot, ...
        bundleRoot, runTimestampZ, collectionMetadataInfo, analysis, ...
        runnerOptions, reviewSummaryTable);
    metricsJson = localBuildMetricsJson(runTimestampZ, bundleRoot, ...
        analysis, reviewSummaryTable);
    comparisonSnapshot = localBuildComparisonSnapshot(datasetId, ...
        runTimestampZ, bundleRoot, collectionMetadataInfo, analysis, ...
        comparisonSummaryTable);
    summaryLines = localBuildSummaryLines(bundleRoot, runTimestampZ, ...
        collectionMetadataInfo, analysis, reviewSummaryTable);
    interpretationNoteLines = localBuildInterpretationNoteLines( ...
        analysis, reviewSummaryTable);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "build_review_artifacts", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, ...
        "Review tables, snapshots, metrics JSON, and text payloads.");

    summaryPath = fullfile(bundleRoot, "summary.md");
    interpretationNotePath = fullfile(bundleRoot, ...
        "passive_baseline_interpretation_note.md");
    configSnapshotPath = fullfile(bundleRoot, "config_snapshot.json");
    metricsJsonPath = fullfile(bundleRoot, "metrics.json");
    metricsMatPath = fullfile(bundleRoot, "metrics.mat");
    rawMapFigurePath = fullfile(figureRoot, ...
        "figure_01_representative_maps_raw_axis.png");
    displayMapFigurePath = fullfile(figureRoot, ...
        "figure_02_representative_maps_display_axis.png");
    directPathFigurePath = fullfile(figureRoot, ...
        "figure_03_direct_path_trends.png");

    stepTimer = tic;
    localWriteRunnerTables(bundleRoot, reviewSummaryTable, ...
        interpretationSummaryTable, cpiDefinitionsTable, ...
        cpiComparisonTable, mapLabelCountsTable, sceneMetricMediansTable, ...
        representativeMapIndexTable, comparisonSummaryTable, analysis);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_tables", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, 13, 0, NaN, ...
        "Current Stage 4 CSV table artifact set.");

    stepTimer = tic;
    localWriteTextFile(summaryPath, summaryLines);
    localWriteTextFile(interpretationNotePath, interpretationNoteLines);
    localWriteJsonFile(configSnapshotPath, configSnapshot);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_text_artifacts", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 3, 0, NaN, ...
        "summary.md; passive baseline note; config_snapshot.json");

    stepTimer = tic;
    localWriteJsonFile(metricsJsonPath, metricsJson);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_metrics_json", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 1, 0, NaN, "metrics.json");

    stepTimer = tic;
    localWriteMetricsMat(metricsMatPath, analysis, g3SyncResults);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_metrics_mat", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, 1, 0, NaN, ...
        "metrics.mat");

    stepTimer = tic;
    try
        comparisonSnapshotPath = helperWriteComparisonSnapshot( ...
            string(bundleRoot), comparisonSnapshot);
    catch saveException
        error("runG4PassiveBaselineMap:SaveComparisonSnapshotFailed", ...
            "Failed to write Stage 4 comparison snapshot: %s", ...
            saveException.message);
    end
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_comparison_snapshot", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 1, 0, NaN, "comparison_snapshot.mat");

    stepTimer = tic;
    localRenderRepresentativeMapFigure(analysis.RepresentativeMaps, ...
        "raw", rawMapFigurePath, runnerOptions.ShowFigures);
    localRenderRepresentativeMapFigure(analysis.RepresentativeMaps, ...
        "display", displayMapFigurePath, runnerOptions.ShowFigures);
    localRenderDirectPathTrendFigure(analysis.MapSummaryTable, ...
        directPathFigurePath, runnerOptions.ShowFigures);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "render_figures", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, 3, 3, NaN, ...
        "Raw-axis maps, display-axis maps, and direct-path trends.");

    [timingSummaryTable, performanceSummary] = ...
        helperFinalizePerformanceInstrumentation(stageArtifactId, ...
        datasetId, string(bundleRoot), runTimestampZ, ...
        runnerOptions.ExecutionMode, runnerOptions.ShowFigures, ...
        timingRows, totalTimer, inputSampleCount, ...
        inputRepetitionCount, string(metricsMatPath));

    results = localBuildResults(datasetId, stageArtifactId, runTimestampZ, ...
        bundleRoot, analysis, reviewSummaryTable, ...
        interpretationSummaryTable, comparisonSnapshotPath, ...
        [string(rawMapFigurePath); string(displayMapFigurePath); ...
        string(directPathFigurePath)], timingSummaryTable, ...
        performanceSummary);

    fprintf("Overall label:\t%s\n", results.OverallLabel);
    fprintf("Analysis execution:\t%s\n", ...
        results.AnalysisExecutionAssessment);
    fprintf("Limitation source:\t%s\n", results.LimitationSourceLabel);
    fprintf("Recommended CPI:\t%s\n", ...
        results.RecommendedBaselineCpiLabel);
    fprintf("Full-rate audit agreement:\t%s\n", ...
        results.FullRateAuditAgreementLabel);
    fprintf("Bundle root:\t%s\n", bundleRoot);
catch mainException
    localWriteFailureBundle(bundleRoot, mainException);
    rethrow(mainException);
end

end
function [g4Options, runnerOptions] = localResolveRunnerOptions(options)

g4Options = options;
runnerOptions = struct();
runnerOptions.ExecutionMode = helperResolveExecutionMode(options);
runnerOptions.ShowFigures = usejava("desktop");
runnerOptions.G3SyncResults = struct();
runnerOptions.G3Options = struct();

if runnerOptions.ExecutionMode == "analysis_only"
    runnerOptions.ShowFigures = false;
end

if isfield(g4Options, "G4Options")
    explicitG4Options = g4Options.G4Options;
    g4Options = rmfield(g4Options, "G4Options");
    g4Options = localMergeStructs(g4Options, explicitG4Options);
end

if isfield(g4Options, "ShowFigures")
    runnerOptions.ShowFigures = logical(g4Options.ShowFigures);
    g4Options = rmfield(g4Options, "ShowFigures");
end

if isfield(g4Options, "G3SyncResults")
    runnerOptions.G3SyncResults = g4Options.G3SyncResults;
    g4Options = rmfield(g4Options, "G3SyncResults");
end

if isfield(g4Options, "G3Options")
    runnerOptions.G3Options = g4Options.G3Options;
    g4Options = rmfield(g4Options, "G3Options");
end

if isfield(g4Options, "ExecutionMode")
    g4Options = rmfield(g4Options, "ExecutionMode");
end

end

function mergedStruct = localMergeStructs(baseStruct, overrideStruct)

mergedStruct = baseStruct;
overrideFields = fieldnames(overrideStruct);

for idx = 1:numel(overrideFields)
    mergedStruct.(overrideFields{idx}) = overrideStruct.(overrideFields{idx});
end

end

