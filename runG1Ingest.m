payloadPacking = localJoinStringValues(readerContract.PayloadPacking);

if readerContract.RawFreadFallbackUsed
    lines = [ ...
        "# Decode Contract Summary"; ...
        ""; ...
        sprintf("- Preferred decode path: `%s`.", readerContract.PreferredReader); ...
        sprintf("- Chosen decode path: `%s`.", chosenReader); ...
        sprintf("- Native path failure category: `%s`.", ...
        localJoinStringValues(readerContract.NativeReaderFailureCategory)); ...
        sprintf("- Native path failure reason: `%s`.", ...
        localJoinStringValues(readerContract.NativeReaderFailureMessage)); ...
        "- The raw fallback is used only because the preferred native reader could not open the files in the current environment."; ...
        "- The fallback scans the embedded `BasebandVer2.0.0` wrapper directly, extracts the textual metadata block, and decodes the payload as complex `int16`."; ...
        sprintf("- Raw payload packing is frozen as `%s`.", ...
        payloadPacking); ...
        sprintf("- The observed payload offset range is `%d` to `%d` bytes from file start, which matches the wrapper-overhead range.", ...
        readerContract.PayloadOffsetBytes(1), ...
        readerContract.PayloadOffsetBytes(end)); ...
        "- Header scalar calibration is frozen as: bytes `21:28` = sample rate `double`, bytes `29:32` = data-type code `1 -> int16`, bytes `33:36` = complex flag `1`, and bytes `37:44` = center frequency `double`."; ...
        sprintf("- Canonical decoded representation remains one repetition per file as an `[N x 2]` complex `int16` matrix where `N = %d` samples.", ...
        radarScans(1).NumSamples); ...
        sprintf("- Column order is frozen as column 1 = `%s`, column 2 = `%s`, based on embedded `Antenna1`/`Antenna2` metadata and the decoded two-channel payload.", ...
        radarScans(1).Antenna1, radarScans(1).Antenna2); ...
        ""; ...
        "## Observed Decode Contract"; ...
        localStructDisplayLines(decodeSummary) ...
        ];
else
    lines = [ ...
        "# Decode Contract Summary"; ...
        ""; ...
        sprintf("- Preferred decode path: `%s`.", readerContract.PreferredReader); ...
        sprintf("- Chosen decode path: `%s`.", chosenReader); ...
        "- Raw `fread` fallback was not used because the native reader opened all files, exposed embedded metadata, and reproduced the expected sample and channel counts consistently."; ...
        sprintf("- Canonical decoded representation is one repetition per file as an `[N x 2]` complex `int16` matrix where `N = %d` samples.", ...
        radarScans(1).NumSamples); ...
        sprintf("- Column order is frozen as column 1 = `%s`, column 2 = `%s`, based on embedded `Antenna1`/`Antenna2` metadata and the presence of two distinct loaded channels in every file.", ...
        radarScans(1).Antenna1, radarScans(1).Antenna2); ...
        ""; ...
        "## Observed Decode Contract"; ...
        localStructDisplayLines(decodeSummary) ...
        ];
end

end

function lines = localBuildTimingContractLines(manifest, radarScans)

recordingUtcVector = [radarScans.RecordingUTC].';
recordingUtcDelta = diff(recordingUtcVector);
sampleSpanBoundaryVector = [radarScans(1:end - 1).SampleSpan_s].';
wallClockMinusSampleSpan = recordingUtcDelta - sampleSpanBoundaryVector;
wallClockMinusSampleSpanAndRequestedSpacing = wallClockMinusSampleSpan - ...
    manifest.capture_repetition_spacing_s;
dateTimeVsRecordingMs = [radarScans.DateTimeVsRecording_ms].';

lines = [ ...
    "# Timing Contract Note"; ...
    ""; ...
    sprintf("- Manifest `capture_duration_s` = `%.6f s`.", ...
        manifest.capture_duration_s); ...
    sprintf("- Observed sample span per file = `%.6f s` from `NumSamples / SampleRate`.", ...
        radarScans(1).SampleSpan_s); ...
    sprintf("- Manifest `capture_repetition_spacing_s` = `%.6f s` is treated as requested pause spacing, not as the expected embedded header delta.", ...
        manifest.capture_repetition_spacing_s); ...
    sprintf("- Embedded `RecordingUTC` boundary deltas range from `%.6f s` to `%.6f s`.", ...
        min(recordingUtcDelta), max(recordingUtcDelta)); ...
    sprintf("- Boundary delta minus sample span ranges from `%.6f s` to `%.6f s`.", ...
        min(wallClockMinusSampleSpan), max(wallClockMinusSampleSpan)); ...
    sprintf("- Boundary delta minus `(sample span + manifest repetition spacing)` ranges from `%.6f s` to `%.6f s`.", ...
        min(wallClockMinusSampleSpanAndRequestedSpacing), ...
        max(wallClockMinusSampleSpanAndRequestedSpacing)); ...
    sprintf("- Embedded `DateTime` corroborates `RecordingUTC` within `%.3f ms` max absolute difference.", ...
        max(abs(dateTimeVsRecordingMs))); ...
    sprintf("- Manifest `radar_epoch_utc` differs from repetition 1 `RecordingUTC` by `%.6f s`.", ...
        abs(manifest.radar_epoch_utc - radarScans(1).RecordingUTC)); ...
    "- Authoritative downstream radar time base is frozen as the per-file `RecordingUTC` repetition anchor sequence, with embedded `DateTime` as corroboration."; ...
    "- `radar_epoch_utc` is treated as the session first-repetition anchor because it matches repetition 1 `RecordingUTC` within tolerance."; ...
    "- The positive residual after subtracting `(sample span + requested repetition spacing)` is interpreted as capture-loop and file-writer overhead, not as a seam defect."; ...
    "- The timing contract explicitly separates per-file sample-span time from inter-file wall-clock repetition timing. Inter-file wall-clock gaps are not treated as seam defects by default." ...
    ];

end

function lines = localBuildCpiContractLines(radarScans)

lines = [ ...
    "# CPI Segmentation Contract Summary"; ...
    ""; ...
    "- CPI segmentation is frozen as intra-file only by default."; ...
    "- Each radar file is one repetition boundary and no CPI may start in one file and continue into the next file unless a later gate explicitly reopens G1 and justifies cross-file integration."; ...
    sprintf("- For any future CPI length `L`, allowable 1-based window starts within repetition `r` are `1` through `N-L+1`, where `N = %d` samples for this dataset.", ...
        radarScans(1).NumSamples); ...
    "- Overlap is permitted only when the entire overlapped window remains inside a single repetition."; ...
    "- Downstream G4/G6 work may choose CPI length and overlap, but not reinterpret repetition seams." ...
    ];

end

function decodeSummary = localBuildDecodeSummaryStruct(radarScans, ...
    readerContract)

decodeSummary = struct();
decodeSummary.PreferredReader = readerContract.PreferredReader;
decodeSummary.Reader = readerContract.Reader;
decodeSummary.RawFreadFallbackUsed = readerContract.RawFreadFallbackUsed;
decodeSummary.FileCount = numel(radarScans);
decodeSummary.NumSamplesPerFile = unique([radarScans.NumSamples].');
decodeSummary.NumChannels = unique([radarScans.NumChannels].');
decodeSummary.DataType = unique(string({radarScans.DataType}).');
decodeSummary.ComplexMatrix = all([radarScans.IsComplex].');
decodeSummary.Channel1Label = unique(string({radarScans.Antenna1}).');
decodeSummary.Channel2Label = unique(string({radarScans.Antenna2}).');
decodeSummary.SampleRateHz = unique([radarScans.SampleRate].');
decodeSummary.CenterFrequencyHz = unique([radarScans.CenterFrequency].');
decodeSummary.PayloadBytes = unique([radarScans.PayloadBytes].');
decodeSummary.PayloadOffsetBytes = readerContract.PayloadOffsetBytes;
decodeSummary.WrapperOverheadBytes = [ ...
    min([radarScans.WrapperOverheadBytes].'), ...
    max([radarScans.WrapperOverheadBytes].') ...
    ];
decodeSummary.MetadataSource = readerContract.MetadataSource;

if readerContract.RawFreadFallbackUsed
    decodeSummary.NativeReaderFailureCategory = ...
        localJoinStringValues(readerContract.NativeReaderFailureCategory);
    decodeSummary.NativeReaderFailureMessage = ...
        localJoinStringValues(readerContract.NativeReaderFailureMessage);
    decodeSummary.HeaderVersion = ...
        localJoinStringValues(readerContract.HeaderVersion);
    decodeSummary.PayloadPacking = ...
        localJoinStringValues(readerContract.PayloadPacking);
end

end

function configSnapshot = localBuildConfigSnapshot(manifest, datasetId, gateId, ...
    repoRoot, bundleRoot, runTimestampZ, sessionData)

configSnapshot = struct();
configSnapshot.dataset_id = datasetId;
configSnapshot.gate_id = gateId;
configSnapshot.run_timestamp_z = runTimestampZ;
configSnapshot.entry_point = "runG1Ingest";
configSnapshot.repo_root = repoRoot;
configSnapshot.bundle_root = string(bundleRoot);
configSnapshot.native_reader = sessionData.NativeReaderContract.PreferredReader;
configSnapshot.chosen_decode_path = sessionData.NativeReaderContract.Reader;
