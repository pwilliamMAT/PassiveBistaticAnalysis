    ];

end

function text = localJoinStringValues(values)

values = unique(string(values));
values = regexprep(values, "\s+", " ");
values = strtrim(values);
values = values(strlength(values) > 0);

if isempty(values)
    text = "";
else
    text = join(values, " | ");
    text = text(1);
end

end

function text = localLogicalWord(value)

if value
    text = "yes";
else
    text = "no";
end

end
