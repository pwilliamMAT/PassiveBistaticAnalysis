function joinedText = localJoinComparisonTokens(values)

tokens = string(values(:));
tokens = strtrim(tokens);
tokens = tokens(strlength(tokens) > 0);

if isempty(tokens)
    joinedText = "";
    return
end

joinedText = strjoin(tokens, " | ");

end

