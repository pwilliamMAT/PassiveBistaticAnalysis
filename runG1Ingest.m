        ];
end

end

function lines = localBuildCaptureProvenanceLines(manifest, radarScans, ...
    readerContract)

recordingUtcDatetime = datetime([radarScans.RecordingUTC], ...
    "ConvertFrom", "posixtime", "TimeZone", "UTC");
recordingUtcDatetime.TimeZone = "America/New_York";

if readerContract.RawFreadFallbackUsed
    decodePathLines = [ ...
        sprintf("- The preferred native reader `%s` was attempted first but could not be used because: `%s`.", ...
        readerContract.PreferredReader, localJoinStringValues( ...
        readerContract.NativeReaderFailureMessage)); ...
        sprintf("- The dual-channel contract is preserved by a calibrated raw fallback that decodes the embedded `BasebandVer2.0.0` wrapper into an `[N x 2]` complex `int16` matrix with payload packing `%s`.", ...
        localJoinStringValues(readerContract.PayloadPacking)) ...
        ];
else
    decodePathLines = ...
        "- The dual-channel contract is preserved natively by `comm.BasebandFileReader` as a two-column complex matrix.";
end

lines = [ ...
    "# Capture Provenance Interpretation Summary"; ...
    ""; ...
    "- The observed radar files match the documented `comm.BasebandFileWriter` provenance."; ...
    "- Each radar file is treated as one capture repetition, not as a shard of a default continuous recording."; ...
    "- The embedded metadata records `Repetition`, `RecordingUTC`, and `DateTime` before the file writer is opened for that repetition."; ...
    decodePathLines; ...
    sprintf("- The first repetition anchor `%s` matches the manifest `radar_epoch_utc` within tolerance.", ...
        string(recordingUtcDatetime(1))); ...
    sprintf("- The manifest declares `%d` repetitions and `%d` radar files were decoded successfully.", ...
        manifest.capture_repetitions, numel(radarScans)); ...
    "- The larger wall-clock gaps between files are interpreted as repetition-level capture timing, including capture blocking time, file-writer overhead, and the requested pause between repetitions." ...
    ];

end

