function results = runG1Ingest(datasetId, repoRoot)
%RUNG1INGEST Execute the G1 ingest gate for a passive bistatic session.
%
%   RESULTS = RUNG1INGEST() runs G1 on the reference dataset
%   20260622T102123 and writes an evidence bundle under:
%   artifacts/<datasetId>/G1_Ingest/<runTimestampZ>/
%
%   RESULTS = RUNG1INGEST(DATASETID, REPOROOT) allows the dataset ID and
%   repository root to be overridden. This gate runner uses LOADIQDATA as
%   its reusable session-ingest dependency.

arguments
    datasetId (1,1) string = "20260622T102123"
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
end

gateId = "G1_Ingest";
repoRoot = helperResolveRepoRoot(repoRoot);
datasetId = string(datasetId);
runTimestampZ = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss'Z'"));
bundleRoot = fullfile(repoRoot, "artifacts", datasetId, gateId, runTimestampZ);
figureRoot = fullfile(bundleRoot, "figures");
logRoot = fullfile(bundleRoot, "logs");

fprintf("Running %s for dataset %s\n", gateId, datasetId);
fprintf("Repository root:\t%s\n", repoRoot);

try
    localEnsureFolder(bundleRoot);
    localEnsureFolder(figureRoot);
    localEnsureFolder(logRoot);

    loadOptions = struct();
    loadOptions.IncludeSamples = false;
    sessionData = loadIQData(datasetId, repoRoot, loadOptions);
    manifest = sessionData.Manifest;
    manifestTable = sessionData.ManifestInventoryTable;
    radarScans = sessionData.RadarScans;
    radarTable = sessionData.RadarTable;
    seamTable = sessionData.SeamTable;
    readerContract = sessionData.NativeReaderContract;
    [decision, failureCause, nextBranch, passFlags] = localDetermineDecision( ...
        manifest, manifestTable, radarScans, seamTable);

    summaryLines = localBuildSummaryLines(manifest, passFlags, ...
        decision, nextBranch, manifestTable, radarScans, seamTable, ...
        bundleRoot, runTimestampZ, readerContract);
    captureProvenanceLines = localBuildCaptureProvenanceLines(manifest, ...
        radarScans, readerContract);
    decodeContractLines = localBuildDecodeContractLines(radarScans, ...
        readerContract);
    timingContractLines = localBuildTimingContractLines(manifest, radarScans);
    cpiContractLines = localBuildCpiContractLines(radarScans);
    decodeFigureLines = localBuildDecodeFigureLines(radarScans, ...
        readerContract);

    requirementsCoverageTable = table( ...
        ["ING-001"; "ING-002"; "ING-003"; "ING-004"], ...
        repmat(decision, 4, 1), ...
        [ ...
            "manifest_vs_observed.csv; figures/figure_01_manifest_vs_observed.png"; ...
            "decode_contract_summary.md; radar_metadata_scan.csv; figures/figure_03_decode_contract_summary.png"; ...
            "timing_contract_note.md; seam_continuity_summary.csv; figures/figure_02_seam_continuity_summary.png"; ...
            "cpi_segmentation_contract_summary.md; summary.md" ...
            ], ...
        [ ...
            "Required radar, truth, and log artifacts reconciled against the manifest."; ...
            "Decode contract frozen with channel order, wrapper-overhead reconciliation, and native-reader fallback provenance when needed."; ...
            "Per-file sample-span timing separated from wall-clock repetition timing."; ...
            "Intra-file-only CPI segmentation frozen for downstream gates." ...
            ], ...
        VariableNames = {'RequirementId', 'Status', 'EvidenceReference', 'Notes'});

    configSnapshot = localBuildConfigSnapshot(manifest, datasetId, gateId, ...
        repoRoot, bundleRoot, runTimestampZ, sessionData);
    metrics = localBuildMetrics(manifest, manifestTable, radarScans, seamTable, ...
        passFlags, decision, nextBranch, readerContract);
    comparisonSnapshot = localBuildComparisonSnapshot(datasetId, gateId, ...
        runTimestampZ, bundleRoot, decision, nextBranch, passFlags, metrics);

    manifestCsvPath = fullfile(bundleRoot, "manifest_vs_observed.csv");
    radarScanCsvPath = fullfile(bundleRoot, "radar_metadata_scan.csv");
    seamCsvPath = fullfile(bundleRoot, "seam_continuity_summary.csv");
    summaryPath = fullfile(bundleRoot, "summary.md");
    captureProvenancePath = fullfile(bundleRoot, ...
        "capture_provenance_interpretation_summary.md");
    decodeContractPath = fullfile(bundleRoot, "decode_contract_summary.md");
    timingContractPath = fullfile(bundleRoot, "timing_contract_note.md");
    cpiContractPath = fullfile(bundleRoot, ...
        "cpi_segmentation_contract_summary.md");
    requirementsCoveragePath = fullfile(bundleRoot, "requirements_coverage.csv");
    configSnapshotPath = fullfile(bundleRoot, "config_snapshot.json");
    metricsJsonPath = fullfile(bundleRoot, "metrics.json");
    metricsMatPath = fullfile(bundleRoot, "metrics.mat");
    decisionPath = fullfile(bundleRoot, "decision.txt");
    nextBranchPath = fullfile(bundleRoot, "next_branch.txt");
    failureCausePath = fullfile(bundleRoot, "failure_cause.txt");
    manifestFigurePath = fullfile(figureRoot, ...
        "figure_01_manifest_vs_observed.png");
    seamFigurePath = fullfile(figureRoot, ...
        "figure_02_seam_continuity_summary.png");
    decodeFigurePath = fullfile(figureRoot, ...
        "figure_03_decode_contract_summary.png");

    try
        writetable(manifestTable, manifestCsvPath);
        writetable(radarTable, radarScanCsvPath);
        writetable(seamTable, seamCsvPath);
        writetable(requirementsCoverageTable, requirementsCoveragePath);
    catch writeTableException
        error("runG1Ingest:WriteTableFailed", ...
            "Failed to write a bundle table artifact: %s", ...
            writeTableException.message);
    end

    localWriteTextFile(summaryPath, summaryLines);
    localWriteTextFile(captureProvenancePath, captureProvenanceLines);
    localWriteTextFile(decodeContractPath, decodeContractLines);
    localWriteTextFile(timingContractPath, timingContractLines);
    localWriteTextFile(cpiContractPath, cpiContractLines);
    localWriteTextFile(decisionPath, decision);
    localWriteTextFile(nextBranchPath, nextBranch);

    if decision ~= "pass"
        localWriteTextFile(failureCausePath, failureCause);
    end

    localWriteJsonFile(configSnapshotPath, configSnapshot);
    localWriteJsonFile(metricsJsonPath, metrics);

    try
        save(metricsMatPath, "metrics", "manifestTable", "radarTable", ...
            "seamTable", "requirementsCoverageTable");
    catch saveException
        error("runG1Ingest:SaveMetricsFailed", ...
            "Failed to write metrics.mat: %s", saveException.message);
    end

    try
        comparisonSnapshotPath = helperWriteComparisonSnapshot( ...
            string(bundleRoot), comparisonSnapshot);
    catch saveException
        error("runG1Ingest:SaveComparisonSnapshotFailed", ...
            "Failed to write G1 comparison snapshot: %s", ...
            saveException.message);
    end

    helperRenderTextSummaryFigure(localTableDisplayLines(manifestTable), ...
        "G1 Manifest vs Observed", manifestFigurePath);
    helperRenderTextSummaryFigure(localTableDisplayLines(seamTable), ...
        "G1 Seam Continuity Summary", seamFigurePath);
    helperRenderTextSummaryFigure(decodeFigureLines, ...
        "G1 Decode Contract Summary", decodeFigurePath);

    results = struct();
    results.DatasetId = datasetId;
    results.GateId = gateId;
    results.RunTimestampZ = runTimestampZ;
    results.BundleRoot = string(bundleRoot);
    results.Decision = decision;
    results.NextBranch = nextBranch;
    results.PassFlags = passFlags;
    results.Metrics = metrics;
    results.ComparisonSnapshotPath = string(comparisonSnapshotPath);

    fprintf("Decision:\t%s\n", decision);
    fprintf("Next branch:\t%s\n", nextBranch);
    fprintf("Bundle root:\t%s\n", bundleRoot);
catch mainException
    localWriteFailureBundle(bundleRoot, mainException);
    rethrow(mainException);
end

end

function [decision, failureCause, nextBranch, passFlags] = localDetermineDecision( ...
    manifest, manifestTable, radarScans, seamTable)

requiredRows = manifestTable.RequiredByManifest;
missingRequiredCount = nnz(requiredRows & ~manifestTable.Observed);
unexpectedSourceArtifactCount = nnz( ...
    manifestTable.Status == "unexpected_extra_source_artifact");
scanCount = numel(radarScans);

repetitionVector = zeros(scanCount, 1);
sampleSpanVector = zeros(scanCount, 1);
durationVector = zeros(scanCount, 1);
recordingUtcVector = zeros(scanCount, 1);
sampleRateVector = zeros(scanCount, 1);
centerFrequencyVector = zeros(scanCount, 1);
channelCountVector = zeros(scanCount, 1);
isComplexVector = false(scanCount, 1);
channel1Labels = strings(scanCount, 1);
channel2Labels = strings(scanCount, 1);
sessionIdVector = strings(scanCount, 1);

for idx = 1:scanCount
    repetitionVector(idx) = radarScans(idx).Repetition;
    sampleSpanVector(idx) = radarScans(idx).SampleSpan_s;
    durationVector(idx) = radarScans(idx).Duration_s;
    recordingUtcVector(idx) = radarScans(idx).RecordingUTC;
    sampleRateVector(idx) = radarScans(idx).SampleRate;
    centerFrequencyVector(idx) = radarScans(idx).CenterFrequency;
    channelCountVector(idx) = radarScans(idx).NumChannels;
    isComplexVector(idx) = radarScans(idx).IsComplex;
    channel1Labels(idx) = radarScans(idx).Antenna1;
    channel2Labels(idx) = radarScans(idx).Antenna2;
    sessionIdVector(idx) = radarScans(idx).SessionID;
end

recordingUtcDelta = diff(recordingUtcVector);
requestedSpacingSeconds = manifest.capture_repetition_spacing_s;
sampleSpanBoundaryVector = sampleSpanVector(1:end - 1);
wallClockMinusSampleSpan = recordingUtcDelta - sampleSpanBoundaryVector;
wallClockMinusSampleSpanAndRequestedSpacing = wallClockMinusSampleSpan - ...
    requestedSpacingSeconds;
dateTimeVsRecordingMs = [radarScans.DateTimeVsRecording_ms].';
allWrapperOverheadPositive = all([radarScans.WrapperOverheadBytes].' > 0);
allNativePayloadCountsStable = isscalar(unique([radarScans.NumSamples].'));

passFlags = struct();
passFlags.InventoryReconciled = missingRequiredCount == 0 && ...
    unexpectedSourceArtifactCount == 0;
passFlags.DecodeContractConfirmed = ...
    allNativePayloadCountsStable && ...
    all(sampleRateVector == manifest.sdr_defaults.sample_rate_hz) && ...
    all(centerFrequencyVector == manifest.sdr_defaults.center_frequency_hz) && ...
    all(channelCountVector == 2) && ...
    all(isComplexVector) && ...
    allWrapperOverheadPositive;
passFlags.ChannelContractConfirmed = ...
    all(channel1Labels == "RF0:RX2") && ...
    all(channel2Labels == "RF1:RX2");
passFlags.TimingModelFrozen = ...
    all(abs(sampleSpanVector - manifest.capture_duration_s) < 1e-12) && ...
    all(abs(durationVector - manifest.capture_duration_s) < 1e-12) && ...
    all(wallClockMinusSampleSpan >= -1e-6) && ...
    all(wallClockMinusSampleSpanAndRequestedSpacing >= -1e-6) && ...
    abs(recordingUtcVector(1) - manifest.radar_epoch_utc) < 0.01 && ...
    max(abs(dateTimeVsRecordingMs)) < 25;
passFlags.SeamChecksPassed = isempty(seamTable) || ...
    all(seamTable.RepetitionIncrement == 1) && ...
    all(seamTable.SampleCountStable) && ...
    all(seamTable.MetadataStable) && ...
    all(seamTable.DecodeContractStable) && ...
    all(seamTable.Status == "ok_gap_expected");
passFlags.CpiSegmentationFrozen = true;
passFlags.ManifestOrderConfirmed = isequal(repetitionVector, (1:scanCount).');
passFlags.SessionIdConfirmed = all(sessionIdVector == string(manifest.session_id));

hardReject = ~passFlags.InventoryReconciled || ...
    ~passFlags.DecodeContractConfirmed || ...
    ~passFlags.ChannelContractConfirmed || ...
    ~passFlags.SeamChecksPassed || ...
    ~passFlags.ManifestOrderConfirmed || ...
    ~passFlags.SessionIdConfirmed;
softRetune = ~passFlags.TimingModelFrozen || ~passFlags.CpiSegmentationFrozen;

if hardReject
    decision = "reject";
elseif softRetune
    decision = "retune";
else
    decision = "pass";
end

if decision == "pass"
    failureCause = "";
    nextBranch = "Proceed to G2_RF_Health with the frozen G1 ingest contract.";
elseif decision == "retune"
    failureCause = "Retune G1 timing semantics before downstream processing.";
    nextBranch = "Retune G1 timing assumptions and rerun G1_Ingest.";
else
    failureCause = "Required ingest contract checks did not pass.";
    nextBranch = "Do not open G2. Rework G1 ingest assumptions or reject the dataset.";
end

end

