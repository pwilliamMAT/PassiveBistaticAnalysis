function impulse = localImpulseMetrics(coefficients, sampleRateHz)

energy = abs(double(coefficients(:))) .^ 2;
energy = energy ./ max(sum(energy), eps);
delay_us = (0:numel(coefficients) - 1).' ./ sampleRateHz .* 1.0e6;
first95Index = find(cumsum(energy) >= 0.95, 1, "first");

impulse = struct();
impulse.FirSpan_us = delay_us(end);
impulse.EnergyCentroidDelay_us = sum(delay_us .* energy);
impulse.Energy95Delay_us = delay_us(first95Index);

end

