function manifest = localBuildReportManifest(result, bundleRoot)

entries = dir(fullfile(bundleRoot, "**", "*"));
entries = entries(~[entries.isdir]);
filePath = string(fullfile({entries.folder}, {entries.name})).';
relativePath = erase(filePath, string(bundleRoot) + filesep);
bytes = double([entries.bytes]).';
sha256 = strings(numel(entries), 1);
rowCount = nan(numel(entries), 1);

for entryIndex = 1:numel(entries)
    sha256(entryIndex) = helperG4RSha256(filePath(entryIndex));

    if endsWith(lower(relativePath(entryIndex)), ".csv")
        try
            rowCount(entryIndex) = height(readtable(filePath(entryIndex)));
        catch
            rowCount(entryIndex) = NaN;
        end
    end
end

manifest = struct();
manifest.SchemaVersion = "g4r_cancellation_report_manifest_v1";
manifest.ArtifactTable = table(relativePath, bytes, sha256, rowCount);
manifest.HtmlPath = "summary.html";
manifest.HtmlLinks = result.ArtifactLinkTable;
manifest.ExternalDependencyFree = isfield(result, "HtmlReport") && ...
    result.HtmlReport.ExternalDependencyFree;

end

