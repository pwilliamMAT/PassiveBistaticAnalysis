function result = runG4RCancellationCharacterization(repoRoot, options)
%RUNG4RCANCELLATIONCHARACTERIZATION Isolate the failed R5A cancellation path.
%
%   RESULT = RUNG4RCANCELLATIONCHARACTERIZATION(REPOROOT, OPTIONS) runs a
%   separate G4-R diagnostic over three fixed saved backgrounds. It compares
%   native-first cancellation with the historical independently reset
%   native/reduced NLMS behavior. This runner does not alter R5A evidence,
%   detector support, G5 selection, or formal G5/G6/G8 status.

arguments
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

repoRoot = helperResolveRepoRoot(repoRoot);
resolvedOptions = localResolveOptions(repoRoot, options);
runTimestampZ = string(datetime("now", TimeZone="UTC", ...
    Format="yyyyMMdd'T'HHmmssSSS'Z'"));
bundleRoot = localResolveBundleRoot(repoRoot, resolvedOptions, runTimestampZ);
totalTimer = tic;
manifest = localBuildManifest(resolvedOptions);

if resolvedOptions.SaveResult
    localEnsureFolder(bundleRoot);
end

try
    if resolvedOptions.ExecutionMode == "dry_run"
        result = localBuildDryRunResult( ...
            runTimestampZ, bundleRoot, resolvedOptions, manifest, ...
            toc(totalTimer));
        localWriteResultBundle(result, resolvedOptions, false);
        return
    end

    selectionTimer = tic;
    shardBenchmark = localLoadShardBenchmarkContract(resolvedOptions);

    if resolvedOptions.ExecutionMode == "background_shard"
        selectionStage = localBuildShardSelectionStage(shardBenchmark, ...
            resolvedOptions);
    else
        selectionStage = localRunWienerSelectionStage( ...
            repoRoot, resolvedOptions, manifest);
    end

    selectionElapsed_s = toc(selectionTimer);

    if resolvedOptions.ExecutionMode == "background_shard"
        shard = localRunBackgroundShard( ...
            repoRoot, resolvedOptions.BackgroundId, selectionStage, ...
            resolvedOptions, manifest);
        result = localBuildResult( ...
            runTimestampZ, bundleRoot, resolvedOptions, manifest, ...
            selectionStage, shard, localEmptyProjection(), ...
            toc(totalTimer));
        localWriteResultBundle(result, resolvedOptions, false);
        return
    end

    benchmarkBackgroundId = resolvedOptions.BackgroundIds(1);
    benchmarkTimer = tic;
    benchmarkShard = localRunBackgroundShard( ...
        repoRoot, benchmarkBackgroundId, selectionStage, ...
        resolvedOptions, manifest);
    benchmarkElapsed_s = toc(benchmarkTimer);
    projection = localBuildProjection( ...
        selectionElapsed_s, benchmarkElapsed_s, resolvedOptions);

    if resolvedOptions.ExecutionMode == "benchmark"
        result = localBuildResult( ...
            runTimestampZ, bundleRoot, resolvedOptions, manifest, ...
            selectionStage, benchmarkShard, projection, toc(totalTimer));
        result.Outcome = "benchmark_completed_not_full_characterization";
        result.NextAction = localBenchmarkNextAction(projection);
        localWriteResultBundle(result, resolvedOptions, false);
        return
    end

    if ~projection.FitsAuthorizedBudget
        result = localBuildResult( ...
            runTimestampZ, bundleRoot, resolvedOptions, manifest, ...
            selectionStage, benchmarkShard, projection, toc(totalTimer));
        result.Outcome = "full_study_not_launched_time_projection";
        result.NextAction = localBenchmarkNextAction(projection);
        localWriteResultBundle(result, resolvedOptions, false);
        return
    end

    if resolvedOptions.ExecutionMode == "auto"
        result = localBuildResult( ...
            runTimestampZ, bundleRoot, resolvedOptions, manifest, ...
            selectionStage, benchmarkShard, projection, toc(totalTimer));
        result.Outcome = ...
            "benchmark_fit_requires_isolated_background_shards";
        result.DecisionRationale = ...
            "The measured projection fits the authorized budget, but the study contract requires three isolated background shards and an exact coordinator audit rather than serial execution.";
        result.NextAction = localBuildShardLaunchAction( ...
            bundleRoot, selectionStage.Selection);
        localWriteResultBundle(result, resolvedOptions, false);
        return
    end

catch runException
    localWriteFailure(bundleRoot, runException);
    rethrow(runException)
end

end

