function truth = localEvaluateTruthWindow( ...
        referenceSignal, residualSignal, sampleRateHz, expectedDelay_s, ...
        expectedDoppler_Hz, cpiDuration_s)

mapProduct = helperFormG4ProductionMap( ...
    referenceSignal, residualSignal, sampleRateHz, ...
    [1.0 ./ cpiDuration_s 1.0 ./ cpiDuration_s]);
power = double(mapProduct.Power);
delayAxis_s = mapProduct.DelayAxis_s;
dopplerAxis_Hz = mapProduct.DopplerAxis_Hz;
delaySpacing_s = median(diff(delayAxis_s));
dopplerSpacing_Hz = median(diff(dopplerAxis_Hz));
[delayGrid_s, dopplerGrid_Hz] = meshgrid(delayAxis_s, dopplerAxis_Hz);
truthMask = abs(delayGrid_s - expectedDelay_s) <= delaySpacing_s & ...
    abs(dopplerGrid_Hz - expectedDoppler_Hz) <= dopplerSpacing_Hz;
localRequire(any(truthMask, "all"), ...
    "runG4RCancellationCharacterization:TruthWindow", ...
    "The fixed target truth window lies outside the map.");
truthMap = power;
truthMap(~truthMask) = -Inf;
[~, peakIndex] = max(truthMap, [], "all");
[peakRow, peakColumn] = ind2sub(size(truthMap), peakIndex);
localMask = abs(delayGrid_s - expectedDelay_s) <= ...
    4.0 .* delaySpacing_s & abs(dopplerGrid_Hz - expectedDoppler_Hz) <= ...
    4.0 .* dopplerSpacing_Hz;
backgroundMask = localMask & ~truthMask;
backgroundValues = power(backgroundMask);

if isempty(backgroundValues)
    backgroundValues = power(~truthMask);
end

truth = struct();
truth.TruthWindowEnergy = sum(power(truthMask), "all");
truth.PeakDelay_s = delayAxis_s(peakColumn);
truth.PeakDoppler_Hz = dopplerAxis_Hz(peakRow);
truth.DelayError_cells = abs( ...
    truth.PeakDelay_s - expectedDelay_s) ./ delaySpacing_s;
truth.DopplerError_cells = abs( ...
    truth.PeakDoppler_Hz - expectedDoppler_Hz) ./ dopplerSpacing_Hz;
truth.PeakWithinOneCell = truth.DelayError_cells <= 1.0 && ...
    truth.DopplerError_cells <= 1.0;
truth.LocalTruthToBackground_dB = pow2db( ...
    max(max(power(truthMask)), eps) ./ ...
    max(median(backgroundValues, "omitnan"), eps));

clear power mapProduct

end

