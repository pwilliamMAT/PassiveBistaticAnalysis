function window = localCenterWindow( ...
        referenceSignal, surveillanceSignal, sampleRateHz, cpiDuration_s)

sampleCount = round(cpiDuration_s .* sampleRateHz);
startSample = floor((numel(referenceSignal) - sampleCount) ./ 2.0) + 1.0;
stopSample = startSample + sampleCount - 1.0;

if startSample < 1 || stopSample > numel(referenceSignal)
    error("runG4RCancellationCharacterization:CpiWindow", ...
        "The fixed 100 ms center window lies outside the score capture.");
end

window = struct();
window.Reference = double(referenceSignal(startSample:stopSample));
window.Surveillance = double(surveillanceSignal(startSample:stopSample));
window.StartSample = double(startSample);
window.StopSample = double(stopSample);
window.SampleCount = double(sampleCount);

end

