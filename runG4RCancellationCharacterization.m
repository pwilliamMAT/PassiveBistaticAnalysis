function [product, coefficientRecord] = localApplyStudyMethod( ...
        method, calibrationWindow, score, scoreWindow, scoreDomain, ...
        reducedStart, reducedStop, selection, resolvedOptions)

nativeReference = scoreDomain.FilteredNativeReference( ...
    scoreWindow.StartSample:scoreWindow.StopSample);
reducedReference = scoreDomain.ReferenceReduced(reducedStart:reducedStop);
coefficientRecord = repmat(localCoefficientRecordTemplate(), 0, 1);

switch method
    case "none"
        nativeResidual = scoreDomain.FilteredNativeSurveillance( ...
            scoreWindow.StartSample:scoreWindow.StopSample);
        reducedResidual = scoreDomain.SurveillanceReduced( ...
            reducedStart:reducedStop);
        nativeInfo = localNoneInfo();
        reducedInfo = localNoneInfo();
        nativeInput = nativeResidual;
        reducedInput = reducedResidual;
        filterOrder = "r4_filter_then_no_cancellation";
    case "current_reset_nlms"
        nativeInput = scoreDomain.FilteredNativeSurveillance( ...
            scoreWindow.StartSample:scoreWindow.StopSample);
        reducedInput = scoreDomain.SurveillanceReduced( ...
            reducedStart:reducedStop);
        nativeInfo = localApplyResetNlms( ...
            nativeReference, nativeInput, resolvedOptions);
        reducedInfo = localApplyResetNlms( ...
            reducedReference, reducedInput, resolvedOptions);
        nativeResidual = nativeInfo.ResidualSignal;
        reducedResidual = reducedInfo.ResidualSignal;
        filterOrder = "r4_filter_then_independent_reset_nlms_at_each_rate";
    case "frozen_native_nlms"
        nativeInfo = helperApplyG4RNativeFirstCancellation( ...
            calibrationWindow.Reference, calibrationWindow.Surveillance, ...
            score.Reference, score.Surveillance, "frozen_nlms", ...
            localNativeFirstOptions(resolvedOptions));
        [nativeResidual, reducedResidual] = localResampleNativeResidual( ...
            nativeInfo.ResidualSignal, scoreWindow, reducedStart, ...
            reducedStop, scoreDomain.FilterCoefficients, ...
            resolvedOptions.DecimationFactor);
        nativeInput = scoreDomain.FilteredNativeSurveillance( ...
            scoreWindow.StartSample:scoreWindow.StopSample);
        reducedInput = scoreDomain.SurveillanceReduced( ...
            reducedStart:reducedStop);
        reducedInfo = nativeInfo;
        filterOrder = "native_nlms_calibration_then_frozen_score_then_r4_resample";
    case "wiener_fir"
        estimate = helperEstimateG4RWienerFir( ...
            calibrationWindow.Reference, calibrationWindow.Surveillance, ...
            selection.SelectedTapCount, ...
            struct("RegularizationFraction", ...
            resolvedOptions.WienerRegularizationFraction));
        nativeInfo = helperApplyG4RNativeFirstCancellation( ...
            calibrationWindow.Reference, calibrationWindow.Surveillance, ...
            score.Reference, score.Surveillance, "wiener_fir", ...
            struct("WienerCoefficients", estimate.Coefficients));
        [nativeResidual, reducedResidual] = localResampleNativeResidual( ...
            nativeInfo.ResidualSignal, scoreWindow, reducedStart, ...
            reducedStop, scoreDomain.FilterCoefficients, ...
            resolvedOptions.DecimationFactor);
        nativeInput = scoreDomain.FilteredNativeSurveillance( ...
            scoreWindow.StartSample:scoreWindow.StopSample);
        reducedInput = scoreDomain.SurveillanceReduced( ...
            reducedStart:reducedStop);
        reducedInfo = nativeInfo;
        filterOrder = "native_wiener_fir_then_r4_resample";
        coefficientRecord = localCoefficientRecord( ...
            selection.SelectedTapCount, estimate);
    otherwise
        error("runG4RCancellationCharacterization:Method", ...
            "Unexpected study method %s.", method);
end

product = struct();
product.NativeReference = nativeReference;
product.NativeInput = nativeInput;
product.NativeResidual = nativeResidual;
product.ReducedReference = reducedReference;
product.ReducedInput = reducedInput;
product.ReducedResidual = reducedResidual;
product.NativeInfo = nativeInfo;
product.ReducedInfo = reducedInfo;
product.FilterOrder = filterOrder;
product.NativeWindowStartSample = scoreWindow.StartSample;
product.ReducedWindowStartSample = reducedStart;

end

