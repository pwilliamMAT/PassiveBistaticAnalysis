localRequire(isfield(loaded, "result"), ...
    "runG4RCancellationCharacterization:ShardBenchmark", ...
    "Benchmark file does not contain result: %s", resultPath);
benchmarkResult = loaded.result;
localRequire(isfield(benchmarkResult, "Projection") && ...
    isfield(benchmarkResult.Projection, "FitsAuthorizedBudget") && ...
    logical(benchmarkResult.Projection.FitsAuthorizedBudget), ...
    "runG4RCancellationCharacterization:ShardBudget", ...
    "Benchmark projection must fit the authorized budget before any shard launches.");
localRequire(isfield(benchmarkResult, "Manifest") && ...
    isfield(benchmarkResult.Manifest, "ExpectedControlCount") && ...
    double(benchmarkResult.Manifest.ExpectedControlCount) == 9.0, ...
    "runG4RCancellationCharacterization:ShardManifest", ...
    "Benchmark result does not contain the required nine-control manifest.");
localRequire(isfield(benchmarkResult, "WienerSelection") && ...
    isfield(benchmarkResult, "WienerSelectionTable") && ...
    isfield(benchmarkResult, "WienerSearchDetailTable"), ...
    "runG4RCancellationCharacterization:ShardSelection", ...
    "Benchmark result does not contain the global Wiener selection.");

contract.Available = true;
contract.ResultPath = resultPath;
contract.WienerSelection = benchmarkResult.WienerSelection;
contract.WienerSelectionTable = benchmarkResult.WienerSelectionTable;
contract.WienerSearchDetailTable = benchmarkResult.WienerSearchDetailTable;
contract.Projection = benchmarkResult.Projection;

end

