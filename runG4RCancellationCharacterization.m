function value = localReadMetadataPath(metadata, dottedPath)

value = "";
pathParts = split(string(dottedPath), ".");
current = metadata;

for partIndex = 1:numel(pathParts)
    fieldName = char(pathParts(partIndex));

    if ~isstruct(current) || ~isfield(current, fieldName)
        return
    end

    current = current.(fieldName);
end

if ischar(current) || isstring(current)
    value = string(current);
elseif isnumeric(current) || islogical(current)
    value = string(current);
else
    value = string(jsonencode(current));
end

end

function selection = localEvaluateWienerCandidates( ...
        background, manifest, resolvedOptions)

backgroundRows = manifest.ControlTable( ...
    manifest.ControlTable.BackgroundId == background.BackgroundId, :);
rows = table();

for pairIndex = 1:height(backgroundRows)
    pairRow = backgroundRows(pairIndex, :);
    calibration = localLoadCorrectedRepetition( ...
        background, pairRow.CalibrationRepetition);
    score = localLoadCorrectedRepetition( ...
        background, pairRow.ScoreRepetition);
    calibrationWindow = localCenterWindow( ...
        calibration.Reference, calibration.Surveillance, ...
        calibration.SampleRateHz, resolvedOptions.CpiDuration_s);
    scoreWindow = localCenterWindow( ...
        score.Reference, score.Surveillance, score.SampleRateHz, ...
        resolvedOptions.CpiDuration_s);

    for tapIndex = 1:numel(resolvedOptions.FirTapCounts)
        tapCount = resolvedOptions.FirTapCounts(tapIndex);
        estimate = helperEstimateG4RWienerFir( ...
            calibrationWindow.Reference, calibrationWindow.Surveillance, ...
            tapCount, struct("RegularizationFraction", ...
            resolvedOptions.WienerRegularizationFraction));
        application = helperApplyG4RNativeFirstCancellation( ...
            calibrationWindow.Reference, calibrationWindow.Surveillance, ...
            scoreWindow.Reference, scoreWindow.Surveillance, "wiener_fir", ...
            struct("WienerCoefficients", estimate.Coefficients));
        metrics = helperComputeG4RCancellationMetrics( ...
            scoreWindow.Reference, scoreWindow.Surveillance, ...
            application.ResidualSignal);
        impulse = localImpulseMetrics( ...
            estimate.Coefficients, score.SampleRateHz);
        row = table( ...
            background.BackgroundId, pairRow.TimePairId, ...
            pairRow.PairPosition, pairRow.CalibrationRepetition, ...
            pairRow.ScoreRepetition, tapCount, ...
            impulse.FirSpan_us, impulse.EnergyCentroidDelay_us, ...
            impulse.Energy95Delay_us, estimate.Regularization, ...
            estimate.RegularizedMatrixConditionNumber, ...
            metrics.InputSurveillancePower_dB, metrics.ResidualPower_dB, ...
            metrics.CancellationDepth_dB, ...
            metrics.ResidualCoherenceSquared, ...
            VariableNames=["BackgroundId", "TimePairId", "PairPosition", ...
            "CalibrationRepetition", "ScoreRepetition", "TapCount", ...
            "FirSpan_us", "ImpulseEnergyCentroidDelay_us", ...
            "ImpulseEnergy95Delay_us", "Regularization", ...
            "RegularizedMatrixConditionNumber", ...
            "InputSurveillancePower_dB", "ResidualPower_dB", ...
            "CancellationDepth_dB", "ResidualCoherenceSquared"]);
