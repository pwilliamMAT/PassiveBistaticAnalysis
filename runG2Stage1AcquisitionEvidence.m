function labelText = localFormatManualChannelLabel(channelInfo)

labelText = strjoin([ ...
    channelInfo.ChannelLabel; ...
    channelInfo.Role; ...
    channelInfo.AntennaName ...
    ], " | ");
labelText = localRemoveEmptyJoinArtifacts(labelText);

end

function outputText = localRemoveEmptyJoinArtifacts(inputText)

tokens = split(string(inputText), "|");
tokens = strtrim(tokens);
tokens = tokens(strlength(tokens) > 0);

if isempty(tokens)
    outputText = "";
else
    outputText = strjoin(tokens, " | ");
end

end

function localRenderAveragePsdFigure(analysis, figurePath, showFigures)

figureHandle = figure("Visible", ...
    localResolveFigureVisibility(showFigures), ...
    "Name", "G2 Stage 1 Average Channel PSD", ...
    "NumberTitle", "off");
cleanupObject = localCreateFigureCleanup(figureHandle, showFigures); %#ok<NASGU>
tiledlayout(1, 1);
nexttile;
plot(analysis.RoleEvidence.PsdFrequencyHz / 1e6, ...
    pow2db(analysis.RoleEvidence.MeanChannel1Psd + eps), ...
    "LineWidth", 1.4);
hold on
plot(analysis.RoleEvidence.PsdFrequencyHz / 1e6, ...
    pow2db(analysis.RoleEvidence.MeanChannel2Psd + eps), ...
    "LineWidth", 1.4);
hold off
grid on
xlabel("Frequency [MHz]");
ylabel("PSD [dB/Hz]");
title("G2 Stage 1 Average Channel PSD");
legend("Channel 1", "Channel 2", Location = "best");
drawnow

try
    exportgraphics(figureHandle, figurePath);
catch exportException
    error("runG2Stage1AcquisitionEvidence:ExportFigureFailed", ...
        "Failed to export %s: %s", figurePath, exportException.message);
end

clear cleanupObject

end

