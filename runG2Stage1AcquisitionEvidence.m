function roleSourceSummary = localBuildRoleSourceSummary( ...
    collectionMetadataInfo, analysis)

referenceLabel = strtrim(string( ...
    collectionMetadataInfo.ReferenceChannel.ChannelLabel));
surveillanceLabel = strtrim(string( ...
    collectionMetadataInfo.SurveillanceChannel.ChannelLabel));
manualRoleSummary = "collection_metadata does not declare both roles";

if strlength(referenceLabel) > 0 && strlength(surveillanceLabel) > 0
    manualRoleSummary = sprintf( ...
        "collection_metadata declares reference %s and surveillance %s", ...
        char(referenceLabel), char(surveillanceLabel));
elseif strlength(referenceLabel) > 0 || strlength(surveillanceLabel) > 0
    manualRoleSummary = sprintf( ...
        "collection_metadata partially declares roles: reference %s | surveillance %s", ...
        char(referenceLabel), char(surveillanceLabel));
end

verificationSummary = "no explicit mapping-verification evidence noted";

if isfield(analysis.Metrics, "audit_flags") && ...
        isfield(analysis.Metrics.audit_flags, ...
        "MappingVerificationCapturePresent") && ...
        analysis.Metrics.audit_flags.MappingVerificationCapturePresent
    verificationSummary = "explicit mapping-verification evidence present";
end

roleSourceSummary = manualRoleSummary + ...
    " | IQ-only inference " + ...
    string(analysis.RoleEvidence.IqOnlyMappingInference) + ...
    " | " + verificationSummary;

end

