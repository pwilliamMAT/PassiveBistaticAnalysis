    receiverIntegrityTable.SurveillanceDcSpike_dB);
hasSevereClipping = any( ...
    receiverIntegrityTable.ReferenceNearRailFraction >= ...
    analysis.Options.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.SurveillanceNearRailFraction >= ...
    analysis.Options.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.ReferenceExactRailFraction > 0.0 | ...
    receiverIntegrityTable.SurveillanceExactRailFraction > 0.0);
hasSevereIqIssue = any( ...
    receiverIntegrityTable.ReferenceIqImpropriety >= ...
    analysis.Options.IqImproprietySevereThreshold | ...
    receiverIntegrityTable.SurveillanceIqImpropriety >= ...
    analysis.Options.IqImproprietySevereThreshold);
hasModerateIqIssue = any( ...
    receiverIntegrityTable.ReferenceIqImpropriety >= ...
    analysis.Options.IqImproprietyDiagnosticThreshold | ...
    receiverIntegrityTable.SurveillanceIqImpropriety >= ...
    analysis.Options.IqImproprietyDiagnosticThreshold);

positiveEvidenceLines = [ ...
    sprintf("- Role mapping source is `%s`, using reference `%s` and surveillance `%s`.", ...
    analysis.RoleInfo.RoleSource, analysis.RoleInfo.ReferenceLabel, ...
    analysis.RoleInfo.SurveillanceLabel); ...
    sprintf("- Manual antenna metadata remains available at `%s`.", ...
    collectionMetadataInfo.MetadataPath); ...
    sprintf("- DC mean-offset and DC-spike metrics remain below the current diagnostic threshold, with worst DC spikes of reference `%.3f dB` and surveillance `%.3f dB` relative to local PSD floor.", ...
    maxReferenceDcSpike, maxSurveillanceDcSpike) ...
    ];

caveatLines = [ ...
    sprintf("- The accepted reference channel is weaker than surveillance in every repetition, with reference-minus-surveillance power ranging from `%.3f dB` to `%.3f dB`.", ...
    min(referencePowerVector), max(referencePowerVector)); ...
    sprintf("- Median mean power is reference `%.3f dBFS` versus surveillance `%.3f dBFS`, so the current role-based power ordering does not match the preferred Stage 2 condition.", ...
    median(receiverIntegrityTable.ReferenceMeanPower_dBFS), ...
    median(receiverIntegrityTable.SurveillanceMeanPower_dBFS)); ...
    sprintf("- Surveillance headroom is tighter than reference, with minimum peak headroom `%.3f dB` versus `%.3f dB`.", ...
    min(receiverIntegrityTable.SurveillancePeakHeadroom_dB), ...
    min(receiverIntegrityTable.ReferencePeakHeadroom_dB)) ...
    ];

if hasSevereClipping
    caveatLines(end + 1, 1) = sprintf("- Severe clipping criteria were met because exact-rail samples or severe near-rail occupancy were observed; maximum near-rail fractions are reference `%.9f` and surveillance `%.9f`, and maximum exact-rail fractions are reference `%.9f` and surveillance `%.9f`.", ...
        maxReferenceNearRailFraction, maxSurveillanceNearRailFraction, ...
        maxReferenceExactRailFraction, maxSurveillanceExactRailFraction);
elseif maxReferenceNearRailFraction > 0.0 || maxSurveillanceNearRailFraction > 0.0
    caveatLines(end + 1, 1) = "- Minor nonzero near-rail occupancy is present even though no exact-rail samples were observed.";
else
    positiveEvidenceLines(end + 1, 1) = sprintf("- No exact-rail samples were observed; maximum near-rail fractions are reference `%.9f` and surveillance `%.9f`.", ...
        maxReferenceNearRailFraction, maxSurveillanceNearRailFraction);
end

if hasSevereIqIssue
    caveatLines(end + 1, 1) = sprintf("- IQ/image-risk proxies are severe on at least one channel; worst impropriety is reference `%.4f` and surveillance `%.4f`.", ...
        maxReferenceImpropriety, maxSurveillanceImpropriety);
elseif hasModerateIqIssue
    caveatLines(end + 1, 1) = sprintf("- IQ/image-risk proxies exceed the current diagnostic threshold on at least one channel; worst impropriety is reference `%.4f` and surveillance `%.4f`.", ...
        maxReferenceImpropriety, maxSurveillanceImpropriety);
else
    positiveEvidenceLines(end + 1, 1) = sprintf("- IQ/image-risk proxies remain below the current diagnostic threshold, with worst impropriety of reference `%.4f` and surveillance `%.4f`.", maxReferenceImpropriety, ...
        maxSurveillanceImpropriety);
end

if analysis.AnalysisValidity == "invalid"
    interpretationLines = [ ...
        "- Stage 2 did not establish a trustworthy receiver-integrity " + ...
        "interpretation for this session."; ...
        "- The current blocker is analysis validity rather than the RF " + ...
        "verdict itself."; ...
        "- Repair the role mapping or incomplete metrics before using " + ...
        "this session to justify later stages." ...
        ];
elseif analysis.ReceiverIntegrityVerdict == "receiver_integrity_hard_fail"
    interpretationLines = [ ...
        "- Receiver integrity shows a hard failure in this session."; ...
        "- The dominant hard-fail driver is severe IQ/image-risk behavior, while the accepted reference channel also remains weaker than surveillance."; ...
        "- Stage 2 therefore recommends `reject` and the dataset should not be carried forward without collection changes or a justified re-interpretation of the channel roles." ...
        ];
elseif analysis.ReceiverIntegrityVerdict == "receiver_integrity_caveated"
    interpretationLines = [ ...
        "- Receiver integrity does not show a hard clipping or DC failure in this session."; ...
        "- The main Stage 2 concern is role-based power ordering: the accepted reference channel is not stronger than surveillance."; ...
        "- Stage 2 therefore recommends `retune` and keeps the dataset `diagnostic` until later stages or a future recollection show a stronger reference view." ...
        ];
else
    interpretationLines = [ ...
        "- Receiver integrity metrics remain within the current Stage 2 thresholds."; ...
        "- The accepted reference channel behavior is consistent enough to support downstream review."; ...
        "- Stage 2 therefore recommends `pass` on receiver integrity for this dataset." ...
        ];
end

lines = [ ...
    "# Receiver Integrity Note"; ...
    ""; ...
    sprintf("- Current Stage 2 verdict: `%s`", ...
    analysis.ReceiverIntegrityVerdict); ...
    sprintf("- Legal recommendation: `%s`", ...
    analysis.LegalGateRecommendation); ...
    sprintf("- Dataset classification recommendation: `%s`", ...
    analysis.DatasetClassificationRecommendation); ...
    sprintf("- Analysis validity: `%s`", ...
    analysis.AnalysisValidity); ...
    sprintf("- Development readiness: `%s`", ...
    analysis.DevelopmentReadiness); ...
    sprintf("- Development reason: `%s`", ...
    analysis.DevelopmentBlockingReason); ...
    ""; ...
    "## Positive Evidence"; ...
    positiveEvidenceLines; ...
    ""; ...
    "## Caveats"; ...
    caveatLines; ...
    ""; ...
    "## Analysis And Development Interpretation"; ...
    sprintf("- Analysis interpretation: %s", ...
    analysis.AnalysisInterpretation); ...
    sprintf("- Development interpretation: %s", ...
    analysis.DevelopmentInterpretation); ...
    ""; ...
    "## Stage 2 Interpretation"; ...
    interpretationLines ...
    ];

end

