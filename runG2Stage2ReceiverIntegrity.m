function results = runG2Stage2ReceiverIntegrity(datasetId, repoRoot, ...
    options)
%RUNG2STAGE2RECEIVERINTEGRITY Execute the Stage 2 G2 manual-review slice.
%
%   RESULTS = RUNG2STAGE2RECEIVERINTEGRITY() runs only the Receiver
%   Integrity stage of G2 on the reference dataset and writes a
%   manual-review evidence bundle under:
%   artifacts/<datasetId>/G2_RF_Health_Stage2_ReceiverIntegrity/<runTimestampZ>/
%
%   This is not the final G2 gate runner. It exists so Stage 2 can be
%   reviewed independently before the later G2 stages are implemented.

arguments
    datasetId (1,1) string = "20260622T102123"
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

stageArtifactId = "G2_RF_Health_Stage2_ReceiverIntegrity";
repoRoot = helperResolveRepoRoot(repoRoot);
datasetId = string(datasetId);
[analysisOptions, runnerOptions] = localResolveRunnerOptions(options);
runTimestampZ = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss'Z'"));
bundleRoot = fullfile(repoRoot, "artifacts", datasetId, stageArtifactId, ...
    runTimestampZ);
figureRoot = fullfile(bundleRoot, "figures");

fprintf("Running G2 Stage 2 Receiver Integrity for dataset %s\n", ...
    datasetId);
fprintf("Repository root:\t%s\n", repoRoot);

try
    localEnsureFolder(bundleRoot);
    localEnsureFolder(figureRoot);

    loadOptions = struct();
    loadOptions.IncludeSamples = false;
    sessionData = loadIQData(datasetId, repoRoot, loadOptions);
    collectionMetadataPath = fullfile(sessionData.DatasetRoot, ...
        "collection_metadata.json");
    collectionMetadataInfo = helperReadCollectionMetadata( ...
        collectionMetadataPath, datasetId);
    analysis = helperAnalyzeG2ReceiverIntegrity(sessionData, ...
        collectionMetadataInfo, analysisOptions);
    configSnapshot = localBuildConfigSnapshot(datasetId, repoRoot, ...
        bundleRoot, runTimestampZ, collectionMetadataInfo, analysis, ...
        runnerOptions);
    comparisonSnapshot = localBuildComparisonSnapshot(datasetId, ...
        runTimestampZ, bundleRoot, analysis);
    summaryLines = localBuildSummaryLines(bundleRoot, runTimestampZ, ...
        collectionMetadataInfo, analysis);
    receiverIntegrityNoteLines = localBuildReceiverIntegrityNoteLines( ...
        collectionMetadataInfo, analysis);

    summaryPath = fullfile(bundleRoot, "summary.md");
    receiverIntegrityNotePath = fullfile(bundleRoot, ...
        "receiver_integrity_note.md");
    receiverIntegrityTablePath = fullfile(bundleRoot, ...
        "receiver_integrity_table.csv");
    channelSummaryPath = fullfile(bundleRoot, "channel_summary_table.csv");
    decisionTracePath = fullfile(bundleRoot, ...
        "decision_traceability_table.csv");
    configSnapshotPath = fullfile(bundleRoot, "config_snapshot.json");
    metricsJsonPath = fullfile(bundleRoot, "metrics.json");
    metricsMatPath = fullfile(bundleRoot, "metrics.mat");
    averagePsdFigurePath = fullfile(figureRoot, ...
        "figure_01_average_role_psd.png");
    receiverMetricsFigurePath = fullfile(figureRoot, ...
        "figure_02_receiver_metrics_overview.png");
    contaminationFigurePath = fullfile(figureRoot, ...
        "figure_03_dc_iq_and_clipping_overview.png");

    try
        writetable(analysis.ReceiverIntegrityTable, ...
            receiverIntegrityTablePath);
        writetable(analysis.ChannelSummaryTable, channelSummaryPath);
        writetable(analysis.DecisionTraceTable, decisionTracePath);
    catch writeTableException
        error("runG2Stage2ReceiverIntegrity:WriteTableFailed", ...
            "Failed to write a Stage 2 table artifact: %s", ...
            writeTableException.message);
    end

    localWriteTextFile(summaryPath, summaryLines);
    localWriteTextFile(receiverIntegrityNotePath, ...
        receiverIntegrityNoteLines);
    localWriteJsonFile(configSnapshotPath, configSnapshot);
    localWriteJsonFile(metricsJsonPath, analysis.Metrics);

    try
        save(metricsMatPath, "analysis");
    catch saveException
        error("runG2Stage2ReceiverIntegrity:SaveMetricsFailed", ...
            "Failed to write Stage 2 metrics.mat: %s", ...
            saveException.message);
    end

    try
        comparisonSnapshotPath = helperWriteComparisonSnapshot( ...
            string(bundleRoot), comparisonSnapshot);
    catch saveException
        error("runG2Stage2ReceiverIntegrity:SaveComparisonSnapshotFailed", ...
            "Failed to write Stage 2 comparison snapshot: %s", ...
            saveException.message);
    end

    localRenderAveragePsdFigure(analysis, averagePsdFigurePath, ...
        runnerOptions.ShowFigures);
    localRenderReceiverMetricsFigure(analysis, ...
        receiverMetricsFigurePath, runnerOptions.ShowFigures);
    localRenderContaminationFigure(analysis, contaminationFigurePath, ...
        runnerOptions.ShowFigures);

    results = struct();
    results.DatasetId = datasetId;
    results.StageId = "Stage2_ReceiverIntegrity";
    results.RunTimestampZ = runTimestampZ;
    results.BundleRoot = string(bundleRoot);
    results.ReceiverIntegrityVerdict = ...
        analysis.ReceiverIntegrityVerdict;
    results.LegalGateRecommendation = ...
        analysis.LegalGateRecommendation;
    results.DatasetClassificationRecommendation = ...
        analysis.DatasetClassificationRecommendation;
    results.AnalysisValidity = analysis.AnalysisValidity;
    results.DevelopmentReadiness = analysis.DevelopmentReadiness;
    results.DevelopmentBlockingReason = ...
        analysis.DevelopmentBlockingReason;
    results.AnalysisInterpretation = analysis.AnalysisInterpretation;
    results.DevelopmentInterpretation = ...
        analysis.DevelopmentInterpretation;
    results.RoleSource = analysis.RoleInfo.RoleSource;
    results.RoleNote = analysis.RoleInfo.RoleNote;
    results.ReferenceLabel = analysis.RoleInfo.ReferenceLabel;
    results.SurveillanceLabel = analysis.RoleInfo.SurveillanceLabel;
    results.CollectionMetadataPath = collectionMetadataInfo.MetadataPath;
    results.ReceiverIntegrityTable = analysis.ReceiverIntegrityTable;
    results.ChannelSummaryTable = analysis.ChannelSummaryTable;
    results.DecisionTraceTable = analysis.DecisionTraceTable;
    results.Metrics = analysis.Metrics;
    results.Options = analysis.Options;
    results.FigurePaths = [string(averagePsdFigurePath); ...
        string(receiverMetricsFigurePath); ...
        string(contaminationFigurePath)];
    results.ComparisonSnapshotPath = string(comparisonSnapshotPath);

    fprintf("Receiver-integrity verdict:\t%s\n", ...
        results.ReceiverIntegrityVerdict);
    fprintf("Legal recommendation:\t%s\n", ...
        results.LegalGateRecommendation);
    fprintf("Classification recommendation:\t%s\n", ...
        results.DatasetClassificationRecommendation);
    fprintf("Analysis validity:\t%s\n", ...
        results.AnalysisValidity);
    fprintf("Development readiness:\t%s\n", ...
        results.DevelopmentReadiness);
    fprintf("Development reason:\t%s\n", ...
        results.DevelopmentBlockingReason);
    fprintf("Bundle root:\t%s\n", bundleRoot);
catch mainException
    localWriteFailureBundle(bundleRoot, mainException);
    rethrow(mainException);
end

end

