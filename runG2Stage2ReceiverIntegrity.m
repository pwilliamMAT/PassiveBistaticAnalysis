function lines = localBuildDecisionTraceLines(decisionTraceTable)

lineCount = height(decisionTraceTable);
lines = strings(lineCount, 1);

for idx = 1:lineCount
    if isnan(decisionTraceTable.WorstCaseIndex(idx))
        worstCaseText = "n/a";
    else
        worstCaseText = sprintf("%d", decisionTraceTable.WorstCaseIndex(idx));
    end

    formatText = "- `%s`: %s | threshold rule: %s | " + ...
        "worst-case repetition: %s | effect: %s";
    lines(idx) = string(sprintf(char(formatText), ...
        char(string(decisionTraceTable.DecisionItem(idx))), ...
        char(string(decisionTraceTable.MetricOrEvidence(idx))), ...
        char(string(decisionTraceTable.ThresholdRule(idx))), ...
        char(string(worstCaseText)), ...
        char(string(decisionTraceTable.Effect(idx)))));
end

end

