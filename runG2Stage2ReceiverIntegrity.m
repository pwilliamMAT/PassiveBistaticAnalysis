function worstMetrics = localComputeWorstMetrics(receiverIntegrityTable)

worstMetrics = struct();
worstMetrics.MinimumPeakHeadroom_dB = min([ ...
    receiverIntegrityTable.ReferencePeakHeadroom_dB; ...
    receiverIntegrityTable.SurveillancePeakHeadroom_dB ...
    ]);
worstMetrics.WorstNearRailFraction = max([ ...
    receiverIntegrityTable.ReferenceNearRailFraction; ...
    receiverIntegrityTable.SurveillanceNearRailFraction ...
    ]);
worstMetrics.WorstExactRailFraction = max([ ...
    receiverIntegrityTable.ReferenceExactRailFraction; ...
    receiverIntegrityTable.SurveillanceExactRailFraction ...
    ]);
worstMetrics.WorstDcMeanRatio_dB = max([ ...
    receiverIntegrityTable.ReferenceDcMeanRatio_dB; ...
    receiverIntegrityTable.SurveillanceDcMeanRatio_dB ...
    ]);
worstMetrics.WorstDcSpike_dB = max([ ...
    receiverIntegrityTable.ReferenceDcSpike_dB; ...
    receiverIntegrityTable.SurveillanceDcSpike_dB ...
    ]);
worstMetrics.WorstIqAmplitudeImbalance_dB = max(abs([ ...
    receiverIntegrityTable.ReferenceIqAmplitudeImbalance_dB; ...
    receiverIntegrityTable.SurveillanceIqAmplitudeImbalance_dB ...
    ]));
worstMetrics.WorstIqPhaseProxy_deg = max(abs([ ...
    receiverIntegrityTable.ReferenceIqPhaseProxy_deg; ...
    receiverIntegrityTable.SurveillanceIqPhaseProxy_deg ...
    ]));
worstMetrics.WorstIqImpropriety = max([ ...
    receiverIntegrityTable.ReferenceIqImpropriety; ...
    receiverIntegrityTable.SurveillanceIqImpropriety ...
    ]);

end

