resolvedOptions.SampleRateHz = sampleRateVector(1);
resolvedOptions.WelchLength = 4096;
resolvedOptions.WelchOverlap = 2048;
resolvedOptions.WelchNfft = 4096;
resolvedOptions.NearRailThresholdFraction = 0.98;
resolvedOptions.SevereClippingFractionThreshold = 1.0e-4;
resolvedOptions.ClippingRiskFractionThreshold = 0.0;
resolvedOptions.ReferencePowerMinimumThreshold_dB = 0.0;
resolvedOptions.ReferencePowerTargetMarginThreshold_dB = 3.0;
resolvedOptions.QuantizationRiskThreshold_dBFS = -35.0;
resolvedOptions.SevereQuantizationThreshold_dBFS = -45.0;
resolvedOptions.DcMeanRatioDiagnosticThreshold_dB = -60.0;
resolvedOptions.DcMeanRatioSevereThreshold_dB = -40.0;
resolvedOptions.DcSpikeDiagnosticThreshold_dB = 3.0;
resolvedOptions.DcSpikeSevereThreshold_dB = 10.0;
resolvedOptions.DcBandHalfWidthHz = 3000.0;
resolvedOptions.DcSpikeLocalHalfWidthHz = 50000.0;
resolvedOptions.DcSpikeExclusionHalfWidthHz = 5000.0;
resolvedOptions.IqAmplitudeImbalanceDiagnosticThreshold_dB = 1.0;
resolvedOptions.IqAmplitudeImbalanceSevereThreshold_dB = 3.0;
