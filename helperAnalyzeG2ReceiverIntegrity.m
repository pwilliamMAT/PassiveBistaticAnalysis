analysis.StageId = "Stage2_ReceiverIntegrity";
analysis.DatasetId = string(sessionData.DatasetId);
analysis.RoleInfo = roleInfo;
analysis.ReceiverIntegrityTable = receiverIntegrityTable;
analysis.ChannelSummaryTable = channelSummaryTable;
analysis.ReceiverIntegrityVerdict = receiverIntegrityVerdict;
analysis.LegalGateRecommendation = legalGateRecommendation;
analysis.DatasetClassificationRecommendation = ...
    datasetClassificationRecommendation;
analysis.ClassificationImpact = classificationImpact;
analysis.AnalysisValidity = analysisValidity;
analysis.DevelopmentReadiness = developmentReadiness;
analysis.DevelopmentBlockingReason = developmentBlockingReason;
analysis.AnalysisInterpretation = analysisInterpretation;
analysis.DevelopmentInterpretation = developmentInterpretation;
analysis.DecisionTraceTable = decisionTraceTable;
analysis.RoleEvidence = roleEvidence;
analysis.CollectionMetadataInfo = collectionMetadataInfo;
analysis.Options = rmfield(resolvedOptions, "WelchWindow");
analysis.Metrics = localBuildMetrics(receiverIntegrityTable, ...
    channelSummaryTable, roleInfo, roleEvidence, ...
    receiverIntegrityVerdict, legalGateRecommendation, ...
    datasetClassificationRecommendation, classificationImpact, ...
    analysisValidity, developmentReadiness, ...
    developmentBlockingReason, analysisInterpretation, ...
    developmentInterpretation);

end

