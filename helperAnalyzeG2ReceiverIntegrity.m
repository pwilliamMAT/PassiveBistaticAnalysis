        surveillanceMetrics.NearRailFraction, ...
        "ReferenceExactRailFraction", ...
        referenceMetrics.ExactRailFraction, ...
        "SurveillanceExactRailFraction", ...
        surveillanceMetrics.ExactRailFraction, ...
        "ReferenceDcMeanRatio_dB", referenceMetrics.DcMeanRatio_dB, ...
        "SurveillanceDcMeanRatio_dB", ...
        surveillanceMetrics.DcMeanRatio_dB, ...
        "ReferenceDcSpike_dB", referenceMetrics.DcSpike_dB, ...
        "SurveillanceDcSpike_dB", surveillanceMetrics.DcSpike_dB, ...
        "ReferenceLowFrequencyBandFraction_dB", ...
        referenceMetrics.LowFrequencyBandFraction_dB, ...
        "SurveillanceLowFrequencyBandFraction_dB", ...
        surveillanceMetrics.LowFrequencyBandFraction_dB, ...
        "ReferenceIqAmplitudeImbalance_dB", ...
        referenceMetrics.IqAmplitudeImbalance_dB, ...
        "SurveillanceIqAmplitudeImbalance_dB", ...
        surveillanceMetrics.IqAmplitudeImbalance_dB, ...
        "ReferenceIqPhaseProxy_deg", ...
        referenceMetrics.IqPhaseProxy_deg, ...
        "SurveillanceIqPhaseProxy_deg", ...
