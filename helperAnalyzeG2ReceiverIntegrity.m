    localBuildReceiverIntegrityTables(sessionData, roleInfo, ...
    resolvedOptions);
[receiverIntegrityVerdict, legalGateRecommendation, ...
    datasetClassificationRecommendation, classificationImpact, ...
    decisionTraceTable] = localDetermineStage2Verdicts( ...
    receiverIntegrityTable, channelSummaryTable, roleInfo, ...
    resolvedOptions);
[analysisValidity, developmentReadiness, developmentBlockingReason, ...
    analysisInterpretation, developmentInterpretation] = ...
    localDetermineDevelopmentStatus(receiverIntegrityTable, ...
    channelSummaryTable, roleInfo, receiverIntegrityVerdict, ...
    resolvedOptions);

