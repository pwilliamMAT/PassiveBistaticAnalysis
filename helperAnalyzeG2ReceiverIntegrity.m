    "ReferenceMinusSurveillancePower_dB", NaN, ...
    "ReferencePAR_dB", NaN, ...
    "SurveillancePAR_dB", NaN, ...
    "ReferencePeakHeadroom_dB", NaN, ...
    "SurveillancePeakHeadroom_dB", NaN, ...
    "ReferenceNearRailFraction", NaN, ...
    "SurveillanceNearRailFraction", NaN, ...
    "ReferenceExactRailFraction", NaN, ...
    "SurveillanceExactRailFraction", NaN, ...
    "ReferenceDcMeanRatio_dB", NaN, ...
    "SurveillanceDcMeanRatio_dB", NaN, ...
    "ReferenceDcSpike_dB", NaN, ...
    "SurveillanceDcSpike_dB", NaN, ...
    "ReferenceLowFrequencyBandFraction_dB", NaN, ...
    "SurveillanceLowFrequencyBandFraction_dB", NaN, ...
    "ReferenceIqAmplitudeImbalance_dB", NaN, ...
    "SurveillanceIqAmplitudeImbalance_dB", NaN, ...
