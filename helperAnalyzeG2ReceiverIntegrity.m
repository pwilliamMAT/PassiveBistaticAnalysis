function [receiverIntegrityVerdict, legalGateRecommendation, ...
    datasetClassificationRecommendation, classificationImpact, ...
    decisionTraceTable] = localDetermineStage2Verdicts( ...
    receiverIntegrityTable, ~, ~, ...
    resolvedOptions)

referencePowerVector = ...
    receiverIntegrityTable.ReferenceMinusSurveillancePower_dB;
referenceMinimumPassFraction = mean(referencePowerVector >= ...
    resolvedOptions.ReferencePowerMinimumThreshold_dB);
referenceTargetPassFraction = mean(referencePowerVector >= ...
    resolvedOptions.ReferencePowerTargetMarginThreshold_dB);

severeClippingMask = receiverIntegrityTable.RepetitionVerdict == ...
    "reject_candidate" & ( ...
    receiverIntegrityTable.ReferenceNearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.SurveillanceNearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.ReferenceExactRailFraction > 0.0 | ...
    receiverIntegrityTable.SurveillanceExactRailFraction > 0.0);
severeReferencePowerDeficitMask = referencePowerVector < ...
    resolvedOptions.ReferencePowerMinimumThreshold_dB;
quantizationRiskMask = ...
    receiverIntegrityTable.ReferenceMeanPower_dBFS <= ...
    resolvedOptions.QuantizationRiskThreshold_dBFS | ...
    receiverIntegrityTable.SurveillanceMeanPower_dBFS <= ...
    resolvedOptions.QuantizationRiskThreshold_dBFS;
severeQuantizationRiskMask = ...
    receiverIntegrityTable.ReferenceMeanPower_dBFS <= ...
    resolvedOptions.SevereQuantizationThreshold_dBFS | ...
    receiverIntegrityTable.SurveillanceMeanPower_dBFS <= ...
    resolvedOptions.SevereQuantizationThreshold_dBFS;
dcIssueMask = receiverIntegrityTable.ReferenceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioDiagnosticThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioDiagnosticThreshold_dB | ...
    receiverIntegrityTable.ReferenceDcSpike_dB >= ...
    resolvedOptions.DcSpikeDiagnosticThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcSpike_dB >= ...
    resolvedOptions.DcSpikeDiagnosticThreshold_dB;
severeDcIssueMask = receiverIntegrityTable.ReferenceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioSevereThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioSevereThreshold_dB | ...
    receiverIntegrityTable.ReferenceDcSpike_dB >= ...
    resolvedOptions.DcSpikeSevereThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcSpike_dB >= ...
    resolvedOptions.DcSpikeSevereThreshold_dB;
iqIssueMask = abs( ...
    receiverIntegrityTable.ReferenceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceDiagnosticThreshold_dB | ...
    abs(receiverIntegrityTable.SurveillanceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceDiagnosticThreshold_dB | ...
    abs(receiverIntegrityTable.ReferenceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxyDiagnosticThreshold_deg | ...
    abs(receiverIntegrityTable.SurveillanceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxyDiagnosticThreshold_deg | ...
    receiverIntegrityTable.ReferenceIqImpropriety >= ...
    resolvedOptions.IqImproprietyDiagnosticThreshold | ...
    receiverIntegrityTable.SurveillanceIqImpropriety >= ...
    resolvedOptions.IqImproprietyDiagnosticThreshold;
severeIqIssueMask = abs( ...
    receiverIntegrityTable.ReferenceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceSevereThreshold_dB | ...
    abs(receiverIntegrityTable.SurveillanceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceSevereThreshold_dB | ...
    abs(receiverIntegrityTable.ReferenceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxySevereThreshold_deg | ...
    abs(receiverIntegrityTable.SurveillanceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxySevereThreshold_deg | ...
    receiverIntegrityTable.ReferenceIqImpropriety >= ...
    resolvedOptions.IqImproprietySevereThreshold | ...
    receiverIntegrityTable.SurveillanceIqImpropriety >= ...
    resolvedOptions.IqImproprietySevereThreshold;

systemicSevereDcOrIq = mean(severeDcIssueMask | severeIqIssueMask) >= 0.5;
anyModerateIssue = any(severeReferencePowerDeficitMask) || ...
    any(quantizationRiskMask) || any(dcIssueMask) || any(iqIssueMask) || ...
    any(receiverIntegrityTable.RepetitionVerdict == "retune_candidate");

if any(severeClippingMask) || any(severeQuantizationRiskMask) || ...
        systemicSevereDcOrIq
    receiverIntegrityVerdict = "receiver_integrity_hard_fail";
    legalGateRecommendation = "reject";
    datasetClassificationRecommendation = "rejected";
    classificationImpact = "Stage 2 identifies a severe " + ...
        "receiver-integrity failure. The current data should not be " + ...
        "carried into later stages without collection changes.";
elseif anyModerateIssue
    receiverIntegrityVerdict = "receiver_integrity_caveated";
    legalGateRecommendation = "retune";
    datasetClassificationRecommendation = "diagnostic";
    classificationImpact = "Stage 2 keeps the dataset diagnostic because " + ...
        "receiver-integrity caveats remain. The accepted reference channel " + ...
        "is not stronger than surveillance and later stages should be " + ...
        "reviewed against that limitation.";
else
    receiverIntegrityVerdict = "receiver_integrity_acceptable";
    legalGateRecommendation = "pass";

    if referenceTargetPassFraction >= 0.9
        datasetClassificationRecommendation = "golden";
        classificationImpact = "Stage 2 finds healthy receiver-integrity " + ...
            "margin with the reference channel stronger than surveillance " + ...
            "across the session.";
    else
        datasetClassificationRecommendation = "diagnostic";
        classificationImpact = "Stage 2 passes the receiver-integrity " + ...
            "screen but retains diagnostic classification because the " + ...
            "reference strength margin is not consistently healthy.";
    end
end

decisionRows = struct( ...
    "DecisionItem", {}, ...
    "MetricOrEvidence", {}, ...
    "ThresholdRule", {}, ...
    "WorstCaseIndex", {}, ...
    "Effect", {} ...
    );

decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "reference_power_order", ...
    sprintf("Reference minus surveillance power median = %.3f dB", ...
    median(referencePowerVector)), ...
    sprintf("Reference should exceed surveillance by >= %.1f dB", ...
    resolvedOptions.ReferencePowerMinimumThreshold_dB), ...
    localWorstCaseRepetitionNumber(referencePowerVector, ...
    receiverIntegrityTable.Repetition, "min"), ...
    localPowerOrderEffect(referenceMinimumPassFraction));
decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "clipping_and_headroom", ...
    sprintf("Worst near-rail fraction = %.9f | worst exact-rail fraction = %.9f", ...
    max([receiverIntegrityTable.ReferenceNearRailFraction; ...
    receiverIntegrityTable.SurveillanceNearRailFraction]), ...
    max([receiverIntegrityTable.ReferenceExactRailFraction; ...
    receiverIntegrityTable.SurveillanceExactRailFraction])), ...
    sprintf("Reject if near-rail fraction >= %.1e or exact rails occur", ...
    resolvedOptions.SevereClippingFractionThreshold), ...
    localWorstNearRailRepetition(receiverIntegrityTable), ...
    localBooleanEffect(any(severeClippingMask), ...
    "severe clipping present", "no severe clipping observed"));
decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "quantization_margin", ...
    sprintf("Lowest mean power = %.3f dBFS", ...
    min([receiverIntegrityTable.ReferenceMeanPower_dBFS; ...
    receiverIntegrityTable.SurveillanceMeanPower_dBFS])), ...
    sprintf("Retune below %.1f dBFS, severe below %.1f dBFS", ...
    resolvedOptions.QuantizationRiskThreshold_dBFS, ...
    resolvedOptions.SevereQuantizationThreshold_dBFS), ...
    localWorstMeanPowerRepetition(receiverIntegrityTable), ...
    localBooleanEffect(any(quantizationRiskMask), ...
    "scale-usage caveat present", "no quantization-risk evidence"));
decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "dc_lo_contamination", ...
    sprintf("Worst DC spike = %.3f dB", ...
    max([receiverIntegrityTable.ReferenceDcSpike_dB; ...
    receiverIntegrityTable.SurveillanceDcSpike_dB])), ...
    sprintf("Retune above %.1f dB, severe above %.1f dB", ...
    resolvedOptions.DcSpikeDiagnosticThreshold_dB, ...
    resolvedOptions.DcSpikeSevereThreshold_dB), ...
    localWorstDcRepetition(receiverIntegrityTable), ...
    localBooleanEffect(any(dcIssueMask), ...
    "DC or LO caveat present", "DC spike and mean offset remain low"));
decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "iq_image_risk", ...
    sprintf("Worst impropriety = %.4f", ...
    max([receiverIntegrityTable.ReferenceIqImpropriety; ...
    receiverIntegrityTable.SurveillanceIqImpropriety])), ...
    sprintf("Retune above %.3f, severe above %.3f", ...
    resolvedOptions.IqImproprietyDiagnosticThreshold, ...
    resolvedOptions.IqImproprietySevereThreshold), ...
    localWorstIqRepetition(receiverIntegrityTable), ...
    localBooleanEffect(any(iqIssueMask), ...
    "IQ/image caveat present", "IQ/image proxies remain low"));
decisionRows(end + 1) = localMakeDecisionRow( ... %#ok<AGROW>
    "stage2_receiver_integrity_verdict", ...
    sprintf("%s | %s", receiverIntegrityVerdict, ...
    datasetClassificationRecommendation), ...
    "Worst-case repetition behavior overrides favorable averages", ...
    NaN, ...
    classificationImpact);

decisionTraceTable = struct2table(decisionRows);

end

function [analysisValidity, developmentReadiness, ...
    developmentBlockingReason, analysisInterpretation, ...
    developmentInterpretation] = localDetermineDevelopmentStatus( ...
    receiverIntegrityTable, channelSummaryTable, roleInfo, ...
    receiverIntegrityVerdict, resolvedOptions)

hasVerifiedRoleMapping = ismember(roleInfo.RoleSource, [ ...
    "collection_metadata_manual_mapping"; ...
    "explicit_generator_contract"; ...
    "explicit_option_mapping" ...
    ]);
hasFiniteReceiverMetrics = localTableHasFiniteNumericValues( ...
    receiverIntegrityTable);
hasFiniteChannelMetrics = localTableHasFiniteNumericValues( ...
    channelSummaryTable);
analysisIsComplete = hasFiniteReceiverMetrics && hasFiniteChannelMetrics;

if ~hasVerifiedRoleMapping
    analysisValidity = "invalid";
    developmentReadiness = "blocked";
    developmentBlockingReason = "missing_role_mapping";
    analysisInterpretation = "Stage 2 computed sample statistics, but " + ...
        "the reference and surveillance roles were not verified from " + ...
        "session-matched collection metadata.";
    developmentInterpretation = "Downstream development stays blocked " + ...
        "until the role mapping is explicitly validated for this session.";
    return
end

if ~analysisIsComplete
    analysisValidity = "invalid";
    developmentReadiness = "blocked";
    developmentBlockingReason = "stage2_analysis_incomplete";
    analysisInterpretation = "Stage 2 did not produce a complete finite " + ...
        "metrics set across the session.";
    developmentInterpretation = "Downstream development stays blocked " + ...
        "until the Stage 2 metrics are complete and trustworthy.";
    return
end

analysisValidity = "valid";
analysisInterpretation = "Stage 2 used a verified role mapping and " + ...
    "produced a complete finite metrics set, so the current result is " + ...
    "analytically trustworthy.";

if receiverIntegrityVerdict == "receiver_integrity_acceptable"
    developmentReadiness = "ready_for_gate_progression";
    developmentBlockingReason = "ready_for_gate_progression";
    developmentInterpretation = "The current Stage 2 RF result supports " + ...
        "formal progression review once the next stage is implemented.";
    return
end

developmentReadiness = "unblocked_with_dataset_caveat";
developmentBlockingReason = localDetermineDatasetCaveatReason( ...
    receiverIntegrityTable, resolvedOptions);
developmentInterpretation = "The current limitation is attributed to " + ...
    "dataset, hardware, or acquisition behavior rather than a broken " + ...
    "Stage 2 analysis path. Development may continue under caveat, but " + ...
    "this does not formally approve Stage 3.";

end

function developmentBlockingReason = localDetermineDatasetCaveatReason( ...
    receiverIntegrityTable, resolvedOptions)

referencePowerVector = ...
    receiverIntegrityTable.ReferenceMinusSurveillancePower_dB;
severeClippingMask = receiverIntegrityTable.ReferenceNearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.SurveillanceNearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold | ...
    receiverIntegrityTable.ReferenceExactRailFraction > 0.0 | ...
    receiverIntegrityTable.SurveillanceExactRailFraction > 0.0;
severeQuantizationRiskMask = ...
    receiverIntegrityTable.ReferenceMeanPower_dBFS <= ...
    resolvedOptions.SevereQuantizationThreshold_dBFS | ...
    receiverIntegrityTable.SurveillanceMeanPower_dBFS <= ...
    resolvedOptions.SevereQuantizationThreshold_dBFS;
severeDcIssueMask = receiverIntegrityTable.ReferenceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioSevereThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioSevereThreshold_dB | ...
    receiverIntegrityTable.ReferenceDcSpike_dB >= ...
    resolvedOptions.DcSpikeSevereThreshold_dB | ...
    receiverIntegrityTable.SurveillanceDcSpike_dB >= ...
    resolvedOptions.DcSpikeSevereThreshold_dB;
severeIqIssueMask = abs( ...
    receiverIntegrityTable.ReferenceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceSevereThreshold_dB | ...
    abs(receiverIntegrityTable.SurveillanceIqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceSevereThreshold_dB | ...
    abs(receiverIntegrityTable.ReferenceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxySevereThreshold_deg | ...
    abs(receiverIntegrityTable.SurveillanceIqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxySevereThreshold_deg | ...
    receiverIntegrityTable.ReferenceIqImpropriety >= ...
    resolvedOptions.IqImproprietySevereThreshold | ...
    receiverIntegrityTable.SurveillanceIqImpropriety >= ...
    resolvedOptions.IqImproprietySevereThreshold;

if any(severeClippingMask) || any(severeQuantizationRiskMask) || ...
        mean(severeDcIssueMask | severeIqIssueMask) >= 0.5
    developmentBlockingReason = "severe_receiver_impairment";
    return
end

if all(referencePowerVector < ...
        resolvedOptions.ReferencePowerMinimumThreshold_dB)
    developmentBlockingReason = "weak_reference_power_ordering";
    return
end

developmentBlockingReason = "receiver_caveats_present";

end

