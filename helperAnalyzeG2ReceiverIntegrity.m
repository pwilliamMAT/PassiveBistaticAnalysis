end

function effectText = localPowerOrderEffect(referenceMinimumPassFraction)

if referenceMinimumPassFraction >= 0.9
    effectText = "reference power ordering supports later stages";
elseif referenceMinimumPassFraction > 0.0
    effectText = "reference power ordering is inconsistent";
else
    effectText = "reference is weaker than surveillance in every repetition";
end

end

function effectText = localBooleanEffect(condition, trueText, falseText)

if condition
    effectText = trueText;
else
    effectText = falseText;
end

end

function value = localWorstCaseRepetitionNumber(metricVector, ...
    repetitionVector, directionText)

if directionText == "min"
    [~, index] = min(metricVector);
else
    [~, index] = max(metricVector);
end

value = repetitionVector(index);

end

function value = localWorstNearRailRepetition(receiverIntegrityTable)

