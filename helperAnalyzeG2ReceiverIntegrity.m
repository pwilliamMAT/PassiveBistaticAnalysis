function value = localTableHasFiniteNumericValues(inputTable)

if isempty(inputTable) || height(inputTable) == 0
    value = false;
    return
end

numericTable = inputTable(:, vartype("numeric"));

if width(numericTable) == 0
    value = true;
    return
end

value = all(isfinite(numericTable{:,:}), "all");

end

function joinedText = localJoinNotes(noteTokens)

noteTokens = string(noteTokens);
noteTokens = strtrim(noteTokens);
noteTokens = noteTokens(strlength(noteTokens) > 0);

if isempty(noteTokens)
    joinedText = "";
    return
end

joinedText = strjoin(noteTokens, " | ");

end
