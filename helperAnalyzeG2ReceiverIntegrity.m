    receiverIntegrityTable.ReferenceMinusSurveillancePower_dB);
roleEvidence.ReferenceMinusSurveillancePower_dB_Max = max( ...
    receiverIntegrityTable.ReferenceMinusSurveillancePower_dB);

end

function [channelMetrics, pxx, frequencyHz] = localComputeChannelMetrics( ...
    samples, resolvedOptions)

fullScale = double(intmax("int16"));
meanPower = mean(abs(samples).^2);
maxMagnitude = max(abs(samples));
maxComponentAbs = max([max(abs(real(samples))), max(abs(imag(samples)))]);
realRailMask = abs(real(samples)) >= fullScale;
imagRailMask = abs(imag(samples)) >= fullScale;
nearRailMask = abs(real(samples)) >= ...
    resolvedOptions.NearRailThresholdFraction * fullScale | ...
    abs(imag(samples)) >= ...
    resolvedOptions.NearRailThresholdFraction * fullScale;
channelMean = mean(samples);

[pxx, frequencyHz] = pwelch(samples, resolvedOptions.WelchWindow, ...
    resolvedOptions.WelchOverlap, resolvedOptions.WelchNfft, ...
    resolvedOptions.SampleRateHz, "centered");

dcBandPower = bandpower(pxx, frequencyHz, ...
    [-resolvedOptions.DcBandHalfWidthHz, ...
    resolvedOptions.DcBandHalfWidthHz], "psd");
dcSpikeDb = localComputeDcSpikeDb(pxx, frequencyHz, resolvedOptions);

realSamples = real(samples);
imagSamples = imag(samples);
realCentered = realSamples - mean(realSamples);
imagCentered = imagSamples - mean(imagSamples);
realScale = sqrt(mean(realCentered.^2));
imagScale = sqrt(mean(imagCentered.^2));
iqCorrelation = localComputeNormalizedCorrelation(realCentered, ...
    imagCentered);
phaseProxyDeg = asind(max(min(iqCorrelation, 1.0), -1.0));
iqAmplitudeImbalanceDb = 20.0 * log10( ...
    max(realScale, eps) / max(imagScale, eps));
iqImpropriety = abs(mean(samples.^2)) / max(meanPower, eps);
iqCompensationCoeff = iqimbal2coef(iqAmplitudeImbalanceDb, ...
    phaseProxyDeg);

channelMetrics = struct();
channelMetrics.MeanPower_dBFS = pow2db(meanPower / (fullScale ^ 2) + eps);
channelMetrics.PAR_dB = pow2db((maxMagnitude ^ 2) / max(meanPower, eps));
channelMetrics.PeakHeadroom_dB = 20.0 * log10( ...
    fullScale / max(maxComponentAbs, eps));
channelMetrics.NearRailFraction = mean(nearRailMask);
channelMetrics.ExactRailFraction = mean(realRailMask | imagRailMask);
channelMetrics.DcMeanRatio_dB = pow2db( ...
    (abs(channelMean) ^ 2) / max(meanPower, eps) + eps);
channelMetrics.DcSpike_dB = dcSpikeDb;
channelMetrics.LowFrequencyBandFraction_dB = pow2db( ...
    dcBandPower / max(meanPower, eps) + eps);
channelMetrics.IqAmplitudeImbalance_dB = iqAmplitudeImbalanceDb;
channelMetrics.IqPhaseProxy_deg = phaseProxyDeg;
channelMetrics.IqImpropriety = iqImpropriety;
channelMetrics.IqCompensationCoeffMagnitude = abs(iqCompensationCoeff);

end

function dcSpikeDb = localComputeDcSpikeDb(pxx, frequencyHz, resolvedOptions)

dcIndex = find(abs(frequencyHz) == min(abs(frequencyHz)), 1, "first");
localMask = abs(frequencyHz) <= ...
    resolvedOptions.DcSpikeLocalHalfWidthHz & ...
    abs(frequencyHz) >= resolvedOptions.DcSpikeExclusionHalfWidthHz;

if ~any(localMask)
    dcSpikeDb = NaN;
    return
end

localMedian = median(pxx(localMask));
dcSpikeDb = pow2db(pxx(dcIndex) / max(localMedian, eps));

end

function correlationValue = localComputeNormalizedCorrelation(x, y)

denominator = sqrt(sum(x .^ 2) * sum(y .^ 2));

if denominator <= eps
    correlationValue = 0.0;
    return
end

correlationValue = sum(x .* y) / denominator;
correlationValue = real(correlationValue);

end

function [powerFlag, repetitionVerdict, caveatNotes] = ...
    localClassifyRepetition(referenceMinusSurveillancePowerDb, ...
    referenceMetrics, surveillanceMetrics, resolvedOptions)

caveatTokens = strings(0, 1);

if referenceMinusSurveillancePowerDb < ...
        resolvedOptions.ReferencePowerMinimumThreshold_dB
    powerFlag = "reference_weaker_than_surveillance";
    caveatTokens(end + 1, 1) = powerFlag;
elseif referenceMinusSurveillancePowerDb < ...
        resolvedOptions.ReferencePowerTargetMarginThreshold_dB
    powerFlag = "reference_margin_below_target";
    caveatTokens(end + 1, 1) = powerFlag;
else
    powerFlag = "reference_margin_ok";
end

severeClipping = localHasSevereClipping(referenceMetrics, ...
    surveillanceMetrics, resolvedOptions);
clippingRisk = localHasClippingRisk(referenceMetrics, ...
    surveillanceMetrics, resolvedOptions);
quantizationRisk = localHasQuantizationRisk(referenceMetrics, ...
    surveillanceMetrics, resolvedOptions);
dcIssue = localHasDcIssue(referenceMetrics, surveillanceMetrics, ...
    resolvedOptions);
iqIssue = localHasIqIssue(referenceMetrics, surveillanceMetrics, ...
    resolvedOptions);

if clippingRisk
    caveatTokens(end + 1, 1) = "near_rail_occupancy_observed";
end

if quantizationRisk
    caveatTokens(end + 1, 1) = "low_rms_scale_usage_detected";
end

if dcIssue
    caveatTokens(end + 1, 1) = "dc_or_lo_contamination_risk";
end

if iqIssue
    caveatTokens(end + 1, 1) = "iq_image_risk";
end

if severeClipping
    repetitionVerdict = "reject_candidate";
elseif powerFlag ~= "reference_margin_ok" || clippingRisk || ...
        quantizationRisk || dcIssue || iqIssue
    repetitionVerdict = "retune_candidate";
else
    repetitionVerdict = "acceptable";
end

caveatNotes = localJoinNotes(caveatTokens);

end

function value = localHasSevereClipping(referenceMetrics, ...
    surveillanceMetrics, resolvedOptions)

value = referenceMetrics.NearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold || ...
    surveillanceMetrics.NearRailFraction >= ...
    resolvedOptions.SevereClippingFractionThreshold || ...
    referenceMetrics.ExactRailFraction > 0.0 || ...
    surveillanceMetrics.ExactRailFraction > 0.0;

end

function value = localHasClippingRisk(referenceMetrics, surveillanceMetrics, ...
    resolvedOptions)

value = referenceMetrics.NearRailFraction > ...
    resolvedOptions.ClippingRiskFractionThreshold || ...
    surveillanceMetrics.NearRailFraction > ...
    resolvedOptions.ClippingRiskFractionThreshold;

end

function value = localHasQuantizationRisk(referenceMetrics, ...
    surveillanceMetrics, resolvedOptions)

value = referenceMetrics.MeanPower_dBFS <= ...
    resolvedOptions.QuantizationRiskThreshold_dBFS || ...
    surveillanceMetrics.MeanPower_dBFS <= ...
    resolvedOptions.QuantizationRiskThreshold_dBFS;

end

function value = localHasDcIssue(referenceMetrics, surveillanceMetrics, ...
    resolvedOptions)

value = referenceMetrics.DcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioDiagnosticThreshold_dB || ...
    surveillanceMetrics.DcMeanRatio_dB >= ...
    resolvedOptions.DcMeanRatioDiagnosticThreshold_dB || ...
    referenceMetrics.DcSpike_dB >= ...
    resolvedOptions.DcSpikeDiagnosticThreshold_dB || ...
    surveillanceMetrics.DcSpike_dB >= ...
    resolvedOptions.DcSpikeDiagnosticThreshold_dB;

end

function value = localHasIqIssue(referenceMetrics, surveillanceMetrics, ...
    resolvedOptions)

value = abs(referenceMetrics.IqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceDiagnosticThreshold_dB || ...
    abs(surveillanceMetrics.IqAmplitudeImbalance_dB) >= ...
    resolvedOptions.IqAmplitudeImbalanceDiagnosticThreshold_dB || ...
    abs(referenceMetrics.IqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxyDiagnosticThreshold_deg || ...
    abs(surveillanceMetrics.IqPhaseProxy_deg) >= ...
    resolvedOptions.IqPhaseProxyDiagnosticThreshold_deg || ...
    referenceMetrics.IqImpropriety >= ...
    resolvedOptions.IqImproprietyDiagnosticThreshold || ...
    surveillanceMetrics.IqImpropriety >= ...
    resolvedOptions.IqImproprietyDiagnosticThreshold;

end

