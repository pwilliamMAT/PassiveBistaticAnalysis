    error("runRealBackgroundSyntheticPipeline:DatasetCount", ...
        "Expected exactly one generated dataset for %s.", caseId);
end
entry = entries(mask);
end

function integrity = localVerifyInputPair( ...
    controlSession, injectedSession, baseCapturePath, ...
    controlEntry, injectedEntry)
controlSamples = controlSession.RadarScans(1).Samples;
injectedSamples = injectedSession.RadarScans(1).Samples;
surveillanceDelta = complex( ...
    double(real(injectedSamples(:, 1))) - ...
    double(real(controlSamples(:, 1))), ...
    double(imag(injectedSamples(:, 1))) - ...
    double(imag(controlSamples(:, 1))));
baseHash = helperG4RSha256(baseCapturePath);
controlHash = helperG4RSha256(controlEntry.output_bb_path);
injectedHash = helperG4RSha256(injectedEntry.output_bb_path);
integrity = struct( ...
    ReferenceChannelExactlyUnchanged=isequal( ...
    injectedSamples(:, 2), controlSamples(:, 2)), ...
    ControlCaptureExactlyUnchanged=baseHash == controlHash, ...
    ControlSurveillanceExactlyUnchanged=baseHash == controlHash, ...
    InjectedSurveillanceDeltaFinite=all( ...
    isfinite(surveillanceDelta), "all"), ...
    InjectedSurveillanceDeltaNonzero=any( ...
    surveillanceDelta ~= 0, "all"), ...
    InjectedSurveillanceDeltaRms=rms(double(surveillanceDelta)), ...
    BaseCaptureSha256=baseHash, ...
    ControlCaptureSha256=controlHash, ...
    InjectedCaptureSha256=injectedHash, ...
    ProducerControlValidationPass=logical( ...
    controlEntry.validation_checks.overall_pass), ...
    ProducerInjectedValidationPass=logical( ...
    injectedEntry.validation_checks.overall_pass));
end

function localRequireInputIntegrity(integrity)
required = [ ...
    integrity.ReferenceChannelExactlyUnchanged, ...
    integrity.ControlCaptureExactlyUnchanged, ...
    integrity.ControlSurveillanceExactlyUnchanged, ...
    integrity.InjectedSurveillanceDeltaFinite, ...
    integrity.InjectedSurveillanceDeltaNonzero, ...
    integrity.ProducerControlValidationPass, ...
    integrity.ProducerInjectedValidationPass];
if ~all(required)
    error("runRealBackgroundSyntheticPipeline:InputIntegrity", ...
        "Generated paired inputs failed a channel-preservation invariant.");
end
end

