function g4 = localBuildG4Contract(session, correction, resolved)
sampleRateHz = double(session.RadarTable.SampleRate_Hz(1));
mapSampleRateHz = sampleRateHz ./ resolved.MapDecimationFactor;
nativeCpiSamples = round(resolved.CpiDurationS .* sampleRateHz);
mapCpiSamples = round(resolved.CpiDurationS .* mapSampleRateHz);
sampleCount = double(session.RadarTable.NumSamples(1));
windowCount = floor(sampleCount ./ nativeCpiSamples);
centerWindowIndex = ceil(windowCount ./ 2.0);
windowStartSample = ...
    (centerWindowIndex - 1.0) .* nativeCpiSamples + 1.0;
mapSummaryTable = table( ...
    1.0, string(session.RadarTable.RelativePath(1)), ...
    "long", "center", windowStartSample, centerWindowIndex, ...
    resolved.CpiDurationS, mapCpiSamples, ...
    VariableNames={ ...
    'Repetition', 'RelativePath', 'CpiLabel', 'WindowLabel', ...
    'WindowStartSample', 'WindowIndex', 'CpiDuration_s', ...
    'CpiSamples'});
originDelayRadius = max(2.0, ceil( ...
    (correction.LagResidualMax_samples + 16.0) ./ ...
    resolved.MapDecimationFactor));
originDopplerRadius = max(5.0, ...
    correction.ResidualFrequencySpread_Hz + 10.0);
baseline = struct( ...
    Method="ambgfun", ...
    MapRateMode="reduced_rate_g5_candidate_product", ...
    MapSampleRateHz=mapSampleRateHz, ...
    MapDecimationFactor=resolved.MapDecimationFactor, ...
    OriginSearchDelayRadius_samples=originDelayRadius, ...
    OriginSearchDopplerRadius_Hz=originDopplerRadius, ...
    ExclusionDelayRadius_samples=max(6.0, ...
    originDelayRadius + 2.0), ...
    ExclusionDopplerRadius_Hz=max(25.0, ...
    2.0 .* originDopplerRadius), ...
    ZeroDopplerRidgeExclusion_Hz=25.0, ...
    AppliedLag_samples=correction.AppliedLag_samples, ...
    AppliedResidualFrequency_Hz= ...
    correction.AppliedResidualFrequency_Hz, ...
    AppliedCorrectionSource=correction.Source);
interpretation = struct( ...
    OverallLabel="diagnostic_only", ...
    OverallRationale="This compact G4 contract supports the paired " + ...
    "diagnostic demonstration only; it does not promote or replace " + ...
    "the passed formal G4-R R4 map-rate-validity evidence.", ...
    SceneObservabilityLabel="NOT_APPLICABLE_SYNTHETIC_PROFILE", ...
    FullRateAuditAgreementLabel="NOT_RUN_DIAGNOSTIC_DEMO", ...
    ReferenceLabel=string(session.RadarTable.Antenna2(1)), ...
    SurveillanceLabel=string(session.RadarTable.Antenna1(1)), ...
    CaveatCodes="r5a_authorized_not_executed");
g4 = struct( ...
    DatasetId=string(session.DatasetId), ...
    StageId="G4_Diagnostic_CAF_Input_Contract", ...
    Options=struct( ...
    MapDecimationFactor=resolved.MapDecimationFactor, ...
    MapSampleRateHz=mapSampleRateHz, ...
    ReviewMapRows=128.0, ReviewMapCols=128.0, ...
    FigureFloor_dB=-60.0), ...
    MapSummaryTable=mapSummaryTable, ...
    BaselineProductDefinition=baseline, ...
    Interpretation=interpretation, ...
    RecommendedBaselineCpiLabel="long");
end

function localVerifyCorrectionReuse(g5, g4, correction, caseLabel)
g4Match = g4.BaselineProductDefinition.AppliedLag_samples == ...
    correction.AppliedLag_samples && ...
    g4.BaselineProductDefinition.AppliedResidualFrequency_Hz == ...
    correction.AppliedResidualFrequency_Hz;
g5Match = g5.AppliedCorrection.AppliedLag_samples == ...
    correction.AppliedLag_samples && ...
    g5.AppliedCorrection.AppliedResidualFrequency_Hz == ...
    correction.AppliedResidualFrequency_Hz;
if ~(g4Match && g5Match)
    error("runRealBackgroundSyntheticPipeline:CorrectionReuse", ...
        "The %s case did not reuse the control-derived G3 correction.", ...
        caseLabel);
end
end

