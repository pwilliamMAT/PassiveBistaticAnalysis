function [results, detectorReplaySession] = ...
    runRealBackgroundSyntheticPipeline(options)
%RUNREALBACKGROUNDSYNTHETICPIPELINE Run the paired field-background demo.
%
%   RESULTS = RUNREALBACKGROUNDSYNTHETICPIPELINE() generates an untouched
%   control and one surveillance-only injected case from part 1 of session
%   20260622T102123, derives G3 once from the control, reuses that correction
%   for both cases, and executes the diagnostic G1-G5 plus G6-D path.
%
%   This is an integration demonstration. It does not alter formal G4-R,
%   G5, G6, or G8 gate state and does not make a field-detection claim.

arguments
    options.BaseSessionId (1,1) string = "20260622T102123"
    options.BasePartIndex (1,1) double {mustBeInteger, mustBePositive} = 1
    options.EchoGainDB (1,1) double {mustBeFinite} = -18
    options.TrajectoryNorthOffsetM (1,1) double {mustBeFinite} = 45000
    options.TrajectoryAltitudeM (1,1) double {mustBeFinite} = 3000
    options.TrajectorySpeedMps (1,1) double {mustBeNonnegative} = 150
    options.TrajectoryHeadingDeg (1,1) double {mustBeFinite} = 0
    options.ReceiverLocalWaypointTable table = table()
    options.GeoTrajectoryTargets struct = struct([])
    options.CpiDurationS (1,1) double {mustBePositive} = 0.100
    options.MapDecimationFactor (1,1) double {mustBeInteger, mustBePositive} = 200
    options.TruthSamplePeriodS (1,1) double {mustBePositive} = 0.01
    options.PfaToHighlight (1,1) double {mustBePositive} = 1.0e-3
    options.ProducerRoot (1,1) string = ""
    options.GeneratedIqRoot (1,1) string = ""
    options.ResultRoot (1,1) string = ""
    options.SuiteId (1,1) string = ""
    options.ShowFigures (1,1) logical = false
    options.SaveResult (1,1) logical = true
end

repoRoot = helperResolveRepoRoot(string(fileparts(mfilename("fullpath"))));
detectorReplaySession = struct();
resolved = localResolveOptions(options, repoRoot);
localValidateNativeFunctions(resolved);
originalPath = path;
pathCleanup = onCleanup(@() path(originalPath));
addpath(repoRoot);
addpath(fullfile(resolved.ProducerRoot, "SyntheticHDTVSimulation"), "-end");
addpath(fullfile(resolved.ProducerRoot, "BistaticDataAnalysis"), "-end");

trajectoryTargets = resolved.GeoTrajectoryTargets;
if isempty(trajectoryTargets)
    if isempty(resolved.ReceiverLocalWaypointTable)
        trajectoryTargets = localBuildDefaultTrajectory(resolved);
    else
        trajectoryTargets = ...
            localBuildReceiverLocalTrajectory(resolved);
    end
end
caseDefinitions = localBuildCaseDefinitions(resolved, trajectoryTargets);
suiteArtifact = generateRealBackgroundSyntheticSuite( ...
    SuiteID=resolved.SuiteId, ...
    OutputRoot=resolved.GeneratedIqRoot, ...
    BaseSessionManifest=resolved.BaseSessionManifest, ...
    BasePartIndex=resolved.BasePartIndex, ...
    TruthWindowMaxS=1.0, ...
    TruthSamplePeriodS=resolved.TruthSamplePeriodS, ...
    TruthSourceMode="geo_trajectory_v1", ...
    GeoTrajectoryTargets=trajectoryTargets, ...
    CaseDefinitions=caseDefinitions, ...
    DirectPathLagSamples=0, ...
    SeedEchoConditioningEnabled=true, ...
    RunValidation=true, ...
    WriteReadme=true, ...
    RetainSampleArrays=false);

controlEntry = localFindDataset( ...
    suiteArtifact.datasets, resolved.ControlCaseId);
injectedEntry = localFindDataset( ...
    suiteArtifact.datasets, resolved.InjectedCaseId);
controlRoot = fullfile(suiteArtifact.suite_folder, ...
    resolved.ControlCaseId);
injectedRoot = fullfile(suiteArtifact.suite_folder, ...
    resolved.InjectedCaseId);
controlSession = loadIQData(resolved.ControlCaseId, repoRoot, struct( ...
    SessionRoot=controlRoot, IncludeSamples=true, PartSelection=1));
injectedSession = loadIQData(resolved.InjectedCaseId, repoRoot, struct( ...
    SessionRoot=injectedRoot, IncludeSamples=true, PartSelection=1));
controlMetadata = helperReadCollectionMetadata( ...
    fullfile(controlRoot, "collection_metadata.json"), ...
    resolved.ControlCaseId);
injectedMetadata = helperReadCollectionMetadata( ...
    fullfile(injectedRoot, "collection_metadata.json"), ...
    resolved.InjectedCaseId);
inputIntegrity = localVerifyInputPair( ...
    controlSession, injectedSession, ...
    suiteArtifact.base_capture_path, controlEntry, injectedEntry);
localRequireInputIntegrity(inputIntegrity);

roleOptions = struct( ...
    DataProfile="synthetic", ...
    ReferenceChannelIndex=2.0, ...
    SurveillanceChannelIndex=1.0);
captureLogInfo = localEmptyCaptureLogInfo();
controlG2 = localRunG2( ...
    controlSession, controlMetadata, captureLogInfo, roleOptions);
injectedG2 = localRunG2( ...
    injectedSession, injectedMetadata, captureLogInfo, roleOptions);

g3Options = roleOptions;
g3Options.ExpectedDatasetId = resolved.ControlCaseId;
g3Options.ExpectedReferenceLabel = ...
    string(controlSession.RadarTable.Antenna2(1));
g3Options.ExpectedSurveillanceLabel = ...
    string(controlSession.RadarTable.Antenna1(1));
g3Options.ExpectedRepetitionCount = 1.0;
g3Options.ConfiguredDirectPathLag_samples = ...
    double(suiteArtifact.direct_path_lag_samples);
g3Options.ConfiguredDirectPathResidualFrequency_Hz = 0.0;
g3Options.ConfiguredDirectPathCorrectionSource = ...
    "generated_control_manifest";
controlG3 = helperAnalyzeG3SyncCore( ...
    controlSession, controlMetadata, g3Options);
correction = controlG3.GlobalCorrection;
correction.Source = "field_only_control_g3_global_session_correction";
correctionHash = helperG4RSha256(correction);
g3Visuals = helperBuildG3SyncVisuals(controlSession, controlG3);

scenarioTruth = helperAdaptG45TruthForPostHocEvidence( ...
    injectedEntry.output_truth_path, resolved.InjectedCaseId);
[controlG5, controlMaps, controlG4Contract] = localRunG4G5( ...
    controlSession, controlMetadata, controlG3, correction, ...
    scenarioTruth, resolved);
localVerifyCorrectionReuse( ...
    controlG5, controlG4Contract, correction, "control");
controlMaps = localIdentifyMaps( ...
    controlMaps, resolved, resolved.ControlCaseId);
controlTruth = localBuildDetectorTruth( ...
    controlG5.SyntheticTargetEvidenceTable, resolved, ...
    resolved.ControlCaseId, "matched_control");
controlTargetViews = helperBuildTargetCenteredMapViews( ...
    controlMaps, controlTruth);
g6Context = struct( ...
    CampaignId=resolved.SuiteId, ...
    BackgroundId=resolved.BaseSessionId, ...
    CaseId=resolved.ControlCaseId, ...
    DetectorConfiguration=resolved.DetectorConfiguration, ...
    Finalize=false);
g6Result = helperAnalyzeG6ProductDiscrimination( ...
    controlMaps, controlTruth, g6Context);
controlCrops = localBuildDetectionRegionCrops( ...
    controlMaps, g6Result.Configuration);
if nargout > 1
    replayControlMaps = controlMaps;
    replayControlTruth = controlTruth;
end
clear controlMaps controlSession

[injectedG5, injectedMaps, injectedG4Contract] = localRunG4G5( ...
    injectedSession, injectedMetadata, controlG3, correction, ...
    scenarioTruth, resolved);
localVerifyCorrectionReuse( ...
    injectedG5, injectedG4Contract, correction, "injected");
injectedMaps = localIdentifyMaps( ...
    injectedMaps, resolved, resolved.InjectedCaseId);
injectedTruth = localBuildDetectorTruth( ...
    injectedG5.SyntheticTargetEvidenceTable, resolved, ...
    resolved.InjectedCaseId, "injected");
injectedTargetViews = helperBuildTargetCenteredMapViews( ...
    injectedMaps, injectedTruth);
g6Context.CaseId = resolved.InjectedCaseId;
g6Result = helperAnalyzeG6ProductDiscrimination( ...
    injectedMaps, injectedTruth, g6Context, g6Result);
injectedCrops = localBuildDetectionRegionCrops( ...
    injectedMaps, g6Result.Configuration);
if nargout > 1
    detectorReplaySession = localBuildDetectorReplaySession( ...
        [replayControlMaps; injectedMaps], ...
        [replayControlTruth; injectedTruth], resolved);
end
clear injectedMaps injectedSession

finalContext = struct( ...
    CampaignId=resolved.SuiteId, ...
    Finalize=true, ...
    EnforceCampaignCounts=true, ...
    ExpectedMapCount=6.0, ...
    ExpectedOperatingPointCount=54.0, ...
    ExpectedTruthOpportunityCount=27.0);
g6Result = helperAnalyzeG6ProductDiscrimination( ...
    struct([]), table(), finalContext, g6Result);

detectionRegionViews = [controlCrops; injectedCrops];
targetCenteredViews = [controlTargetViews; injectedTargetViews];
verification = localBuildVerification( ...
    inputIntegrity, controlG3, correctionHash, controlG5, ...
    injectedG5, injectedTruth, g6Result, resolved);
stageSummary = localBuildStageSummary( ...
    controlSessionSummary(controlEntry, controlG2), ...
    injectedSessionSummary(injectedEntry, injectedG2), ...
    controlG3, verification);

results = struct();
results.SchemaVersion = "field_background_synthetic_pipeline_demo_v2";
results.AnalysisTimestampZ = string(datetime("now", TimeZone="UTC", ...
    Format="yyyyMMdd'T'HHmmssSSS'Z'"));
results.ClaimBoundary = struct( ...
    DiagnosticIntegrationOnly=true, ...
    FieldDetectionClaimed=false, ...
    TrackingClaimed=false, ...
    FormalG4RStateChanged=false, ...
    FormalG6OrG8Enabled=false, ...
    TruthUse="post_hoc_association_only");
results.Configuration = localCompactConfiguration(resolved);
results.NativeFunctionAudit = localNativeFunctionAudit();
results.Provenance = localBuildProvenance( ...
    suiteArtifact, controlEntry, injectedEntry, correctionHash, ...
    resolved);
results.Trajectory = localBuildTrajectorySummary( ...
    trajectoryTargets, suiteArtifact.truth_bundle_all);
results.InputIntegrity = inputIntegrity;
results.StageSummary = stageSummary;
results.G2 = struct( ...
    Control=localCompactG2(controlG2), ...
    Injected=localCompactG2(injectedG2));
results.G3 = struct( ...
    DerivedCaseId=resolved.ControlCaseId, ...
    ReusedCaseId=resolved.InjectedCaseId, ...
    OverallLabel=localG3OverallLabel(controlG3), ...
    RecommendedStrategyCandidate= ...
    string(controlG3.RecommendedStrategyCandidate), ...
    Correction=correction, ...
    CorrectionSha256=correctionHash, ...
    Visuals=g3Visuals);
results.G4G5 = struct( ...
    Control=localCompactG5(controlG5, controlG4Contract), ...
    Injected=localCompactG5(injectedG5, injectedG4Contract));
results.G6D = g6Result;
results.DetectionRegionViews = detectionRegionViews;
results.TargetCenteredViews = targetCenteredViews;
results.Verification = verification;
results.Conclusion = localBuildConclusion(verification, resolved);
results.ResultPath = "";
compactAudit = localAuditCompactResult(results);
results.CompactResultAudit = compactAudit;
if ~compactAudit.Compact
    error("runRealBackgroundSyntheticPipeline:CompactRetention", ...
        "The result contains raw IQ or a complete map.");
end

if resolved.SaveResult
    runFolder = fullfile(resolved.ResultRoot, resolved.SuiteId);
    if ~isfolder(runFolder)
        mkdir(runFolder);
    end
    resultPath = fullfile(runFolder, ...
        "fieldBackgroundSyntheticPipelineResults.mat");
    results.ResultPath = string(resultPath);
    save(resultPath, "results");
    savedResult = load(resultPath, "results");
    savedAudit = localAuditCompactResult(savedResult.results);
    if ~savedAudit.Compact
        error("runRealBackgroundSyntheticPipeline:SavedRetention", ...
            "The saved result violates compact-retention requirements.");
    end
end

if resolved.ShowFigures
    localPlotSummary(results);
end
clear pathCleanup
end

function resolved = localResolveOptions(options, repoRoot)
resolved = options;
if strlength(resolved.ProducerRoot) == 0
    resolved.ProducerRoot = fullfile(fileparts(repoRoot), ...
        "flightTest_SynthDataBranch");
end
if strlength(resolved.GeneratedIqRoot) == 0
    resolved.GeneratedIqRoot = fullfile(repoRoot, "artifacts", ...
        "generated_iq", "FieldBackgroundSyntheticDemo");
end
if strlength(resolved.ResultRoot) == 0
    resolved.ResultRoot = fullfile(repoRoot, "artifacts", ...
        resolved.BaseSessionId, "Field_Background_Synthetic_Demo");
end
if strlength(resolved.SuiteId) == 0
    resolved.SuiteId = "field_background_demo_" + ...
        string(datetime("now", TimeZone="UTC", ...
        Format="yyyyMMdd'T'HHmmssSSS"));
end
resolved.BaseSessionManifest = fullfile( ...
    repoRoot, resolved.BaseSessionId, "session_manifest.json");
resolved.ControlCaseId = "field_only_control";
resolved.InjectedCaseId = "field_plus_geo_target";
resolved.RepoRoot = repoRoot;
resolved.DetectorConfiguration = helperBuildG6DDetectorConfiguration();
end

function localValidateNativeFunctions(resolved)
requiredFiles = [ ...
    fullfile(resolved.ProducerRoot, "SyntheticHDTVSimulation", ...
    "generateRealBackgroundSyntheticSuite.m"); ...
    resolved.BaseSessionManifest];
if ~isfolder(resolved.ProducerRoot) || any(~isfile(requiredFiles))
    error("runRealBackgroundSyntheticPipeline:MissingInput", ...
        "Producer root or base session manifest is unavailable.");
end
requiredFunctions = [ ...
    "ambgfun"; "resample"; "imdilate"; "bwconncomp"; ...
    "reckon"; "wgs84Ellipsoid"];
for functionIndex = 1:numel(requiredFunctions)
    if exist(requiredFunctions(functionIndex), "file") ~= 2
        error("runRealBackgroundSyntheticPipeline:MissingFunction", ...
            "Required MATLAB function is unavailable: %s.", ...
            requiredFunctions(functionIndex));
    end
end
if exist("dsp.LMSFilter", "class") ~= 8 || ...
        exist("phased.CFARDetector2D", "class") ~= 8
    error("runRealBackgroundSyntheticPipeline:MissingSystemObject", ...
        "DSP LMS and phased-array CFAR System objects are required.");
end
end

function targets = localBuildDefaultTrajectory(resolved)
times_s = [0; 0.5; 1.0];
north_m = resolved.TrajectoryNorthOffsetM + ...
    resolved.TrajectorySpeedMps .* cosd( ...
    resolved.TrajectoryHeadingDeg) .* times_s;
east_m = resolved.TrajectorySpeedMps .* sind( ...
    resolved.TrajectoryHeadingDeg) .* times_s;
waypointTable = table(times_s, north_m, east_m, ...
    repmat(resolved.TrajectoryAltitudeM, numel(times_s), 1), ...
    VariableNames={'Time_s', 'North_m', 'East_m', 'Altitude_m'});
resolved.ReceiverLocalWaypointTable = waypointTable;
targets = localBuildReceiverLocalTrajectory(resolved);
end

