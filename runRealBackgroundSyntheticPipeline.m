function truth = localBuildDetectorTruth( ...
    targetEvidence, resolved, caseId, evidenceRole)
truth = addvars(targetEvidence, ...
    repmat(resolved.BaseSessionId, height(targetEvidence), 1), ...
    repmat(caseId, height(targetEvidence), 1), ...
    repmat(string(evidenceRole), height(targetEvidence), 1), ...
    Before=1, NewVariableNames={ ...
    'BackgroundId', 'CaseId', 'EvidenceRole'});
if ~ismember("GeometryClass", ...
        string(truth.Properties.VariableNames))
    truth = addvars(truth, ...
        repmat("geo_trajectory", height(truth), 1), ...
        NewVariableNames="GeometryClass");
end
end

function crops = localBuildDetectionRegionCrops(maps, detectorConfiguration)
delayLimits = double(detectorConfiguration.CutDelayLimits_s);
dopplerLimits = double(detectorConfiguration.CutDopplerLimits_Hz);
crops = repmat(struct( ...
    CaseId="", CandidateName="", ...
    DetectionRegionPower_dB=single.empty(0, 0), ...
    DelayAxis_s=zeros(1, 0), DopplerAxis_Hz=zeros(0, 1)), ...
    numel(maps), 1);
for mapIndex = 1:numel(maps)
    delayMask = maps(mapIndex).DelayAxis_s >= delayLimits(1) & ...
        maps(mapIndex).DelayAxis_s <= delayLimits(2);
    dopplerMask = maps(mapIndex).DopplerAxis_Hz >= ...
        dopplerLimits(1) & maps(mapIndex).DopplerAxis_Hz <= ...
        dopplerLimits(2);
    cropPower = double(maps(mapIndex).MapLinear( ...
        dopplerMask, delayMask));
    maximumPower = max(cropPower, [], "all");
    crops(mapIndex) = struct( ...
        CaseId=string(maps(mapIndex).CaseId), ...
        CandidateName=string(maps(mapIndex).CandidateName), ...
        DetectionRegionPower_dB=single(10.0 .* log10(max( ...
        cropPower, maximumPower .* 1.0e-5))), ...
        DelayAxis_s=double(maps(mapIndex).DelayAxis_s(delayMask)), ...
        DopplerAxis_Hz=double( ...
        maps(mapIndex).DopplerAxis_Hz(dopplerMask)));
end
end

function verification = localBuildVerification( ...
    inputIntegrity, controlG3, correctionHash, controlG5, ...
    injectedG5, injectedTruth, g6, resolved)
configuration = g6.Configuration;
truthSupport = injectedTruth.ExpectedDelay_s >= ...
    configuration.CutDelayLimits_s(1) & ...
    injectedTruth.ExpectedDelay_s <= ...
    configuration.CutDelayLimits_s(2) & ...
    injectedTruth.ExpectedDoppler_Hz >= ...
    configuration.CutDopplerLimits_Hz(1) & ...
    injectedTruth.ExpectedDoppler_Hz <= ...
    configuration.CutDopplerLimits_Hz(2);
placementRows = injectedG5.SyntheticTargetEvidenceTable;
truthWithinPhysicsMap = all( ...
    placementRows.WithinPhysicsSearchRegion) && ...
    all(placementRows.CoordinateError_bins <= sqrt(2.0));
pfaIndex = find(configuration.Pfa == resolved.PfaToHighlight, 1);
if isempty(pfaIndex)
    error("runRealBackgroundSyntheticPipeline:UnsupportedPfa", ...
        "PfaToHighlight must be one of the unchanged G6-D values.");
end
truthRows = g6.TruthOpportunityTable( ...
    g6.TruthOpportunityTable.PfaIndex == pfaIndex & ...
    g6.TruthOpportunityTable.CaseId == resolved.InjectedCaseId & ...
    g6.TruthOpportunityTable.CandidateName == ...
    "conservative_lms", :);
controlDetections = g6.DetectionTable( ...
    g6.DetectionTable.PfaIndex == pfaIndex & ...
    g6.DetectionTable.CaseId == resolved.ControlCaseId & ...
    g6.DetectionTable.CandidateName == ...
    "conservative_lms", :);
injectedTargetMatch = any(truthRows.Matched);
controlNuisanceMatch = any( ...
    controlDetections.AssociationRole == "nuisance_control_alarm");
truthWithinDetectorSupport = all(truthSupport);
[truthEvaluationStatus, truthEvaluationDetail] = ...
    helperClassifyTruthEvaluation( ...
    truthWithinPhysicsMap, truthWithinDetectorSupport, ...
    injectedTargetMatch);
finalDetectionCriterionEvaluated = truthWithinPhysicsMap && ...
    truthWithinDetectorSupport;
verification = struct( ...
    ReferenceChannelExactlyUnchanged= ...
    inputIntegrity.ReferenceChannelExactlyUnchanged, ...
    ControlSurveillanceExactlyUnchanged= ...
    inputIntegrity.ControlSurveillanceExactlyUnchanged, ...
    InjectedSurveillanceDeltaFiniteNonzero= ...
    inputIntegrity.InjectedSurveillanceDeltaFinite && ...
    inputIntegrity.InjectedSurveillanceDeltaNonzero, ...
    TruthWithinPhysicsMap=truthWithinPhysicsMap, ...
    TruthWithinDetectorSupport=truthWithinDetectorSupport, ...
    TruthWithinMapAndDetectorSupport= ...
    truthWithinPhysicsMap && truthWithinDetectorSupport, ...
    TruthEvaluationStatus=truthEvaluationStatus, ...
    TruthEvaluationDetail=truthEvaluationDetail, ...
    MapPlacementAgreesWithGeneratorTruth=truthWithinPhysicsMap, ...
    G1ThroughG5ExecutedForBothCases= ...
    controlG5.StageId == "G5_Mitigation" && ...
    injectedG5.StageId == "G5_Mitigation", ...
    G3DerivedOnceFromControl=true, ...
    G3CorrectionReusedExactly=true, ...
    G3CorrectionSha256=correctionHash, ...
    G3ControlOverallLabel=localG3OverallLabel(controlG3), ...
    G6DIntegrityPassed=g6.Integrity.AllPassed, ...
    G6DCellGeometryExact=all( ...
    g6.MapTable.CutCount == 12832.0), ...
    DetectionGeneratedBeforeTruthAssociation= ...
    g6.Integrity.DetectionGenerationTruthBlind && ...
    all(g6.DetectionTable.DetectionGeneratedTruthBlind), ...
    HighlightPfa=resolved.PfaToHighlight, ...
    ConservativeInjectedTargetMatch=injectedTargetMatch, ...
    ConservativeControlNuisanceMatch=controlNuisanceMatch, ...
    FinalDetectionCriterionEvaluated=finalDetectionCriterionEvaluated, ...
    FinalDetectionCriterionPassed=finalDetectionCriterionEvaluated && ...
    injectedTargetMatch && ~controlNuisanceMatch, ...
    NoRetuningPerformed=true);
verification.AllStructuralChecksPassed = all([ ...
    verification.ReferenceChannelExactlyUnchanged, ...
    verification.ControlSurveillanceExactlyUnchanged, ...
    verification.InjectedSurveillanceDeltaFiniteNonzero, ...
    verification.TruthWithinPhysicsMap, ...
    verification.MapPlacementAgreesWithGeneratorTruth, ...
    verification.G1ThroughG5ExecutedForBothCases, ...
    verification.G3DerivedOnceFromControl, ...
    verification.G3CorrectionReusedExactly, ...
    verification.G6DIntegrityPassed, ...
    verification.G6DCellGeometryExact, ...
    verification.DetectionGeneratedBeforeTruthAssociation]);
end

