function paths = localFindProhibitedFields(value, currentPath)
paths = strings(0, 1);
names = ["samples"; "radarscans"; "rawiq"; "maplinear"; ...
    "fullmap"; "fullmapcollection"];
if isstruct(value)
    fields = string(fieldnames(value));
    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(fields)
            field = fields(fieldIndex);
            nextPath = currentPath + "." + field;
            if any(lower(field) == names)
                paths(end + 1, 1) = nextPath; %#ok<AGROW>
            end
            paths = [paths; localFindProhibitedFields( ...
                value(elementIndex).(field), nextPath)]; %#ok<AGROW>
        end
    end
elseif istable(value)
    variables = string(value.Properties.VariableNames);
    for variableIndex = 1:numel(variables)
        if any(lower(variables(variableIndex)) == names)
            paths(end + 1, 1) = currentPath + "." + ...
                variables(variableIndex); %#ok<AGROW>
        end
    end
elseif iscell(value)
    for elementIndex = 1:numel(value)
        paths = [paths; localFindProhibitedFields( ...
            value{elementIndex}, currentPath)]; %#ok<AGROW>
    end
end
end

function sizes = localCollectNumericSizes(value)
sizes = 0;
if isnumeric(value) || islogical(value)
    sizes = numel(value);
elseif isstruct(value)
    fields = fieldnames(value);
    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(fields)
            sizes = [sizes; localCollectNumericSizes( ...
                value(elementIndex).(fields{fieldIndex}))]; %#ok<AGROW>
        end
    end
elseif istable(value)
    variables = value.Properties.VariableNames;
    for variableIndex = 1:numel(variables)
        sizes = [sizes; localCollectNumericSizes( ...
            value.(variables{variableIndex}))]; %#ok<AGROW>
    end
elseif iscell(value)
    for elementIndex = 1:numel(value)
        sizes = [sizes; localCollectNumericSizes( ...
            value{elementIndex})]; %#ok<AGROW>
    end
end
end

function conclusion = localBuildConclusion(verification, resolved)
if verification.TruthEvaluationStatus == "outside_physics_map_invalid"
    outcome = "invalid_truth_outside_physics_map";
    detail = "Generator truth did not pass full-map placement validation; " + ...
        "the fixed detection criterion is not interpretable.";
elseif ~verification.FinalDetectionCriterionEvaluated
    outcome = "not_evaluated_outside_detector_support";
    detail = "Conservative LMS was not evaluated at the truth location " + ...
        "because truth lies outside the fixed CFAR/NMS support. " + ...
        "Parameters were not retuned.";
elseif verification.FinalDetectionCriterionPassed
    outcome = "criterion_passed";
    detail = sprintf( ...
        "Conservative LMS at Pfa %.0e produced an injected-target match " + ...
        "and no matched-control nuisance alarm.", ...
        resolved.PfaToHighlight);
else
    outcome = "criterion_failed_without_retuning";
    detail = sprintf( ...
        "Conservative LMS at Pfa %.0e did not satisfy the fixed paired " + ...
        "criterion. Parameters were not retuned.", ...
        resolved.PfaToHighlight);
end
conclusion = struct( ...
    Outcome=outcome, ...
    Detail=string(detail), ...
    Limitation= ...
    "Diagnostic synthetic integration only; no field detection or tracking claim.");
end

