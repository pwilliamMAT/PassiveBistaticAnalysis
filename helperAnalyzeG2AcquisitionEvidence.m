function [channelRoleEvidenceTable, roleEvidence] = ...
    localBuildChannelRoleEvidence(sessionData, roleInfo, resolvedOptions)

radarTable = sessionData.RadarTable;
repetitionCount = height(radarTable);
sampleRateHz = resolvedOptions.SampleRateHz;

channelPowerDeltaDb = radarTable.ChannelPowerDelta_dB;
meanCoherence = zeros(repetitionCount, 1);
maxCoherence = zeros(repetitionCount, 1);
zeroLagCorrelationMagnitude = zeros(repetitionCount, 1);
peakCorrelationMagnitude = zeros(repetitionCount, 1);
peakCorrelationLagSamples = zeros(repetitionCount, 1);
roleInference = strings(repetitionCount, 1);
referenceCandidateIsChannel1 = false(repetitionCount, 1);
channel1PsdAccumulator = [];
channel2PsdAccumulator = [];
coherenceAccumulator = [];
correlationAccumulator = [];
psdFrequencyHz = [];
coherenceFrequencyHz = [];
correlationLags = [];

for idx = 1:repetitionCount
    samples = helperResolveRadarSamples(sessionData, idx);
    channel1 = double(samples(:, 1));
    channel2 = double(samples(:, 2));

    [channel1Psd, psdFrequencyHz] = pwelch(channel1, ...
        resolvedOptions.WelchWindow, resolvedOptions.WelchOverlap, ...
        resolvedOptions.WelchNfft, sampleRateHz);
    [channel2Psd, ~] = pwelch(channel2, resolvedOptions.WelchWindow, ...
        resolvedOptions.WelchOverlap, resolvedOptions.WelchNfft, ...
        sampleRateHz);
    [coherenceValues, coherenceFrequencyHz] = mscohere(channel1, channel2, ...
        resolvedOptions.WelchWindow, resolvedOptions.WelchOverlap, ...
        resolvedOptions.WelchNfft, sampleRateHz);

    correlationSampleCount = min(numel(channel1), ...
        resolvedOptions.CorrelationSampleCount);
    [correlationValues, correlationLags] = xcorr( ...
        channel1(1:correlationSampleCount), ...
        channel2(1:correlationSampleCount), ...
        resolvedOptions.CorrelationMaxLagSamples, "normalized");

    if isempty(channel1PsdAccumulator)
        channel1PsdAccumulator = zeros(size(channel1Psd));
        channel2PsdAccumulator = zeros(size(channel2Psd));
        coherenceAccumulator = zeros(size(coherenceValues));
        correlationAccumulator = zeros(numel(correlationValues), ...
            repetitionCount);
    end

    channel1PsdAccumulator = channel1PsdAccumulator + channel1Psd;
    channel2PsdAccumulator = channel2PsdAccumulator + channel2Psd;
    coherenceAccumulator = coherenceAccumulator + coherenceValues;
    correlationAccumulator(:, idx) = abs(correlationValues);
    meanCoherence(idx) = mean(coherenceValues, "omitnan");
    maxCoherence(idx) = max(coherenceValues);
    zeroLagIndex = find(correlationLags == 0, 1, "first");
    zeroLagCorrelationMagnitude(idx) = abs(correlationValues(zeroLagIndex));
    [peakCorrelationMagnitude(idx), peakIndex] = max(abs(correlationValues));
    peakCorrelationLagSamples(idx) = correlationLags(peakIndex);
    referenceCandidateIsChannel1(idx) = channelPowerDeltaDb(idx) >= ...
        resolvedOptions.ReferenceCandidatePowerDeltaThreshold_dB;
    roleInference(idx) = localDetermineRoleInference( ...
        channelPowerDeltaDb(idx), ...
        resolvedOptions.ReferenceCandidatePowerDeltaThreshold_dB);
end

meanChannel1Psd = channel1PsdAccumulator ./ repetitionCount;
meanChannel2Psd = channel2PsdAccumulator ./ repetitionCount;
meanCoherenceSpectrum = coherenceAccumulator ./ repetitionCount;
medianCorrelationMagnitude = median(correlationAccumulator, 2);

[psdFrequencyHz, meanChannel1Psd, meanChannel2Psd] = localCenterTwoSided( ...
    psdFrequencyHz, meanChannel1Psd, meanChannel2Psd, sampleRateHz);
[coherenceFrequencyHz, meanCoherenceSpectrum] = localCenterSingleSpectrum( ...
    coherenceFrequencyHz, meanCoherenceSpectrum, sampleRateHz);

channelRoleEvidenceTable = table(radarTable.Repetition, ...
    radarTable.RelativePath, repmat(radarTable.Antenna1(1), repetitionCount, 1), ...
    repmat(radarTable.Antenna2(1), repetitionCount, 1), channelPowerDeltaDb, ...
    meanCoherence, maxCoherence, zeroLagCorrelationMagnitude, ...
    peakCorrelationMagnitude, peakCorrelationLagSamples, ...
    referenceCandidateIsChannel1, roleInference, ...
    VariableNames = {'Repetition', 'RelativePath', 'Channel1Label', ...
    'Channel2Label', 'ChannelPowerDelta_dB', 'MeanCoherence', ...
    'MaxCoherence', 'ZeroLagCorrelationMagnitude', ...
    'PeakCorrelationMagnitude', 'PeakCorrelationLagSamples', ...
    'ReferenceCandidateIsChannel1', 'RoleInference'});

roleEvidence = struct();
roleEvidence.PsdFrequencyHz = psdFrequencyHz;
roleEvidence.MeanChannel1Psd = meanChannel1Psd;
roleEvidence.MeanChannel2Psd = meanChannel2Psd;
roleEvidence.ReferenceMeanPsd = localSelectRolePsd( ...
    meanChannel1Psd, meanChannel2Psd, roleInfo.ReferenceColumnIndex);
roleEvidence.SurveillanceMeanPsd = localSelectRolePsd( ...
    meanChannel1Psd, meanChannel2Psd, ...
    roleInfo.SurveillanceColumnIndex);
roleEvidence.ReferenceLabel = roleInfo.ReferenceLabel;
roleEvidence.SurveillanceLabel = roleInfo.SurveillanceLabel;
roleEvidence.RoleSource = roleInfo.RoleSource;
