function roleText = localDetermineRoleInference(powerDeltaDb, thresholdDb)

if powerDeltaDb >= thresholdDb
    roleText = "channel_1_reference_candidate";
elseif powerDeltaDb <= -thresholdDb
    roleText = "channel_2_reference_candidate";
else
    roleText = "ambiguous";
end

end

function summaryText = localSummarizeRoleInference(roleInference, ...
    peakCorrelationMagnitude)

if all(roleInference == "channel_1_reference_candidate") && ...
        median(peakCorrelationMagnitude) >= 0.05
    summaryText = "consistent_channel_1_reference_candidate";
elseif all(roleInference == "channel_2_reference_candidate") && ...
        median(peakCorrelationMagnitude) >= 0.05
    summaryText = "consistent_channel_2_reference_candidate";
else
    summaryText = "ambiguous_from_iq_only";
end

end

function [frequencyHz, spectrum1, spectrum2] = localCenterTwoSided( ...
    frequencyHz, spectrum1, spectrum2, sampleRateHz)

if max(frequencyHz) <= sampleRateHz / 2
    return
end

frequencyHz = frequencyHz - sampleRateHz / 2;
spectrum1 = fftshift(spectrum1);
spectrum2 = fftshift(spectrum2);

end

function [frequencyHz, spectrum] = localCenterSingleSpectrum( ...
    frequencyHz, spectrum, sampleRateHz)

if max(frequencyHz) <= sampleRateHz / 2
    return
end

frequencyHz = frequencyHz - sampleRateHz / 2;
spectrum = fftshift(spectrum);

end

