function analysis = helperAnalyzeG2AcquisitionEvidence(sessionData, ...
    captureLogInfo, collectionMetadataInfo, options)
%HELPERANALYZEG2ACQUISITIONEVIDENCE Analyze Stage 1 acquisition evidence.

arguments
    sessionData (1,1) struct
    captureLogInfo (1,1) struct
    collectionMetadataInfo (1,1) struct
    options (1,1) struct = struct()
end

resolvedOptions = localResolveOptions(sessionData, options);
roleInfo = helperResolveChannelRoles(sessionData, collectionMetadataInfo, ...
    resolvedOptions);
[metadataAuditTable, auditFlags] = localBuildMetadataAuditTable( ...
    sessionData, captureLogInfo, collectionMetadataInfo, resolvedOptions);
receiverStateTable = localBuildReceiverStateTable(sessionData, ...
    captureLogInfo, collectionMetadataInfo);
[channelRoleEvidenceTable, roleEvidence] = localBuildChannelRoleEvidence( ...
    sessionData, roleInfo, resolvedOptions);
[collectionValidityVerdict, aircraftReadinessImpact, ...
    classificationImpact, decisionTrace] = localDetermineStageVerdicts( ...
    auditFlags, roleEvidence, roleInfo, resolvedOptions);

missingRequiredMask = metadataAuditTable.Required & ...
    ~metadataAuditTable.Present;
missingRequiredItems = metadataAuditTable.EvidenceItem(missingRequiredMask);

analysis = struct();
analysis.StageId = "Stage1_AcquisitionEvidence";
analysis.DatasetId = string(sessionData.DatasetId);
analysis.MetadataAuditTable = metadataAuditTable;
analysis.ReceiverStateTable = receiverStateTable;
analysis.ChannelRoleEvidenceTable = channelRoleEvidenceTable;
analysis.CollectionValidityVerdict = collectionValidityVerdict;
analysis.AircraftReadinessImpact = aircraftReadinessImpact;
analysis.ClassificationImpact = classificationImpact;
analysis.DecisionTrace = decisionTrace;
analysis.MissingRequiredItems = missingRequiredItems;
analysis.RoleEvidence = roleEvidence;
analysis.RoleInfo = roleInfo;
analysis.DataProfile = string(resolvedOptions.DataProfile);
analysis.CollectionMetadataInfo = collectionMetadataInfo;
analysis.Options = rmfield(resolvedOptions, "WelchWindow");
analysis.Metrics = localBuildMetrics(metadataAuditTable, auditFlags, ...
    captureLogInfo, collectionMetadataInfo, roleEvidence, ...
    collectionValidityVerdict, aircraftReadinessImpact, ...
    classificationImpact, missingRequiredItems);

end

function resolvedOptions = localResolveOptions(sessionData, options)

sampleRateVector = unique(sessionData.RadarTable.SampleRate_Hz);

resolvedOptions = struct();
resolvedOptions.SampleRateHz = sampleRateVector(1);
resolvedOptions.WelchLength = 4096;
resolvedOptions.WelchOverlap = 2048;
resolvedOptions.WelchNfft = 4096;
resolvedOptions.CorrelationSampleCount = 131072;
resolvedOptions.CorrelationMaxLagSamples = 4096;
resolvedOptions.ReferenceCandidatePowerDeltaThreshold_dB = 3.0;
resolvedOptions.DataProfile = "field_capture";
resolvedOptions.WelchWindow = hann(resolvedOptions.WelchLength, ...
    "periodic");

optionFields = fieldnames(options);

for idx = 1:numel(optionFields)
    fieldName = optionFields{idx};
    resolvedOptions.(fieldName) = options.(fieldName);
end

resolvedOptions.WelchOverlap = min(resolvedOptions.WelchOverlap, ...
    resolvedOptions.WelchLength - 1);
resolvedOptions.WelchWindow = hann(resolvedOptions.WelchLength, ...
    "periodic");

end

