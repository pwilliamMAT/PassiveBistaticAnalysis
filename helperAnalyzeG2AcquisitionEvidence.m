end

function outputText = localRemoveEmptyJoinArtifacts(inputText)

tokens = split(string(inputText), "|");
tokens = strtrim(tokens);
tokens = tokens(strlength(tokens) > 0);

if isempty(tokens)
    outputText = "";
else
    outputText = strjoin(tokens, " | ");
end

end

function text = localFirstNonemptyText(varargin)

text = "";

for idx = 1:nargin
    candidate = strtrim(string(varargin{idx}));

    if strlength(candidate) > 0 && candidate ~= "no"
        text = candidate;
        return
    end
end

if nargin > 0
    text = strtrim(string(varargin{1}));
end

end

