function [collectionValidityVerdict, aircraftReadinessImpact, ...
    classificationImpact, decisionTrace] = localDetermineStageVerdicts( ...
    auditFlags, roleEvidence, roleInfo, resolvedOptions)

if strcmpi(string(resolvedOptions.DataProfile), "synthetic")
    collectionValidityVerdict = "synthetic_hardware_checks_not_applicable";
    aircraftReadinessImpact = "synthetic_numeric_analysis_only";
    classificationImpact = "Field-hardware evidence is NOT_APPLICABLE; " + ...
        "the explicit generator channel contract governs this run.";
    decisionTrace = [ ...
        "Data profile: synthetic"; ...
        "Field hardware checks: NOT_APPLICABLE"; ...
        "Role source: " + roleInfo.RoleSource; ...
        sprintf("Reference-role power-order support fraction: %.3f", ...
        roleEvidence.ReferenceCandidatePassFraction); ...
        sprintf("Median peak correlation magnitude: %.3f", ...
        roleEvidence.PeakCorrelationMagnitude_Median) ...
        ];
    return;
end

coreEvidencePresent = all([ ...
    auditFlags.ManifestSessionIdPresent; ...
    auditFlags.RadioNamePresent; ...
    auditFlags.CenterFrequencyPresent; ...
    auditFlags.SampleRatePresent; ...
    auditFlags.CaptureLogPresent; ...
    auditFlags.CaptureLogSessionIdMatches; ...
    auditFlags.SelectedAntennasPresent; ...
    auditFlags.RadioProductPresent; ...
    auditFlags.SerialNumberPresent; ...
    auditFlags.ClockSourcePresent; ...
    auditFlags.TimeSourcePresent; ...
    auditFlags.CaptureRoundsMatch; ...
    auditFlags.ChannelLabelsStable; ...
    auditFlags.RecordingUtcPresent ...
    ]);

advancedValidationPresent = all([ ...
    auditFlags.OverrunCountersPresent; ...
    auditFlags.LockStatusPresent; ...
    auditFlags.PhysicalAntennaIdentityPresent; ...
    auditFlags.PerChannelGainMappingPresent; ...
    auditFlags.AgcStatePresent; ...
    auditFlags.MappingVerificationCapturePresent ...
    ]);

iqMappingConsistent = ...
    roleEvidence.ReferenceCandidatePassFraction >= 0.9 && ...
    roleEvidence.PeakCorrelationMagnitude_Median >= 0.05;

if coreEvidencePresent && advancedValidationPresent && iqMappingConsistent
    collectionValidityVerdict = "hardware_configuration_validated";
elseif coreEvidencePresent
    collectionValidityVerdict = "hardware_state_partially_evidenced";
else
    collectionValidityVerdict = "hardware_state_not_established";
end

if collectionValidityVerdict == "hardware_configuration_validated"
    aircraftReadinessImpact = "fit_for_later_aircraft_related_analysis";
elseif coreEvidencePresent && iqMappingConsistent
    aircraftReadinessImpact = "diagnostic_use_only";
else
    aircraftReadinessImpact = "insufficient_evidence";
end

if auditFlags.MappingVerificationCapturePresent
    classificationImpact = ...
        "Stage 1 leaves the dataset classification open for later G2 " + ...
        "stages because explicit mapping proof is available.";
elseif iqMappingConsistent
    classificationImpact = ...
        "Stage 1 holds the dataset at diagnostic until explicit mapping " + ...
        "proof and the missing acquisition evidence are collected.";
else
    classificationImpact = ...
        "Stage 1 keeps the dataset diagnostic because the current " + ...
        "acquisition evidence does not prove channel mapping.";
end

decisionTrace = [ ...
    sprintf("Core acquisition evidence present: %d", coreEvidencePresent); ...
    sprintf("Advanced validation evidence present: %d", ...
    advancedValidationPresent); ...
    sprintf("IQ-only mapping inference: %s", ...
    roleEvidence.IqOnlyMappingInference); ...
    sprintf("Reference candidate pass fraction: %.3f", ...
    roleEvidence.ReferenceCandidatePassFraction); ...
    sprintf("Median peak correlation magnitude: %.3f", ...
    roleEvidence.PeakCorrelationMagnitude_Median) ...
    ];

end

