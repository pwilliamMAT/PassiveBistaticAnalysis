end

function interpretationNoteLines = localBuildSyncInterpretationNoteLines( ...
    collectionMetadataInfo, analysis)

questionSummaries = analysis.QuestionSummaries;
recommendedRow = analysis.StrategyComparisonTable( ...
    analysis.StrategyComparisonTable.Recommended, :);

if analysis.Interpretation.OverallLabel == "ready"
    readinessLines = [ ...
        "- All four Stage 3 review questions remain analytically supported on the frozen baseline session."; ...
        "- The current sync-core evidence is suitable for downstream progression review, but it is still not a formal whole-gate G3 approval."; ...
        "- The recommended strategy candidate is simple enough to carry forward without reopening the Stage 2 role contract." ...
        ];
elseif analysis.Interpretation.OverallLabel == "caveated"
    readinessLines = [ ...
        "- At least one Stage 3 question remains caveated even though none are blocked."; ...
        "- Downstream review can continue under caveat, but the exported bundle should be treated as a manual-review evidence set rather than a final G3 gate decision."; ...
        "- Any later G4/G5 work should keep the current sync caveats visible in its assumptions and evidence bundle." ...
        ];
else
    readinessLines = [ ...
        "- At least one Stage 3 question is blocked on the baseline session."; ...
        "- The current sync-core evidence should not be treated as downstream-ready until the blocking findings are resolved or explicitly waived."; ...
        "- The exported bundle is still useful because it freezes which observable failed and why." ...
        ];
end

interpretationNoteLines = [ ...
    "# Sync Interpretation Note"; ...
    ""; ...
    sprintf("- Current overall label: `%s`", ...
    analysis.Interpretation.OverallLabel); ...
    sprintf("- Overall rationale: %s", ...
    analysis.Interpretation.OverallRationale); ...
    sprintf("- Reference label: `%s`", ...
    analysis.Interpretation.ReferenceLabel); ...
    sprintf("- Surveillance label: `%s`", ...
    analysis.Interpretation.SurveillanceLabel); ...
    sprintf("- Role mapping note: %s", ...
    analysis.Interpretation.RoleNote); ...
    sprintf("- Collection metadata path: `%s`", ...
    collectionMetadataInfo.MetadataPath); ...
    sprintf("- Recommended strategy candidate: `%s`", ...
    analysis.RecommendedStrategyCandidate); ...
    sprintf("- Recommended strategy rationale: %s", ...
    string(recommendedRow.Rationale(1))); ...
    ""; ...
    "## Question Assessments"; ...
    localBuildQuestionAssessmentLines(questionSummaries); ...
    ""; ...
    "## Blocking Findings"; ...
    localBuildBlockingFindingLines(analysis.BlockingFindings); ...
    ""; ...
    "## Reviewer Guidance"; ...
    readinessLines ...
    ];

end

