function results = runG3SyncCore(datasetId, repoRoot, options)
%RUNG3SYNCCORE Execute the Stage 3 manual-review sync-core runner.
%
%   RESULTS = RUNG3SYNCCORE() runs the current standalone Stage 3
%   sync-analysis core on the reference dataset and writes a manual-review
%   evidence bundle under:
%   artifacts/<datasetId>/G3_Sync_Core/<runTimestampZ>/
%
%   This is not the final G3 gate runner. It exists so the implemented
%   Stage 3 sync review can be run, exported, and reviewed independently
%   while the whole-gate acceptance logic remains non-final.

arguments
    datasetId (1,1) string = "20260622T102123"
    repoRoot (1,1) string = string(fileparts(mfilename("fullpath")))
    options (1,1) struct = struct()
end

totalTimer = tic;
stepTimer = tic;
stageArtifactId = "G3_Sync_Core";
repoRoot = helperResolveRepoRoot(repoRoot);
datasetId = string(datasetId);
[analysisOptions, runnerOptions] = localResolveRunnerOptions(options);
runTimestampZ = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss'Z'"));
bundleRoot = fullfile(repoRoot, "artifacts", datasetId, stageArtifactId, ...
    runTimestampZ);
figureRoot = fullfile(bundleRoot, "figures");
timingRows = helperMakeTimingSummaryRow(stageArtifactId, ...
    "resolve_inputs", 0.0, runnerOptions.ExecutionMode);
timingRows(1) = [];
timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
    "resolve_inputs", toc(stepTimer), runnerOptions.ExecutionMode, ...
    NaN, NaN, NaN, NaN, NaN, "");
fprintf("Running G3 Sync Core manual review for dataset %s\n", datasetId);
fprintf("Repository root:\t%s\n", repoRoot);
fprintf("Execution mode:\t%s\n", runnerOptions.ExecutionMode);

try
    localEnsureFolder(bundleRoot);
    localEnsureFolder(figureRoot);

    stepTimer = tic;
    loadOptions = struct();
    loadOptions.IncludeSamples = true;
    sessionData = loadIQData(datasetId, repoRoot, loadOptions);
    inputRepetitionCount = double(numel(sessionData.RadarScans));
    inputSampleCount = double(sum([sessionData.RadarScans.NumSamples]));
    collectionMetadataPath = fullfile(sessionData.DatasetRoot, ...
        "collection_metadata.json");
    collectionMetadataInfo = helperReadCollectionMetadata( ...
        collectionMetadataPath, datasetId);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "load_session_with_samples", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, ...
        "loadIQData IncludeSamples=true plus collection metadata parse.");

    stepTimer = tic;
    analysis = helperAnalyzeG3SyncCore(sessionData, ...
        collectionMetadataInfo, analysisOptions);
    cpiDefinitionsTable = localBuildCpiDefinitionTable(analysis.Options);
    interpretationSummaryTable = localBuildInterpretationSummaryTable( ...
        analysis);
    configSnapshot = localBuildConfigSnapshot(datasetId, repoRoot, ...
        bundleRoot, runTimestampZ, collectionMetadataInfo, analysis, ...
        runnerOptions);
    comparisonSnapshot = localBuildComparisonSnapshot(datasetId, ...
        runTimestampZ, bundleRoot, collectionMetadataInfo, analysis);
    summaryLines = localBuildSummaryLines(bundleRoot, runTimestampZ, ...
        collectionMetadataInfo, analysis);
    syncInterpretationNoteLines = localBuildSyncInterpretationNoteLines( ...
        collectionMetadataInfo, analysis);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "run_g3_sync_helper", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, NaN, NaN, NaN, ...
        "G3 sync analysis helper plus bundle summary preparation.");

    summaryPath = fullfile(bundleRoot, "summary.md");
    interpretationNotePath = fullfile(bundleRoot, ...
        "sync_interpretation_note.md");
    questionSummariesPath = fullfile(bundleRoot, "question_summaries.csv");
    lagTablePath = fullfile(bundleRoot, "lag_table.csv");
    residualFrequencyTablePath = fullfile(bundleRoot, ...
        "residual_frequency_table.csv");
    cpiCoherenceTablePath = fullfile(bundleRoot, ...
        "cpi_coherence_table.csv");
    strategyComparisonTablePath = fullfile(bundleRoot, ...
        "strategy_comparison_table.csv");
    cpiDefinitionsPath = fullfile(bundleRoot, "cpi_definitions.csv");
    interpretationSummaryPath = fullfile(bundleRoot, ...
        "interpretation_summary.csv");
    blockingFindingsPath = fullfile(bundleRoot, "blocking_findings.csv");
    configSnapshotPath = fullfile(bundleRoot, "config_snapshot.json");
    metricsJsonPath = fullfile(bundleRoot, "metrics.json");
    metricsMatPath = fullfile(bundleRoot, "metrics.mat");
    lagFigurePath = fullfile(figureRoot, ...
        "figure_01_lag_stability_overview.png");
    residualFrequencyFigurePath = fullfile(figureRoot, ...
        "figure_02_residual_frequency_overview.png");
    coherenceStrategyFigurePath = fullfile(figureRoot, ...
        "figure_03_coherence_and_strategy_overview.png");

    stepTimer = tic;
    try
        writetable(analysis.QuestionSummaries, questionSummariesPath);
        writetable(analysis.LagTable, lagTablePath);
        writetable(analysis.ResidualFrequencyTable, ...
            residualFrequencyTablePath);
        writetable(analysis.CpiCoherenceTable, cpiCoherenceTablePath);
        writetable(analysis.StrategyComparisonTable, ...
            strategyComparisonTablePath);
        writetable(cpiDefinitionsTable, cpiDefinitionsPath);
        writetable(interpretationSummaryTable, interpretationSummaryPath);

        if ~isempty(analysis.BlockingFindings)
            writetable(localBuildBlockingFindingsTable( ...
                analysis.BlockingFindings), blockingFindingsPath);
        end
    catch writeTableException
        error("runG3SyncCore:WriteTableFailed", ...
            "Failed to write a Stage 3 table artifact: %s", ...
            writeTableException.message);
    end
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_tables", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, ...
        7 + double(~isempty(analysis.BlockingFindings)), 0, NaN, ...
        "Question, lag, residual-frequency, coherence, strategy, CPI, interpretation, and optional blocking CSVs.");

    stepTimer = tic;
    localWriteTextFile(summaryPath, summaryLines);
    localWriteTextFile(interpretationNotePath, ...
        syncInterpretationNoteLines);
    localWriteJsonFile(configSnapshotPath, configSnapshot);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_text_artifacts", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 3, 0, NaN, ...
        "Summary, interpretation note, and config JSON.");

    stepTimer = tic;
    localWriteJsonFile(metricsJsonPath, analysis.Metrics);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_metrics_json", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 1, 0, NaN, "metrics.json");

    stepTimer = tic;
    try
        save(metricsMatPath, "analysis");
    catch saveException
        error("runG3SyncCore:SaveMetricsFailed", ...
            "Failed to write Stage 3 metrics.mat: %s", ...
            saveException.message);
    end
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_metrics_mat", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, 1, 0, NaN, ...
        "metrics.mat");

    stepTimer = tic;
    try
        comparisonSnapshotPath = helperWriteComparisonSnapshot( ...
            string(bundleRoot), comparisonSnapshot);
    catch saveException
        error("runG3SyncCore:SaveComparisonSnapshotFailed", ...
            "Failed to write Stage 3 comparison snapshot: %s", ...
            saveException.message);
    end
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "write_comparison_snapshot", toc(stepTimer), ...
        runnerOptions.ExecutionMode, inputSampleCount, ...
        inputRepetitionCount, 1, 0, NaN, "comparison_snapshot.mat");

    stepTimer = tic;
    localRenderLagOverviewFigure(analysis, lagFigurePath, ...
        runnerOptions.ShowFigures);
    localRenderResidualFrequencyFigure(analysis, ...
        residualFrequencyFigurePath, runnerOptions.ShowFigures);
    localRenderCoherenceStrategyFigure(analysis, ...
        coherenceStrategyFigurePath, runnerOptions.ShowFigures);
    timingRows(end + 1) = helperMakeTimingSummaryRow(stageArtifactId, ...
        "render_figures", toc(stepTimer), runnerOptions.ExecutionMode, ...
        inputSampleCount, inputRepetitionCount, 3, 3, NaN, ...
        "Lag, residual-frequency, and coherence/strategy figures.");

    [timingSummaryTable, performanceSummary] = ...
        helperFinalizePerformanceInstrumentation(stageArtifactId, ...
        datasetId, string(bundleRoot), runTimestampZ, ...
        runnerOptions.ExecutionMode, runnerOptions.ShowFigures, ...
        timingRows, totalTimer, inputSampleCount, ...
        inputRepetitionCount, string(metricsMatPath));

    results = struct();
    results.DatasetId = datasetId;
    results.StageId = string(analysis.StageId);
    results.RunTimestampZ = runTimestampZ;
    results.BundleRoot = string(bundleRoot);
    results.OverallLabel = string(analysis.Interpretation.OverallLabel);
    results.OverallRationale = string( ...
        analysis.Interpretation.OverallRationale);
    results.RecommendedStrategyCandidate = string( ...
        analysis.RecommendedStrategyCandidate);
    results.ReferenceLabel = string( ...
        analysis.Interpretation.ReferenceLabel);
    results.SurveillanceLabel = string( ...
        analysis.Interpretation.SurveillanceLabel);
    results.BlockingFindings = string(analysis.BlockingFindings(:));
    results.QuestionSummaries = analysis.QuestionSummaries;
    results.LagTable = analysis.LagTable;
    results.ResidualFrequencyTable = analysis.ResidualFrequencyTable;
    results.CpiCoherenceTable = analysis.CpiCoherenceTable;
    results.StrategyComparisonTable = analysis.StrategyComparisonTable;
    results.Interpretation = analysis.Interpretation;
    results.Metrics = analysis.Metrics;
    results.Options = analysis.Options;
    results.FigurePaths = [string(lagFigurePath); ...
        string(residualFrequencyFigurePath); ...
        string(coherenceStrategyFigurePath)];
    results.ComparisonSnapshotPath = string(comparisonSnapshotPath);
    results.TimingSummaryTable = timingSummaryTable;
    results.PerformanceSummary = performanceSummary;

    fprintf("Overall label:\t%s\n", results.OverallLabel);
    fprintf("Recommended strategy:\t%s\n", ...
        results.RecommendedStrategyCandidate);
    fprintf("Blocking findings:\t%d\n", numel(results.BlockingFindings));
    fprintf("Bundle root:\t%s\n", bundleRoot);
catch mainException
    localWriteFailureBundle(bundleRoot, mainException);
    rethrow(mainException);
end

end

function [analysisOptions, runnerOptions] = localResolveRunnerOptions(options)

analysisOptions = options;
runnerOptions = struct();
runnerOptions.ExecutionMode = helperResolveExecutionMode(options);
runnerOptions.ShowFigures = usejava("desktop");

if runnerOptions.ExecutionMode == "analysis_only"
    runnerOptions.ShowFigures = false;
end

if isfield(options, "ShowFigures")
    runnerOptions.ShowFigures = logical(options.ShowFigures);
    analysisOptions = rmfield(analysisOptions, "ShowFigures");
end

if isfield(analysisOptions, "ExecutionMode")
    analysisOptions = rmfield(analysisOptions, "ExecutionMode");
end

end

function cpiDefinitionTable = localBuildCpiDefinitionTable(optionsOutput)

cpiDefinitions = optionsOutput.CpiDefinitions;
cpiCount = numel(cpiDefinitions);
cpiLabel = strings(cpiCount, 1);
duration_s = zeros(cpiCount, 1);
samples = zeros(cpiCount, 1);
windowHopSamples = zeros(cpiCount, 1);

for idx = 1:cpiCount
    cpiLabel(idx) = string(cpiDefinitions(idx).Label);
    duration_s(idx) = double(cpiDefinitions(idx).Duration_s);
    samples(idx) = double(cpiDefinitions(idx).Samples);
    windowHopSamples(idx) = double(cpiDefinitions(idx).WindowHopSamples);
end

cpiDefinitionTable = table(cpiLabel, duration_s, samples, ...
    windowHopSamples, VariableNames = {'CpiLabel', 'Duration_s', ...
    'Samples', 'WindowHopSamples'});

end

function interpretationSummaryTable = localBuildInterpretationSummaryTable( ...
    analysis)

blockingFindingsText = localJoinStringVector(analysis.BlockingFindings);
interpretationSummaryTable = table( ...
    string(analysis.Interpretation.OverallLabel), ...
    string(analysis.Interpretation.OverallRationale), ...
    string(analysis.RecommendedStrategyCandidate), ...
    string(analysis.Interpretation.ReferenceLabel), ...
    string(analysis.Interpretation.SurveillanceLabel), ...
    double(analysis.Interpretation.BlockingFindingCount), ...
    blockingFindingsText, ...
    VariableNames = {'OverallLabel', 'OverallRationale', ...
    'RecommendedStrategyCandidate', 'ReferenceLabel', ...
    'SurveillanceLabel', 'BlockingFindingCount', ...
    'BlockingFindingsText'});

end

function blockingFindingsTable = localBuildBlockingFindingsTable( ...
    blockingFindings)

blockingFindingsTable = table(string(blockingFindings(:)), ...
    VariableNames = {'BlockingFinding'});

end

