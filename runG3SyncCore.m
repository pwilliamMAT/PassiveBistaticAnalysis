function blockingFindingLines = localBuildBlockingFindingLines( ...
    blockingFindings)

if isempty(blockingFindings)
    blockingFindingLines = "- None.";
    return
end

blockingFindingLines = strings(numel(blockingFindings), 1);

for idx = 1:numel(blockingFindings)
    blockingFindingLines(idx) = sprintf("- `%s`", ...
        string(blockingFindings(idx)));
end

end

function joinedText = localJoinStringVector(inputVector)

inputVector = string(inputVector(:));
inputVector = strtrim(inputVector);
inputVector = inputVector(strlength(inputVector) > 0);

if isempty(inputVector)
    joinedText = "none";
    return
end

joinedText = strjoin(inputVector, " | ");

end

function localRenderLagOverviewFigure(analysis, figurePath, showFigures)

lagTable = analysis.LagTable;
