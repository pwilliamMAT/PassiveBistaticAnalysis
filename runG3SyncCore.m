end

function strategyRow = localExtractStrategyRow(strategyComparisonTable, ...
    strategyCandidate)

strategyRow = strategyComparisonTable( ...
    strategyComparisonTable.StrategyCandidate == strategyCandidate, :);

if height(strategyRow) ~= 1
    error("runG3SyncCore:MissingStrategyRow", ...
        "Expected one strategy row for %s.", strategyCandidate);
end

end

