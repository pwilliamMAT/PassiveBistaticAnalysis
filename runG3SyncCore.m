    strategyDisplayStrings(idx) = strrep(strategyCandidates(idx), ...
        "_correction", "");
    strategyDisplayStrings(idx) = strrep(strategyDisplayStrings(idx), ...
        "_", " ");
end

strategyDisplayLabels = categorical(strategyDisplayStrings, ...
    cellstr(strategyDisplayStrings));

end

