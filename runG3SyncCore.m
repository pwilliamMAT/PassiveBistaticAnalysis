    helperMakeComparisonMetricRow("overall_label", ...
    "Overall Label", analysis.Interpretation.OverallLabel, "", ...
    "Overall Stage 3 manual-review interpretation."); ...
    helperMakeComparisonMetricRow("recommended_strategy_candidate", ...
    "Recommended Strategy Candidate", ...
    analysis.RecommendedStrategyCandidate, "", ...
    "Recommended correction strategy candidate."); ...
    helperMakeComparisonMetricRow("reference_label", ...
    "Reference Label", analysis.Interpretation.ReferenceLabel, "", ...
    "Reference-channel label fixed from Stage 2."); ...
    helperMakeComparisonMetricRow("surveillance_label", ...
    "Surveillance Label", analysis.Interpretation.SurveillanceLabel, "", ...
    "Surveillance-channel label fixed from Stage 2."); ...
    helperMakeComparisonMetricRow("blocking_finding_count", ...
    "Blocking Finding Count", ...
