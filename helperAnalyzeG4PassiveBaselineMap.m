function widthBins = localMeasureWidth(profileVector, centerIndex, threshold)

aboveThreshold = profileVector >= threshold;
leftIndex = centerIndex;
rightIndex = centerIndex;

while leftIndex > 1 && aboveThreshold(leftIndex - 1)
    leftIndex = leftIndex - 1;
end

while rightIndex < numel(profileVector) && aboveThreshold(rightIndex + 1)
    rightIndex = rightIndex + 1;
end

widthBins = rightIndex - leftIndex + 1;

end

function r = localComputeCorrelation(a, b)

a = double(a(:));
b = double(b(:));
a = a - mean(a, "omitnan");
b = b - mean(b, "omitnan");
denominator = norm(a) * norm(b);

if denominator <= eps
    r = 0.0;
    return
end

r = dot(a, b) / denominator;

end

