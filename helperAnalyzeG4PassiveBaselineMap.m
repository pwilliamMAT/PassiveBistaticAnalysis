function score = localComputeSceneObservabilityScore( ...
    offOriginNonzeroDopplerEnergyFraction, offOriginOccupiedFraction, ...
    zeroDopplerRidgeEnergyFraction, directPathToOffRidgeEnergy_dB, ...
    resolvedOptions)

score = ...
    resolvedOptions.SceneScoreOffOriginEnergyWeight .* ...
    double(offOriginNonzeroDopplerEnergyFraction) + ...
    resolvedOptions.SceneScoreOccupiedFractionWeight .* ...
    double(offOriginOccupiedFraction) - ...
    resolvedOptions.SceneScoreZeroDopplerPenaltyWeight .* ...
    double(zeroDopplerRidgeEnergyFraction) - ...
    resolvedOptions.SceneScoreDirectPathDominancePenaltyWeight .* ...
    max(double(directPathToOffRidgeEnergy_dB) - ...
    resolvedOptions.SceneScoreDirectPathDominanceReference_dB, 0.0);

end
function [annulusValues, directPathWidth_bins] = localBuildLocalAnnulus( ...
    mapLinear, directPathRow, directPathCol, localProminenceOuterRadius)

rowIndices = max(1, directPathRow - localProminenceOuterRadius): ...
    min(size(mapLinear, 1), directPathRow + localProminenceOuterRadius);
colIndices = max(1, directPathCol - localProminenceOuterRadius): ...
    min(size(mapLinear, 2), directPathCol + localProminenceOuterRadius);
[columnGrid, rowGrid] = meshgrid(colIndices, rowIndices);
distanceGrid = max(abs(rowGrid - directPathRow), ...
    abs(columnGrid - directPathCol));
annulusMask = distanceGrid >= 2 & distanceGrid <= localProminenceOuterRadius;
localPatch = mapLinear(rowIndices, colIndices);
annulusValues = double(localPatch(annulusMask));

if isempty(annulusValues)
    annulusValues = eps;
end

directPathRowProfile = mapLinear(directPathRow, :);
threshold = max(mapLinear(directPathRow, directPathCol) / 2.0, eps("single"));
directPathWidth_bins = localMeasureWidth(directPathRowProfile, ...
    directPathCol, threshold);

end

function clutterValues = localBuildClutterValues(mapLinear, ...
    delayAxis_samples, dopplerAxis_Hz, directPathDelay_samples, ...
    exclusionDelayRadius_samples)

