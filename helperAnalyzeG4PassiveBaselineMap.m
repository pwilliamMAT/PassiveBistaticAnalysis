function rawMapProduct = localBuildRawRateAuditProductFromCuts( ...
    referenceWindow, surveillanceWindow, cpiDefinition, ...
    baselineProductDefinition, auditOptions, reducedRow, resolvedOptions)

sampleRateHz = double(auditOptions.MapSampleRateHz);
expectedDelay_samples = double(reducedRow.DirectPathDelay_samples(1)) .* ...
    resolvedOptions.MapDecimationFactor;
expectedDoppler_Hz = double(reducedRow.DirectPathDoppler_Hz(1));
dopplerCutValues_Hz = localBuildCenteredCutValues(expectedDoppler_Hz, ...
    double(resolvedOptions.FullRateAuditDopplerCutSearchRadius_Hz), ...
    double(resolvedOptions.FullRateAuditDopplerCutCount));
[delayCutMagnitude, delayAxis_s] = ambgfun(referenceWindow, ...
    surveillanceWindow, sampleRateHz, cpiDefinition.PRFVector_Hz, ...
    Cut = "Doppler", CutValue = dopplerCutValues_Hz);
delayCutLinear = max(single(delayCutMagnitude) .^ 2, eps("single"));
delayAxis_s = double(delayAxis_s(:).');
delayAxis_samples = delayAxis_s .* sampleRateHz;
delaySearchMask = abs(delayAxis_samples - expectedDelay_samples) <= ...
    double(resolvedOptions.FullRateAuditDelayCutSearchRadius_nativeSamples);

if ~any(delaySearchMask)
    delaySearchMask(localFindNearestIndex(delayAxis_samples, ...
        expectedDelay_samples)) = true;
end

searchLinear = delayCutLinear(:, delaySearchMask);
[directDelayCutPower, searchPeakIndex] = max(searchLinear, [], "all");
[delayCutRow, delaySearchCol] = ind2sub(size(searchLinear), ...
    searchPeakIndex);
delaySearchIndices = find(delaySearchMask);
directDelayIndex = delaySearchIndices(delaySearchCol);
directPathDelay_samples = delayAxis_samples(directDelayIndex);
directPathDelay_s = delayAxis_s(directDelayIndex);
coarseDirectPathDoppler_Hz = dopplerCutValues_Hz(delayCutRow);
[dopplerCutMagnitude, dopplerAxis_Hz] = ambgfun(referenceWindow, ...
    surveillanceWindow, sampleRateHz, cpiDefinition.PRFVector_Hz, ...
    Cut = "Delay", CutValue = directPathDelay_s);
dopplerCutLinear = max(single(dopplerCutMagnitude(:)) .^ 2, eps("single"));
dopplerAxis_Hz = double(dopplerAxis_Hz(:));
dopplerSearchMask = abs(dopplerAxis_Hz - coarseDirectPathDoppler_Hz) <= ...
    double(resolvedOptions.FullRateAuditDopplerCutSearchRadius_Hz);

if ~any(dopplerSearchMask)
    dopplerSearchMask(localFindNearestIndex(dopplerAxis_Hz, ...
        coarseDirectPathDoppler_Hz)) = true;
end

dopplerSearchValues = dopplerCutLinear(dopplerSearchMask);
[directDopplerCutPower, dopplerSearchPeakIndex] = max( ...
    dopplerSearchValues);
dopplerSearchIndices = find(dopplerSearchMask);
directDopplerIndex = dopplerSearchIndices(dopplerSearchPeakIndex);
directPathDoppler_Hz = dopplerAxis_Hz(directDopplerIndex);
directPathPower = max(directDelayCutPower, directDopplerCutPower);
sceneDelayValues_samples = localBuildBoundedSceneDelayCutSamples( ...
    directPathDelay_samples, delayAxis_samples, resolvedOptions);
sceneDelayValues_s = sceneDelayValues_samples ./ sampleRateHz;
[sceneCutMagnitude, sceneDopplerAxis_Hz] = ambgfun(referenceWindow, ...
    surveillanceWindow, sampleRateHz, cpiDefinition.PRFVector_Hz, ...
    Cut = "Delay", CutValue = sceneDelayValues_s);
sceneLinear = max(single(sceneCutMagnitude), eps("single")) .^ 2;
sceneDopplerAxis_Hz = double(sceneDopplerAxis_Hz(:));
sceneMetrics = localComputeCutProxySceneMetrics(sceneLinear, ...
    sceneDelayValues_samples, sceneDopplerAxis_Hz, directPathDelay_samples, ...
    directPathDoppler_Hz, directPathPower, baselineProductDefinition, ...
    resolvedOptions);
originNeighborhoodContainsGlobalPeak = ...
    abs(directPathDelay_samples) <= ...
    baselineProductDefinition.OriginSearchDelayRadius_samples && ...
    abs(directPathDoppler_Hz) <= ...
    baselineProductDefinition.OriginSearchDopplerRadius_Hz;
localProminenceValues = [ ...
    double(reshape(delayCutLinear(:, delaySearchMask), [], 1)); ...
    double(dopplerSearchValues(:)) ...
    ];
localProminenceValues = localProminenceValues( ...
    localProminenceValues < double(directPathPower));

if isempty(localProminenceValues)
    localProminenceValues = eps;
end

rawMapProduct = struct();
rawMapProduct.MapRateMode = "raw_rate_audit";
rawMapProduct.RawRateAuditMethod = string(auditOptions.FullRateAuditMethod);
rawMapProduct.MapDecimationFactor = 1.0;
rawMapProduct.MapSampleRateHz = sampleRateHz;
rawMapProduct.GlobalPeakDelay_samples = double(directPathDelay_samples);
rawMapProduct.GlobalPeakDelay_s = double(directPathDelay_s);
rawMapProduct.GlobalPeakDoppler_Hz = double(directPathDoppler_Hz);
rawMapProduct.GlobalPeak_dB = pow2db(double(directPathPower));
rawMapProduct.OriginNeighborhoodContainsGlobalPeak = ...
    logical(originNeighborhoodContainsGlobalPeak);
rawMapProduct.DirectPathDelay_samples = double(directPathDelay_samples);
rawMapProduct.DirectPathDelay_s = double(directPathDelay_s);
rawMapProduct.DirectPathDoppler_Hz = double(directPathDoppler_Hz);
rawMapProduct.RawDirectPathDelayOffset_samples = ...
    double(directPathDelay_samples);
rawMapProduct.RawDirectPathDopplerOffset_Hz = double(directPathDoppler_Hz);
rawMapProduct.DirectPathPeak_dB = pow2db(double(directPathPower));
rawMapProduct.DirectPathLocalProminence_dB = pow2db( ...
    double(directPathPower) ./ max(max(localProminenceValues), eps));
rawMapProduct.DirectPathToOffRidgeEnergy_dB = ...
    sceneMetrics.DirectPathToOffRidgeEnergy_dB;
rawMapProduct.OffOriginNonzeroDopplerEnergyFraction = ...
    sceneMetrics.OffOriginNonzeroDopplerEnergyFraction;
rawMapProduct.ZeroDopplerRidgeEnergyFraction = ...
    sceneMetrics.ZeroDopplerRidgeEnergyFraction;
rawMapProduct.OffOriginOccupiedFraction_abovePeakMinus20dB = ...
    sceneMetrics.OffOriginOccupiedFraction_abovePeakMinus20dB;
rawMapProduct.SceneObservabilityScore = localComputeSceneObservabilityScore( ...
    sceneMetrics.OffOriginNonzeroDopplerEnergyFraction, ...
    sceneMetrics.OffOriginOccupiedFraction_abovePeakMinus20dB, ...
    sceneMetrics.ZeroDopplerRidgeEnergyFraction, ...
    sceneMetrics.DirectPathToOffRidgeEnergy_dB, resolvedOptions);

end

function cutValues = localBuildCenteredCutValues(centerValue, radius, count)

count = max(1, round(double(count)));

if mod(count, 2) == 0
    count = count + 1;
end

if count == 1 || radius <= 0.0
    cutValues = double(centerValue);
else
    cutValues = linspace(double(centerValue) - double(radius), ...
        double(centerValue) + double(radius), count);
end

cutValues = unique(double(cutValues), "stable");

end

function sceneDelayValues_samples = localBuildBoundedSceneDelayCutSamples( ...
    centerDelay_samples, delayAxis_samples, resolvedOptions)

sceneDelayValues_samples = localBuildCenteredCutValues( ...
    centerDelay_samples, ...
    double(resolvedOptions.FullRateAuditSceneDelaySpan_nativeSamples) ./ 2.0, ...
