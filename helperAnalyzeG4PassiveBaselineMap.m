function [repeatabilityRow, representativeMap] = ...
    localBuildRepeatabilityOutputs(groupMapRows, groupProducts, ...
    baselineProductDefinition, resolvedOptions)

mapCount = numel(groupProducts);
correlationMatrix = eye(mapCount);
referenceProduct = groupProducts{1};
reviewDelayAxis_samples = referenceProduct.ReviewDelayAxis_samples;
reviewDopplerAxis_Hz = referenceProduct.ReviewDopplerAxis_Hz;
maskedCorrelationValues = zeros(mapCount * (mapCount - 1) / 2, 1);
fullCorrelationValues = zeros(size(maskedCorrelationValues));
pairIndex = 0;
commonMask = ~localBuildExclusionMask(reviewDelayAxis_samples, ...
    reviewDopplerAxis_Hz, baselineProductDefinition) & ...
    abs(reviewDopplerAxis_Hz) > ...
    baselineProductDefinition.ZeroDopplerRidgeExclusion_Hz;
similarityScore = zeros(mapCount, 1);

if mapCount == 1
    representativeIndex = 1;
    delaySpread_samples = 0;
    dopplerSpread_Hz = 0;
    maskedCorrelationMedian = NaN;
    maskedCorrelationMinimum = NaN;
    interpretationLabel = "NOT_ASSESSED_SINGLE_PART";
    rationale = "Repeatability is NOT_ASSESSED_SINGLE_PART.";
else
for rowIndex = 1:mapCount - 1
    for columnIndex = rowIndex + 1:mapCount
        pairIndex = pairIndex + 1;
        fullCorrelationValues(pairIndex) = localComputeCorrelation( ...
            groupProducts{rowIndex}.ReviewLinearMap, ...
            groupProducts{columnIndex}.ReviewLinearMap);
        maskedCorrelationValues(pairIndex) = localComputeCorrelation( ...
            groupProducts{rowIndex}.ReviewLinearMap(commonMask), ...
            groupProducts{columnIndex}.ReviewLinearMap(commonMask));
        correlationMatrix(rowIndex, columnIndex) = ...
            maskedCorrelationValues(pairIndex);
        correlationMatrix(columnIndex, rowIndex) = ...
            maskedCorrelationValues(pairIndex);
    end
end

for idx = 1:mapCount
    similarityScore(idx) = mean(correlationMatrix(idx, ...
        setdiff(1:mapCount, idx)), "omitnan");
