end
function eligibilityRank = localResolveEligibilityRank(g3EligibilityLabel)

switch string(g3EligibilityLabel)
    case "ready"
        eligibilityRank = 3;
    case "caveated"
        eligibilityRank = 2;
    case "not_available"
        eligibilityRank = 2;
    otherwise
        eligibilityRank = 1;
end

end

function sortTable = localApplyShortCpiTieBreak(sortTable, resolvedOptions)

if height(sortTable) < 2
    return
end

firstRow = sortTable(1, :);
secondRow = sortTable(2, :);

if firstRow.EligibilityRank ~= secondRow.EligibilityRank
    return
end

maskedClose = abs(firstRow.MaskedCorrelationScore - ...
    secondRow.MaskedCorrelationScore) <= ...
    resolvedOptions.RankingMaskedCorrelationEpsilon;
sceneClose = abs(firstRow.SceneScore - secondRow.SceneScore) <= ...
    resolvedOptions.RankingSceneScoreEpsilon;
coordClose = abs(firstRow.CoordinateScore - secondRow.CoordinateScore) <= ...
    resolvedOptions.RankingCoordinateScoreEpsilon;

if ~(maskedClose && sceneClose && coordClose)
    return
end

if secondRow.Duration_s < firstRow.Duration_s
    sortTable([1 2], :) = sortTable([2 1], :);
end

end

