function selectedWindows = localBuildSelectedWindowTable(windowObservations, ...
    resolvedOptions)

selectedWindows = table();

for cpiIndex = 1:numel(resolvedOptions.CpiLabels)
    cpiLabel = resolvedOptions.CpiLabels(cpiIndex);

    for repetitionValue = 1:resolvedOptions.ExpectedRepetitionCount
        subset = windowObservations(windowObservations.Repetition == ...
            repetitionValue & windowObservations.CpiLabel == cpiLabel, :);

        if isempty(subset)
            selection = localBuildDerivedSelectedWindowRows( ...
                windowObservations, repetitionValue, cpiLabel, cpiIndex, ...
                resolvedOptions);
        else
            selectedIndices = localResolveSelectedWindowIndices( ...
                height(subset), resolvedOptions.WindowLabels);
            selection = subset(selectedIndices, :);
            selection.WindowLabel = resolvedOptions.WindowLabels;
        end

        selectedWindows = [selectedWindows; selection]; %#ok<AGROW>
    end
end

selectedWindows = sortrows(selectedWindows, ...
    ["Repetition", "CpiDuration_s", "WindowStartSample"]);

end

function selection = localBuildDerivedSelectedWindowRows(windowObservations, ...
    repetitionValue, cpiLabel, cpiIndex, resolvedOptions)

[lowerCpiLabel, upperCpiLabel] = localResolveBracketingCpiLabels(cpiLabel);
repetitionSubset = windowObservations(windowObservations.Repetition == ...
    repetitionValue, :);
lowerSubset = repetitionSubset(repetitionSubset.CpiLabel == ...
    lowerCpiLabel, :);
upperSubset = repetitionSubset(repetitionSubset.CpiLabel == ...
    upperCpiLabel, :);

if isempty(lowerSubset) || isempty(upperSubset)
    error("helperAnalyzeG4PassiveBaselineMap:MissingDerivedCpiBracket", ...
        "CPI %s requires non-blocked bracketing G3 anchor rows.", ...
        cpiLabel);
end

cpiSamples = round(resolvedOptions.CpiDurations_s(cpiIndex) .* ...
    resolvedOptions.SampleRateHz);
maxStartSample = resolvedOptions.SamplesPerRepetition - cpiSamples + 1;
windowStarts = 1:cpiSamples:maxStartSample;
    selectedIndices = localResolveSelectedWindowIndices( ...
        numel(windowStarts), resolvedOptions.WindowLabels);
selection = lowerSubset(ones(numel(selectedIndices), 1), :);
selection.WindowLabel = strings(numel(selectedIndices), 1);

for idx = 1:numel(selectedIndices)
    windowIndex = selectedIndices(idx);
    windowStartSample = windowStarts(windowIndex);
    windowStopSample = windowStartSample + cpiSamples - 1;
    lowerRow = localFindNearestWindowRow(lowerSubset, windowStartSample);
    upperRow = localFindNearestWindowRow(upperSubset, windowStartSample);
    selection(idx, :) = localBlendDerivedWindowRows(lowerRow, upperRow, ...
        cpiLabel, resolvedOptions.CpiDurations_s(cpiIndex), ...
        cpiSamples, windowIndex, windowStartSample, windowStopSample, ...
        resolvedOptions.WindowLabels(idx));
end

end

function selectedIndices = localResolveSelectedWindowIndices( ...
    availableWindowCount, windowLabels)

selectedIndices = zeros(numel(windowLabels), 1);

for idx = 1:numel(windowLabels)
    switch string(windowLabels(idx))
        case "early"
            selectedIndices(idx) = 1;
        case "center"
            selectedIndices(idx) = ceil(availableWindowCount / 2);
        case "late"
            selectedIndices(idx) = availableWindowCount;
    end
end

end

function [lowerCpiLabel, upperCpiLabel] = localResolveBracketingCpiLabels( ...
    cpiLabel)

switch string(cpiLabel)
    case "short_mid"
        lowerCpiLabel = "short";
        upperCpiLabel = "medium";
    case "medium_long"
        lowerCpiLabel = "medium";
        upperCpiLabel = "long";
    otherwise
        error("helperAnalyzeG4PassiveBaselineMap:UnsupportedDerivedCpi", ...
            "CPI %s is not a derived G4 sensitivity CPI.", cpiLabel);
end

end

function row = localFindNearestWindowRow(windowSubset, windowStartSample)

[~, rowIndex] = min(abs(windowSubset.WindowStartSample - windowStartSample));
row = windowSubset(rowIndex, :);

end

function row = localBlendDerivedWindowRows(lowerRow, upperRow, cpiLabel, ...
    cpiDuration_s, cpiSamples, windowIndex, windowStartSample, ...
    windowStopSample, windowLabel)

row = lowerRow;
row.CpiLabel = cpiLabel;
row.CpiDuration_s = double(cpiDuration_s);
row.CpiSamples = double(cpiSamples);
row.WindowIndex = double(windowIndex);
row.WindowStartSample = double(windowStartSample);
row.WindowStopSample = double(windowStopSample);
row.WindowLabel = string(windowLabel);
row.CanonicalLagSamples = round(mean([ ...
    double(lowerRow.CanonicalLagSamples), ...
    double(upperRow.CanonicalLagSamples) ...
    ]));
row.ResidualFrequencyHz = mean([ ...
    double(lowerRow.ResidualFrequencyHz), ...
    double(upperRow.ResidualFrequencyHz) ...
    ]);
row.FindDelayLagSamples = round(mean([ ...
    double(lowerRow.FindDelayLagSamples), ...
    double(upperRow.FindDelayLagSamples) ...
    ]));
row.XcorrLagSamples = round(mean([ ...
    double(lowerRow.XcorrLagSamples), ...
    double(upperRow.XcorrLagSamples) ...
    ]));
row.DelayEstimateAgreement = lowerRow.DelayEstimateAgreement & ...
    upperRow.DelayEstimateAgreement;

numericVariables = [ ...
    "PeakCorrelationMagnitude"; ...
    "ZeroLagCorrelationMagnitude"; ...
    "PeakToSidelobe_dB"; ...
    "PeakToZero_dB"; ...
    "PhaseExcursion_deg"; ...
    "PhaseFitRmse_deg"; ...
    "SpectrogramBandBinCount"; ...
    "CoherenceMean"; ...
    "CoherenceP10"; ...
    "CoherenceMinimum" ...
    ];

for idx = 1:numel(numericVariables)
    variableName = numericVariables(idx);
    row.(variableName) = mean([ ...
        double(lowerRow.(variableName)), ...
        double(upperRow.(variableName)) ...
        ], "omitnan");
end

end
function preprocessedSignals = localBuildPreprocessedSignals(sessionData, ...
    syncPrep, appliedCorrection, resolvedOptions)

repetitionCount = height(sessionData.RadarTable);
preprocessedSignals = repmat(struct( ...
    "Repetition", NaN, ...
    "RelativePath", "", ...
    "ReferenceMapSamples", single([]), ...
    "SurveillanceMapSamples", single([]) ...
    ), repetitionCount, 1);

for repetitionIndex = 1:repetitionCount
    scan = localResolveScanWithSamples(sessionData, repetitionIndex);
    referenceSamples = double(scan.Samples(:, ...
        syncPrep.RoleInfo.ReferenceColumnIndex));
    surveillanceSamples = double(scan.Samples(:, ...
        syncPrep.RoleInfo.SurveillanceColumnIndex));
    correctedSurveillance = localApplyIntegerDelay(surveillanceSamples, ...
        appliedCorrection.AppliedLag_samples);
    correctedSurveillance = localApplyResidualFrequencyCorrection( ...
        correctedSurveillance, ...
        appliedCorrection.AppliedResidualFrequency_Hz, ...
        syncPrep.ResolvedOptions.SampleRateHz);
    referenceMapSamples = helperResampleG4FullRepetition( ...
        referenceSamples, resolvedOptions.MapDecimationFactor);
    surveillanceMapSamples = helperResampleG4FullRepetition( ...
        correctedSurveillance, resolvedOptions.MapDecimationFactor);

    preprocessedSignals(repetitionIndex).Repetition = ...
        double(sessionData.RadarTable.Repetition(repetitionIndex));
    preprocessedSignals(repetitionIndex).RelativePath = ...
        string(sessionData.RadarTable.RelativePath(repetitionIndex));
    preprocessedSignals(repetitionIndex).ReferenceMapSamples = ...
        referenceMapSamples(:);
    preprocessedSignals(repetitionIndex).SurveillanceMapSamples = ...
        surveillanceMapSamples(:);
end

end

function baselineProductDefinition = localBuildBaselineProductDefinition( ...
    syncPrep, appliedCorrection, resolvedOptions)

originDelayRadius_samples = max( ...
    resolvedOptions.OriginMinDelayRadius_samples, ...
    ceil((syncPrep.GlobalCorrection.LagResidualMax_samples + ...
    resolvedOptions.OriginDelayAllowance_samples) / ...
    resolvedOptions.MapDecimationFactor));
originDopplerRadius_Hz = max( ...
