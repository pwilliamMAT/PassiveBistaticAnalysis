function [mapSummaryTable, repeatabilityTable, representativeMaps, ...
    targetEvidenceTable, targetRegionViews] = ...
    localBuildMapProducts(selectedWindows, preprocessedSignals, ...
    baselineProductDefinition, resolvedOptions, appliedCorrection)

mapRows = repmat(localBuildMapSummaryRowTemplate(), ...
    height(selectedWindows), 1);
repeatabilityRows = repmat(localBuildRepeatabilityRowTemplate(), ...
    numel(resolvedOptions.CpiLabels) * numel(resolvedOptions.WindowLabels), ...
    1);
representativeMaps = repmat(localBuildRepresentativeMapTemplate(), ...
    numel(resolvedOptions.CpiLabels) * numel(resolvedOptions.WindowLabels), ...
    1);
mapRowIndex = 0;
groupIndex = 0;
targetEvidenceTable = table();
targetRegionViews = struct([]);

for cpiIndex = 1:numel(resolvedOptions.CpiLabels)
    cpiLabel = resolvedOptions.CpiLabels(cpiIndex);
    cpiDefinition = resolvedOptions.MapCpiDefinitions(cpiIndex);

    for windowIndex = 1:numel(resolvedOptions.WindowLabels)
        windowLabel = resolvedOptions.WindowLabels(windowIndex);
        windowSubset = selectedWindows(selectedWindows.CpiLabel == ...
            cpiLabel & selectedWindows.WindowLabel == windowLabel, :);
        groupMapRows = repmat(localBuildMapSummaryRowTemplate(), ...
            height(windowSubset), 1);
        groupProducts = cell(height(windowSubset), 1);

        for repetitionIndex = 1:height(windowSubset)
            selectedWindow = windowSubset(repetitionIndex, :);
            preprocessedSignal = preprocessedSignals( ...
                selectedWindow.Repetition);
            mapWindowStart = localConvertStartSampleToMapDomain( ...
                selectedWindow.WindowStartSample, ...
                resolvedOptions.MapDecimationFactor);
            mapWindowStop = mapWindowStart + cpiDefinition.MapSamples - 1;

            if mapWindowStop > numel(preprocessedSignal.ReferenceMapSamples)
                error("helperAnalyzeG4PassiveBaselineMap:InvalidMapWindow", ...
                    "Map-domain window [%d %d] does not fit repetition %d.", ...
                    mapWindowStart, mapWindowStop, ...
                    selectedWindow.Repetition);
            end

            referenceWindow = preprocessedSignal.ReferenceMapSamples( ...
                mapWindowStart:mapWindowStop);
            surveillanceWindow = preprocessedSignal.SurveillanceMapSamples( ...
                mapWindowStart:mapWindowStop);
            mapProduct = localBuildMapProduct(referenceWindow, ...
                surveillanceWindow, cpiDefinition, ...
                baselineProductDefinition, resolvedOptions);
            [interpretationLabel, rationale] = localClassifyMapProduct( ...
                mapProduct, resolvedOptions);
            mapRowIndex = mapRowIndex + 1;
            groupMapRows(repetitionIndex) = localBuildMapSummaryRow( ...
                selectedWindow, cpiDefinition, mapProduct, ...
                appliedCorrection, interpretationLabel, rationale);
            mapRows(mapRowIndex) = groupMapRows(repetitionIndex);
            if resolvedOptions.RunPostHocSyntheticTargetEvidence
                evidenceContext = localBuildTargetEvidenceContext( ...
                    selectedWindow, mapProduct, appliedCorrection, ...
                    resolvedOptions);
                targetEvidence = helperAnalyzeSyntheticTargetEvidence( ...
                    mapProduct.MapLinear, mapProduct.RawDelayAxis_s, ...
                    mapProduct.RawDopplerAxis_Hz, ...
                    resolvedOptions.SyntheticTruth, evidenceContext);
                targetEvidenceTable = [targetEvidenceTable; ...
                    targetEvidence.TargetTable]; %#ok<AGROW>

                if isempty(targetRegionViews)
                    targetRegionViews = ...
                        targetEvidence.TargetRegionViews;
                else
                    targetRegionViews = [targetRegionViews; ...
                        targetEvidence.TargetRegionViews]; %#ok<AGROW>
                end
            end

            groupProducts{repetitionIndex} = rmfield(mapProduct, ...
                "MapLinear");
        end

        groupIndex = groupIndex + 1;
        [repeatabilityRow, representativeMap] = ...
            localBuildRepeatabilityOutputs(groupMapRows, groupProducts, ...
            baselineProductDefinition, resolvedOptions);
        repeatabilityRows(groupIndex) = repeatabilityRow;
        representativeMaps(groupIndex) = representativeMap;
    end
end

