function cpiEligibility = localResolveG4CpiEligibility(cpiLabel, ...
    cpiAdmissibilityTable)

cpiLabel = string(cpiLabel);
anchorRow = cpiAdmissibilityTable(cpiAdmissibilityTable.CpiLabel == ...
    cpiLabel, :);

if ~isempty(anchorRow)
    cpiEligibility = struct();
    cpiEligibility.Label = string(anchorRow.G3EligibilityLabel(1));
    cpiEligibility.Eligible = logical(anchorRow.Eligible(1));
    cpiEligibility.Rank = localResolveEligibilityRank( ...
        cpiEligibility.Label);
    cpiEligibility.Rationale = string(anchorRow.Rationale(1));
    return
end

[lowerCpiLabel, upperCpiLabel] = localResolveBracketingCpiLabels(cpiLabel);
lowerEligibility = localResolveG4CpiEligibility(lowerCpiLabel, ...
    cpiAdmissibilityTable);
upperEligibility = localResolveG4CpiEligibility(upperCpiLabel, ...
    cpiAdmissibilityTable);
cpiEligibility = struct();
cpiEligibility.Label = "derived_from_bracketing_cpis";
cpiEligibility.Eligible = lowerEligibility.Eligible && ...
    upperEligibility.Eligible;
cpiEligibility.Rank = min([lowerEligibility.Rank, ...
    upperEligibility.Rank]) - 0.1;

if ~cpiEligibility.Eligible
    cpiEligibility.Rank = 0.0;
    cpiEligibility.Rationale = sprintf("%s is a G4-only sensitivity CPI " + ...
        "derived from %s and %s, but at least one bracket is blocked.", ...
        cpiLabel, lowerCpiLabel, upperCpiLabel);
else
    cpiEligibility.Rationale = sprintf("%s is marked " + ...
        "derived_from_bracketing_cpis and may rank only because %s and " + ...
        "%s are not blocked in G3.", cpiLabel, lowerCpiLabel, ...
        upperCpiLabel);
end

end

function label = localResolveRateAuditAgreementLabel(cpiLabel, ...
    fullRateAuditSummaryTable, resolvedOptions)

