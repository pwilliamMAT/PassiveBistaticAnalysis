function analysis = helperAnalyzeG4PassiveBaselineMap(sessionData, ...
    collectionMetadataInfo, g3SyncResults, options)
%HELPERANALYZEG4PASSIVEBASELINEMAP Analyze the first executable G4 slice.
%
%   ANALYSIS = HELPERANALYZEG4PASSIVEBASELINEMAP(SESSIONDATA, ...
%   COLLECTIONMETADATAINFO, G3SYNCRESULTS, OPTIONS) computes the frozen
%   first-slice passive baseline review products on top of the accepted G3
%   contracts. The helper keeps the Stage 4 outputs review-oriented and
%   non-final: it returns descriptive tables, representative maps, a
%   provisional CPI ranking, and a split interpretation model rather than a
%   formal pass / retune / reject gate decision.

arguments
    sessionData (1,1) struct
    collectionMetadataInfo (1,1) struct
    g3SyncResults (1,1) struct
    options (1,1) struct = struct()
end

upstreamStatus = localResolveUpstreamStatus(g3SyncResults);
localValidateUpstreamStatus(upstreamStatus);

syncOptions = localBuildSyncOptions(options);
syncPrep = helperPrepareG3SyncInputs(sessionData, collectionMetadataInfo, ...
    syncOptions, g3SyncResults);
resolvedOptions = localResolveOptions(syncPrep.ResolvedOptions, options);
appliedCorrection = localResolveAppliedCorrection(syncPrep, resolvedOptions);
selectedWindows = localBuildSelectedWindowTable(syncPrep.WindowObservations, ...
    resolvedOptions);
preprocessedSignals = localBuildPreprocessedSignals(sessionData, syncPrep, ...
    appliedCorrection, resolvedOptions);
baselineProductDefinition = localBuildBaselineProductDefinition(syncPrep, ...
    appliedCorrection, resolvedOptions);
[mapSummaryTable, repeatabilityTable, representativeMaps, ...
    targetEvidenceTable, targetRegionViews] = ...
    localBuildMapProducts(selectedWindows, preprocessedSignals, ...
    baselineProductDefinition, resolvedOptions, appliedCorrection);
fullRateAuditSummaryTable = localBuildFullRateAuditSummaryTable( ...
    sessionData, syncPrep, appliedCorrection, mapSummaryTable, ...
    resolvedOptions);
[cpiSelectionTable, recommendedBaselineCpiLabel, rankingTrace] = ...
    localBuildCpiSelectionTable(mapSummaryTable, repeatabilityTable, ...
    syncPrep.CpiAdmissibilityTable, fullRateAuditSummaryTable, ...
    resolvedOptions);
questionSummaries = localBuildQuestionSummaries(mapSummaryTable, ...
    repeatabilityTable, cpiSelectionTable, recommendedBaselineCpiLabel, ...
    rankingTrace, resolvedOptions);
interpretation = localBuildInterpretation(questionSummaries, ...
    mapSummaryTable, repeatabilityTable, syncPrep, upstreamStatus, ...
    recommendedBaselineCpiLabel, fullRateAuditSummaryTable, ...
    resolvedOptions);
interpretation = localApplyDataProfileInterpretation(interpretation, ...
    targetEvidenceTable, resolvedOptions);
mapIntegrity = localBuildMapIntegrity(mapSummaryTable, ...
    representativeMaps);

analysis = struct();
analysis.DatasetId = string(sessionData.DatasetId);
analysis.StageId = "G4_Passive_Baseline_Analysis_Core";
analysis.Options = localBuildOptionsOutput(resolvedOptions, ...
    appliedCorrection);
analysis.CpiDefinitions = localBuildCpiDefinitionsOutput( ...
    resolvedOptions.MapCpiDefinitions);
analysis.BaselineProductDefinition = baselineProductDefinition;
analysis.MapSummaryTable = mapSummaryTable;
analysis.RepeatabilityTable = repeatabilityTable;
analysis.CpiSelectionTable = cpiSelectionTable;
analysis.FullRateAuditSummaryTable = fullRateAuditSummaryTable;

if resolvedOptions.RunFullRateAudit
    analysis.FullRateAuditStatus = "executed";
else
    analysis.FullRateAuditStatus = "NOT_RUN_QUICK_MODE";
end

analysis.QuestionSummaries = questionSummaries;
analysis.Interpretation = interpretation;
analysis.MapIntegrity = mapIntegrity;
analysis.RecommendedBaselineCpiLabel = recommendedBaselineCpiLabel;
analysis.RepresentativeMaps = representativeMaps;
analysis.RawAxisRepresentativeMaps = representativeMaps;
analysis.SyntheticTargetEvidenceTable = targetEvidenceTable;
analysis.SyntheticTargetRegionViews = targetRegionViews;

end

function syncOptions = localBuildSyncOptions(options)

syncOptions = options;
mapOnlyFields = [ ...
    "MapCpiLabels"; ...
    "MapCpiDurations_s"; ...
    "MapWindowLabels"; ...
    "RunFullRateAudit"; ...
    "RunPostHocSyntheticTargetEvidence"; ...
    "SyntheticTruth"; ...
    "TargetLagUncertainty_samples"; ...
    "TargetResidualFrequencyUncertainty_Hz" ...
    ];

for idx = 1:numel(mapOnlyFields)
    fieldName = mapOnlyFields(idx);

    if isfield(syncOptions, fieldName)
        syncOptions = rmfield(syncOptions, fieldName);
    end
end

end

function upstreamStatus = localResolveUpstreamStatus(g3SyncResults)

if isempty(fieldnames(g3SyncResults))
    error("helperAnalyzeG4PassiveBaselineMap:MissingG3Result", ...
        "Stage 4 requires a qualifying in-session G3 result.");
end

upstreamStatus = struct();
upstreamStatus.OverallLabel = localResolveStructStringField( ...
    g3SyncResults, "OverallLabel");
upstreamStatus.RecommendedStrategyCandidate = ...
    localResolveStructStringField(g3SyncResults, ...
    "RecommendedStrategyCandidate");
upstreamStatus.BlockingFindings = localResolveStringVectorField( ...
    g3SyncResults, "BlockingFindings");
upstreamStatus.QuestionSummaries = localResolveTableField(g3SyncResults, ...
    "QuestionSummaries");

if strlength(upstreamStatus.OverallLabel) == 0 && ...
        isfield(g3SyncResults, "Interpretation") && ...
        isstruct(g3SyncResults.Interpretation)
    interpretation = g3SyncResults.Interpretation;
    upstreamStatus.OverallLabel = localResolveStructStringField( ...
        interpretation, "OverallLabel");
    upstreamStatus.RecommendedStrategyCandidate = ...
        localResolveStructStringField(interpretation, ...
        "RecommendedStrategyCandidate");

    if isempty(upstreamStatus.BlockingFindings)
        upstreamStatus.BlockingFindings = localResolveStringVectorField( ...
            interpretation, "BlockingFindings");
    end
end

if strlength(upstreamStatus.RecommendedStrategyCandidate) == 0 && ...
        isfield(g3SyncResults, "Interpretation") && ...
        isstruct(g3SyncResults.Interpretation)
    upstreamStatus.RecommendedStrategyCandidate = ...
        localResolveStructStringField(g3SyncResults.Interpretation, ...
        "RecommendedStrategyCandidate");
end

upstreamStatus.CaveatCodes = strings(0, 1);

if ~isempty(upstreamStatus.QuestionSummaries)
    caveatedRows = upstreamStatus.QuestionSummaries( ...
        upstreamStatus.QuestionSummaries.InterpretationLabel == ...
        "caveated", :);

    if ~isempty(caveatedRows)
        upstreamStatus.CaveatCodes = "g3_" + ...
            string(caveatedRows.QuestionId) + "_caveated";
    end
end

if upstreamStatus.OverallLabel == "caveated" && ...
        isempty(upstreamStatus.CaveatCodes)
    upstreamStatus.CaveatCodes = "g3_overall_caveated";
end

if ~isempty(upstreamStatus.BlockingFindings)
    upstreamStatus.CaveatCodes = [ ...
        upstreamStatus.CaveatCodes; ...
        string(upstreamStatus.BlockingFindings(:)) ...
        ];
end

upstreamStatus.CaveatCodes = unique(upstreamStatus.CaveatCodes);
upstreamStatus.CaveatCodes = upstreamStatus.CaveatCodes( ...
    strlength(upstreamStatus.CaveatCodes) > 0);

end

function localValidateUpstreamStatus(upstreamStatus)

if strlength(upstreamStatus.OverallLabel) == 0
    error("helperAnalyzeG4PassiveBaselineMap:MissingG3OverallLabel", ...
        "Stage 4 requires G3 to provide an overall interpretation label.");
end

if upstreamStatus.OverallLabel ~= "ready" && ...
        upstreamStatus.OverallLabel ~= "caveated"
    error("helperAnalyzeG4PassiveBaselineMap:NonQualifyingG3Status", ...
        "Stage 4 requires G3 OverallLabel to be ready or caveated, " + ...
        "but found %s.", upstreamStatus.OverallLabel);
end

if upstreamStatus.RecommendedStrategyCandidate ~= ...
        "global_session_correction"
    error("helperAnalyzeG4PassiveBaselineMap:UnexpectedG3Strategy", ...
        "Stage 4 is currently locked to the G3 recommended strategy " + ...
        "global_session_correction, but found %s.", ...
        upstreamStatus.RecommendedStrategyCandidate);
end

end

