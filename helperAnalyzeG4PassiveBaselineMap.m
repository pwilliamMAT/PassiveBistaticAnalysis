zeroDopplerRow = double(mapLinear(zeroDopplerIndex, :));
delayMask = abs(delayAxis_samples - directPathDelay_samples) > ...
    exclusionDelayRadius_samples;
clutterValues = zeroDopplerRow(delayMask);

if isempty(clutterValues)
    clutterValues = double(zeroDopplerRow);
end

end

function backgroundValues = localBuildBackgroundValues(mapLinear, ...
    delayAxis_samples, dopplerAxis_Hz, baselineProductDefinition)

