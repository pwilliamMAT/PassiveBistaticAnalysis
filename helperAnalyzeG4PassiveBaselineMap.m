function fullRateAuditSummaryTable = localBuildFullRateAuditSummaryTable( ...
    sessionData, syncPrep, appliedCorrection, mapSummaryTable, ...
    resolvedOptions)

if ~resolvedOptions.RunFullRateAudit
    fullRateAuditSummaryTable = struct2table(repmat( ...
        localBuildFullRateAuditRowTemplate(), 0, 1));
    return;
end

auditCpiLabels = string(resolvedOptions.FullRateAuditCpiLabels(:));
auditRepetitions = double(resolvedOptions.FullRateAuditRepetitions(:));
auditRowCount = numel(auditRepetitions) * numel(auditCpiLabels);
auditRows = repmat(localBuildFullRateAuditRowTemplate(), ...
    auditRowCount, 1);
auditOptions = resolvedOptions;
auditOptions.MapRateMode = "raw_rate_audit";
auditOptions.MapDecimationFactor = 1;
auditOptions.MapSampleRateHz = resolvedOptions.SampleRateHz;
auditOptions.MapCpiSampleCounts = round( ...
    auditOptions.CpiDurations_s .* auditOptions.MapSampleRateHz);
auditOptions.MapCpiDefinitions = localBuildMapCpiDefinitions( ...
    auditOptions.CpiLabels, auditOptions.CpiDurations_s, ...
    auditOptions.MapCpiSampleCounts);
auditBaselineDefinition = localBuildBaselineProductDefinition(syncPrep, ...
    appliedCorrection, auditOptions);
rowIndex = 0;

for repetitionIndex = 1:numel(auditRepetitions)
    repetitionValue = auditRepetitions(repetitionIndex);
    scan = localResolveScanWithSamples(sessionData, repetitionValue);
    referenceSamples = double(scan.Samples(:, ...
        syncPrep.RoleInfo.ReferenceColumnIndex));
    surveillanceSamples = double(scan.Samples(:, ...
        syncPrep.RoleInfo.SurveillanceColumnIndex));
    correctedSurveillance = localApplyIntegerDelay(surveillanceSamples, ...
        appliedCorrection.AppliedLag_samples);
    correctedSurveillance = localApplyResidualFrequencyCorrection( ...
        correctedSurveillance, ...
        appliedCorrection.AppliedResidualFrequency_Hz, ...
        syncPrep.ResolvedOptions.SampleRateHz);

    for cpiIndex = 1:numel(auditCpiLabels)
        cpiLabel = auditCpiLabels(cpiIndex);
        reducedRow = mapSummaryTable( ...
            mapSummaryTable.Repetition == repetitionValue & ...
            mapSummaryTable.CpiLabel == cpiLabel & ...
            mapSummaryTable.WindowLabel == ...
            resolvedOptions.FullRateAuditWindowLabel, :);

        if height(reducedRow) ~= 1
            error("helperAnalyzeG4PassiveBaselineMap:MissingAuditReducedRow", ...
                "Expected one reduced-rate audit row for repetition %d CPI %s.", ...
                repetitionValue, cpiLabel);
        end

        rawCpiIndex = find(auditOptions.CpiLabels == cpiLabel, 1, "first");
        rawCpiDefinition = auditOptions.MapCpiDefinitions(rawCpiIndex);
        rawStartSample = double(reducedRow.WindowStartSample(1));
        rawStopSample = rawStartSample + rawCpiDefinition.MapSamples - 1;

        if rawStopSample > numel(referenceSamples)
            error("helperAnalyzeG4PassiveBaselineMap:InvalidRawAuditWindow", ...
                "Raw audit window [%d %d] does not fit repetition %d.", ...
                rawStartSample, rawStopSample, repetitionValue);
        end

        rawReferenceWindow = single(referenceSamples( ...
            rawStartSample:rawStopSample));
        rawSurveillanceWindow = single(correctedSurveillance( ...
            rawStartSample:rawStopSample));
        rawMapProduct = localBuildRawRateAuditProductFromCuts( ...
            rawReferenceWindow, rawSurveillanceWindow, rawCpiDefinition, ...
            auditBaselineDefinition, auditOptions, reducedRow, ...
            resolvedOptions);
        [rawInterpretationLabel, ~] = localClassifyMapProduct( ...
            rawMapProduct, resolvedOptions);
        [agreementLabel, rationale, auditDeltas] = ...
            localClassifyFullRateAudit(rawMapProduct, rawInterpretationLabel, ...
            reducedRow, resolvedOptions);
        rowIndex = rowIndex + 1;
        auditRows(rowIndex) = localBuildFullRateAuditRow( ...
            repetitionValue, cpiLabel, ...
            resolvedOptions.FullRateAuditWindowLabel, rawMapProduct, ...
            rawInterpretationLabel, reducedRow, agreementLabel, ...
            rationale, auditDeltas, resolvedOptions);
    end
end

fullRateAuditSummaryTable = struct2table(auditRows(1:rowIndex));

end

